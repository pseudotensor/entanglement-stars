#!/usr/bin/env python3
"""route2_core_b29_table_v1.py (busi lane, inbox #349): the tables of B29's core stage (route 2) and its comparison with route 1
(CORE_HF_full_v1.2's per-slice jsons), read from the jsons only (nothing computed beyond arithmetic on stored numbers).

The error budget of every compared number is built first, from stored quantities only, and printed before the comparison:
  rows   the rows' roundoff, 1e-12 relative (declared from the fixture: on prod T16 kappa 1 the two codes realize the same discrete rows,
         M on the grid to 1.4e-15, the windows b to 5.5e-16, B and V to 4.4e-14; so the discretization is common to both routes);
  shared the rows' discretization itself, 2 |X(dr 0.1) - X(dr 0.05)| / |X| from route 2's dr study at the same evaluation point: an
         accuracy shared by both routes, printed beside the verdict and not part of the agreement budget;
  dress  the dressing: |X(beta GMRES on the exact operator) - X(beta dense solve with the explicit matrix)| / |X| (route 2's two
         solves), plus 2 rho/sigma_min with rho the larger of the two routes' solve residuals; for the dressed exchange the
         explicit response's relative error (the larger of route 2's matrix-vs-exact-operator test, route 2's dropped-SVD bound
         and route 1's matrix-vs-operator test) times the dressing's own share |X_dressed - X_bare| / |X|;
  contr  the contraction's roundoff: route 1's Gram-vs-direct check Q6' (relative) for the variances; for the exchange
         1e-13 times the block cancellation sum|blocks|/|E_F| (roundoff amplified by the cancellation);
  quad   route 1's window and response quadrature: its exponential-sum error and its matrix-vs-operator test (relative).
The storage floor (complex64) is common to both routes (the same stored columns, both Loewdin-orthonormalized): it is not a source
of disagreement and is not in the budget; its own size is route 1's C2 control (at most 2.4e-8 on variances, 2e-9 on the exchange).
Usage: route2_core_b29_table_v1.py --r2dir DIR --r1dir DIR --out FILE.md [--json FILE.json]
"""
import argparse
import json
import math
import os

SLICES = [('prod', 15.0), ('prod', 16.0), ('s8', 14.0), ('s8', 16.0)]
R1_SUB = {'prod': 'card_bench1b/prod', 's8': 'card_R2/s8'}
LABELS = ('R_in', 'R_50', 'R_t')
EPS = 2.2e-16
ROWS_ROUNDOFF = 1e-12   # declared: 100 times the fixture's largest rows difference (M 1.4e-15, b 5.5e-16, B 4.4e-14, V 4.4e-14 relative)


def rel(a, b):
    return abs(a - b) / max(abs(b), 1e-300)


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def r1_check(J, prefix):
    for c in J.get('checks', []):
        if c['name'].startswith(prefix):
            return float(c['value'])
    return None


def fmt(x, n=6):
    if x is None:
        return '-'
    if isinstance(x, str):
        return x
    if x == 0:
        return '0'
    a = abs(x)
    if 1e-3 <= a < 1e5:
        return ('%.' + str(n) + 'g') % x
    return ('%.' + str(n - 1) + 'e') % x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--r2dir', default='<internal>/route2_core')
    ap.add_argument('--r1dir', default='<internal>/core_hf_v1')
    ap.add_argument('--r1rerun', default='<internal>/core_hf_prod_T0016.00.json')
    ap.add_argument('--out', required=True)
    ap.add_argument('--json', default=None)
    a = ap.parse_args()
    L = []
    P = L.append
    allrows = []
    summary = {}
    P('# B29 core stage, route 2 (route2_core_b29_v1) against route 1 (CORE_HF_full v1.2): tables\n')
    P('Generated by route2_core_b29_table_v1.py from the route-2 jsons in %s and route 1\'s per-slice jsons in %s (card runs). '
      'Every route-2 number: the stored channel set kappa <= 10 (the angular regulator), past the record\'s own hydrodynamic limit, '
      'one GPU (complex128) and the box CPU (the rows).\n' % (a.r2dir, a.r1dir))
    for hist, t in SLICES:
        tag = '%s_T%07.2f' % (hist, t)
        J2 = load(os.path.join(a.r2dir, tag + '.json'))
        Jd = load(os.path.join(a.r2dir, tag + '_dr05.json'))
        J1 = load(os.path.join(a.r1dir, R1_SUB[hist], 'core_hf_%s.json' % tag))
        if J2 is None or J1 is None:
            P('\n## %s T/r_s %g: missing (route 2 %s, route 1 %s)\n' % (hist, t, J2 is not None, J1 is not None))
            continue
        P('\n## %s T/r_s %g (%s; route 1 card json, its stamped code_md5 %s)\n' % (hist, t, 'complex64' if J2['complex64'] else 'complex128', J1.get('code_md5')))
        # ---------------- route 2's own controls on this slice
        ch = J2['channels']
        fails = [c for c in J2['checks'] if c['status'] == 'FAIL']
        P('Route 2 checks: %d PASS, %d FAIL%s. Per channel: ||(1 - P_ref) h_m P_ref||_F/||h_m||_F %s to %s (all %s); P_ref resolution against route 2\'s '
          'own eigenvectors %s to %s; e against the stored e_k at most %s; Loewdin orthonormality %s; stored orthonormality %s to %s; N_B %s.'
          % (sum(c['status'] == 'PASS' for c in J2['checks']), len(fails), (' (' + '; '.join('%s %.2e' % (c['name'], c['value']) for c in fails) + ')') if fails else '',
             fmt(min(c['comm_h_Pref_rel'] for c in ch), 2), fmt(max(c['comm_h_Pref_rel'] for c in ch), 2),
             'resolved' if all(c['status'] == 'resolved' for c in ch) else 'NOT all resolved',
             fmt(min(c['pref_resolution_defect'] for c in ch), 2), fmt(max(c['pref_resolution_defect'] for c in ch), 2),
             fmt(max(c['e_vs_stored_abs'] for c in ch), 2), fmt(max(c['loewdin_orthonormality'] for c in ch), 2),
             fmt(min(c['stored_orthonormality'] for c in ch), 2), fmt(max(c['stored_orthonormality'] for c in ch), 2), fmt(J2['N_B'], 12)))
        fc = J2['rows']['field_check']
        rs = J2['response']
        kn = J2['kernel']
        P('Rows: field check dN %s, dv %s (%s); E(R_out) %s against the record %s; first law b(R_out) against the gradient %s. Response: rank of the '
          'Cauchy-kernel SVD %s to %s per channel, dropped-part bound %s of ||P^A||_2; explicit matrix against the exact operator %s; '
          '||P^A (N, v)||/||(N, v)|| %s (exact operator). sigma_min(I + B P^A) %s, certified lower bound %s.'
          % (fmt(fc['N_rel_maxdev'], 2), fmt(fc['v_rel_maxdev'], 2), fc['label'], fmt(fc['E_rows_R_out'], 10), fmt(fc['E_record'], 10),
             fmt(J2['rows']['first_law_b_Rout_vs_gradient'], 2),
             min(v['rank'] for v in rs['per_channel'].values()), max(v['rank'] for v in rs['per_channel'].values()), fmt(rs['dropped_bound_rel'], 2),
             ', '.join('%s %s' % (k, fmt(v, 2)) for k, v in rs['matrix_vs_exact_operator_rel'].items()), fmt(rs.get('PA_phi_applied_over_phi_exact'), 2),
             fmt(kn['sigma_min_I_plus_BPA_computed'], 8), fmt(kn['sigma_min_certified_lower'], 8)))
        gm = [(l, nm, J2['variance'][l]['dressing'][nm]['residual_rel'], J2['variance'][l]['dressing'][nm]['iterations'])
              for l in J2['variance'] for nm in ('full', 'nocur_dressed') if nm in J2['variance'][l].get('dressing', {})]
        if gm:
            P('GMRES (full, from zero, matrix-free exact operator): true residuals %s to %s in %d to %d iterations (criterion 1e-10); the dressed pair energy by '
              'GMRES against the dense kernel %s.' % (fmt(min(x[2] for x in gm), 2), fmt(max(x[2] for x in gm), 2), min(x[3] for x in gm), max(x[3] for x in gm),
                                                     fmt(J2['exchange']['dressed'].get('E_pair_gmres_vs_dense_rel'), 2)))
        # ---------------- the budgets
        s_min = kn['sigma_min_certified_lower']
        rho = max([x[2] for x in gm] + [J1.get('kernel_info', {}).get('Jm_true_residual') or 0.0])
        q6 = r1_check(J1, "Q6'") or 1e-9
        r1resp = J1.get('response', {})
        r1q = max([float(x) for x in (r1resp.get('matrix_vs_operator_rel') or [0.0])] + [float(r1resp.get('quadrature_max_rel_err') or 0.0)])
        r2P = max(list(rs['matrix_vs_exact_operator_rel'].values()) + [rs['dropped_bound_rel']])
        relP = max(r2P, r1q)
        rows = []

        def disc_of(getter):
            if Jd is None:
                return None
            try:
                x0, x1 = getter(J2), getter(Jd)
                return 2.0 * rel(x0, x1) if x0 else None
            except (KeyError, TypeError):
                return None

        def add(name, v1, v2, budget_parts, printed=None):
            # the discretization is shared (the fixture: both routes realize the same discrete rows to 1.4e-15): printed as the number's own
            # accuracy, not summed into the agreement budget; in its place the rows' roundoff (ROWS_ROUNDOFF) for every rows-dependent number
            if 'disc' in budget_parts:
                budget_parts['shared_disc'] = budget_parts.pop('disc')
                budget_parts['rows'] = ROWS_ROUNDOFF
            bud = sum(v for k, v in budget_parts.items() if v is not None and k != 'shared_disc')
            bud = max(bud, 1e-13)
            d = rel(v2, v1)
            rows.append(dict(slice=tag, quantity=name, route1=v1, route2=v2, rel_diff=d, budget=bud, parts=budget_parts,
                             verdict='agree' if d <= bud else 'DISAGREE', printed_v1_2=printed))

        dsc_default = None
        for l in LABELS:
            if l not in J2['variance'] or l not in J1['variance']:
                continue
            v2 = J2['variance'][l]
            v1 = J1['variance'][l]
            M1, M2 = J1['radii'][l]['M_H'], v2['M_H']
            same_row = (J1['radii'][l]['grid_row'] == v2['grid_row'])
            dM = disc_of(lambda J: J['variance'][l]['M_H'])
            add('%s M_H (row %s%s)' % (l, v2['grid_row'], '' if same_row else ' / route 1 row %s' % J1['radii'][l]['grid_row']), M1, M2, dict(disc=dM))
            for nm in ('noref', 'full'):
                if nm not in v2['variants'] or nm not in v1['variants']:
                    continue
                w2, w1 = v2['variants'][nm], v1['variants'][nm]
                dr_ = (v2.get('dressing', {}).get('full', {}).get('residual_rel', 0.0)) if nm == 'full' else 0.0
                dress = (v2.get('gmres_vs_dense_VarC_rel', 0.0) + 2.0 * rho / s_min) if nm == 'full' else 0.0
                for q, key in (('Var_C', 'Var_C'), ('Var_C0 (sea part)', 'Var_C0'), ('signed excess', 'signed_excess')):
                    dq = disc_of(lambda J: J['variance'][l]['variants'][nm][key])
                    # a sea part or excess inherits the absolute budget of Var_C and Var_C0 in proportion
                    scale = 1.0
                    if key == 'signed_excess':
                        scale = (abs(w2['Var_C']) + abs(w2['Var_C0'])) / max(abs(w2['signed_excess']), 1e-300)
                    add('%s %s %s' % (l, nm, q), w1[key], w2[key], dict(disc=dq, dress=dress * scale if dress else None, contr=q6 * scale, quad=r1q * scale if nm == 'full' else None))
                dq = disc_of(lambda J: J['variance'][l]['variants'][nm]['sqrt_VarC_over_M'])
                add('%s %s sqrt(Var_C)/M_H' % (l, nm), w1['sqrt_VarC_over_M'], w2['sqrt_VarC_over_M'],
                    dict(disc=dq, dress=0.5 * dress if dress else None, contr=0.5 * q6, quad=0.5 * r1q if nm == 'full' else None))
            if 'full' in v2['variants'] and 'full' in v1['variants'] and 'noref' in v1['variants']:
                rr1 = v1['variants']['full']['Var_C'] / v1['variants']['noref']['Var_C'] - 1.0
                rr2 = v2['reference_response_rel']
                # an absolute comparison of a small difference: the budget is that of Var_C (full) and Var_C (noref) over the shift's size
                b_full = [r for r in rows if r['quantity'] == '%s full Var_C' % l][0]['budget']
                b_nor = [r for r in rows if r['quantity'] == '%s noref Var_C' % l][0]['budget']
                bud = (b_full + b_nor) * (1 + abs(rr2)) / max(abs(rr2), 1e-300)
                d = rel(rr2, rr1)
                rows.append(dict(slice=tag, quantity='%s reference response (Var_C full/noref - 1)' % l, route1=rr1, route2=rr2, rel_diff=d, budget=bud,
                                 parts=dict(from_Var_C_budgets=bud), verdict='agree' if d <= bud else 'DISAGREE'))
        for kname in ('dressed', 'bare'):
            e2, e1 = J2['exchange'].get(kname), J1['exchange'].get(kname)
            if not e2 or not e1:
                continue
            canc = 1.0 / e2['blocks']['cancellation_E_F']
            dshare = abs(J2['exchange']['dressed']['E_F'] - J2['exchange']['bare']['E_F']) / abs(J2['exchange']['dressed']['E_F'])
            dshare_p = abs(J2['exchange']['dressed']['E_pair'] - J2['exchange']['bare']['E_pair']) / abs(J2['exchange']['dressed']['E_pair'])
            dEF = disc_of(lambda J: J['exchange'][kname]['E_F'])
            dEp = disc_of(lambda J: J['exchange'][kname]['E_pair'])
            dress_F = relP * dshare if kname == 'dressed' else None
            dress_p = (relP * dshare_p + (J2['exchange']['dressed'].get('E_pair_gmres_vs_dense_rel') or 0.0)) if kname == 'dressed' else None
            add('E_F (%s)' % kname, e1['E_F'], e2['E_F'], dict(disc=dEF, dress=dress_F, contr=1e-13 * canc, quad=r1q * dshare if kname == 'dressed' else None))
            add('E_pair (%s)' % kname, e1['E_pair'], e2['E_pair'], dict(disc=dEp, dress=dress_p, contr=1e-13 / e2['blocks']['cancellation_E_pair'],
                                                                         quad=r1q * dshare_p if kname == 'dressed' else None))
            bF = [r for r in rows if r['quantity'] == 'E_F (%s)' % kname][0]
            bp = [r for r in rows if r['quantity'] == 'E_pair (%s)' % kname][0]
            add('E_F/|E_pair| (%s)' % kname, e1['E_F_over_abs_E_pair'], e2['E_F_over_abs_E_pair'], dict(from_parts=bF['budget'] + bp['budget']))
        if J2['exchange'].get('dressed') and J1['exchange'].get('dressed'):
            x1 = J1['exchange']['dressed']['E_F'] / J1['exchange']['bare']['E_F'] - 1
            x2 = J2['exchange']['dressed']['dressed_over_bare_E_F_minus_1']
            bF = [r for r in rows if r['quantity'] == 'E_F (dressed)'][0]['budget'] + [r for r in rows if r['quantity'] == 'E_F (bare)'][0]['budget']
            bud = bF * (1 + abs(x2)) / abs(x2)
            d = rel(x2, x1)
            rows.append(dict(slice=tag, quantity='dressed/bare E_F - 1', route1=x1, route2=x2, rel_diff=d, budget=bud, parts=dict(from_E_F_budgets=bud),
                             verdict='agree' if d <= bud else 'DISAGREE'))
        ki1 = J1.get('kernel_info', {})
        for q, k1, k2, bud in (('sigma_min(I + B P^A)', 'smin_I_plus_BPA', 'sigma_min_I_plus_BPA_computed', None),
                               ('||V - B||_F/||B||_F', 'V_minus_B_rel', 'V_minus_B_rel_F', None),
                               ('eig B min', 'B_eig_min', 'B_eig_min', None), ('eig B max', 'B_eig_max', 'B_eig_max', None),
                               ('eig V min', 'V_eig_min', 'V_eig_min', None), ('eig V max', 'V_eig_max', 'V_eig_max', None)):
            if ki1.get(k1) is None or kn.get(k2) is None:
                continue
            dq = disc_of(lambda J: J['kernel'][k2])
            add(q, ki1[k1], kn[k2], dict(disc=dq, dress=relP if 'V' in q or 'sigma' in q else None))
        add('N_B', float(J1['status']['N_B']) if 'N_B' in J1.get('status', {}) else 640.0, J2['N_B'], dict(floor=1e-5 if J2['complex64'] else 1e-9))
        r50_1 = J1['radii']['R_50']['r']
        add('R_50 (dust half radius)', r50_1, J2['radii']['R_50']['r'], dict(roundoff=1e-12))
        # ---------------- print the budgets first, then the comparison
        P('\n### Error budgets (declared before the comparison; relative)\n')
        P('Sources: shared discretization from route 2\'s dr 0.05 rerun of this slice %s; dress from route 2\'s two solves and rho = %s, certified sigma_min = %s; contr from '
          'route 1\'s Q6\' (%s) and the block cancellation (1/%.3f); quad from route 1\'s response (%s); the explicit response\'s relative error %s.\n'
          % ('(present)' if Jd is not None else '(ABSENT: disc not budgeted)', fmt(rho, 2), fmt(s_min, 6), fmt(q6, 2),
             J2['exchange']['dressed']['blocks']['cancellation_E_F'] if J2['exchange'].get('dressed') else float('nan'), fmt(r1q, 2), fmt(relP, 2)))
        P('| quantity | rows | dress | contr | quad | other | agreement budget | shared discretization (not in the budget) |')
        P('|---|---|---|---|---|---|---|---|')
        for r in rows:
            pp = r['parts']
            other = sum(v for k, v in pp.items() if k not in ('rows', 'dress', 'contr', 'quad', 'shared_disc') and v is not None)
            P('| %s | %s | %s | %s | %s | %s | %s | %s |' % (r['quantity'], fmt(pp.get('rows'), 2), fmt(pp.get('dress'), 2), fmt(pp.get('contr'), 2), fmt(pp.get('quad'), 2),
                                                          fmt(other, 2) if other else '-', fmt(r['budget'], 2), fmt(pp.get('shared_disc'), 2)))
        P('\n### Comparison with route 1 (full precision from route 1\'s json)\n')
        P('| quantity | route 1 | route 2 | relative difference | budget | verdict |')
        P('|---|---|---|---|---|---|')
        for r in rows:
            P('| %s | %s | %s | %s | %s | %s |' % (r['quantity'], fmt(r['route1'], 10), fmt(r['route2'], 10), fmt(r['rel_diff'], 2), fmt(r['budget'], 2), r['verdict']))
        dg = load(os.path.join(a.r2dir, 'diag_%s.json' % tag))
        if dg:
            P('\n### Diagnosis of the disagreements (route2_core_b29_diag_v1.py; the declared verdicts above stand)\n')
            P('The sea part of the vertices at the radii below, per channel by three contractions on route 2\'s code with route 1\'s stored vertices (equal to '
              'route 2\'s to 3e-13): the residual form (route 2\'s, roundoff about 2 eps sqrt(s)), the unreduced difference and the Gram quadratic form '
              '(route 1\'s, roundoff about eps s per channel), s = ||A R2||^2/Var_P the cancellation scale. A scale-aware contraction budget for the Gram route '
              'is 10 eps max(s) (ten channels).\n')
            P('| vertex | residual (route 2) | unreduced | Gram (rebuilt) | route 1 json | unreduced - residual | Gram - residual | route 1 - residual | max s | 10 eps max(s) | verdict at that budget |')
            P('|---|---|---|---|---|---|---|---|---|---|---|')
            for k_, e in dg['labels'].items():
                bud = 10 * EPS * e['max_scale']
                P('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (k_, fmt(e['residual'], 13), fmt(e['unreduced'], 13), fmt(e['gram'], 13),
                  fmt(e['route1_json_Var_C0'], 13), fmt(e['unreduced_minus_residual_rel'], 2), fmt(e['gram_minus_residual_rel'], 2),
                  fmt(e['route1_minus_residual_rel'], 2), fmt(e['max_scale'], 2), fmt(bud, 2), 'agree' if abs(e['route1_minus_residual_rel']) <= bud else 'DISAGREE'))
        nd = sum(r['verdict'] != 'agree' for r in rows)
        summary[tag] = dict(n=len(rows), agree=len(rows) - nd, disagree=nd)
        allrows += rows
        # ---------------- route 2's own numbers beyond the comparison (blocks, split, Gram bound, regulator)
        P('\n### Route 2 only on this slice\n')
        for kname in ('bare', 'dressed'):
            e2 = J2['exchange'].get(kname)
            if e2:
                b = e2['blocks']
                P('- Exchange blocks (%s): E_F energy %s, mixed %s, current %s (|E_F|/sum|blocks| %.3f); E_pair energy %s, mixed %s, current %s (%.3f); the Gram bound '
                  '(1/2)||V||_2 sum w Tr T^{|D|} = %s, %.1f times |E_F|; sign of E_F %s, of E_pair %s.'
                  % (kname, fmt(b['E_F']['energy']), fmt(b['E_F']['mixed']), fmt(b['E_F']['current']), b['cancellation_E_F'], fmt(b['E_pair']['energy']),
                     fmt(b['E_pair']['mixed']), fmt(b['E_pair']['current']), b['cancellation_E_pair'], fmt(e2['gram_bound'], 4), e2['gram_bound_over_abs_E_F'],
                     e2['sign_E_F'], e2['sign_E_pair']))
        if J2['exchange'].get('sign_change_bare_to_dressed'):
            P('- Sign change from bare to dressed (fix 31\'s record): E_F %s, E_pair %s.' % tuple(J2['exchange']['sign_change_bare_to_dressed'][k] for k in ('E_F', 'E_pair')))
        for l in LABELS:
            if l in J2['variance'] and 'full' in J2['variance'][l]['variants']:
                f_ = J2['variance'][l]['variants']['full']
                sp = f_.get('split', {})
                P('- %s full: Var_C %s = sea columns %s + dust columns %s + blocking %s (sum minus Var_C %s); Var_C0 by R2 %s, by route 2\'s eigenvectors %s; '
                  'general mixed-state formula %s%s; rms/M_interp %s; N_<^{-1/2} %s.'
                  % (l, fmt(f_['Var_C'], 8), fmt(sp.get('sea_columns'), 6), fmt(sp.get('dust_columns'), 6), fmt(sp.get('blocking'), 6), fmt(sp.get('sum_minus_VarC'), 2),
                     fmt(f_['Var_C0'], 8), fmt(f_.get('Var_C0_eig'), 8), fmt(f_['Var_C_general_formula'], 10),
                     ('; raw-column covariance %s (floor footprint %s)' % (fmt(f_['Var_C_raw_columns'], 10), fmt(f_['floor_footprint_rel'], 2))) if 'Var_C_raw_columns' in f_ else '',
                     fmt(f_['sqrt_VarC_over_M_interp'], 4), fmt(f_['N_r_inv_sqrt'], 4)))
        cr = J2.get('route1_cross')
        if cr:
            P('- Route 1\'s stored arrays on route 2\'s code: M on the grid %s (max rel), sources s %s, back-averaged fields %s, eig B %s (max abs), eig V %s, exchange '
              'block diagonals %s; the vertices: %s.'
              % (fmt(cr.get('M_grid_max_rel_diff'), 2), fmt(cr['s_total_rel_diff'], 2), fmt(cr['Phi_resolved_rel_diff'], 2), fmt(cr['B_eigs_max_abs_diff'], 2),
                 fmt(cr.get('V_eigs_max_abs_diff'), 2), fmt(max(cr['T_diag_rel_diff'].values()), 2) if cr['T_diag_rel_diff'] else '-',
                 '; '.join('%s %s: ||beta_1 - beta_2||/||beta_2|| %s, Var_C of route 1\'s beta on route 2 %s (route 2 own %s)'
                           % (l, nm, fmt(e['beta_rel_diff'], 2), fmt(e['Var_C_route1_beta'], 10),
                              fmt(J2['variance'][l]['variants'][nm]['Var_C'], 10)) for l, d in cr['radii'].items() for nm, e in d.items() if l != 'R_out')))
        reg = J2.get('angular_regulator')
        if reg:
            P('- Angular regulator (%s): per-copy sea variance by channel %s; weighted partial sums %s.'
              % (reg['vertex'], ', '.join(fmt(x, 4) for x in reg['VarP_per_copy']), ', '.join(fmt(x, 4) for x in reg['weighted_partial_sums'])))
    # prod T16 bare blocks against route 1's v1.1 rerun
    J1r = load(a.r1rerun)
    J2 = load(os.path.join(a.r2dir, 'prod_T0016.00.json'))
    if J1r and J2:
        P('\n## prod T/r_s 16: the bare exchange blocks against route 1\'s v1.1 CPU rerun (C1)\n')
        P('| block | route 1 E_F | route 2 E_F | rel | route 1 E_pair | route 2 E_pair | rel |')
        P('|---|---|---|---|---|---|---|')
        b1 = J1r['exchange']['bare']['blocks']
        b2 = J2['exchange']['bare']['blocks']
        for k in ('energy', 'mixed', 'current'):
            P('| %s | %s | %s | %s | %s | %s | %s |' % (k, fmt(b1['E_F'][k], 10), fmt(b2['E_F'][k], 10), fmt(rel(b2['E_F'][k], b1['E_F'][k]), 2),
                                                     fmt(b1['E_pair'][k], 10), fmt(b2['E_pair'][k], 10), fmt(rel(b2['E_pair'][k], b1['E_pair'][k]), 2)))
            allrows.append(dict(slice='prod_T0016.00', quantity='bare E_F %s block (route 1 rerun)' % k, route1=b1['E_F'][k], route2=b2['E_F'][k],
                                rel_diff=rel(b2['E_F'][k], b1['E_F'][k]), budget=None, verdict='-'))
    # the fixture: prod T16, channel 1 only, both routes run on it today (route 1's driver on the same GPU, its kernels saved)
    F2 = load(os.path.join(a.r2dir, 'fixture', 'prod_T0016.00_k1x.json'))
    F1 = load(os.path.join(a.r2dir, 'fixture_route1', 'prod', 'core_hf_prod_T0016.00_k1.json'))
    if F2 and F1:
        cr = F2['route1_cross']
        P('\n## Fixture: prod T/r_s 16, channel kappa = 1 only, both routes run on it (route 1: core_hf_slices_v1_1.py --kappas 1 --save-kernels)\n')
        P('Where the two routes compute the same discrete object from the same input, they must agree to roundoff: the response matrix '
          '(route 1 an exponential sum, route 2 the SVD of the Cauchy kernel), the exchange contraction with route 1\'s kernels, the variance contraction with '
          'route 1\'s vertices. The rows are written differently (route 1: S10\'s RK4 on the fine grid and its tangent-linear map; route 2: RK4 with '
          'half-point kernels, Simpson windows, the closed-form enclosure Hessian), but they are the same discrete scheme, so they too must agree to roundoff.\n')
        P('| quantity | value | expected |')
        P('|---|---|---|')
        P('| P^A: ||P_1 - P_2||_F/||P_1||_F | %s | roundoff and the two quadratures (route 1 %s, route 2 %s) |' % (fmt(cr.get('PA_rel_diff_F'), 2),
            fmt(max(F1['response'].get('matrix_vs_operator_rel') or [0]), 2), fmt(max(F2['response']['matrix_vs_exact_operator_rel'].values()), 2)))
        P('| B: ||B_1 - B_2||_F/||B_1||_F | %s | roundoff (the same discrete rows) |' % fmt(cr.get('B_rel_diff_F'), 2))
        P('| V: ||V_1 - V_2||_F/||V_1||_F | %s | roundoff |' % fmt(cr.get('V_rel_diff_F'), 2))
        P('| M on the grid (max rel) | %s | roundoff |' % fmt(cr.get('M_grid_max_rel_diff'), 2))
        P('| sources s (rel) | %s | roundoff |' % fmt(cr['s_total_rel_diff'], 2))
        P('| exchange block diagonal T_kappa=1 (rel) | %s | roundoff |' % fmt(max(cr['T_diag_rel_diff'].values()), 2))
        for kname, kk in (('bare', 'B'), ('dressed', 'V')):
            e1 = F1['exchange'][kname]
