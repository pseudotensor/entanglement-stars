#!/usr/bin/env python
"""Strand 5 J4 stage 1, sec. 10(m) items (1), (2) and (4) (spec solve/specs/SPEC_strand5_kernel_star.md; builder analyst), from the stage-1
family files (strand5_lattice_star_v2/v3: lstar_<tag>.json), the refined members (J4refine1) and J1's reference family (star_v4.json), with
strand5_J4_report_v2's loader, maximum estimator (the parabola in log z_c through the largest member and its neighbours) and continuum map.
(1) The scaling table: per kernel family (each (m a, aH), couplings and kernel build) beside its local_ka0 partner (the same k_op): the mass
shift (M_kernel - M_local)/M_kernel at the kernel's largest member (T5's convention) and at the fitted maxima; r_s at that member and at the
kernel's fitted maximum (the parabola through the three members' r_s in log z_c); L = sum eta log m_s^2 over (m_l, (m_l^2 + aH^2)^(1/2)
twice, (m_l^2 + 2 aH^2)^(1/2)), eta = (+, -, -, +), g_4 = L/(2 pi^2), g_4/(k_op r_s^2) and the ratio shift/(g_4/(k_op r_s^2)); aH r_s and
m r_s.  (2a) The estimator's bias: J1's reference M(z_c) (the cubic spline in log z_c of the 60 members) sampled at J4's 20 z_c values, at
the refined triple (0.80, 0.8343, 0.87) and at 40 and 80 geometric z_c in [0.05, 3], passed through the same estimator: z_c and M at the
estimate against J1's reference maximum, M_est/M_max - 1, the compactness 2M/R_s (J1's splines) at the estimate and at the nearest sample;
beside them the spline's own maximum (dense evaluation) against the reference maximum.  (2b) The refined local families: the parabola
through the three refined members, M_max, z_c and the compactness at the fitted maximum (the parabola through the members' compactness),
against the coarse estimate and against J1's maximum mapped with the family's G = 1/(2 pi k_op).  (2c) Every family's compactness at its
fitted maximum (the same parabola) beside the largest member's.  (4) Per family the most compact member: z_c, 2GM/R_s, r_s/A, r_s/B.
Writes the tables to --md and the numbers to --json.  Numbers emitted, not retyped."""
import argparse
import json
import os
import sys

import numpy as np
from scipy.interpolate import CubicSpline

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import strand5_J4_report_v2 as R2  # noqa: E402

f, table = R2.f, R2.table


def parab_at(mem, i, key, xm):
    """The parabola in log z_c through members i-1, i, i+1 of `key`, evaluated at log z_c = xm."""
    x = np.log([mem[j]["z_c"] for j in (i - 1, i, i + 1)])
    c = np.polyfit(x, [mem[j][key] for j in (i - 1, i, i + 1)], 2)
    return float(np.polyval(c, xm))


def fitted(R):
    """maximum() plus r_s and the compactness at the fitted maximum."""
    mem = sorted(R2.members(R).values(), key=lambda d: d["z_c"])
    mx = R2.maximum(R)
    if mx is None or not mx["interior"]:
        return mx, mem, None
    i = int(np.argmax([d["M"] for d in mem]))
    xm = np.log(mx["z_c"])
    mx = dict(mx)
    mx["r_s_at_max"] = parab_at(mem, i, "r_s", xm)
    mx["compactness_at_max"] = parab_at(mem, i, "compactness", xm)
    mx["index"] = i
    return mx, mem, i


def estimator(zs, Mf):
    Ms = np.array([Mf(z) for z in zs])
    i = int(np.argmax(Ms))
    if i == 0 or i == len(zs) - 1:
        return None
    x = np.log(zs[i - 1:i + 2])
    c = np.polyfit(x, Ms[i - 1:i + 2], 2)
    xm = -c[1] / (2 * c[0])
    return {"z_est": float(np.exp(xm)), "M_est": float(np.polyval(c, xm)), "nearest_z": float(zs[i]), "spacing_log": float(x[1] - x[0])}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--refine", required=True)
    ap.add_argument("--j1", required=True)
    ap.add_argument("--md", required=True)
    ap.add_argument("--json", required=True)
    a = ap.parse_args()
    fams = R2.load(a.runs.split(","))
    ref = R2.load([a.refine])
    J1 = json.load(open(a.j1))
    at, rm = R2.cont_mapper(J1)
    out = ["# Strand 5 J4 sec. 10(m) items (1), (2), (4) (generated by solve/code/strand5/strand5_J4_items12_v1.py)", ""]
    summ = []
    res = {"scaling": [], "bias": [], "refined": [], "compactness": [], "extrema": []}
    # (1)
    rows = []
    for (m, aH) in R2.POINTS:
        for c in R2.COUPS:
            for pk in (False, True):
                key = lambda op: (round(m, 10), round(aH, 10), op, tuple(round(x, 10) for x in c), pk)
                Rk, Rl = fams.get(key("kernel")), fams.get(key("local_ka0"))
                if Rk is None or Rl is None:
                    continue
                kop = Rk["meta"]["k_op"]
                if abs(Rl["meta"]["k_op"] / kop - 1) > 1e-12:
                    raise SystemExit("k_op differs between %s and %s" % (Rk["_path"], Rl["_path"]))
                mk, memk, ik = fitted(Rk)
                ml, meml, il = fitted(Rl)
                dk = memk[ik]
                dl = R2.members(Rl).get(round(dk["z_c"], 10))
                ms = [m, np.sqrt(m * m + aH * aH), np.sqrt(m * m + aH * aH), np.sqrt(m * m + 2 * aH * aH)]
                L = float(np.sum(np.array([1, -1, -1, 1]) * np.log(np.array(ms) ** 2)))
                g4 = L / (2 * np.pi ** 2)
                sh_mem = (dk["M"] - dl["M"]) / dk["M"]
                sh_fit = (mk["M"] - ml["M"]) / mk["M"]
                pred_mem = g4 / (kop * dk["r_s"] ** 2)
                pred_fit = g4 / (kop * mk["r_s_at_max"] ** 2)
                r = {"family": Rk["_path"], "partner": Rl["_path"], "m": m, "aH": aH, "couplings": list(c), "packet_built": pk, "k_op": kop, "L": L, "g_4": g4,
                     "member_z_c": dk["z_c"], "shift_member": sh_mem, "r_s_member": dk["r_s"], "pred_member": pred_mem, "ratio_member": sh_mem / pred_mem,
                     "z_max_kernel": mk["z_c"], "z_max_local": ml["z_c"], "shift_fitted": sh_fit, "r_s_fitted": mk["r_s_at_max"], "pred_fitted": pred_fit,
                     "ratio_fitted": sh_fit / pred_fit, "aH_r_s": aH * dk["r_s"], "m_r_s": m * dk["r_s"]}
                res["scaling"].append(r)
                rows.append(["%g, %g" % (m, aH), "%g, %g" % c, "packets" if pk else "table", f(kop, 8), f(L, 6), f(g4, 6), f(dk["z_c"], 5),
                             f(sh_mem, 4), f(dk["r_s"], 6), f(pred_mem, 4), f(sh_mem / pred_mem, 5), f(sh_fit, 4), f(mk["r_s_at_max"], 6),
                             f(pred_fit, 4), f(sh_fit / pred_fit, 5), f(aH * dk["r_s"], 5), f(m * dk["r_s"], 5)])
    out += ["## I1 The scaling table: the kernel-minus-local_ka0 mass shift (M_kernel - M_local)/M_kernel at the kernel's largest member and "
            "at the fitted maxima, beside g_4/(k_op r_s^2), g_4 = L/(2 pi^2), L = sum eta log m_s^2, r_s at that member and at the kernel's "
            "fitted maximum; the ratios; aH r_s and m r_s at the member", "",
            table(["(m a, aH)", "(g_M, g_B)", "kernel", "k_op", "L", "g_4", "member z_c", "shift (member)", "r_s (member)", "g_4/(k_op r_s^2)",
                   "ratio (member)", "shift (fitted maxima)", "r_s (fitted)", "g_4/(k_op r_s^2) (fitted)", "ratio (fitted)", "aH r_s", "m r_s"], rows), ""]
    for r in res["scaling"]:
        summ.append("I1 (%g, %g; %g, %g; %s): shift %s at the member (ratio to g_4/(k_op r_s^2) %s), %s at the fitted maxima (ratio %s); aH r_s %s." % (
            r["m"], r["aH"], r["couplings"][0], r["couplings"][1], "packets" if r["packet_built"] else "table", f(r["shift_member"], 4),
            f(r["ratio_member"], 4), f(r["shift_fitted"], 4), f(r["ratio_fitted"], 4), f(r["aH_r_s"], 5)))
    # (2a)
    refz = sorted(J1["reference"], key=lambda r: r["z_c"])
    lz = np.log([r["z_c"] for r in refz])
    sM = CubicSpline(lz, [r["M"] for r in refz])
    sR = CubicSpline(lz, [r["R_s_areal"] for r in refz])
    comp = lambda z: 2 * float(sM(np.log(z))) / float(sR(np.log(z)))
    dense = np.geomspace(0.6, 1.1, 200001)
    Md = sM(np.log(dense))
    jd = int(np.argmax(Md))
    res["spline_max"] = {"z": float(dense[jd]), "M": float(Md[jd]), "M_over_ref_minus_1": float(Md[jd] / rm["M"] - 1), "z_minus_ref": float(dense[jd] - rm["z_c"]),
                         "compactness": comp(dense[jd])}
    zgrid20 = np.array(sorted(next(iter(fams.values()))["meta"]["z_c"]))
    rows = []
    for name, zs in (("J4's 20", zgrid20), ("refined triple", np.geomspace(0.80, 0.87, 3)), ("40 in [0.05, 3]", np.geomspace(0.05, 3, 40)),
                     ("80 in [0.05, 3]", np.geomspace(0.05, 3, 80))):
        e = estimator(zs, lambda z: float(sM(np.log(z))))
        e.update({"grid": name, "M_bias": e["M_est"] / rm["M"] - 1, "z_minus_ref": e["z_est"] - rm["z_c"], "compactness_at_est": comp(e["z_est"]),
                  "compactness_at_nearest": comp(e["nearest_z"]), "compactness_ref": rm["compactness_2GM_over_Rs"]})
        res["bias"].append(e)
        rows.append([name, f(e["spacing_log"], 4), f(e["nearest_z"], 6), f(e["z_est"], 7), f(e["z_minus_ref"], 3), f(e["M_est"], 9), f(e["M_bias"], 3),
                     f(e["compactness_at_est"], 7), f(e["compactness_at_nearest"], 6), f(rm["compactness_2GM_over_Rs"], 7)])
        summ.append("I2a (%s, spacing %s in log z_c): the estimator's M bias %s, z_c offset %s; compactness at the estimate %s (reference %s), "
                    "at the nearest sample %s." % (name, f(e["spacing_log"], 4), f(e["M_bias"], 3), f(e["z_minus_ref"], 3), f(e["compactness_at_est"], 7),
                                                   f(rm["compactness_2GM_over_Rs"], 7), f(e["compactness_at_nearest"], 6)))
    sp = res["spline_max"]
    out += ["## I2a The three-point estimator on J1's reference family: J1's M(z_c) (the cubic spline in log z_c of its 60 members) sampled at "
            "each grid and passed through the same estimator, against J1's reference maximum (z_c %s, M %s, 2GM/R_s %s); the spline's own "
            "maximum by dense evaluation: z_c %s, M/M_ref - 1 = %s, compactness %s" % (f(rm["z_c"], 7), f(rm["M"], 9), f(rm["compactness_2GM_over_Rs"], 7),
                                                                                     f(sp["z"], 7), f(sp["M_over_ref_minus_1"], 3), f(sp["compactness"], 7)), "",
            table(["grid", "spacing (log z_c)", "nearest sample z_c", "estimated z_c", "z_c - z_ref", "estimated M", "M_est/M_ref - 1",
                   "compactness at the estimate", "compactness at the nearest sample", "reference compactness"], rows), ""]
    # (2b)
    rows = []
    for k_, Rr in sorted(ref.items(), key=lambda kv: (kv[0][0], kv[0][2], kv[0][3])):
        m, aH, op, c, pk = k_
        mr, memr, ir = fitted(Rr)
        Rc = fams.get((m, aH, op, c, False))
        mc = R2.maximum(Rc) if Rc is not None else None
        kop = Rr["meta"]["k_op"]
        G = 1.0 / (2 * np.pi * kop)
        ell = 1.0 / (m * m * np.sqrt(G))
        Mcont = rm["M"] * ell / G
        b3 = [e for e in res["bias"] if e["grid"] == "refined triple"][0]["M_bias"]
        b20 = [e for e in res["bias"] if e["grid"] == "J4's 20"][0]["M_bias"]
        r = {"family": Rr["_path"], "m": m, "aH": aH, "operator": op, "couplings": list(c), "k_op": kop, "members_z_c": [d["z_c"] for d in memr],
             "members_M": [d["M"] for d in memr], "interior": bool(mr and mr["interior"])}
        if mr and mr["interior"]:
            r.update({"z_max": mr["z_c"], "M_max": mr["M"], "compactness_at_max": mr["compactness_at_max"], "r_s_at_max": mr["r_s_at_max"],
                      "M_cont": Mcont, "ratio_minus_1": mr["M"] / Mcont - 1, "estimator_bias_refined": b3,
                      "coarse_M_max": mc["M"] if mc else None, "coarse_ratio_minus_1": (mc["M"] / Mcont - 1) if mc else None, "estimator_bias_20": b20})
            rows.append(["%g, %g" % (m, aH), op, "%g, %g" % c, " ".join(f(z, 5) for z in r["members_z_c"]), f(mr["z_c"], 6), f(mr["M"], 9),
                         f(mr["compactness_at_max"], 6), f(Mcont, 9), f(mr["M"] / Mcont - 1, 3), f(b3, 2), f(mc["M"] if mc else None, 8),
                         f(r["coarse_ratio_minus_1"], 3), f(b20, 3)])
            summ.append("I2b (%g, %g; %s; %g, %g): refined M_max %s at z_c %s, compactness at the fitted maximum %s; against J1's maximum mapped "
                        "with the family's G: %s (the estimator's bias on the refined triple %s); the coarse estimate gave %s (its bias %s)." % (
                            m, aH, op, c[0], c[1], f(mr["M"], 9), f(mr["z_c"], 6), f(mr["compactness_at_max"], 6), f(mr["M"] / Mcont - 1, 3), f(b3, 2),
                            f(r["coarse_ratio_minus_1"], 3), f(b20, 3)))
        else:
            rows.append(["%g, %g" % (m, aH), op, "%g, %g" % c, " ".join(f(z, 5) for z in r["members_z_c"]), "not interior"] + ["-"] * 8)
        res["refined"].append(r)
    out += ["## I2b The refined local families (three members z_c = 0.80, 0.8343, 0.87): the parabola's maximum, the compactness at the fitted "
            "maximum, J1's maximum mapped with the family's G = 1/(2 pi k_op), their ratio - 1, the estimator's bias on this triple (I2a); the "
            "coarse 20-member estimate and its ratio - 1, the estimator's bias on the 20-member grid (I2a)", "",
            table(["(m a, aH)", "operator", "(g_M, g_B)", "members z_c", "z_c at max", "M_max", "2GM/R_s at max", "J1 M_max mapped", "ratio - 1",
                   "bias (triple)", "coarse M_max", "coarse ratio - 1", "bias (20)"], rows), ""]
    # (2c) and (4)
    rows, rows4 = [], []
    for (m, aH) in R2.POINTS:
        for c in R2.COUPS:
            for op in R2.OPS:
                for pk in (False, True):
                    Rf = fams.get((round(m, 10), round(aH, 10), op, tuple(round(x, 10) for x in c), pk))
                    if Rf is None:
                        continue
                    mx, mem, i = fitted(Rf)
                    lab = ["%g, %g" % (m, aH), op, "%g, %g" % c, "packets" if pk else "table"]
                    if mx and mx["interior"]:
                        res["compactness"].append({"family": Rf["_path"], "z_max": mx["z_c"], "M_max": mx["M"], "compactness_at_max": mx["compactness_at_max"],
                                                   "compactness_largest_member": mem[i]["compactness"]})
                        rows.append(lab + [f(mx["z_c"], 6), f(mx["M"], 8), f(mx["compactness_at_max"], 6), f(mem[i]["compactness"], 6)])
                    dmax = max(mem, key=lambda d: d["compactness"])
                    res["extrema"].append({"family": Rf["_path"], "z_c": dmax["z_c"], "compactness": dmax["compactness"], "r_s_over_A": dmax["r_s"] / dmax["A"],
                                           "r_s_over_B": dmax["r_s"] / dmax["B"]})
                    rows4.append(lab + [f(dmax["z_c"], 5), f(dmax["compactness"], 5), f(dmax["r_s"] / dmax["A"], 5), f(dmax["r_s"] / dmax["B"], 5)])
    out += ["## I2c Every family's compactness at its fitted maximum (the parabola through the three members' 2GM/R_s in log z_c) beside the "
            "largest member's", "", table(["(m a, aH)", "operator", "(g_M, g_B)", "kernel", "z_c at max", "M_max", "2GM/R_s at max", "2GM/R_s (largest member)"],
                                          rows), "",
            "## I4 Per family the most compact member: z_c, 2GM/R_s, r_s/A and r_s/B (the exterior lapse N = (r - B)/(r + A) vanishes at r = B)", "",
            table(["(m a, aH)", "operator", "(g_M, g_B)", "kernel", "z_c", "2GM/R_s", "r_s/A", "r_s/B"], rows4), ""]
    ext = max(res["extrema"], key=lambda e: e["compactness"])
    ext2 = min(res["extrema"], key=lambda e: e["r_s_over_B"])
    summ.append("I4: the largest compactness over the families is %s (%s, z_c %s; r_s/A %s, r_s/B %s); the smallest r_s/B is %s (%s, z_c %s)." % (
        f(ext["compactness"], 5), ext["family"], f(ext["z_c"], 4), f(ext["r_s_over_A"], 5), f(ext["r_s_over_B"], 5), f(ext2["r_s_over_B"], 5),
        ext2["family"], f(ext2["z_c"], 4)))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    json.dump(res, open(a.json, "w"), indent=1, default=float)
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md, a.json)


if __name__ == "__main__":
    main()
