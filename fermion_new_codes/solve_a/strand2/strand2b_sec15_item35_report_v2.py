#!/usr/bin/env python
"""Strand 2b sec. 15 report, items 3 and 5 (builder analyst): tables from the pass-2 rerun with driver v12 / library v7 (pass2v12/case_*.json,
beside the earlier pass2/case_*.json), the cube's FD Jacobian two-step check (c8jac2step/run.log lines) and item 5 (sec15item5/item5.json).
Numbers emitted, not retyped.  (Version 2: starts that ended in an eigensolver exception carry {"trial", "error"} only; counted as
failed with stop reason "error".)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


RADII = ("0.0001", "0.001", "0.01", "0.1")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--new", required=True, help="pass2v12 folder")
    ap.add_argument("--old", required=True, help="pass2 folder")
    ap.add_argument("--jac2", required=True, help="c8jac2step/run.log")
    ap.add_argument("--item5", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    key = lambda d: (d["block"], d["m"], d["gM"], d["gB"], d["Lambda"], d["k"])
    new = {key(d): d for d in (json.load(open(p)) for p in glob.glob(os.path.join(a.new, "case_*.json")))}
    old = {key(d): d for d in (json.load(open(p)) for p in glob.glob(os.path.join(a.old, "case_*.json")))}
    out = ["# Strand 2b sec. 15 items 3 and 5, tables (generated by solve/code/strand2/strand2b_sec15_item35_report_v2.py)", ""]
    # ---- item 3: uniqueness with the full start records
    rows = []
    tot = {"cases": 0, "conv": 0, "distinct_gt1": 0, "neg": 0, "with_cont": 0}
    for kk in sorted(new):
        d = new[kk]
        U = d["uniqueness"]
        recs = U["starts_record"]
        stops = {}
        for r in recs:
            if "error" in r:                                 # a start whose eigensolver raised (recorded by the driver)
                stops["error"] = stops.get("error", 0) + 1
            elif not r["ok"]:
                stops[r["stop"]] = stops.get(r["stop"], 0) + 1
        conv = [r for r in recs if r.get("ok")]
        dmax = max((r["distance_to_continuation"] for r in conv), default=None)
        tres = max((r["terminal_residual"] for r in conv), default=None)
        o = old.get(kk)
        rows.append([d["block"], f(d["m"]), "%g, %g" % (d["gM"], d["gB"]), f(d["Lambda"]), f(d["k"]), d["d0"], f(d["residual"], 2),
                     len(recs), U["converged_positive"], U["distinct_positive"], U["negative_converged"],
                     ", ".join("%s %d" % (s, c) for s, c in sorted(stops.items(), key=lambda t: str(t[0]))) or "-",
                     f(dmax, 2), f(tres, 2), f(U["contains_continuation_solution"]),
                     (o["uniqueness"].get("distinct_positive") if o else "-")])
        tot["cases"] += 1
        tot["conv"] += U["converged_positive"]
        tot["distinct_gt1"] += int(U["distinct_positive"] > 1)
        tot["neg"] += U["negative_converged"]
        tot["with_cont"] += int(bool(U["contains_continuation_solution"]))
    out += ["## Item 3 (a): the 20 starts per case with the repaired library (projector denominators w_i - w_mm, the strict line search: a "
            "start fails when no acceptable step is found); per case the continuation solution's residual, the converged positive starts, "
            "the distinct positive solutions among them, converged starts with a negative component, the failed starts by stop reason, the "
            "largest distance of a converged start's limit from the continuation solution, the largest terminal residual among converged "
            "starts, and the earlier pass 2's distinct count", "",
            table(["block", "m", "(g_M, g_B)", "Lambda", "k", "d0", "residual", "starts", "converged positive", "distinct positive", "negative",
                   "failed (stop reason)", "max distance (converged)", "max terminal residual (converged)", "contains continuation",
                   "pass 2 distinct"], rows), "",
            "Totals: %d cases; %d converged positive starts in all; cases with more than one distinct positive solution: %d; converged starts "
            "with a negative component: %d; cases whose converged set contains the continuation solution: %d." % (
                tot["cases"], tot["conv"], tot["distinct_gt1"], tot["neg"], tot["with_cont"]), ""]
    rows = []
    for kk in sorted(new):
        d = new[kk]
        U = d["uniqueness"]
        rows.append([d["block"], f(d["m"]), "%g, %g" % (d["gM"], d["gB"]), f(d["k"]), U["wording"]])
    out += ["## Item 3 (b): the uniqueness wording per case (the spec's form)", "", table(["block", "m", "(g_M, g_B)", "k", "wording"], rows), ""]
    # ---- item 3: the sampled contraction test with the repaired J
    rows = []
    for kk in sorted(new):
        d = new[kk]
        E = d["enclosure"]
        o = old.get(kk)
        cells = []
        for r in RADII:
            x = E["radii"][r]
            cells.append("%s (q %s, gap %s)" % ("pass" if (x["passed"] and x["positive_domain"]) else "FAIL", f(x["q"], 3), f(x["min_cluster_gap_sampled"], 3)))
        rows.append([d["block"], f(d["m"]), "%g, %g" % (d["gM"], d["gB"]), f(d["k"]), f(E["Y_F"], 2), f(E["norm_Y"], 4)] + cells +
                    [f(E["largest_passing_r_in_domain"]), f(o["enclosure"]["largest_passing_r_in_domain"]) if o else "-"])
    out += ["## Item 3 (c): the sampled contraction test at the four radii with the repaired J (Y_F = |Y F(z)|, norm_Y = |Y|; per radius r "
            "pass or FAIL, the sampled contraction factor q and the minimum sampled cluster gap e[d_0] - e[d_0 - 1]; the gap-minus-curvature "
            "column dropped), the largest passing radius beside the earlier pass 2's", "",
            table(["block", "m", "(g_M, g_B)", "k", "Y_F", "norm_Y"] + ["r = %s" % r for r in RADII] + ["largest passing r", "pass 2"], rows), ""]
    # ---- item 3: the cube's FD Jacobian two-step check
    rows = []
    for line in open(a.jac2):
        line = line.strip()
        if not line.startswith("{"):
            continue
        r = json.loads(line)
        rows.append([f(r["k"]), f(r["rel"], 3)] + ["%s / %s" % (f(b["max_abs_diff"], 3), f(b["max_abs_J"], 5)) for b in r["blocks"].values()])
        bnames = list(r["blocks"].keys())
    out += ["## Item 3 (d): the cube's FD Jacobian at h = 1e-6 against 1e-7 at the two enclosure cases ((2,0), m 0.1, (0.2, 1, 1)): max |J(1e-6) - "
            "J(1e-7)| relative to max |J(1e-6)|, and per block the max difference / max |J|", "",
            table(["k", "relative"] + bnames, rows), ""]
    # ---- item 5
    I5 = json.load(open(a.item5))
    rows = []
    for name, lst in I5["part_a"].items():
        for r in lst:
            rows.append([name, f(r["k"]), r.get("status", "continuation"), f(r.get("converged")), f(r.get("best"), 2), f(r.get("noise_floor"), 2),
                         f(r.get("E"), 8), f(r.get("E_sel"), 8), f(r.get("gap"), 4), f(r.get("sigma_min_J"), 3), f(r.get("min_component"), 5),
                         f(r.get("distance_to_uniform"), 3)])
    out += ["## Item 5 (a): the uniform continuation solution and the two non-uniform classes of sec. 14 carried upward in k ((2,0), m 0.1, "
            "(0.2, 1, 1), d_0 fixed at the record's); per (class, k): the status (persists: distance to the uniform solution above 1e-6 over "
            "the 48 symmetries; merged; lost: no convergence at the noise floor), the best residual and the noise floor, E, E_sel, the gap, "
            "sigma_min of the FD Jacobian, the smallest component and the distance to the uniform solution", "",
            table(["class", "k", "status", "converged", "best residual", "noise floor", "E", "E_sel", "gap", "sigma_min(J)", "min component",
                   "distance to uniform"], rows), ""]
    rows = []
    for r in I5["part_b"]:
        u = r["uniform"]
        rows.append(["%g, %g" % (r["g"][0], r["g"][1]), f(r["d0"]), f(r["continuation_ok"]), f(u["E"], 8), f(u["E_sel"], 8), r["starts"],
                     r["converged_positive"], len(r["orbits"]),
                     "; ".join("%d starts: E %s, E_sel %s, distance %s" % (o["starts"], f(o["E"], 8), f(o["E_sel"], 8), f(o["distance_to_uniform"], 3))
                               for o in r["orbits"])])
    out += ["## Item 5 (b): the 16 near starts at k = 1 for (2,0), m 0.1, Lambda = 1, at (g_M, g_B) = (0.05, 0) and (0, 0) (d_0 fixed at the "
            "flat start's value); the uniform continuation solution, the converged positive starts and their orbits under the 48 symmetries", "",
            table(["(g_M, g_B)", "d0", "continuation ok", "uniform E", "uniform E_sel", "starts", "converged positive", "orbits",
                   "orbits (starts, E, E_sel, distance to uniform)"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
