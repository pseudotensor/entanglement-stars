#!/usr/bin/env python
"""Strand 2a addendum report (builder analyst): tables from addendum.json (items A.1-A.3, B; script v1) and addendum2.json
(items A.1c, A.4; script v2).  Numbers emitted, not retyped; no physics reading."""
import argparse
import json


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--a1", required=True)
    ap.add_argument("--a2", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    A1 = json.load(open(a.a1))
    A2 = json.load(open(a.a2))
    out = ["# Strand 2a addendum tables (generated by solve/code/strand2/strand2a_addendum_report.py)", ""]
    for item, title in (("A1_ruler", "A.1 ruler modulation psi = 1 + eps cos(2 pi x/L), N = 1"),
                        ("A2_clock", "A.2 clock modulation N = 1 + eps cos(2 pi x/L), psi = 1 (m N_min = m (1 - eps))"),
                        ("A3_Npsi1", "A.3 N = psi^-1 (N psi = 1)"), ("A3_N_eq_psi", "A.3 N = psi (L = psi^2)")):
        rows = [[r["L"], f(r["m"]), f(r["eps"]), " ".join(f(v, 6) for v in r["law_lowest4"]), " ".join(f(v, 6) for v in r["native_lowest4"]),
                 f(r["law_shift_below_m"]), f(r["native_shift_below_m"]), f(r["law_bottom_split"]), f(r["native_bottom_split"]), f(r["m_Nmin"])]
                for r in A1["A"] if r["item"] == item]
        out += ["## " + title, "", table(["L", "m", "eps", "law lowest 4", "native lowest 4", "law m - lowest", "native m - lowest",
                                          "law bottom split", "native bottom split", "m N_min"], rows), ""]
    rows = [[f(r["m"]), r.get("L", "-"), f(r.get("eps")), str(r.get("L_pair", "-")), f(r.get("power_in_eps")), f(r.get("power_in_1_over_L"))]
            for r in A1["A_fits"]]
    out += ["## A.1 fitted powers of the law's shift below m (in eps at fixed L; in 1/L between successive L)", "",
            table(["m", "L", "eps", "L pair", "power in eps", "power in 1/L"], rows), ""]
    c = A2["A1c"]
    out += ["## A.1c <rho^M_0> - <rho^P_0> in single- and two-valley states (L = 256, m = 0.1, psi = N = 1)", "",
            table(["state", "value"], [[k, f(v, 6)] for k, v in c.items()]), ""]
    rows = [[r["L"], f(r["m"]), r["j"], f(r["eps"]), r["valley"], "%s %+si" % (f(r["b"][0]), f(r["b"][1])), "%s %+si" % (f(r["c"][0]), f(r["c"][1])),
             "%s %+si" % (f(r["prediction_b"][0]), f(r["prediction_b"][1])), f(r["prediction_c"][0]), f(r["rel_residual"]),
             f(r["HF_lowest_shift"]), f(r["HF_vertex_00"])] for r in A2["A4"]]
    out += ["## A.4 the first-order ruler vertex: (V_law - V_nat)/u_pp' = b (p' - p) + c (p' - p)^2, fitted, against the red team's form", "",
            table(["L", "m", "j", "eps", "valley", "b", "c", "predicted b", "predicted c (1/m)", "relative residual",
                   "lowest positive level shift (law)", "first-order diagonal vertex x eps"], rows), ""]
    for key, rec in A1["B"].items():
        if key.startswith("B1"):
            rows = [[name, " ".join(f(v) for v in s["X1_nonzero"]), f(s["M1_min"]), f(s["M1_max"]), f(s["witness_energy"])]
                    for name, s in rec["sites"].items()]
            out += ["## B.1 open 3 x 3 x 3 cube, psi = 1 (requested m %s, used m %s; min eig A^dag A at requested m %s)" % (
                f(rec["m_requested"]), f(rec["m_used"]), f(rec["min_eig_AdagA_at_requested_m"])), "",
                "One-particle spectrum (distinct levels): " + " ".join(f(v) for v in rec["one_particle_spectrum"]), "",
                table(["site", "nonzero one-particle eigs of X1_x", "min eig M1_x", "max eig M1_x", "witness energy"], rows), ""]
        else:
            out += ["## B.2 periodic 4^3 box, psi = 1, m %s" % f(rec["m"]), "",
                    "Site 0: nonzero one-particle eigenvalues of X1_0: %s; min eig of M1_0: %s (witness energy %s)." % (
                        " ".join(f(v) for v in rec["X1_nonzero"]), f(rec["M1_min"]), f(rec["witness_energy"])), "",
                    "Valley at 0, momenta k_j in {0, +-pi/2}, lowest shells with at least 8 states (%d states, both spins): ||X_pp|| %s, "
                    "||M_pp|| %s, ||M_pp - X_pp|| %s, ||M_anom|| %s, ||X_anom|| %s; eigenstate check %s." % (
                        rec["n_states"], f(rec["norm_X_pp"]), f(rec["norm_M_pp"]), f(rec["norm_pp_diff"]), f(rec["norm_M_anom"]),
                        f(rec["norm_X_anom"]), f(rec["check_states_are_eigenstates"])), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
