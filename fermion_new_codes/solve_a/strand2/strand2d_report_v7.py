#!/usr/bin/env python
"""Strand 2d report, version 4 (builder analyst): SPEC_strand2d_jet.md with the rulings of sec. 7, from strand2d_jet_v1/v2's JSON
(jet_<lattice>_vacuum.json, jet_<lattice>_gM<gM>_gB<gB>.json) and strand2d_prep31_v1's JSON (prep31_<lattice>_gM<gM>_gB<gB>.json).
T1 the vacuum jet against the code target; T2 per coupling: J^sus = the multiplet-average jet (sec. 7(1)), the lowest eigenvalue's jet
beside it with the multiplet's width per unit lam at the stencil points (the splitting slope), J^prep = J^prep_(2,0)' (the
un-renormalized block-restricted functional) + J^prep_(3,1)' (psi psi entry only; the free evaluation of stage 1), J^prep,vac and
J^prep,mat = J^prep - J^prep,vac, the norm-defect check, C3 (eigenvalues of J^prep - J^sus), C2, C6; T3 totals; T4 widths and gaps.
Richardson values (100 J(1e-4) - J(1e-3))/99; step agreement relative when the larger value exceeds 1e-6 in size, else absolute.
Numbers emitted, not retyped.
(version 5: with --dressed, the cube's stage-2 values through the q-block route (strand2d_prep31_dressed_v2): on C8 the dressed J^prep_(3,1)'
and J^prep,vac beside the free ones and J^prep with the dressed term; on B4 the cube's ratio dressed/free per q at the same coupling beside
the free estimate (sec. 7(2): the stated uncertainty of the B4 entry at (0.2, 1)))
(version 6: with --vac11, the dressed fixed-vacuum cost from strand2d_vac11_dressed_v1 (the (1,1) block with the completion; sec. 8(2)):
on C8 its check against the q-block route's E11 values, on B4 the direct dressed J^prep,vac per q beside the free one and the cube's ratio,
and J^prep,mat psi psi with it; with --c7, control C7 (sec. 8(1)): the exact one-body J^prep and J^prep,vac at g = 0 against stage 1 per
entry and q, the step agreement, and on B4 the momentum support of dP_+/dlam_psi (sec. 8(3)))
(version 7: the B4 vacuum table's heading names the device recorded in the vac11 JSON; version 6 wrote "on GPU" although the run was on
the CPU)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def agree_str(a, b):
    big = max(abs(a), abs(b))
    return f(abs(a - b) / big) if big > 1e-6 else "abs " + f(abs(a - b))


def rich(j1, j2):
    return {k: (100 * j2[k] - j1[k]) / 99 for k in j1}


def qname(q):
    return {0.0: "0", round(np.pi / 2, 12): "pi/2", round(np.pi, 12): "pi"}.get(round(q, 12), "%.4f" % q)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--prep", required=True)
    ap.add_argument("--lattice", required=True)
    ap.add_argument("--md", required=True)
    ap.add_argument("--dressed", default="", help="folder with prep31_dressed_C8_gM*_gB*.json")
    ap.add_argument("--vac11", default="", help="folder with vac11_<lattice>_gM*_gB*.json (and vac11_C8_* for the check)")
    ap.add_argument("--c7", default="", help="folder with c7_<lattice>.json")
    a = ap.parse_args()
    out = ["# Strand 2d tables, %s (generated by solve/code/strand2/strand2d_report_v7.py)" % a.lattice, ""]
    vac = json.load(open(os.path.join(a.run, "jet_%s_vacuum.json" % a.lattice)))
    vac_rich = {}
    rows, rows_c = [], []
    for H in sorted(set(j["H"] for j in vac["jets"]), reverse=True):
        k = vac["J"]["H%g" % H]["k_lat"]
        for q in sorted(set(j["q"] for j in vac["jets"])):
            js = {j["h"]: j for j in vac["jets"] if j["H"] == H and j["q"] == q}
            h1, h2 = max(js), min(js)
            R = rich(js[h1]["jet"], js[h2]["jet"])
            T = rich(js[h1]["target_code_k1"], js[h2]["target_code_k1"])
            vac_rich[(H, q)] = R
            rows.append([f(H), qname(q), f(R["NN"]), f(R["Npsi"]), f(R["psipsi"]), f(k * T["Npsi"]), f(k * T["psipsi"]),
                         f(R["Npsi"] / (k * T["Npsi"])) if T["Npsi"] else "-", f(R["psipsi"] / (k * T["psipsi"])) if T["psipsi"] else "-",
                         f(R["psipsi"] / R["Npsi"]) if abs(R["Npsi"]) > 1e-6 else "-",
                         " ".join("%s %s" % (kk, agree_str(js[h1]["jet"][kk], js[h2]["jet"][kk])) for kk in ("NN", "Npsi", "psipsi"))])
            cx = js[h2]["cross_with_uniform"]
            if q == 0:
                mx = max(abs(v) for j in js.values() for v in j["values"].values())
                rows_c.append([f(H), "C1: largest |W_0| over the q = 0 stencil points (both h)", f(mx)])
            rows_c.append([f(H), "cross block with the uniform mode at q = %s (NN, Npsi, psiN, psipsi; h 1e-4)" % qname(q),
                           " ".join(f(cx[kk]) for kk in ("NN", "Npsi", "psiN", "psipsi"))])
    out += ["## T1 Vacuum jet J^vac(q) of W_{0,a} (Richardson), against the target -k_lat sum_x grad psi . grad(N psi) by code", "",
            table(["H", "q", "NN", "N psi", "psi psi", "target N psi", "target psi psi", "N psi / target", "psi psi / target", "psi psi / N psi",
                   "step agreement"], rows), "", "### C1 and the row sums", "", table(["H", "item", "values"], rows_c), "",
            "J, sum rule and k_lat: " + "; ".join("H %s: J %s, sum rule %s, k_lat %s" % (kk[1:], f(v["J"], 8), f(v["sum_rule"]), f(v["k_lat"], 8))
                                                  for kk, v in vac["J"].items()), ""]
    for mf in sorted(glob.glob(os.path.join(a.run, "jet_%s_gM*.json" % a.lattice))):
        M = json.load(open(mf))
        gM, gB = M["meta"]["gM"], M["meta"]["gB"]
        pf = os.path.join(a.prep, "prep31_%s_gM%g_gB%g.json" % (a.lattice, gM, gB))
        P31 = {round(r["q"], 12): r for r in json.load(open(pf))["rows"]} if os.path.exists(pf) else {}
        df = os.path.join(a.dressed, "prep31_dressed_C8_gM%g_gB%g.json" % (gM, gB)) if a.dressed else ""
        PD = {round(r["q"], 12): r for r in json.load(open(df))["rows"]} if df and os.path.exists(df) else {}
        vf = os.path.join(a.vac11, "vac11_%s_gM%g_gB%g.json" % (a.lattice, gM, gB)) if a.vac11 else ""
        V11 = json.load(open(vf)) if vf and os.path.exists(vf) else None
        VR = {round(r["q"], 12): r for r in V11["rows"]} if V11 else {}
        rowsV = []
        out += ["## Matter at (g_M, g_B) = (%s, %s): (2,0) block dimension %d, d_0 = %d at the flat point; flat gap above the multiplet %s"
                % (f(gM), f(gB), M["dim"], M["d0"], f(M["flat_gap"])), ""]
        rows, rowsP, rowsC3, rowsW, rowsD = [], [], [], [], []
        for s in M["summary"]:
            q = s["q"]
            Js = {j["h"]: j["jets"] for j in M["jets"] if abs(j["q"] - q) < 1e-12}
            h1, h2 = max(Js), min(Js)

            def ag(fn):
                return " ".join("%s %s" % (kk, agree_str(Js[h1][fn][kk], Js[h2][fn][kk])) for kk in ("NN", "Npsi", "psipsi"))
            for fn, lab in (("mult", "J^sus (multiplet average)"), ("low", "lowest eigenvalue (beside, not J^sus)"),
                            ("one_particle_mult_2x_avg", "C6: 2 x mean of the lowest one-particle multiplet")):
                if fn in s:
                    R = s[fn]["rich"]
                    rows.append([qname(q), lab, f(R["NN"]), f(R["Npsi"]), f(R["psipsi"]), f(R["dN"]), f(R["dpsi"]), ag(fn)])
            # splitting slopes: multiplet width per unit lam at the stencil points along N and along psi, both steps
            pts = [p for p in M["points"] if abs(p["q"] - q) < 1e-12]
            for h in (h1, h2):
                wN = [p["split"] / h for p in pts if p["h"] == h and p["b"] == 0 and p["a"] != 0]
                wP = [p["split"] / h for p in pts if p["h"] == h and p["a"] == 0 and p["b"] != 0]
                rowsW.append([qname(q), f(h), " ".join(f(v) for v in wN), " ".join(f(v) for v in wP),
                              f(min((p["gap"] for p in pts if p["h"] == h and p["gap"] is not None), default=None))])
            # J^prep pieces (psi psi entry carries the (3,1)' term)
            R20 = s["prep_mult_raw"]["rich"]
            p31 = P31.get(round(q, 12))
            J31 = p31["J_prep_31_free"] if p31 else None
            Jvac = p31["J_prep_vac_free"] if p31 else None
            Jpp = R20["psipsi"] + (J31 if J31 is not None else 0.0)
            rowsP.append([qname(q), f(R20["NN"]), f(R20["Npsi"]), f(R20["psipsi"]), f(J31), f(Jpp), f(Jvac),
                          f(Jpp - Jvac) if Jvac is not None else "-",
                          f(p31["norm2_ZPhi"]) if p31 else "-", f(p31["norm2_pauli_formula"]) if p31 else "-",
                          f(p31["norm_defect"]["0.0001"]["second_diff"]) if p31 else "-", f(p31["norm_defect_check_rel"]) if p31 else "-",
                          f(p31["z_step_agreement_rel"]) if p31 else "-"])
            S = s["mult"]["rich"]
            Dm = np.array([[R20["NN"] - S["NN"], R20["Npsi"] - S["Npsi"]], [R20["Npsi"] - S["Npsi"], Jpp - S["psipsi"]]])
            rowsC3.append([qname(q), " ".join(f(v) for v in np.linalg.eigvalsh(Dm)),
                           " ".join(f(v) for v in s["C3_mult_raw_eigs"])])
            pdq = PD.get(round(q, 12))
            if pdq is None and PD and a.lattice == "B4":
                pdq = PD.get(round(np.pi, 12)) if abs(q) > 1e-12 else PD.get(0.0)
            if pdq and "J_prep_31_dressed" in pdq:
                r31 = pdq["ratio_31_dressed_over_free"]
                rv = pdq["ratio_vac_dressed_over_free"]
                if a.lattice == "C8":
                    rowsD.append([qname(q), f(pdq["J_prep_31_free"]), f(pdq["J_prep_31_dressed"]), f(r31), f(pdq["J_prep_vac_free"]),
                                  f(pdq["J_prep_vac_dressed"]), f(rv), f(R20["psipsi"] + pdq["J_prep_31_dressed"]),
                                  f(R20["psipsi"] + pdq["J_prep_31_dressed"] - pdq["J_prep_vac_dressed"])])
                elif J31 is not None:
                    rowsD.append([qname(q), "C8 q = %s" % qname(pdq["q"]), f(J31), f(r31), f(J31 * r31), f(Jvac), f(rv), f(Jvac * rv), "-"])
            vr = VR.get(round(q, 12))
            if vr is not None and "J_prep_vac_dressed" in vr and a.lattice == "C8":
                rowsV.append([qname(q), f(vr["J_prep_vac_free"], 10), f(Jvac, 10) if Jvac is not None else "-",
                              agree_str(vr["J_prep_vac_free"], Jvac) if Jvac is not None else "-",
                              f(vr["J_prep_vac_dressed"], 10), f(pdq["J_prep_vac_dressed"], 10) if pdq and "J_prep_vac_dressed" in pdq else "-",
                              agree_str(vr["J_prep_vac_dressed"], pdq["J_prep_vac_dressed"]) if pdq and "J_prep_vac_dressed" in pdq else "-",
                              vr.get("taylor_terms", "-")])
            elif vr is not None and "J_prep_vac_dressed" in vr:
                Jv_d = vr["J_prep_vac_dressed"]
                rcube = pdq["ratio_vac_dressed_over_free"] if pdq and "ratio_vac_dressed_over_free" in pdq else None
                r31c = pdq["ratio_31_dressed_over_free"] if pdq and "ratio_31_dressed_over_free" in pdq else None
                rowsV.append([qname(q), f(vr["J_prep_vac_free"], 8), agree_str(vr["J_prep_vac_free"], Jvac) if Jvac is not None else "-",
                              f(Jv_d, 8), f(vr["ratio_dressed_over_free"], 6), f(rcube, 6) if rcube is not None else "-",
                              f(Jpp - Jv_d) if J31 is not None else "-",
                              f(R20["psipsi"] + J31 * r31c - Jv_d) if (J31 is not None and r31c is not None) else "-",
                              vr.get("taylor_terms", "-")])
        out += ["### T2 J^sus and the lowest eigenvalue (Richardson; first derivatives from the same stencil)", "",
                table(["q", "functional", "NN", "N psi", "psi psi", "dE/dlam_N", "dE/dlam_psi", "step agreement"], rows), "",
                "### T2 J^prep = J^prep_(2,0)' + J^prep_(3,1)' (the latter in psi psi only, free evaluation), the fixed-vacuum cost and the "
                "matter's share; the amplitude checks", "",
                table(["q", "J^prep_(2,0)' NN", "N psi", "psi psi", "J^prep_(3,1)' (free)", "J^prep psi psi", "J^prep,vac (free)",
                       "J^prep,mat psi psi", "<||Z Phi||^2>", "Pauli formula", "norm defect'' (h 1e-4)", "defect'' vs 2<||Z Phi||^2> (rel)",
                       "z step agreement"], rowsP), "",
                "### C3 eigenvalues of J^prep - J^sus (J^prep with the (3,1)' term; and the block-restricted J^prep_(2,0)' alone)", "",
                table(["q", "full J^prep", "J^prep_(2,0)' only"], rowsC3), "",
                "C2 affinity E(1.1 N) - 1.1 E(N) at psi = 1: lowest %s, multiplet %s." % (f(M["C2_affinity"]["low"]), f(M["C2_affinity"]["mult"])), ""]
        if rowsD and a.lattice == "C8":
            out += ["### T2 the dressed (3,1)' term and fixed-vacuum cost through the q-block route (stage 2), beside the free ones; J^prep psi psi "
                    "with the dressed term and its matter share", "",
                    table(["q", "J^prep_(3,1)' free", "dressed", "dressed/free", "J^prep,vac free", "dressed", "dressed/free",
                           "J^prep psi psi (dressed)", "J^prep,mat psi psi (dressed)"], rowsD), ""]
        elif rowsD:
            out += ["### T2 the B4 (3,1)' and vacuum entries: free evaluation, the cube's dressed/free ratio at the same coupling (C8 has q in {0, pi}; "
                    "q = pi/2 takes the C8 q = pi ratio), and their product (sec. 7(2): the ratio is the stated uncertainty of the B4 entry)", "",
                    table(["q", "C8 ratio from", "J^prep_(3,1)' free", "C8 ratio", "product", "J^prep,vac free", "C8 ratio", "product", "-"], rowsD), ""]
        if rowsV and a.lattice == "C8":
            out += ["### Check of the (1,1) route used on B4 (strand2d_vac11_dressed_v1: the completion's ph block built from the seed's Kronecker "
                    "terms, u = e^S w by its Taylor series) against the gate's q-block route (strand2d_prep31_dressed_v2) on C8; S Hermitian to %s"
                    % f(V11["meta"]["S_hermiticity"]), "",
                    table(["q", "J^prep,vac free (vac11)", "free (stage 1)", "agreement", "J^prep,vac dressed (vac11)", "dressed (q-block)",
                           "agreement", "Taylor terms"], rowsV), ""]
        elif rowsV:
            out += ["### T2 the B4 dressed fixed-vacuum cost, direct (sec. 8(2): the (1,1) block with the completion, n_W^2 = 16384-dimensional; "
                    "strand2d_vac11_dressed_v1, device %s; S Hermitian to %s), the cube's ratio beside it, and J^prep,mat psi psi with it (the (3,1)' "
                    "term free, and times the cube's (3,1)' ratio)" % (V11["meta"].get("device"), f(V11["meta"]["S_hermiticity"])), "",
                    table(["q", "J^prep,vac free", "agreement with stage 1", "J^prep,vac dressed", "dressed/free", "C8 dressed/free",
                           "J^prep,mat psi psi ((3,1)' free)", "J^prep,mat psi psi ((3,1)' x C8 ratio)", "Taylor terms"], rowsV), ""]
        out += ["",
                "### T4 the multiplet width per unit lam at the stencil points (lam_N = +-h; lam_psi = +-h) and the smallest gap above the "
                "multiplet over the stencil (the lowest d_0 + 1 levels at every point are in the JSON when the jet driver is version 2)", "",
                table(["q", "h", "width/h along N", "width/h along psi", "min gap"], rowsW), ""]
        if vac_rich:
            rows = []
            for (H, q), R in sorted(vac_rich.items()):
                sm = [s for s in M["summary"] if abs(s["q"] - q) < 1e-12]
                if sm:
                    S = sm[0]["mult"]["rich"]
                    rows.append([f(H), qname(q), f(R["NN"] + S["NN"]), f(R["Npsi"] + S["Npsi"]), f(R["psipsi"] + S["psipsi"])])
            out += ["### T3 Totals J^tot = J^vac + J^sus (multiplet average; Richardson)", "", table(["H", "q", "NN", "N psi", "psi psi"], rows), ""]
    cf = os.path.join(a.c7, "c7_%s.json" % a.lattice) if a.c7 else ""
    if cf and os.path.exists(cf):
        C7 = json.load(open(cf))
        rows = []
        for r in C7["rows"]:
            ob, st, ov = r["onebody_prep"], r["stage1_prep"], r["onebody_vac"]
            def dif(x, y):
                big = max(abs(x), abs(y))
                return ("rel " + f(abs(x - y) / big)) if big > 1e-4 else ("abs " + f(abs(x - y)))
            rows.append([qname(r["q"]), " ".join(f(ob[e], 8) for e in ("NN", "Npsi", "psipsi")), " ".join(f(st[e], 8) for e in ("NN", "Npsi", "psipsi")),
                         "; ".join(dif(ob[e], st[e]) for e in ("NN", "Npsi", "psipsi")),
                         " ".join(f(ov[e], 8) for e in ("NN", "Npsi", "psipsi")), f(r["stage1_vac"]["psipsi"], 8), f(r["rel_diff_vac_psipsi"]),
                         " ".join(f(r["abs_diff_vac"][e]) for e in ("NN", "Npsi")),
                         f(max(v for k in r["step_agreement"].values() for v in k.values())),
                         f(r["z_support_outside_k_kpmq_rel"]) if "z_support_outside_k_kpmq_rel" in r else "-"])
        out += ["## C7 (sec. 8(1)) at (g_M, g_B) = (0, 0): the exact one-body E_prep = Tr(h Gamma_0) - E_vac and E_prep,vac = Tr(h Gamma_vac) - "
                "E_vac (Richardson) against stage 1 (J^prep_(2,0)' + J^prep_(3,1)'(free); J^prep,vac free); g_1 = %d, d_0 = %d; on B4 the "
                "momentum support of dP_+/dlam_psi outside the (k, k +- q) blocks (sec. 8(3))" % (C7["meta"]["g1"], C7["meta"]["d0"]), "",
                table(["q", "one-body J^prep (NN, N psi, psi psi)", "stage 1", "difference (relative where an entry exceeds 1e-4, else absolute)",
                       "one-body J^prep,vac (NN, N psi, psi psi)",
                       "stage 1 J^prep,vac psi psi", "rel diff psi psi", "abs diff vac NN, N psi", "max step agreement (h 1e-3 vs 1e-4)",
                       "z support outside (rel)"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
