#!/usr/bin/env python
"""Strand 2d report (builder analyst): tables T1-T4 and controls C1-C6 of SPEC_strand2d_jet.md from strand2d_jet_v1.py's JSON files
(jet_<lattice>_vacuum.json, jet_<lattice>_gM<gM>_gB<gB>.json).  Both matter functionals (lowest eigenvalue, multiplet average) and
both preparation-cost forms (raw, normalized) are tabulated; the choice is the lead's.  Numbers emitted, not retyped."""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def rich(j1, j2):
    return {k: (100 * j2[k] - j1[k]) / 99 for k in j1}


def qname(q):
    return {0.0: "0", round(np.pi / 2, 12): "pi/2", round(np.pi, 12): "pi"}.get(round(q, 12), "%.4f" % q)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--lattice", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    out = ["# Strand 2d tables, %s (generated by solve/code/strand2/strand2d_report_v1.py)" % a.lattice, ""]
    vf = os.path.join(a.run, "jet_%s_vacuum.json" % a.lattice)
    vac = json.load(open(vf)) if os.path.exists(vf) else None
    nsite = 8 if a.lattice == "C8" else 64
    Lcube = None if a.lattice == "C8" else 4
    vac_rich = {}
    if vac:
        rows, rows_x, rows_c1 = [], [], []
        Hs = sorted(set(j["H"] for j in vac["jets"]), reverse=True)
        for H in Hs:
            k = vac["J"]["H%g" % H]["k_lat"]
            for q in sorted(set(j["q"] for j in vac["jets"])):
                js = {j["h"]: j for j in vac["jets"] if j["H"] == H and j["q"] == q}
                h1, h2 = max(js), min(js)
                R = rich(js[h1]["jet"], js[h2]["jet"])
                T = rich(js[h1]["target_code_k1"], js[h2]["target_code_k1"])
                vac_rich[(H, q)] = R
                ql2 = 2 * (1 - np.cos(q))
                closed = {"Npsi": -k * ql2 * nsite / 2, "psipsi": -k * ql2 * nsite} if Lcube else None
                rows.append([f(H), qname(q), f(R["NN"]), f(R["Npsi"]), f(R["psipsi"]), f(k * T["Npsi"]), f(k * T["psipsi"]),
                             f(R["Npsi"] / (k * T["Npsi"])) if T["Npsi"] else "-", f(R["psipsi"] / (k * T["psipsi"])) if T["psipsi"] else "-",
                             f(R["psipsi"] / R["Npsi"]) if R["Npsi"] else "-",
                             " ".join("%s %s" % (kk, f(abs(js[h1]["jet"][kk] - js[h2]["jet"][kk]) / max(abs(js[h2]["jet"][kk]), 1e-300)))
                                      for kk in ("NN", "Npsi", "psipsi"))])
                cx = js[h2]["cross_with_uniform"]
                rows_x.append([f(H), qname(q), f(cx["NN"]), f(cx["Npsi"]), f(cx["psiN"]), f(cx["psipsi"])])
                if closed:
                    rows_c1.append([f(H), qname(q), f(k * T["Npsi"]), f(closed["Npsi"]), f(k * T["psipsi"]), f(closed["psipsi"])])
                if q == 0:
                    rows_c1.append([f(H), "C1 (q = 0): vacuum entries NN, Npsi, psipsi at h = %g" % h2, f(js[h2]["jet"]["NN"]),
                                    f(js[h2]["jet"]["Npsi"]), f(js[h2]["jet"]["psipsi"]), "-"])
        out += ["## T1 Vacuum jet J^vac(q) of W_{0,a} (Richardson values over h = 1e-3, 1e-4), against the target -k_lat sum_x grad psi . "
                "grad(N psi) evaluated by code on the same stencil (k_lat = 3J/pi^2)", "",
                table(["H", "q", "NN", "N psi", "psi psi", "target N psi", "target psi psi", "N psi / target", "psi psi / target",
                       "psi psi / N psi", "step agreement (relative)"], rows), "",
                "### T1 cross block between the q-mode and the uniform mode (the row sums; h = 1e-4)", "",
                table(["H", "q", "N(q) N(0)", "N(q) psi(0)", "psi(q) N(0)", "psi(q) psi(0)"], rows_x), "",
                "### C1 and C5: the vacuum's q = 0 entries; the code target against the closed form -k q_lat^2 L^3/2, -k q_lat^2 L^3 (B4)", "",
                table(["H", "q / item", "code target N psi (or NN)", "closed form N psi (or N psi)", "code target psi psi (or psi psi)",
                       "closed form psi psi"], rows_c1), "",
                "J, sum rule and k_lat: " + "; ".join("H %s: J %s, sum rule %s, k_lat %s" % (kk[1:], f(v["J"], 8), f(v["sum_rule"]), f(v["k_lat"], 8))
                                                      for kk, v in vac["J"].items()), ""]
    for mf in sorted(glob.glob(os.path.join(a.run, "jet_%s_gM*.json" % a.lattice))):
        M = json.load(open(mf))
        gM, gB = M["meta"]["gM"], M["meta"]["gB"]
        out += ["## Matter at (g_M, g_B) = (%s, %s), Lambda %s: (2,0) block dimension %d, d_0 = %d at the flat point" % (
            f(gM), f(gB), f(M["meta"]["Lambda"]), M["dim"], M["d0"]), "",
                "Flat-point levels (lowest d_0 + 8): " + " ".join(f(x, 8) for x in M["flat_levels"]) + "; gap above the multiplet " +
                f(M["flat_gap"]) + ("; one-particle flat multiplicity %d" % M["one_particle_flat_multiplicity"]
                                    if "one_particle_flat_multiplicity" in M else ""), ""]
        rows, rowsC3 = [], []
        for s in M["summary"]:
            for fn in ("low", "mult", "prep_low_raw", "prep_low_norm", "prep_mult_raw", "prep_mult_norm", "one_particle_low2",
                       "one_particle_mult_2x_avg"):
                if fn not in s:
                    continue
                R, G = s[fn]["rich"], s[fn]["agree"]
                rows.append([qname(s["q"]), fn, f(R["NN"]), f(R["Npsi"]), f(R["psipsi"]), f(R["dN"]), f(R["dpsi"]),
                             " ".join("%s %s" % (kk, f(G[kk])) for kk in ("NN", "Npsi", "psipsi"))])
            for tag in ("low", "mult"):
                for pv in ("raw", "norm"):
                    rowsC3.append([qname(s["q"]), "%s, prep %s" % (tag, pv), " ".join(f(x) for x in s["C3_%s_%s_eigs" % (tag, pv)])])
        out += ["### T2 Matter jets (Richardson values; first derivatives dN, dpsi from the same stencil; step agreement h 1e-3 against 1e-4)", "",
                table(["q", "functional", "NN", "N psi", "psi psi", "dE/dlam_N", "dE/dlam_psi", "step agreement (relative)"], rows), "",
                "### C3 eigenvalues of J^prep - J^sus (Richardson values)", "", table(["q", "pairing", "eigenvalues"], rowsC3), "",
                "C2 affinity E(1.1 N) - 1.1 E(N) at psi = 1: lowest %s, multiplet %s." % (f(M["C2_affinity"]["low"]), f(M["C2_affinity"]["mult"])), ""]
        pts = M["points"]
        rows = []
        for q in sorted(set(p["q"] for p in pts)):
            P = [p for p in pts if p["q"] == q]
            rows.append([qname(q), f(min(p["gap"] for p in P if p["gap"] is not None)), f(max(p["split"] for p in P)),
                         f(max(abs(p["prep_mult_norm_defect"]) for p in P)), f(max(abs(p["prep_low_norm_defect"]) for p in P))])
        out += ["### T4 Spectra over the stencil points: smallest gap above the multiplet, largest splitting inside it; largest norm defect "
                "1 - ||C'||^2 of the projected flat state (multiplet, single vector)", "",
                table(["q", "min gap", "max split", "max norm defect (multiplet)", "max norm defect (vector)"], rows), ""]
        if vac_rich:
            rows = []
            for (H, q), R in sorted(vac_rich.items()):
                sm = [s for s in M["summary"] if abs(s["q"] - q) < 1e-12]
                if not sm:
                    continue
                for fn in ("low", "mult"):
                    S = sm[0][fn]["rich"]
                    rows.append([f(H), qname(q), fn, f(R["NN"] + S["NN"]), f(R["Npsi"] + S["Npsi"]), f(R["psipsi"] + S["psipsi"])])
            out += ["### T3 Totals J^tot = J^vac + J^sus (Richardson values)", "",
                    table(["H", "q", "J^sus functional", "NN", "N psi", "psi psi"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
