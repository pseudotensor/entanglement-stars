#!/usr/bin/env python
"""Strand 2b items 6 and 7 report (builder analyst): tables from the R4 driver v13 records (pass2v13), the cube driver v7 records
(c8encl_v7), the historical lock rows (R4 pass 1 and pass 2, the cube's pass 1 and its enclosure cases; R_free by the closed form
2 Q^2/(k kappa + 2 Q) beside the recorded differenced value, kappa = 1^T K 1 of each lattice) and item 7's parts (sec15item7).
Numbers emitted, not retyped."""
import argparse
import glob
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "frozen"))
import native_core as nc  # noqa: E402
import strand2a_lib as S2  # noqa: E402


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if not np.isfinite(v):
        return str(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def lab(r):
    return [r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), str(r["Lambda"]), f(r["k"])]


def load(pattern):
    out = []
    for p in sorted(glob.glob(pattern)):
        try:
            d = json.load(open(p))
        except Exception:  # noqa: BLE001
            continue
        d["_path"] = p
        out.append(d)
    return out


def path_stats(rec):
    path = rec.get("continuation", {}).get("path", [])
    gc = [s.get("gap_cluster") for s in path if s.get("gap_cluster") is not None]
    sm = [s.get("sigma_min_J") for s in path if s.get("sigma_min_J") is not None]
    return len(path) - 1, (min(gc) if gc else None), (min(sm) if sm else None)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True, help="s2b_row")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    B = a.base
    kap = {}
    for lat_name, nat_name in (("R4", "ring4"), ("C8", "C8")):
        if lat_name == "R4":
            K, _ = nc.K_matrix(nc.lattice("ring4")["positions"])
        else:
            K, _ = nc.K_matrix(S2.lattice("C8")["positions"].tolist())
        K = np.asarray(K, float)
        kap[lat_name] = float(np.ones(len(K)) @ K @ np.ones(len(K)))
    out = ["# Strand 2b items 6 and 7 tables (generated by solve/code/strand2/strand2b_sec15_item67_report_v1.py)", ""]
    summ = []
    for lat_name, pat, old_pat in (("R4", "pass2v13/case_*.json", "pass2v12/case_%s.json"), ("C8", "c8encl_v7/case_*.json", "c8pass1v5/enclosure/case_%s.json")):
        R = load(os.path.join(B, pat))
        if not R:
            out += ["## %s: no records yet" % lat_name, ""]
            continue
        # I6a continuation and uniqueness
        rows, tot_starts, tot_acc, stops_all = [], 0, 0, {}
        incon = []
        for r in R:
            nst, gcmin, smmin = path_stats(r)
            u = r.get("uniqueness", {})
            starts = u.get("starts_record", [])
            tot_starts += len(starts)
            tot_acc += u.get("converged_positive", 0)
            for kk, vv in u.get("stop_counts", {}).items():
                stops_all[kk] = stops_all.get(kk, 0) + vv
            rej = [s for s in starts if not s.get("ok") and s.get("own_residual") is not None]
            near = min(rej, key=lambda s: s["own_residual"]) if rej else None
            if u.get("converged_positive", 1) == 0:
                incon.append(r)
            rows.append(lab(r) + [f(r.get("continuation", {}).get("ok")), nst, f(gcmin, 3), f(smmin, 3), u.get("wording", "-"),
                                  "; ".join("%s %d" % (k_, v_) for k_, v_ in sorted(u.get("stop_counts", {}).items(), key=lambda kv: str(kv[0]))),
                                  f(near["own_residual"], 2) if near else "-", f(near.get("correction_at_returned"), 2) if near else "-",
                                  f(near.get("distance_to_reference"), 3) if near else "-"])
        out += ["## I6a %s: the continuation (accepted steps, the smallest cluster gap and sigma_min of J along the path) and the uniqueness scan "
                "(the wording, the stop counts; among the rejected starts the one nearest a root: its own residual, ||J^-1 F|| at it and its "
                "distance from the continuation solution)" % lat_name, "",
                table(["block", "m", "g_M", "g_B", "Lambda", "k", "continuation ok", "steps", "min cluster gap (path)", "min sigma_min (path)",
                       "uniqueness", "stops", "nearest rejected: residual", "its ||J^-1 F||", "its distance"], rows), ""]
        summ.append("I6a (%s, %d cases): %d starts, %d accepted positive; stops: %s; scans with no accepted start: %d (%s)." % (
            lat_name, len(R), tot_starts, tot_acc, ", ".join("%s %d" % (k_, v_) for k_, v_ in sorted(stops_all.items(), key=lambda kv: str(kv[0]))),
            len(incon), "; ".join(" ".join(lab(r)) for r in incon) or "none"))
        # I6b the inconclusive scans' starts in full
        for r in incon:
            rows = []
            for s in r["uniqueness"]["starts_record"]:
                rows.append([s.get("trial"), s.get("stop"), f(s.get("ok")), f(s.get("best"), 3), f(s.get("own_residual"), 3), f(s.get("correction_at_returned"), 3),
                             f(s.get("distance_to_reference"), 3), f(s.get("min_component"), 3), s.get("iterations"), (s.get("error") or "")[:60]])
            out += ["## I6b %s %s: the scan with no accepted start, every start (stop, accepted, best residual, the returned vector's own residual, "
                    "||J^-1 F|| there, distance from the continuation solution, smallest component, residual evaluations, error)" % (lat_name, " ".join(lab(r))), "",
                    table(["start", "stop", "accepted", "best", "own residual", "||J^-1 F||", "distance", "min component", "evaluations", "error"], rows), ""]
        # I6c enclosure
        rows, changed = [], []
        for r in R:
            e = r.get("enclosure")
            if not e:
                continue
            tag = os.path.basename(r["_path"])[5:-5]
            old = None
            op = os.path.join(B, old_pat % tag)
            if os.path.exists(op):
                old = json.load(open(op)).get("enclosure")
            cells = []
            for rad, v in sorted(e["radii"].items(), key=lambda kv: float(kv[0])):
                ov = old["radii"].get(rad, {}).get("passed") if old else None
                cells.append("%s: %s (failed %d, skipped %d of %d; min cluster gap %s)" % (rad, "pass" if v["passed"] else "fail", v["failed_points"],
                                                                                          v["skipped_nonpositive"], v["sampled_points"], f(v.get("min_cluster_gap_sampled"), 3)))
                if ov is not None and bool(ov) != bool(v["passed"]):
                    changed.append("%s r = %s: %s -> %s" % (" ".join(lab(r)), rad, "pass" if ov else "fail", "pass" if v["passed"] else "fail"))
            rows.append(lab(r) + [f(e["Y_F"], 3), "; ".join(cells), f(e.get("largest_passing_r_in_domain"))])
        nfailed = sum(1 for r in R if r.get("enclosure") for v in r["enclosure"]["radii"].values() if v["failed_points"] > 0)
        nskipped = sum(1 for r in R if r.get("enclosure") for v in r["enclosure"]["radii"].values() if v["skipped_nonpositive"] > 0)
        out += ["## I6c %s: the sampled enclosure per radius with the failed and skipped counts (a radius passes only with zero failed evaluations), "
                "against the previous run's verdict" % lat_name, "",
                table(["block", "m", "g_M", "g_B", "Lambda", "k", "||Y F||", "per radius", "largest passing r (domain)"], rows), ""]
        summ.append("I6c (%s): radii with failed evaluations %d, with skipped non-positive points %d; verdicts changed against the previous run: %s." % (
            lat_name, nfailed, nskipped, "; ".join(changed) or "none"))
        # I6d lock: warm b-solves and R_free
        rows, worst_rel = [], 0.0
        notok = []
        for r in R:
            L = r.get("lock")
            if not L:
                continue
            bs = L.get("warm_b_solves", [])
            bad = [b_ for b_ in bs if not b_.get("ok")]
            if bad:
                notok.append(" ".join(lab(r)))
            cf, dfv = L.get("R_free_closed_form"), L.get("R_free_differenced")
            rel = abs(dfv - cf) / abs(cf) if (cf not in (None, 0) and dfv is not None) else None
            U = L.get("uniformity", {})
            if rel is not None and U.get("psi_rel_spread", 1) < 1e-10:
                worst_rel = max(worst_rel, rel)
            rows.append(lab(r) + ["%d of %d ok (%s)" % (len(bs) - len(bad), len(bs), ", ".join(sorted(set(str(b_.get("stop")) for b_ in bs)))),
                                  f(max((b_.get("best") or 0) for b_ in bs), 2) if bs else "-", f(L["Q"], 6), f(cf, 6), f(dfv, 6), f(rel, 2),
                                  f(L.get("R_mat"), 6), f(U.get("psi_rel_spread"), 2), f(U.get("source_rel_spread"), 2)])
        out += ["## I6d %s: the lock's warm b-solves (accepted of four, their stops, the worst best residual) and R_free by the closed form "
                "2 Q^2/(k kappa + 2 Q) (kappa = %s) beside the differenced value, R_mat = R - R_free (closed form), and the solution's and "
                "the source's relative spreads (the closed form is exact for uniform fields)" % (lat_name, f(kap[lat_name], 10)), "",
                table(["block", "m", "g_M", "g_B", "Lambda", "k", "b-solves", "worst best", "Q", "R_free (closed form)", "R_free (differenced)",
                       "|difference|/closed", "R_mat", "psi spread", "source spread"], rows), ""]
        summ.append("I6d (%s): b-solves not all accepted in %s; on the uniform solutions the differenced R_free departs from the closed form by "
                    "up to %s relative." % (lat_name, "; ".join(notok) or "no case", f(worst_rel, 2)))
    # I6e historical lock rows
    rows = []
    worst = {}
    for lat_name, pats in (("R4", ["pass1/case_*.json", "pass2/case_*.json"]), ("C8", ["c8pass1v5/case_*.json", "c8pass1v5/enclosure/case_*.json"])):
        for pat in pats:
            for r in load(os.path.join(B, pat)):
                L = r.get("lock")
                if not L or r.get("psi") is None:
                    continue
                Q, k = L["Q"], r["k"]
                cf = 2 * Q * Q / (k * kap[lat_name] + 2 * Q)
                psi = np.array(r["psi"])
                src = np.array(r.get("source", [np.nan]))
                ps = float(np.ptp(psi) / np.mean(psi))
                ss = float(np.ptp(src) / max(abs(np.mean(src)), 1e-300))
                rel = abs(L["R_free"] - cf) / abs(cf) if cf != 0 else None
                if ps < 1e-10 and rel is not None:
                    worst[lat_name] = max(worst.get(lat_name, 0.0), rel)
                rows.append([lat_name, os.path.dirname(pat)] + lab(r) + [f(Q, 6), f(L["R_free"], 6), f(cf, 6), f(rel, 2), f(L["R"] - cf, 6), f(ps, 2), f(ss, 2)])
    out += ["## I6e The historical lock rows (T3 of revisions 1 to 5): the recorded differenced R_free beside the closed form 2 Q^2/(k kappa + 2 Q), "
            "R_mat with the closed form, and the solution's and source's relative spreads (rows with a nonuniform solution: the closed form is the "
            "uniform problem's, not exact there)", "",
            table(["lattice", "run", "block", "m", "g_M", "g_B", "Lambda", "k", "Q", "R_free (recorded)", "R_free (closed form)", "|difference|/closed",
                   "R_mat (closed form)", "psi spread", "source spread"], rows), ""]
    summ.append("I6e: over the historical rows with uniform solutions the recorded R_free departs from the closed form by up to %s relative." % (
        ", ".join("%s on %s" % (f(v, 2), k_) for k_, v in sorted(worst.items())) or "-"))
    # item 7
    I7 = {p: (json.load(open(os.path.join(B, "sec15item7", "item7_%s.json" % p))) if os.path.exists(os.path.join(B, "sec15item7", "item7_%s.json" % p)) else None)
          for p in ("class1", "class2", "uniform", "doublet")}
    for p in ("class1", "class2"):
        d = I7[p]
        if d is None:
            continue
        rows = [[f(s["k"], 6), f(s.get("dk"), 3), f(s["amplitude"], 5), f(s["amplitude"] ** 2, 5), f(s["E"], 10), f(s["E_sel"], 8), f(s["gap_cluster"], 4),
                 " ".join(f(x, 4) for x in s["sigma_smallest3"]), f(s["sym_eig_smallest_modulus"], 4), "%s %s" % (f(s["J_eig_smallest_modulus"][0], 4), f(s["J_eig_smallest_modulus"][1], 2)),
                 f(s.get("best"), 2), s.get("newton")] for s in d["steps"]]
        out += ["## I7 %s: the branch-preserving continuation in k from 5 (k, the step, the amplitude a and a^2, E, E_sel, the cluster gap, the "
                "three smallest singular values of J, the symmetric part's eigenvalue of smallest modulus, J's eigenvalue of smallest modulus, "
                "the best residual, the residual evaluations); outcome: %s; rejected steps: %d" % (d.get("class", p), d.get("outcome"), len(d.get("rejections", []))), "",
                table(["k", "dk", "a", "a^2", "E", "E_sel", "cluster gap", "sigma (3 smallest)", "sym. eig.", "J eig. (re im)", "best", "evaluations"], rows), ""]
        if len(d["steps"]) >= 3:
            ks = np.array([s["k"] for s in d["steps"][-3:]])
            a2 = np.array([s["amplitude"] ** 2 for s in d["steps"][-3:]])
            c = np.polyfit(ks, a2, 1)
            kb = -c[1] / c[0] if c[0] != 0 else None
            summ.append("I7 (%s): %s; the last three steps' a^2 linear in k extrapolates to zero at k = %s." % (d.get("class", p), d.get("outcome"), f(kb, 6)))
        else:
            summ.append("I7 (%s): %s." % (d.get("class", p), d.get("outcome")))
    d = I7["uniform"]
    if d is not None:
        rows = [[f(s["k"], 6), f(s.get("converged")), " ".join(f(x, 4) for x in s["sigma_smallest3"]), f(s["sym_eig_smallest_modulus"], 4), f(s["sym_eig_lowest"], 4),
                 f(s["rayleigh_vJv"], 4), "%s %s" % (f(s["J_eig_smallest_modulus"][0], 4), f(s["J_eig_smallest_modulus"][1], 2)), f(s["E"], 10), f(s["gap_cluster"], 4)]
                for s in sorted(d["scan"] + d.get("refine", []), key=lambda s: s["k"])]
        out += ["## I7 uniform branch: per k the three smallest singular values of the FD Jacobian, the symmetric part's eigenvalue of smallest "
                "modulus and its lowest eigenvalue, the Rayleigh quotient along sigma_min's right singular vector, J's eigenvalue of smallest "
                "modulus, E and the cluster gap (the 0.25 scan and the refinement around the smallest sigma_min)", "",
                table(["k", "converged", "sigma (3 smallest)", "sym. eig. (smallest modulus)", "sym. eig. (lowest)", "v^T J v", "J eig. (re im)", "E", "cluster gap"], rows), ""]
        tc = d.get("two_step_check", {})
        allp = [s for s in d["scan"] + d.get("refine", []) if s.get("converged")]
        sb = min(allp, key=lambda s: s["sigma_smallest3"][0]) if allp else None
        sgn = [(s["k"], np.sign(s["J_eig_smallest_modulus"][0])) for s in sorted(allp, key=lambda s: s["k"])]
        flips = ["%s to %s" % (f(a_[0], 6), f(b_[0], 6)) for a_, b_ in zip(sgn[:-1], sgn[1:]) if a_[1] != b_[1]]
        summ.append("I7 (uniform branch): the smallest sigma_min %s at k = %s; J's smallest-modulus eigenvalue changes sign between %s; two-step "
                    "Jacobian check at k = %s: entries %s relative, sigma_min %s (h 1e-6) and %s (h 1e-7); the exact dF/dk against a central "
                    "difference in k: %s relative." % (f(sb["sigma_smallest3"][0], 4) if sb else "-", f(sb["k"], 6) if sb else "-", "; ".join(flips) or "no k",
                                                       f(tc.get("k"), 6), f(tc.get("max_rel_entry_diff"), 2), f(tc.get("sigma_min_h1e-6"), 4),
                                                       f(tc.get("sigma_min_h1e-7"), 4), f(d.get("dF_dk_check"), 2)))
    d = I7["doublet"]
    if d is not None:
        rows = [[c["x"], f(c["trace_over_2"], 6), " ".join(f(x, 6) for x in c["eigenvalues"]), f(c["nonscalar"], 3)] for c in d["clock_sources"]]
        out += ["## I7 doublet at (g_M, g_B) = (0.05, 0), k = 1: d_0 %d, levels %s, splitting %s, gap above %s, Tr rho^2 %s; the 2 x 2 clock-source "
                "matrices on the doublet per site (trace/2, eigenvalues, non-scalar part); the adjoint sources' largest non-scalar part %s (over "
                "entries above 1e-3 of the largest: %s)" % (d["d0"], " ".join(f(x, 8) for x in d["levels"]), f(d["splitting"], 4), f(d["gap_above"], 4),
                                                            f(d["Tr_rho2"], 6), f(d["adjoint_nonscalar_max"], 3), f(d["adjoint_nonscalar_max_significant"], 3)), "",
                table(["site", "trace/2", "eigenvalues", "non-scalar part"], rows), ""]
        summ.append("I7 (doublet at (0.05, 0)): splitting %s, gap above %s, Tr rho^2 %s; the clock sources' largest non-scalar part %s, the adjoint "
                    "sources' %s (%s over the entries above 1e-3 of the largest)." % (f(d["splitting"], 4), f(d["gap_above"], 4), f(d["Tr_rho2"], 6),
                                                                                    f(d["clock_nonscalar_max"], 3), f(d["adjoint_nonscalar_max"], 3),
                                                                                    f(d["adjoint_nonscalar_max_significant"], 3)))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
