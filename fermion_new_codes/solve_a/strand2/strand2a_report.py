#!/usr/bin/env python
"""Strand 2a report: the gate tables G1 to G8 from gate_L2.json, gate_R4.json, gate_C8.json (builder analyst; numbers not retyped)."""
import argparse
import json
import os


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, str):
        return v
    v = float(v)
    if v == 0:
        return "0"
    a = abs(v)
    if a < 1e-3 or a >= 1e5:
        return "%.*e" % (sig - 1, v)
    return "%.*g" % (sig, v)


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    G = {}
    for lat in ("L2", "R4", "C8"):
        p = os.path.join(a.run, "gate_%s.json" % lat)
        if os.path.exists(p):
            G[lat] = json.load(open(p))
    out = ["# Strand 2a gate tables (generated by solve/code/strand2/strand2a_report.py)", ""]
    for lat, g in G.items():
        m = g["meta"]
        out.append("%s: host %s, python %s, numpy %s, scipy %s, %.0f s (%s to %s UTC); mode order: %s." % (
            lat, m["host"], m["python"], m["numpy"], m["scipy"], m["seconds"], m["start_utc"], m["end_utc"], m["mode_order"]))
    out.append("")
    rows = []
    for lat, g in G.items():
        for k, v in g["backgrounds"].items():
            rows.append([lat, k, " ".join(f(x) for x in v["psi"]), " ".join(f(x) for x in v["N"])])
    out += ["## Backgrounds", "", table(["lattice", "background", "psi_x", "N_x"], rows), ""]
    # ---------------- gate summary
    rows = []
    for lat, g in G.items():
        L = g["light"]
        rows.append([lat, "G1 S_* - S_*^dag (max over blocks and cases)", "<= 1e-12", f(max(r["G1"]["S_hermitian"] for r in L))])
        rows.append([lat, "G1 S_* on n_exc <= 1 (max abs entry)", "0", f(max(r["G1"]["S_on_nexc_le1"] for r in L))])
        rows.append([lat, "G1 [S_*, n_exc], [S_*, N_c]", "0", L[0]["G1"]["S_commutes_n_exc_and_N_c"]])
        if "G1c_vIJ_alg_minus_fock" in L[0]:
            rows.append([lat, "G1c algebraic v_IJ - Fock-route v_IJ (max)", "<= 1e-12", f(max(r["G1c_vIJ_alg_minus_fock"] for r in L))])
            for key in ("isometry", "S", "Vstar", "H_exc", "H_free", "leak_H_exc"):
                vals = [it[key] for r in L for it in r["G1c_blocks"].values() if key in it]
                rows.append([lat, "G1c q-block route against the Fock route: %s (max over blocks and cases)" % key, "<= 1e-12",
                             f(max(vals)) if vals else "-"])
            rows.append([lat, "G1d H_exc|(2,0) - e^S H_0^pp e^S on the Fock route (max)", "<= 1e-12", f(max(r["G1d_fock"] for r in L))])
            rows.append([lat, "G2b lowest eig of c^dag h_1 c (half filling) + Tr B_10 (max abs)", "<= 1e-12",
                         f(max(abs(r["G2b"]["lowest_bilinear_plus_TrB10"]) for r in L))])
            rows.append([lat, "G2b ||H_exc Omega|| (max)", "<= 1e-12", f(max(r["G2b"]["H_exc_Omega"] for r in L))])
        rows.append([lat, "G2a sum of negative eigenvalues of h_s + Tr L E_{s,j(s)} (max over packets, backgrounds, m, H)", "<= 1e-12",
                     f(max(v["G2a_max"] for v in g["vacuum"]))])
        uni = [abs(v["W0"]) for v in g["vacuum"] if v["bg"] == "flat"]
        rows.append([lat, "G2c W_0 at the flat background (max abs)", "<= 1e-12", f(max(uni))])
        rows.append([lat, "G3 ||P_1 (H_exc - H_free) P_1|| (max over (1,0), (0,1) and cases)", "<= 1e-12",
                     f(max(max(r["G3"]["P1_(1,0)"], r["G3"]["P1_(0,1)"]) for r in L))])
        rows.append([lat, "G3 ||H_exc Omega|| on the q-route (max)", "0", f(max(r["G3"]["H_exc_on_Omega"] for r in L))])
        rows.append([lat, "G4 |W_0[cN] - c W_0[N]|, c = 0.7, 1.3 (max)", "<= 1e-12",
                     f(max(max(v["G4_affinity"].values()) for v in g["vacuum"]))])
        rows.append([lat, "G4 dW_0/dN_x at the flat background (max abs)", "<= 1e-12",
                     f(max(max(abs(x) for x in v["dW0_dN"]) for v in g["vacuum"] if v["bg"] == "flat"))])
        rows.append([lat, "G4 dW_0/dN_x formula - central difference h = 1e-4 (max)", "report",
                     f(max(v["dW0_dN_fd_minus_formula"] for v in g["vacuum"]))])
        rows.append([lat, "G4 K_NN of W_0, central differences h = 0.1 (max abs)", "<= 1e-12", f(max(v["K_NN_W0_max"] for v in g["vacuum"]))])
        if g.get("manybody"):
            kn = [mb["K_NN_mb_max"] for mb in g["manybody"] if "K_NN_mb_max" in mb]
            rows.append([lat, "G4 K_NN of the many-body vacuum energy (row gM 0.2, gB 1, Lambda 1; h = 0.1; max abs)", "<= 1e-9",
                         f(max(kn)) if kn else "-"])
            rows.append([lat, "G5 spread of the many-body E_vac over coupling rows and Lambda (max)", "<= 1e-14",
                         f(max(mb["G5_spread_E_vac"] for mb in g["manybody"]))])
        rows.append([lat, "G5 W_0 depends on (g_M, g_B, Lambda)", "no", "no: computed from the packets alone"])
        g6 = [abs(r["G6"]["ratio"][k] - r["G6"]["expected"]) for r in L for k in r["G6"]["ratio"]]
        rows.append([lat, "G6 mutation S' = 0.1 n_exc: |ratio - (e^0.2 - 1)| on (1,0), (0,1) (max)", "<= 1e-10",
                     "%s (expected %s)" % (f(max(g6)), f(L[0]["G6"]["expected"], 6))])
        rows.append([lat, "min eig H_exc over blocks and cases", ">= -1e-12", f(min(min(r["min_eig_Hexc"].values()) for r in L))])
    out += ["## Gate summary (G1 to G6)", "", table(["lattice", "item", "tolerance", "measured"], rows), ""]
    # ---------------- W_0 pieces
    rows = []
    for lat, g in G.items():
        for v in g["vacuum"]:
            pk = v["packets"]
            rows.append([lat, v["bg"], f(v["m"]), f(v["H"]), f(v["W0"], 6)] + [f(p["total"], 6) for p in pk] +
                        [f(v["J"], 6), f(v["k_lat"], 6), f(v["sum_rule"])])
    out += ["## G2c W_0 = sum_s eta_s Tr L (E_s1 - E_s0) and its four packet pieces; J, k_lat = 3J/pi^2, sum rule", "",
            table(["lattice", "bg", "m", "H", "W_0", "packet 1 (+)", "packet 2 (-)", "packet 3 (-)", "packet 4 (+)", "J", "k_lat",
                   "sum_s eta_s m_s^2"], rows), ""]
    rows = []
    for lat, g in G.items():
        for v in g["vacuum"]:
            if v["bg"] != "flat":
                rows.append([lat, v["bg"], f(v["m"]), f(v["H"]), " ".join(f(x) for x in v["dW0_dN"])])
    out += ["## G4 dW_0/dN_x = psi_x sum_s eta_s Tr_x(E_s1 - E_s0) at the nonuniform backgrounds", "",
            table(["lattice", "bg", "m", "H", "dW_0/dN_x per site"], rows), ""]
    # ---------------- G3 P2 and G7
    rows = []
    for lat, g in G.items():
        for r in g["light"]:
            g7 = r["G7"]
            rows.append([lat, r["bg"], f(r["m"]), f(r["gM"]), f(r["gB"]), r["Lambda"], f(r["G3"]["P2_(2,0)"]), f(r["G3"]["P2_(1,1)"]),
                         f(r["G3"]["P2_(0,2)"]), f(g7["2,0"]["E_min_minus_2eps"]), f(g7["2,0"]["V_star_free_ground"]),
                         f(g7["2,0"]["remainder"]), f(g7["1,1"]["E_min_minus_2eps"]), f(g7["1,1"]["V_star_free_ground"]),
                         f(g7["1,1"]["remainder"])])
    out += ["## G3 n_exc = 2 norms and G7 two-body numbers ((1,1) on C8 reported as computed)", "",
            table(["lattice", "bg", "m", "g_M", "g_B", "Lambda", "||P_2(H_exc - H_free)P_2|| (2,0)", "(1,1)", "(0,2)",
                   "E_(2,0)^min - 2 eps_min", "<V_*> free (2,0) ground", "remainder (2,0)", "E_(1,1)^min - 2 eps_min",
                   "<V_*> free (1,1) ground", "remainder (1,1)"], rows), ""]
    rows = []
    for lat, g in G.items():
        idx = {}
        for r in g["light"]:
            idx[(r["bg"], r["m"], r["gM"], r["gB"], r["Lambda"])] = r
        for (bg, m, gM, gB, L), r in idx.items():
            if gM == 0.05 and gB == 0.0:
                r2 = idx.get((bg, m, 0.2, 0.0, L))
                if r2:
                    for blk in ("2,0", "1,1"):
                        a1, a2 = r["G7"][blk]["remainder"], r2["G7"][blk]["remainder"]
                        rows.append([lat, bg, f(m), L, blk, f(a1), f(a2), f(a2 / a1) if a1 else "-"])
    out += ["## G7 remainder ratio g_M = 0.2 over 0.05 at g_B = 0 (16 if O(U^2); the (0.2, 0) row is a builder addition for this ratio)", "",
            table(["lattice", "bg", "m", "Lambda", "block", "remainder at 0.05", "remainder at 0.2", "ratio"], rows), ""]
    # ---------------- G8
    if "C8" in G and G["C8"]["stiffness"]:
        rows = []
        for s in G["C8"]["stiffness"]:
            rows.append([f(s["m"]), f(s["H"]), f(max(abs(x) for x in s["Kpp_row_sums"])), " ".join(f(x) for x in s["Kpp_eigs"]),
                         f(max(abs(x) for x in s["KpN_row_sums"])), " ".join(f(x) for x in s["KpN_sym_eigs"]), f(s["KpN_max_singular"])])
        out += ["## G8 C8 lattice stiffness of the four-packet vacuum at (psi, N) = (1, 1) (central differences h = 1e-4)", "",
                table(["m", "H", "max |row sum| d2W/dpsi dpsi", "eigenvalues (sym)", "max |row sum| d2W/dpsi dN",
                       "eigenvalues of its symmetric part", "largest singular value"], rows), ""]
    with open(a.md, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s" % a.md)


if __name__ == "__main__":
    main()
