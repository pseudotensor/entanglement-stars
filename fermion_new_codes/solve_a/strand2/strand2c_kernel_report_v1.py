#!/usr/bin/env python
"""Strand 2c addendum part A report (builder analyst): from strand2c_kernel_v1.py's kernel_L<L>.json: the dense control, and per the spec
(i) k_a(q)/k_lat and mixed/k_a per (aH, q) (a q subset in the table, all in the JSON); (ii) k_a(0; aH)/k_lat by the least-squares fit
a + b q^2 over the q <= aH/4 (at least 4 points; else the value at the smallest q, stated); (iii) 1 - k_a(0)/k_lat against aH with the fit
a (aH)^2 log(aH) + b (aH)^2 over the aH values that have a fit, and its residuals; (iv) the crossover q_c(aH) where k_a(q)/k_a(0) = 1/2
(linear interpolation between grid points) and q_c/aH; (v) the physical row's k_a(q)/k_lat.  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    K = json.load(open(a.json))
    L = K["meta"]["L"]
    out = ["# Strand 2c addendum part A tables (generated by solve/code/strand2/strand2c_kernel_report_v1.py; L = %d)" % L, ""]
    if "control" in K:
        rows = [[r["L"], f(r["H"]), f(r["W2_kernel"], 10), f(r["W2_dense_R2"], 10), f(r["rel_diff_R2"]), f(r["rel_diff_R1"]),
                 f(r["rel_diff_eps1e-3"]), f(r["k_a_kernel"], 8), f(r["mixed_over_k_a"], 10)] for r in K["control"]]
        out += ["## Control: the momentum-space second-order coefficient W^(2) against the dense real-space W_0/eps^2 (2c's packet routine), "
                "extrapolated twice in eps (eps 2e-2, 1e-2, 5e-3), and against the single eps = 1e-3 value of the 2c run", "",
                table(["L", "H", "W^(2) kernel", "W^(2) dense (R2)", "rel diff R2", "rel diff R1", "rel diff eps 1e-3", "k_a kernel",
                       "mixed/k_a"], rows), ""]
    eq = K["equal"]
    aHs = sorted(set(r["aH"] for r in eq), reverse=True)
    rows_fit, rows_q = [], []
    k0 = {}
    for aH in aHs:
        R = sorted([r for r in eq if r["aH"] == aH], key=lambda r: r["q"])
        q = np.array([r["q"] for r in R])
        ka = np.array([r["k_a"] for r in R])
        kl = R[0]["k_lat"]
        sel = q <= aH / 4
        if sel.sum() >= 4:
            A = np.column_stack([np.ones(sel.sum()), q[sel] ** 2])
            c = np.linalg.lstsq(A, ka[sel], rcond=None)[0]
            k0[aH] = (c[0], "fit a + b q^2 over %d points q <= %s" % (sel.sum(), f(aH / 4)))
        else:
            k0[aH] = (ka[0], "value at the smallest q = %s (fewer than 4 points below aH/4)" % f(q[0]))
        half = k0[aH][0] / 2
        qc = None
        for i in range(len(q) - 1):
            if (ka[i] - half) * (ka[i + 1] - half) <= 0:
                qc = q[i] + (half - ka[i]) * (q[i + 1] - q[i]) / (ka[i + 1] - ka[i])
                break
        rows_fit.append([f(aH), f(kl, 8), f(k0[aH][0], 8), f(k0[aH][0] / kl, 8), f(1 - k0[aH][0] / kl), k0[aH][1], f(qc), f(qc / aH) if qc else "-",
                         f(max(abs(r["mixed_over_k_a"] - 0.5) for r in R))])
        for r in R:
            if r["n"] in (1, 2, 4, 8, 16, 32, 64, 128):
                rows_q.append([f(aH), r["n"], f(r["q"]), f(r["k_a"], 8), f(r["k_a_over_k_lat"], 8), f(r["mixed_over_k_a"], 10)])
    out += ["## (ii) and (iv): k_a(0; aH) and the crossover q_c (equal rectangle, m_light = 0.1, twist 0)", "",
            table(["aH", "k_lat", "k_a(0)", "k_a(0)/k_lat", "1 - k_a(0)/k_lat", "how k_a(0) is obtained", "q_c (k_a = k_a(0)/2)", "q_c/aH",
                   "max |mixed/k_a - 1/2| over q"], rows_fit), ""]
    pts = [(aH, 1 - k0[aH][0] / [r for r in eq if r["aH"] == aH][0]["k_lat"]) for aH in aHs if k0[aH][1].startswith("fit")]
    if len(pts) >= 2:
        x = np.array([p[0] for p in pts])
        y = np.array([p[1] for p in pts])
        A = np.column_stack([x ** 2 * np.log(x), x ** 2])
        c = np.linalg.lstsq(A, y, rcond=None)[0]
        resid = A @ c - y
        out += ["## (iii) 1 - k_a(0)/k_lat = a (aH)^2 log(aH) + b (aH)^2 over the aH values with a q^2 fit: a = %s, b = %s; residuals %s" % (
            f(c[0]), f(c[1]), " ".join("aH %s: %s" % (f(xx), f(rr)) for xx, rr in zip(x, resid))), ""]
    out += ["## (i) k_a(q)/k_lat and mixed/k_a at q = 2 pi n/L, n in {1, 2, 4, ..., 128} (all n in the JSON)", "",
            table(["aH", "n", "q", "k_a", "k_a/k_lat", "mixed/k_a"], rows_q), ""]
    ph = K["physical"]
    rows = [[r["n"], f(r["q"]), f(r["k_a"], 8), f(r["k_a_over_k_lat"], 8), f(r["mixed_over_k_a"], 10)] for r in ph["rows"]
            if r["n"] in (1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 48, 64, 96, 128)]
    out += ["## (v) the physical row: strand 3's lambda = 1 rectangle at a/l_P = 0.0213 (q_s a = %s), the light packet massless with the "
            "twist %s on every axis; k_lat = %s" % (" ".join(f(q, 6) for q in ph["masses"]), ph["twist"], f(ph["rows"][0]["k_lat"], 8)), "",
            table(["n", "q", "k_a", "k_a/k_lat", "mixed/k_a"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
