#!/usr/bin/env python
"""Strand 2c addendum parts B and C report (builder analyst): tables from strand2c_addendum_BC_v1.py's addBC.json.
B1 per profile and H: rel ||Delta C|| on I with k_lat and with k_a(0; aH), sum_x w_x and sum_x w_x/psi_x over the open box, the local
row's Gauss charge, W_0 and the Euler-trace check, the harmonic exterior's largest |psi - 1|; B2 the interior rows per site; B3 the
exterior profile of w by shells; B4 the flat open box's smallest heavy singular value against the masses; C the bump width table.
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    m = R["meta"]
    out = ["# Strand 2c addendum parts B and C tables (generated by solve/code/strand2/strand2c_addendum_BC_report_v1.py; L = %d)" % m["L"], "",
           "k_a(0; aH) from part A's kernel_L256.json: " + "; ".join("H %s: %s (%s)" % (H, f(v[0], 8), v[1]) for H, v in m["k_a0"].items()), ""]
    B = R["B"]
    if B:
        rows = [[r["profile"], f(r["H"]), f(r["k_lat"], 6), f(r["k_a0"], 6), f(r["rel_DeltaC"]), f(r["rel_DeltaC_k_a0"]), f(r["sum_w_box"]),
                 f(r["sum_w_over_psi_box"]), f(r["gauss_charge_local_row"]), f(r["W0"]), f(r["euler_minus_trace"]), f(r["psi_exterior_max_dev"])]
                for r in B]
        out += ["## B1 Open box (psi = N = 1 on the boundary layer, harmonic exterior): the mismatch on I and the box sums", "",
                table(["profile", "H", "k_lat", "k_a(0)", "||Delta C||/||w|| on I (k_lat)", "same with k_a(0)", "sum_x w_x (box)",
                       "sum_x w_x/psi_x (box)", "Gauss charge of the local row", "W_0", "|W_0 - Euler trace|", "max |psi - 1| off I"], rows), ""]
        rows = []
        for r in B:
            for i, (w, ins, insa, dc, dca) in enumerate(zip(r["w_I"], r["installed_I"], r["installed_I_k_a0"], r["DeltaC_I"], r["DeltaC_I_k_a0"])):
                rows.append([r["profile"], f(r["H"]), i, f(w, 6), f(ins, 6), f(insa, 6), f(dc), f(dca)])
        out += ["## B2 The interior rows on I per site: w_x, the installed row -k psi_x [K_I (psi - 1)]_x with k = k_lat and k = k_a(0), "
                "Delta C_x", "", table(["profile", "H", "site", "w_x", "installed (k_lat)", "installed (k_a(0))", "Delta C_x (k_lat)",
                                         "Delta C_x (k_a(0))"], rows), ""]
        rows = []
        for r in B:
            for s in r["shells"]:
                rows.append([r["profile"], f(r["H"]), f(s["distance"]), s["count"], f(s["sum_w"]), f(s["mean_w"])])
        out += ["## B3 The exterior profile of w by shells (distance from the nearest site of I)", "",
                table(["profile", "H", "distance", "sites", "sum w", "mean w"], rows), ""]
        seen = {}
        for r in B:
            seen.setdefault(r["H"], r)
        rows = [[f(H), " ".join(f(x, 6) for x in r["masses"]), " ".join(f(x, 6) for x in r["minsv_flat_open_box"])] for H, r in sorted(seen.items(), reverse=True)]
        out += ["## B4 The flat open box: the smallest singular value of A per packet (the one-body spectrum's minimum) against the masses", "",
                table(["H", "masses m_s (light, heavy, heavy, heavy)", "smallest singular value per packet"], rows), ""]
    C = R["C"]
    if C:
        rows = [[f(r["sigma2"]), f(r["H"]), f(r["sigma_H"]), f(r["image_weight"]), f(r["k_lat"], 6), f(r["k_a0"], 6), f(r["rel_DeltaC"]),
                 f(r["rel_DeltaC_k_a0"]), f(r["w_centre"]), f(r["installed_centre"]), f(r["centre_ratio"], 6), f(r["centre_ratio_k_a0"], 6),
                 f(r["W0"]), f(r["euler_minus_trace"])] for r in C]
        out += ["## C The bump psi = 1 + 0.2 exp(-r^2/sigma^2) on the periodic L = 16 box, N = 1: the row +k psi Lap(psi - 1) with k = k_lat "
                "and k = k_a(0)", "",
                table(["sigma^2", "H", "sigma H", "image weight exp(-(L/2)^2/sigma^2)", "k_lat", "k_a(0)", "||Delta C||/||w|| (k_lat)",
                       "same (k_a(0))", "w centre", "installed centre (k_lat)", "w/installed (k_lat)", "w/installed (k_a(0))", "W_0",
                       "|W_0 - Euler trace|"], rows), ""]
    out += ["Run time %s s on %s (GPU %s)." % (f(m.get("seconds")), m.get("host"), m.get("gpu")), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
