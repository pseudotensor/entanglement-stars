#!/usr/bin/env python
"""Strand 2a red-team checks report (builder analyst): tables from strand2a_rtchecks_AB_v1.py (rtchecks_AB.json) and
strand2a_rtchecks_CDE_v1.py (rtchecks_C.json, rtchecks_D.json, rtchecks_E.json), in the order of SPEC_strand2a_redteam_checks.md.
Numbers emitted, not retyped; no reading."""
import argparse
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, (list, tuple)) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        return "%s%s%si" % (f(v[0], sig), "+" if v[1] >= 0 else "-", f(abs(v[1]), sig))
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def load(d, name):
    p = os.path.join(d, name)
    return json.load(open(p)) if os.path.exists(p) else None


