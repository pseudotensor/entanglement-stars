        out += ["## B.2 Step study on flat C8 (m = 0.1): the uniform mode, the row sums, the eigenvalue clusters (mean x multiplicity), the "
                "antisymmetric parts", "",
                table(["H", "h", "uniform: ruler-ruler", "uniform: mixed", "max abs row sum (ruler-ruler)", "max abs row sum (mixed)",
                       "ruler-ruler clusters", "mixed clusters", "ruler-ruler antisym/sym", "mixed antisym/sym"], rows), ""]
        rows = [[f(r["m"]), f(r["H"]), f(r["gamma"], 8), " ".join(f(x, 8) for x in r["over_2_4_6"]), f(r["Kpp_extreme_over_12"], 8)] for r in AB["B3"]]
        out += ["## B.3 gamma = (3/2) sum_s eta_s/(m_s^2 + 3/4)^(1/2) against the mixed clusters divided by -2, -4, -6 and the ruler-ruler extreme "
                "divided by -12 (h = 1e-4)", "", table(["m", "H", "gamma", "mixed clusters / (-2, -4, -6)", "ruler-ruler extreme / (-12)"], rows), ""]
