#!/usr/bin/env python
"""Strand 2b R4 report (builder analyst): tables T1 (solutions), T3 (lock pieces; fits in 1/k; additivity, dressing and mass
comparisons; the native control beside the law; the strand 1 baseline parsed from its committed table), T4 (uniform-dilation
derivatives), the ruler variances, and T2 (enclosure) when present.  Numbers emitted, not retyped; no physics reading.
(version 2: Lambda normalised to "1"/"inf" in keys and tables; version 1 keyed finite Lambda as "1.0" and so emitted an empty
additivity/dressing table and only the Lambda = inf rows of the mass-dependence table)
(version 3: A and B in T1; the degree d log E_block/d log b in T4 (D3); the R_mat/R_free read-off at k = 1e4 (D2(b)); the
native control's k-fits beside the law's)
(version 4, renamed from strand2b_report_R4: any lattice; C8 records (strand2b_row_C8_v2) lack the R4-only fields, which print "-";
a C8 table with the fixed-Fock-vector step agreement and the sea-rotation term; --title)
(version 5: SPEC sec. 12(c): the fits table carries c_1/E_block(1)^2 and R_inf/E_block(1), with E_block(1) the block's lowest energy at
N = 1, psi = 1 (k-independent, from the k = 1 record))
(version 6: the two ratio columns print "-" where |E_block(1)| < 1e-12 (the q = 0 vacuum block, whose energy is zero to rounding))
(version 7: a pipe inside a table cell is escaped, so headers such as ||Y F|| keep the columns)"""
import argparse
import glob
import json
import os
import re

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, str):
        return v
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def load(run):
    law = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(run, "case_*.json")))]
    for r in law:  # batch error records carry only the case tuple: give them the case fields so T1 shows them
        if "error" in r and "block" not in r and "case" in r:
            r.update(dict(zip(("block", "m", "gM", "gB", "Lambda", "k"), r["case"])))
    nat = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(run, "native", "native_q*.json")))]
    var = os.path.join(run, "native", "native_ruler_variance.json")
    return law, nat, (json.load(open(var)) if os.path.exists(var) else [])


def lam(r):
    v = r.get("Lambda")
    return "inf" if v in ("inf", None) or not np.isfinite(float(v)) else "%g" % float(v)


def ckey(r):
    return (r["block"], r["m"], r["gM"], r["gB"], lam(r))


def fit_k(rows):
    """R(k) - R_inf = a + c1/k + c2/k^2 over k in {10, 100, 1e3, 1e4}; log-log exponent of |R - R_inf - a| over k = 100..1e4."""
    pts = sorted((r["k"], r["lock"]["R"] - r["lock"]["R_inf"]) for r in rows if "lock" in r and r["k"] >= 10)
    if len(pts) < 3:
        return None
    k = np.array([p[0] for p in pts])
    y = np.array([p[1] for p in pts])
    A = np.column_stack([np.ones_like(k), 1 / k, 1 / k ** 2])
    coef = np.linalg.lstsq(A, y, rcond=None)[0]
    sel = k >= 100
    ex = None
    if sel.sum() >= 2:
        yy = np.abs(y[sel])
        ex = float(np.polyfit(np.log(k[sel]), np.log(yy), 1)[0]) if np.all(yy > 0) else None
    return {"a": float(coef[0]), "c1": float(coef[1]), "c2": float(coef[2]), "exponent_100_1e4": ex}


def baseline_rows(path):
    rows = []
    if not os.path.exists(path):
        return rows
    started = False
    for line in open(path):
        if line.startswith("| promotion | m | q | form"):
            started = True
            continue
        if started:
            if not line.startswith("|"):
                break
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells[0].startswith("---"):
                continue
            rows.append(cells)
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--baseline", required=True, help="the committed strand 1 k-scan tables (RESULTS_native_kscan_tables.md)")
    ap.add_argument("--md", required=True)
    ap.add_argument("--title", default="Strand 2b R4 tables")
    a = ap.parse_args()
    law, nat, var = load(a.run)
    out = ["# %s (generated by solve/code/strand2/strand2b_report_v6.py)" % a.title, ""]
    # T1 solutions
    rows = []
    for r in law:
        c = r.get("continuation", {})
        if "psi" not in r:
            rows.append([r.get("block"), f(r.get("m")), f(r.get("gM")), f(r.get("gB")), lam(r), f(r.get("k")),
                         "lost at lambda %s" % f(c.get("lost_at_lam")) if "lost_at_lam" in c else r.get("error", "-")] + ["-"] * 13)
            continue
        rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(r["k"]), f(min(r["psi"]), 6), f(min(r["N"]), 6),
                     f(r["E"], 6), r["d0"], f(r.get("multiplet_splitting")), f(r["gap_block"]), f(r["Q"]), f(r.get("A")), f(r.get("B")),
                     f(r["A_over_B_minus_1"]),
                     f(c.get("final_residual_best", r.get("residual"))), f(r.get("residual_noise_floor")), f(r["sigma_min_J"]),
                     len(c.get("path", []))])
    out += ["## T1 Solutions (min over sites of psi and N shown; full vectors in the JSON; on C8 the final residual is the record's residual)", "",
            table(["block", "m", "g_M", "g_B", "Lambda", "k", "psi", "N", "E", "d_0", "multiplet splitting", "gap", "Q", "A", "B", "A/B - 1",
                   "final residual (best)", "noise floor", "sigma_min J", "path steps"], rows), ""]
    # T3 lock
    rows = []
    for r in law:
        if "lock" not in r:
            continue
        L = r["lock"]
        dq = L["dQdb"]
        rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(r["k"]), f(L["Q"]), f(dq.get("fd_h1e-03")),
                     f(dq.get("fd_h1e-04")), f(dq.get("implicit")), f(L["R"]), f(L["R_free"]), f(L["R_mat"]), f(L["R_inf"])])
    out += ["## T3 Lock pieces: R = Q + dQ/db at b = 1 (dQ/db by central differences at h = 1e-3, 1e-4 and implicitly), R_free (matter "
            "source frozen), R_mat = R - R_free, R_inf = dE_block/db at N = 1, psi = b 1", "",
            table(["block", "m", "g_M", "g_B", "Lambda", "k", "Q", "dQ/db fd 1e-3", "fd 1e-4", "implicit", "R", "R_free", "R_mat", "R_inf"], rows), ""]
    rows = []
    for r in law:
        if "lock" in r and r["k"] == 1e4:
            L = r["lock"]
            rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(L["R_free"]), f(L["R_mat"]),
                         f(abs(L["R_mat"]) / abs(L["R_free"])) if L["R_free"] else "-"])
    out += ["### T3 read-off for D2(b): R_free, R_mat and |R_mat|/|R_free| at k = 1e4", "",
            table(["block", "m", "g_M", "g_B", "Lambda", "R_free", "R_mat", "|R_mat|/|R_free|"], rows), ""]
    groups = {}
    for r in law:
        groups.setdefault(ckey(r), []).append(r)
    rows, fits = [], {}
    for key, rs in sorted(groups.items()):
        ft = fit_k(rs)
        fits[key] = ft
        if ft:
            r1 = [r for r in rs if "lock" in r and r["k"] == 1.0]
            Eb = r1[0]["lock"]["E_block_flat"] if r1 else None
            Ri = r1[0]["lock"]["R_inf"] if r1 else None
            rows.append(list(key) + [f(ft["a"]), f(ft["c1"]), f(ft["c2"]), f(ft["exponent_100_1e4"]), f(Eb, 6),
                                     f(ft["c1"] / Eb ** 2) if Eb is not None and abs(Eb) > 1e-12 else "-",
                                     f(Ri / Eb) if Eb is not None and abs(Eb) > 1e-12 else "-"])
    out += ["### T3 fits over k in {10, 100, 1e3, 1e4}: R(k) - R_inf = a + c_1/k + c_2/k^2; log-log exponent over k = 100..1e4", "",
            table(["block", "m", "g_M", "g_B", "Lambda", "a", "c_1", "c_2", "exponent", "E_block(1)", "c_1/E_block(1)^2",
                   "R_inf/E_block(1)"], rows), ""]
    rows = []
    for m in (0.1, 0.2, 0.4):
        c10 = fits.get(("1,0", m, 0.0, 0.0, "1"))
        c20 = fits.get(("2,0", m, 0.0, 0.0, "1"))
        c01 = fits.get(("0,1", m, 0.0, 0.0, "1"))
        c21 = fits.get(("2,1", m, 0.0, 0.0, "1"))
        if c10 and c20:
            rows.append([f(m), "(2,0) vs 2 x (1,0) at g = 0", f(c20["c1"]), f(2 * c10["c1"]), f(c20["c1"] - 2 * c10["c1"])])
        if c21 and c10 and c01:
            rows.append([f(m), "(2,1) vs 2 x (1,0) + (0,1) at g = 0", f(c21["c1"]), f(2 * c10["c1"] + c01["c1"]),
                         f(c21["c1"] - 2 * c10["c1"] - c01["c1"])])
        for blk in ("2,0", "2,1", "1,1"):
            b0 = fits.get((blk, m, 0.0, 0.0, "1"))
            for g in ((0.05, 0.0, "1"), (0.2, 1.0, "1"), (0.05, 0.0, "inf")):
                bg = fits.get((blk, m) + g)
                if b0 and bg:
                    rows.append([f(m), "dressing change of c_1 on (%s): (g_M, g_B, Lambda) = (%s, %s, %s) minus g = 0" % ((blk,) + g),
                                 f(bg["c1"]), f(b0["c1"]), f(bg["c1"] - b0["c1"])])
    out += ["### T3 additivity and dressing comparisons of c_1 (the (2,1) comparison uses the (0,1) block, a builder addition)", "",
            table(["m", "comparison", "first", "second", "difference"], rows), ""]
    rows = []
    for blk in ("1,0", "2,0", "2,1", "1,1"):
        for g in ((0.0, 0.0, "1"), (0.05, 0.0, "1"), (0.2, 1.0, "1"), (0.05, 0.0, "inf")):
            pts = [(m, fits.get((blk, m) + g)) for m in (0.1, 0.2, 0.4)]
            pts = [(m, ft["c1"]) for m, ft in pts if ft and ft["c1"] != 0]
            if len(pts) >= 2 and (all(c > 0 for _, c in pts) or all(c < 0 for _, c in pts)):
                ms = np.array([p[0] for p in pts])
                cs = np.abs(np.array([p[1] for p in pts]))
                rows.append([blk] + [str(x) for x in g] + [" ".join(f(c) for _, c in pts), f(np.polyfit(np.log(ms), np.log(cs), 1)[0])])
    out += ["### T3 mass dependence of c_1 (fitted power of |c_1| in m over m = 0.1, 0.2, 0.4)", "",
            table(["block", "g_M", "g_B", "Lambda", "c_1 at m = 0.1, 0.2, 0.4", "power"], rows), ""]
    # C8 route diagnostics (sec. 10)
    rows = []
    for r in law:
        if "sea_rotation_term_max" in r:
            rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(r["k"]), f(r.get("d1_step_agreement_rel")),
                         f(r["sea_rotation_term_max"]), f(r.get("cond_J"))])
    if rows:
        out += ["## C8 route (sec. 10): fixed-Fock-vector derivative step agreement (h 1e-4 against 1e-5, relative), the sea-rotation term "
                "max |t_fixed Fock - t_fixed coefficients aligned|, cond(J)", "",
                table(["block", "m", "g_M", "g_B", "Lambda", "k", "step agreement", "sea-rotation term", "cond J"], rows), ""]
    # T4
    rows = []
    for r in law:
        if "lock" in r and r["k"] == 1.0:
            e = r["lock"]["E_block_derivs"]
            E1 = r["lock"]["E_block_flat"]
            rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(E1, 6), f(e.get("dEdb_h1e-03")),
                         f(e.get("dEdb_h1e-04")), f(e.get("d2Edb2_h1e-03")), f(e.get("d2Edb2_h1e-04")),
                         f(e.get("dEdb_h1e-04") / E1) if E1 else "-"])
    out += ["## T4 Uniform-dilation derivatives of the block's lowest energy at N = 1 (k-independent; from the k = 1 rows)", "",
            table(["block", "m", "g_M", "g_B", "Lambda", "E_block(1)", "dE/db h 1e-3", "h 1e-4", "d2E/db2 h 1e-3", "h 1e-4",
                   "d log E/d log b (h 1e-4; D3)"], rows), ""]
    # T2 enclosure when present
    rows = []
    for r in law:
        enc = r.get("enclosure")
        if enc:
            gm = enc.get("gap_minus_r_hessian", {})
            best_gap = max([float(x) for x, v in gm.items() if v > 0 and enc["radii"].get(x, {}).get("passed")], default=None)
            rows.append([r["block"], f(r["m"]), f(r["gM"]), f(r["gB"]), lam(r), f(r["k"]), f(enc["Y_F"]), f(enc["norm_Y"]),
                         " ".join("%s:%s" % (x, "pass" if v["passed"] else "fail") for x, v in enc["radii"].items()), f(enc["D2F_estimate"]),
                         f(enc.get("largest_passing_r_in_domain")), f(best_gap),
                         "%s/%s" % (r.get("uniqueness", {}).get("distinct_positive", "-"), r.get("uniqueness", {}).get("negative_converged", "-"))])
    if rows:
        out += ["## T2 Enclosure (sampled, numerical; reduced map) and uniqueness (distinct positive / negative converged of 20 starts)", "",
                table(["block", "m", "g_M", "g_B", "Lambda", "k", "||Y F||", "||Y||", "test per r", "||D^2 F||",
                       "largest r passing (domain)", "largest r passing with gap - r ||D^2 F|| > 0", "uniqueness"], rows), ""]
    # native control
    rows = []
    for r in nat:
        if "lock" in r:
            L = r["lock"]
            rows.append([r["q"], f(r["m"]), f(r["U"]), f(r["k"]), f(min(r["psi"]), 6), f(min(r["N"]), 6), f(r["E"], 6), r["d0"], f(L["Q"]),
                         f(L["R"]), f(L["R_free"]), f(L["R_mat"]), f(L["R_inf"]), f(r["continuation"].get("final_residual_best"))])
        else:
            rows.append([r.get("q"), f(r.get("m")), f(r.get("U")), f(r.get("k")), "not converged"] + ["-"] * 9)
    if rows:
        out += ["## Control (sec. 11.3): the native scalar source e_x^nat(s) in the same commuting row (block = the whole sector q)", "",
                table(["q", "m", "U", "k", "s", "N", "E", "d_0", "Q", "R", "R_free", "R_mat", "R_inf", "final residual"], rows), ""]
        ng = {}
        for r in nat:
            if "lock" in r:
                ng.setdefault((r["q"], r["m"], r["U"]), []).append(r)
        rows = []
        for key, rs in sorted(ng.items()):
            ft = fit_k(rs)
            if ft:
                rows.append([key[0], f(key[1]), f(key[2]), f(ft["a"]), f(ft["c1"]), f(ft["c2"]), f(ft["exponent_100_1e4"])])
        out += ["### Control fits over k in {10, 100, 1e3, 1e4}: R(k) - R_inf = a + c_1/k + c_2/k^2 for the native scalar row", "",
                table(["q", "m", "U", "a", "c_1", "c_2", "exponent"], rows), ""]
    if var:
        rows = [[v["file"], " ".join(f(x, 6) for x in v["mean_S"]), " ".join(f(x) for x in v["variance_S"])] for v in var]
        out += ["## Control (sec. 11.3): per-site ruler mean and variance <S_x^2> - <S_x>^2 in the lowest state of the native operator solutions "
                "(strand 0 full_v3/mats)", "", table(["solution file", "<S_x>", "variance"], rows), ""]
    b = baseline_rows(a.baseline)
    if b:
        out += ["## Strand 1 baseline (native action, U = 0; parsed from the committed k-scan table, not retyped)", "",
                table(["promotion", "m", "q", "form", "eig", "exponent", "a", "b (1/k coefficient)", "c", "k x remainder at 1e4"], b), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
