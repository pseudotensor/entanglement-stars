#!/usr/bin/env python
"""Strand 2c report (builder analyst): tables T1-T4 and controls C1-C6 of SPEC_strand2c_mismatch.md from
strand2c_mismatch_v2.py's mismatch_L<L>.json (run2; P1, P3, k_a(q)) and strand2c_mismatch_v3.py's mismatch_P2_L<L>.json (P2
runs), plus the GPU-against-CPU check at L = 4.  The lattice spacing is a = 1, so aH = H.  Numbers emitted, not retyped;
no physics reading.
(version 3: control C3' from the saved fields: sum_x w_x/psi_x, which vanishes identically when E_s1 and E_s0 are isospectral
(sum_x w_x/psi_x = sum_s eta_s Tr(E_s1 - E_s0)); for P1 it fixes the leak at -(sum of w on I)/(1 + eps).  Version 2 was an
unmodified copy of version 1 (a failed patch) and was removed)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def fl(vs, sig=4):
    return " ".join(f(v, sig) for v in vs)


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def fit_power(H, y):
    """log y = log a + p log H; returns a, p, relative residual."""
    H, y = np.asarray(H, float), np.abs(np.asarray(y, float))
    if len(H) < 2 or np.any(y <= 0):
        return None
    p, la = np.polyfit(np.log(H), np.log(y), 1)
    pred = np.exp(la) * H ** p
    return {"a": float(np.exp(la)), "p": float(p), "res": float(np.linalg.norm(pred - y) / np.linalg.norm(y))}


def fit_h2log(H, y):
    """y = a H^2 log H + b H^2; returns a, b, relative residual."""
    H, y = np.asarray(H, float), np.asarray(y, float)
    if len(H) < 2:
        return None
    A = np.column_stack([H ** 2 * np.log(H), H ** 2])
    c = np.linalg.lstsq(A, y, rcond=None)[0]
    return {"a": float(c[0]), "b": float(c[1]), "res": float(np.linalg.norm(A @ c - y) / max(np.linalg.norm(y), 1e-300))}


def fit_trend(H, y):
    """y = a + b H^2 log H; returns a, b, relative residual of y - a."""
    H, y = np.asarray(H, float), np.asarray(y, float)
    A = np.column_stack([np.ones_like(H), H ** 2 * np.log(H)])
    c = np.linalg.lstsq(A, y, rcond=None)[0]
    return {"a": float(c[0]), "b": float(c[1]), "res": float(np.linalg.norm(A @ c - y) / max(np.linalg.norm(y - c[0]), 1e-300))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="run2 dir (mismatch_L<L>.json, npz, check_gpu, check_cpu)")
    ap.add_argument("--p2", nargs="*", default=[], help="P2 run dirs (mismatch_P2_L<L>.json)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    runs = {}
    for p in sorted(glob.glob(os.path.join(a.run, "mismatch_L*.json"))):
        r = json.load(open(p))
        runs[r["meta"]["L"]] = r
    for d in a.p2:
        for p in sorted(glob.glob(os.path.join(d, "mismatch_P2_L*.json"))):
            r = json.load(open(p))
            runs.setdefault(r["meta"]["L"], {"meta": r["meta"], "controls": {}, "kq": [], "profiles": []})
            runs[r["meta"]["L"]]["profiles"] += r["profiles"]
    Ls = sorted(runs)
    out = ["# Strand 2c tables (generated by solve/code/strand2/strand2c_report_v1.py)", ""]
    # controls
    rows = []
    for L in Ls:
        c = runs[L]["controls"]
        for key in sorted(k for k in c if k.startswith("H")):
            cc = c[key]
            rows.append([L, key[1:], f(cc.get("C2_max_w_flat")), f(cc.get("C2_W0_flat")), f(cc.get("C3_isospectral_max")),
                         f(cc.get("C4_sum_rule")), f(cc.get("J"), 8), f(cc.get("k_lat"), 8)])
    out += ["## Controls C2-C4 at the uniform background (per box L and heavy mass H; C3 computed at L <= 12)", "",
            table(["L", "H", "C2 max abs w (flat)", "C2 W_0 (flat)", "C3 max isospectral defect", "C4 sum rule", "J", "k_lat"], rows), ""]
    rows = []
    for L in Ls:
        c = runs[L]["controls"]
        eul = [p["euler_minus_trace"] for p in runs[L]["profiles"]] + [k["euler_minus_trace"] for k in runs[L]["kq"]]
        rows.append([L, f(c.get("D_hermitian")), f(c.get("C6_lap_plane_wave")), f(max(eul) if eul else None), len(eul)])
    out += ["## Controls C1 (Euler: max over records of |sum_x N_x w_x - sum_s eta_s Tr L (E_s1 - E_s0)|) and C6 (periodic Laplacian on "
            "a plane wave)", "", table(["L", "||D - D^dag||", "C6 max error", "C1 max Euler defect", "records"], rows), ""]
    gj, cj = os.path.join(a.run, "check_gpu", "mismatch_L4.json"), os.path.join(a.run, "check_cpu", "mismatch_L4.json")
    if os.path.exists(gj) and os.path.exists(cj):
        G, Cc = json.load(open(gj)), json.load(open(cj))
        rows = []
        for pg, pc in zip(G["profiles"], Cc["profiles"]):
            dw = max(abs(x - y) for x, y in zip(pg.get("w_I", [0]), pc.get("w_I", [0]))) if "w_I" in pg else None
            rows.append([pg["profile"], f(pg["H"]), f(abs(pg["W0"] - pc["W0"])), f(dw)])
        for kg, kc in zip(G["kq"], Cc["kq"]):
            rows.append(["k_a(q)", f(kg["H"]), f(abs(kg["W0_psi"] - kc["W0_psi"])), "-"])
        out += ["## GPU against CPU at L = 4 (same script, --gpu 0 against --gpu -1)", "",
                table(["profile", "H", "|W_0 gpu - W_0 cpu|", "max |w_I gpu - w_I cpu|"], rows), ""]
    # C3' field-level sum rule from the saved npz fields
    rows = []
    dirs = [a.run] + list(a.p2)
    for L in Ls:
        worst, worst_name, cnt = 0.0, "-", 0
        for p in runs[L]["profiles"]:
            for d in dirs:
                z = os.path.join(d, "w_L%d_%s_H%g.npz" % (L, p["profile"], p["H"]))
                if os.path.exists(z):
                    Z = np.load(z)
                    v = abs(float(np.sum(Z["w"] / Z["psi"])))
                    rel = v / max(float(np.sum(np.abs(Z["w"]))), 1e-300)
                    cnt += 1
                    if rel >= worst:
                        worst, worst_name = rel, "%s H %g (|sum| %s)" % (p["profile"], p["H"], f(v))
                    break
        rows.append([L, cnt, f(worst), worst_name])
    out += ["## Control C3' (field level): |sum_x w_x/psi_x| relative to sum_x |w_x| (zero by isospectrality); max over the saved fields", "",
            table(["L", "fields", "max relative", "at"], rows), ""]
    # T1
    rows = []
    trend = {}
    for L in Ls:
        for k in runs[L]["kq"]:
            rows.append([L, f(k["H"]), f(k["k_lat"], 6), f(k["k_a_qlat"], 6), f(k["k_a_q2"], 6), f(k["ratio_k_a_qlat"], 6),
                         f(k["k_a_q2"] / k["k_lat"], 6), f(k["mixed_qlat"], 6), f(k["ratio_mixed_qlat"], 6),
                         f(k["mixed_qlat"] / k["k_a_qlat"], 6), f(k["euler_minus_trace"])])
            trend.setdefault(L, []).append((k["H"], k["ratio_k_a_qlat"], k["ratio_mixed_qlat"]))
    out += ["## T1 The two-derivative coefficient: k_a(q) = -2 W_0/(eps^2 q_lat^2 L^3) (and with q^2), the mixed coefficient "
            "-W_0^mixed/(eps eps_N q_lat^2 L^3), against k_lat = 3J/pi^2 (q = 2 pi/L, eps = eps_N = 1e-3)", "",
            table(["L", "H", "k_lat", "k_a (q_lat^2)", "k_a (q^2)", "k_a/k_lat (q_lat^2)", "k_a/k_lat (q^2)", "mixed (q_lat^2)",
                   "mixed/k_lat", "mixed/k_a", "Euler defect"], rows), ""]
    rows = []
    for L in Ls:
        t = trend.get(L)
        if t and len(t) >= 2:
            H = [x[0] for x in t]
            for name, idx in (("k_a/k_lat", 1), ("mixed/k_lat", 2)):
                ft = fit_trend(H, [x[idx] for x in t])
                rows.append([L, name, fl(H), fl([x[idx] for x in t], 6), f(ft["a"], 6), f(ft["b"]), f(ft["res"])])
    out += ["### T1 trend in H at fixed L: ratio = a + b H^2 log H (3 points, 2 parameters; residual relative to |ratio - a|)", "",
            table(["L", "ratio", "H", "values", "a", "b", "relative residual"], rows), ""]
    # T2 interior profiles
    prof = {}
    for L in Ls:
        for p in runs[L]["profiles"]:
            prof.setdefault(p["profile"], {}).setdefault(L, {})[p["H"]] = p
    rows, rows3 = [], []
    for name in sorted(prof):
        for L in sorted(prof[name]):
            for H in sorted(prof[name][L], reverse=True):
                p = prof[name][L][H]
                if "w_I" in p:
                    rows.append([name, L, f(H), fl(p["w_I"]), fl(p["installed_I"]), fl(p["DeltaC_I"]), f(np.linalg.norm(p["DeltaC_I"])),
                                 f(p["rel_DeltaC"]), f(p["leak"]), f(p["interior_sum_w"]),
                                 f(p["leak"] / p["interior_sum_w"]) if p["interior_sum_w"] else "-", f(p["W0"], 8), f(p["euler_minus_trace"])])
                    rows3.append([name, L, f(H), " ".join("%s:%s/%s" % (f(sh["distance"], 3), sh["count"], f(sh["sum_w"])) for sh in p["shells"])])
    out += ["## T2 Interior profiles (P1 and P2): w_x on I, the installed row -k_lat psi_x [K_I (psi - 1)]_x, Delta C_x = w_x - installed, "
            "the leak (sum of w outside I) and W_0", "",
            table(["profile", "L", "H", "w on I", "installed on I", "Delta C on I", "||Delta C||_2", "||Delta C||/||w|| on I", "leak",
                   "sum of w on I", "leak / sum on I", "W_0", "Euler defect"], rows), "",
            "### T2 exterior profile: shells by distance from I (distance:count/sum of w over the shell), first 6 shells", "",
            table(["profile", "L", "H", "shells"], rows3), ""]
    rows = []
    for name in sorted(prof):
        if 12 in prof[name] and 16 in prof[name]:
            for H in sorted(prof[name][16], reverse=True):
                p16, p12 = prof[name][16].get(H), prof[name][12].get(H)
                if p16 and p12 and "w_I" in p16:
                    w16, w12 = np.array(p16["w_I"]), np.array(p12["w_I"])
                    rows.append([name, f(H), f(np.max(np.abs(w16 - w12)) / max(np.max(np.abs(w16)), 1e-300)),
                                 f(abs(p16["leak"] - p12["leak"]) / max(abs(p16["leak"]), 1e-300)), f(abs(p16["W0"] - p12["W0"]) / max(abs(p16["W0"]), 1e-300))])
    out += ["## C5 Box convergence (L = 12 against L = 16): max relative change of w on I, relative change of the leak and of W_0", "",
            table(["profile", "H", "w on I", "leak", "W_0"], rows), ""]
    # P3
    rows = []
    for L in Ls:
        for p in runs[L]["profiles"]:
            if p["profile"] == "P3_bump":
                z = os.path.join(a.run, "w_L%d_P3_bump_H%g.npz" % (L, p["H"]))
                nw = float(np.linalg.norm(np.load(z)["w"])) if os.path.exists(z) else None
                rows.append([L, f(p["H"]), f(p["w_centre"]), f(p["installed_centre_literal"]), f(p["rel_DeltaC_literal"]),
                             f(p["rel_DeltaC_alt_sign"]), f(p["max_abs_w"]), f(p["sum_w"]), f(nw), f(p["W0"], 8), f(p["euler_minus_trace"])])
    out += ["## T2 P3 smooth bump psi = 1 + 0.2 exp(-|x - x_c|^2/4) over the box; installed row -k_lat psi Lap(psi - 1) (literal sign) and "
            "+k_lat psi Lap(psi - 1) (the sign with K_I <-> -Lap, flagged by the builder)", "",
            table(["L", "H", "w at centre", "installed at centre (literal)", "||Delta C||/||w|| literal", "alternative sign", "max |w|",
                   "sum of w", "||w||_2", "W_0", "Euler defect"], rows), ""]
    # T3
    rows = []
    for name in sorted(prof):
        for L in sorted(prof[name]):
            for H in sorted(prof[name][L], reverse=True):
                p = prof[name][L][H]
                if p.get("source_2b_I"):
                    s = np.array(p["source_2b_I"], float)
                    dC = np.array(p["DeltaC_I"])
                    rows.append([name, p.get("case_2b"), L, f(H), fl(s), fl(dC), fl(dC / s)])
    if rows:
        out += ["## T3 Delta C_x against the 2b matter source s_x = Tr(rho rho^P_x) at the same site (P2 profiles)", "",
                table(["profile", "2b case", "L", "H", "source on I", "Delta C on I", "Delta C / source"], rows), ""]
    # T4
    rows = []
    for name in sorted(prof):
        for L in sorted(prof[name]):
            Hs = sorted(prof[name][L])
            if len(Hs) < 2:
                continue
            if "DeltaC_I" in prof[name][L][Hs[0]]:
                y = [np.linalg.norm(prof[name][L][H]["DeltaC_I"]) for H in Hs]
                lk = [prof[name][L][H]["leak"] for H in Hs]
            else:
                y, lk = [], []
                for H in Hs:
                    z = os.path.join(a.run, "w_L%d_P3_bump_H%g.npz" % (L, H))
                    if not os.path.exists(z):
                        break
                    y.append(prof[name][L][H]["rel_DeltaC_literal"] * float(np.linalg.norm(np.load(z)["w"])))
                if len(y) != len(Hs):
                    continue
            fp, fh = fit_power(Hs, y), fit_h2log(Hs, y)
            fpl = fit_power(Hs, lk) if lk else None
            rows.append([name, L, fl(Hs), fl(y), f(fp["a"]) if fp else "-", f(fp["p"]) if fp else "-", f(fp["res"]) if fp else "-",
                         f(fh["a"]), f(fh["b"]), f(fh["res"]), fl(lk) if lk else "-", f(fpl["p"]) if fpl else "-", f(fpl["res"]) if fpl else "-"])
    out += ["## T4 Scaling with aH (a = 1): ||Delta C||_2 on I (P3: over the box, literal sign) against H in {1, 0.5, 0.25}: fits a H^p and "
            "a H^2 log H + b H^2 (3 points; relative residuals); the leak's power likewise", "",
            table(["profile", "L", "H", "||Delta C||", "a (power fit)", "p", "residual", "a (H^2 log H)", "b (H^2)", "residual", "leak",
                   "leak power", "residual"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
