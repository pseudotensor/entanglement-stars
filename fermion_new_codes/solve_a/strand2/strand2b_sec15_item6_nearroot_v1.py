#!/usr/bin/env python
"""Strand 2b sec. 15 item 6 addendum (builder analyst): from the driver v13 (R4) and v7 (cube) case records, per case whose uniqueness
scan accepted no start, or whose scan has rejected starts that returned within 1e-12 of the continuation solution: the number of such
near-root rejected starts, their stop reasons, the range of their own residuals, the case's residual noise floor and the acceptance
threshold 1e-11 against it.  Numbers emitted, not retyped."""
import argparse
import glob
import json
import os

ACCEPT = 1e-11
NEAR = 1e-12


def f(v):
    return "-" if v is None else "%.2e" % v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dirs", required=True, help="comma-separated case-record folders (pass2v13, c8encl_v7)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    rows, summ = [], []
    for d in a.dirs.split(","):
        n_cases = n_with = n_near = 0
        for p in sorted(glob.glob(os.path.join(d, "case_*.json"))):
            r = json.load(open(p))
            u = r.get("uniqueness") or {}
            st = u.get("starts_record") or []
            n_cases += 1
            near = [x for x in st if (not x.get("ok")) and x.get("distance_to_reference") is not None and x["distance_to_reference"] < NEAR]
            acc = sum(1 for x in st if x.get("ok"))
            if not near and acc > 0:
                continue
            n_with += 1 if near else 0
            n_near += len(near)
            stops = {}
            for x in near:
                stops[x["stop"]] = stops.get(x["stop"], 0) + 1
            res = [x["own_residual"] for x in near if x.get("own_residual") is not None]
            nf = r.get("residual_noise_floor")
            rows.append("| %s | %s | %d | %d | %d | %s | %s to %s | %s | %s |" % (
                os.path.basename(d), os.path.basename(p).replace("case_", "").replace(".json", ""), len(st), acc, len(near),
                "; ".join("%s %d" % kv for kv in sorted(stops.items())) or "-", f(min(res)) if res else "-", f(max(res)) if res else "-", f(nf),
                ("below" if (nf is not None and ACCEPT < nf) else "above") if nf is not None else "-"))
        summ.append("%s: %d cases; %d with rejected starts within %g of the continuation solution (%d such starts in all); the rows below "
                    "list those cases and every case with no accepted start." % (os.path.basename(d), n_cases, n_with, NEAR, n_near))
    out = ["# Strand 2b sec. 15 item 6: the rejected starts at the continuation solution (generated by solve/code/strand2/strand2b_sec15_item6_nearroot_v1.py)",
           "", "## S Summary (emitted)", ""] + ["- " + s for s in summ] + [
        "", "## I6f Per case: starts, accepted, rejected starts within 1e-12 of the continuation solution, their stops and own residuals, the case's "
            "residual noise floor, and the acceptance threshold 1e-11 against that floor", "",
        "| record | case | starts | accepted | rejected within 1e-12 | their stops | their own residuals | noise floor | 1e-11 against the floor |",
        "|---|---|---|---|---|---|---|---|---|"] + rows
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("\n".join(rows))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
