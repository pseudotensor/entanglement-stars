#!/usr/bin/env python
"""Strand 4 Part B report (builder analyst): tables from strand4_partB1_v1.py's partB1.json (B.1 reproduction, B.2 the variable
asymptotic ruler) and strand4_partB3_v1.py's partB3.json (B.3 the dilation family's transport checks; B.4 the pieces per step and
Richardson; the direct total against R_stat + S_inf).  The pieces are reported as computed; no combination beyond the identity
Total = R_stat + S_inf, which holds by construction of the family, is formed.  [paper, control]  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--b1", required=True)
    ap.add_argument("--b3", default="")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    P1 = json.load(open(a.b1))
    out = ["# Strand 4 Part B tables (generated by solve/code/strand4/strand4_partB_report_v1.py)", "",
           "G_0 = %s, T_s = %s." % (f(P1["meta"]["G"], 8), f(P1["meta"]["Ts"])), ""]
    rows = []
    for s in P1["states"]:
        rows.append([s["state"], s["Ns"], f(s["NB"], 8), f(s["E_rows_max_abs_diff"]), f(s["D_rows_max_abs_diff"]),
                     "%s / %s" % (f(s["A_ext"], 10), f(s["A_stored"], 10)), "%s / %s" % (f(s["B_ext"], 10), f(s["B_stored"], 10)),
                     "%s / %s" % (f(s["A_over_B_minus_1"], 8), f(s["A_over_B_minus_1_stored"], 8)),
                     "%s / %s / %s" % (f(s["MA_sum"], 10), f(s["MA_ext"], 10), f(s["MA_stored"], 10)),
                     "%s / %s / %s" % (f(s["MB_sum"], 10), f(s["MB_ext"], 10), f(s["MB_stored"], 10)),
                     "%s / %s / %s" % (f(s["Dlat_ext"], 10), f(s["Dlat_sum"], 10), f(s["Dlat_rows"], 10)),
                     f(s["A_K_charge"], 10), f(s["E_ret_over_E_partial_minus_1"])])
    out += ["## B1 Reproduction at the stored states (the paper's chain re-evaluated at the stored fields)", "",
            table(["state", "N_s", "N_B", "max |E row - stored|", "max |D row - stored|", "A (exterior / stored)", "B (exterior / stored)",
                   "A/B - 1 (computed / stored)", "M_A (sum / exterior / stored)", "M_B (sum / exterior / stored)", "D_lat (exterior / sums / rows)",
                   "charge 1^T K u/(4 pi)", "E_ret/E_partial - 1"], rows), ""]
    rows = [[s["state"], f(s["B2_closed"], 12), f(s["B2_fd"], 12), f(s["B2_target_A_minus_B_over_G"], 12), f(s["B2_closed_minus_target"]),
             f(s["B2_fd_minus_target"])] for s in P1["states"]]
    out += ["## B2 The variable asymptotic ruler: (1/2) dF_g^a/ds_inf at s_inf = 1, closed form (k/2) 1^T K [(s - 1) + (n s - 1)] and central "
            "difference, against (A - B)/G_0", "",
            table(["state", "closed form", "central difference", "(A - B)/G_0", "closed - target", "difference - target"], rows), ""]
    if a.b3:
        P3 = json.load(open(a.b3))
        rows, rowsP, rowsR = [], [], []
        for s in P3["states"]:
            for h, st in s["steps"].items():
                rows.append([s["state"], h, f(st["NB_change"]), f(st["Socc_change"]), f(s["fields_lam1_max_dev"]), f(s["E_mat_minus_E_exc"])])
                rowsP.append([s["state"], h, f(st["D_vac"], 10), f(st["D_boundary_term"], 8), f(st["D_mat"], 10),
                              " ".join(f(st["D_mat_terms"][t], 8) for t in ("mass", "radial", "angular", "E2")),
                              " ".join(f(st["D_mat_dressing_tables"][t], 8) for t in ("mass", "radial", "angular")),
                              " ".join(f(st["D_mat_fixed_covariance"][t], 8) for t in ("mass", "radial", "angular", "E2")),
                              f(st["R_stat"], 10), f(s["S_inf"], 10), f(st["Total"], 10), f(st["Total_minus_R_stat_minus_S_inf"])])
            r = s["richardson"]
            rowsR.append([s["state"], f(r["D_vac"], 10), f(r["D_boundary_term"], 8), f(r["D_mat"], 10),
                          " ".join(f(r["D_mat_terms"][t], 8) for t in ("mass", "radial", "angular", "E2")),
                          " ".join(f(r["D_mat_dressing_tables"][t], 8) for t in ("mass", "radial", "angular")),
                          f(r["R_stat"], 10), f(s["S_inf"], 10), f(r["Total"], 10), f(r["Total"] - r["R_stat"] - s["S_inf"]),
                          f(s["A_minus_B_over_G"], 10), f(r["D_vac"] + s["A_minus_B_over_G"], 8)])
        out += ["## B3 The transport: changes of N_B = Tr X and S_occ along the family (largest over lam = 1 +- h), the fields at lam = 1 "
                "against the stored ones, and E_mat at lam = 1 against B.1's E_exc,ret", "",
                table(["state", "h", "max |N_B change|", "max |S_occ change|", "fields at lam = 1: max |dev|", "E_mat(1) - E_exc,ret"], rows), "",
                "## B4 The pieces per step (central differences in lam): D_vac = dF_g(lam; 1)/dlam, the boundary term's share, D_mat by term "
                "(mass, radial hopping, angular, E2), the dressing tables' share (the same with kappa_L, mu_L frozen), the fields-only part "
                "(covariance fixed), R_stat = D_vac + D_mat, S_inf = (1/2) dF_g(1; sigma)/dsigma, the direct total d/dlam [F_g(lam; lam^(1/2)) "
                "+ E_mat(lam)] and Total - R_stat - S_inf", "",
                table(["state", "h", "D_vac", "boundary term", "D_mat", "D_mat: mass, radial, angular, E2", "tables' share: mass, radial, angular",
                       "fields only: mass, radial, angular, E2", "R_stat", "S_inf", "Total", "Total - R_stat - S_inf"], rowsP), "",
                "## B4 Richardson (100 J(1e-4) - J(1e-3))/99, with (A - B)/G_0 and D_vac + (A - B)/G_0 beside", "",
                table(["state", "D_vac", "boundary term", "D_mat", "D_mat: mass, radial, angular, E2", "tables' share: mass, radial, angular",
                       "R_stat", "S_inf", "Total", "Total - R_stat - S_inf", "(A - B)/G_0", "D_vac + (A - B)/G_0"], rowsR), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
