#!/usr/bin/env python
"""Strand 4 Part A report (builder analyst): tables A0 (controls) and A1 (jets, target ratios, xi) from strand4_partA_v1.py's
partA_L<L>_m0<m0>_<dict>.json files.  [paper, control]  Numbers emitted, not retyped; no reading.
(version 2, the lead's post-processing after the reviewer B red team: the kernel-normalized screening length xi^2 = (J_ss(0)/(2 J_ss(q)) - 1)/q_lat^2
(the cosine modes have squared norm L^3/2 against the uniform profile's L^3, so a local kernel gives J(q) = J(0)/2) from the jets in the JSON,
beside version 1's (J_ss(0)/J_ss(q) - 1)/q_lat^2, which is labelled as such)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, (list, tuple)) and len(v) == 2:
        v = complex(v[0], v[1])
    if isinstance(v, complex):
        return "%s%+.3ei" % (f(v.real, sig), v.imag) if abs(v.imag) > 1e-14 else f(v.real, sig)
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def qname(q, L):
    n = int(round(q * L / (2 * np.pi)))
    return "0" if n == 0 else "%d x 2 pi/L" % n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.run, "partA_L*.json")))
    D = [json.load(open(p)) for p in files]
    out = ["# Strand 4 Part A tables [paper, control] (generated by solve/code/strand4/strand4_partA_report_v2.py)", ""]
    rows = []
    for d in D:
        m = d["meta"]
        for lev, x in d["levels"].items():
            fl = x["flat"]
            rows.append([m["L"], f(m["m0"], 8), m["dict"], lev, fl["it"], f(fl["resid"]), f(fl["gap"]), f(fl["E_wick_per_site"], 10),
                         f(fl["uniform_q_star"], 8), f(fl["uniform_m_fock"], 8), f(max(fl["diff_E_hs"], fl["diff_E_wick"])),
                         f(max(fl["diff_sigma"], fl["diff_b"])), f(fl["diff_gap"]), f(x["affinity"]["E_hs"]), f(x["affinity"]["E_wick"]),
                         f(max(p["resid"] for p in x["points"]))])
    out += ["## A0 Controls: the flat point against hf_closure_3d.uniform_solve (same L, twist 0); affinity E(1.1 N) - 1.1 E(N); the "
            "largest self-consistency residual over the stencil", "",
            table(["L", "m0", "dict", "level", "it", "resid", "gap", "E_Wick per site", "q_* (uniform)", "m_Fock (uniform)",
                   "|dE| vs uniform", "|d sigma|, |d b|", "|d gap|", "affinity E_HS", "affinity E_Wick", "max stencil resid"], rows), "",
            "Slater quadratic check of the free part (central difference at 1e-4 against the second-order sum): " +
            "; ".join("L %d: fd %s, analytic %s" % (d["meta"]["L"], f(d["quadratic_check"]["fd"], 10), f(d["quadratic_check"]["analytic"], 10))
                      for d in D if d["meta"]["dict"] == "spec" and abs(d["meta"]["m0"] - 0.3) < 1e-9), ""]
    for d in D:
        m = d["meta"]
        L = m["L"]
        rows, rows3 = [], []
        for lev, x in d["levels"].items():
            for s in x["summary"]:
                for fn in ("sus_hs", "sus_wick", "prep_wick", "prep_hs"):
                    J, G = s[fn], s[fn + "_agree"]
                    rt = s.get(fn + "_ratio_to_target", {})
                    xi2 = s.get(fn + "_xi2")
                    s0 = [t for t in x["summary"] if abs(t["q"]) < 1e-12]
                    J0 = s0[0][fn]["ss"] if s0 else None
                    xi2k = ((J0 / (2 * J["ss"]) - 1) / s["q_lat2"]) if (J0 is not None and J["ss"] != 0 and s["q_lat2"] > 0) else None
                    rows.append([lev, qname(s["q"], L), fn, f(J["NN"]), f(J["Ns"]), f(J["ss"]), f(J["dN"]), f(J["ds"]),
                                 f(s["target"]["Ns"]), f(s["target"]["ss"]), f(rt.get("Ns")), f(rt.get("ss")),
                                 f(xi2k), f(np.sqrt(xi2k)) if xi2k is not None and xi2k > 0 else "-", f(xi2),
                                 " ".join("%s %s" % (k, f(G[k])) for k in ("NN", "Ns", "ss"))])
                rows3.append([lev, qname(s["q"], L), " ".join(f(v) for v in s["C3_prep_wick_minus_sus_wick_eigs"]),
                              " ".join(f(v) for v in s["C3_prep_hs_minus_sus_hs_eigs"])])
        out += ["## A1 L = %d, m0 = %s, dictionary %s: jets (Richardson over h = 1e-3, 1e-4), the selected functional's target "
                "-k [[0, K], [K, 2K]] (k = 1/(2 pi G_0), G_0 = 0.2745414, K = -Laplacian), ratios, and the kernel-normalized xi^2 = (J_ss(0)/(2 J_ss(q)) - 1)/q_lat^2 "
                "(version 1's (J_ss(0)/J_ss(q) - 1)/q_lat^2 beside it, labelled)"
                % (L, f(m["m0"], 8), m["dict"]), "",
                table(["level", "q", "functional", "NN", "Ns", "ss", "dE/dlam_N", "dE/dlam_s", "target Ns", "target ss", "Ns/target",
                       "ss/target", "xi^2 (kernel-normalized)", "xi (kernel-normalized)", "xi^2 (version 1 formula)", "step agreement"], rows), "",
                "### C3 eigenvalues of J^prep - J^sus", "", table(["level", "q", "prep_wick - sus_wick", "prep_hs - sus_hs"], rows3), ""]
    out += ["Paper's printed comparison values (06_hda_einstein lines 174, 176 and 225, quoted, not computed here): xi = 0.58 a; the scale gap "
            "2/U_B; the auxiliary self-Hessian 6.225; Zhat/What 0.71 and 0.88. The auxiliary-field Hessian and Zhat/What are not exposed by "
            "hf_closure_3d.py and are not computed here.", ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
