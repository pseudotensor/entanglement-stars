#!/usr/bin/env python
"""Strand 4 Part B audit report (builder analyst): tables from strand4_partB_audit_v1.py's partB_audit.json: B1'' the three-way D_lat,
the charge and E_ret/E_partial at every stored state; B6 the one-state audit at the 0.1 maximum (the paper's dressing-residual expression on
the reconstruction beside the stored value; the replace-by-1 share split into its explicit and orbital parts; the frozen-at-stored share),
per term and in total, per consecutive step pair.  [paper, control]  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    out = ["# Strand 4 Part B audit tables (generated by solve/code/strand4/strand4_partB_audit_report_v1.py)", ""]
    rows = [[r["state"], r["Ns"], f(r["Dlat_exterior"], 12), f(r["Dlat_sums"], 12), f(r["Dlat_rows"], 12), f(r["A"], 12), f(r["A_K_charge"], 12),
             f(r["E_ret_over_E_partial_minus_1"])] for r in R["B1_all"]]
    out += ["## B1'' D_lat three ways, the charge against A and E_ret/E_partial - 1 at every stored state", "",
            table(["state", "N_s", "D_lat (exterior)", "D_lat (source sums)", "D_lat (rows)", "A", "charge 1^T K u/(4 pi)", "E_ret/E_partial - 1"], rows), ""]
    A = R["audit"]
    if A:
        out += ["## B6 The one-state audit at the 0.1 maximum (N_c %s)" % f(A["Nc"], 10), "",
                "(a) The paper lane's printed dressing-residual dilation defect is the expression 0.5 sum_n m_* N_n sz_n psi_n dmu_L(psi_n) of "
                "dev30_tails_virial.py (fixed covariance). On the reconstructed state it is %s; the stored value (stage2_members.json, tails_virial "
                "entry at N_c %s) is %s; D_lat = %s." % (f(A["paper_dressing_residual_expression_on_reconstruction"], 13), f(A["stored_Nc"], 10),
                                                       f(A["stored_dilation_defect"], 13), f(A["D_lat_exterior"], 10)), ""]
        rows = []
        for pr, r in A["richardson_pairs"].items():
            for grp in ("share_replace_by_1", "explicit_fixed_covariance", "orbital_work", "share_frozen_at_stored"):
                g = r[grp]
                rows.append([pr, grp, f(g["mass"], 8), f(g["radial"], 8), f(g["angular"], 8), f(g["total"], 8)])
        out += ["(b), (c) The tables' shares of D_mat per step pair (Richardson): the replace-by-1 share, its explicit part (fields dilated, "
                "covariance held at lam = 1) and its orbital part (the difference), and the share with the tables frozen at their stored "
                "spatial profiles", "", table(["step pair", "share", "mass (mu_L)", "radial (kappa_L at psibar)", "angular (kappa_L)", "total"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
