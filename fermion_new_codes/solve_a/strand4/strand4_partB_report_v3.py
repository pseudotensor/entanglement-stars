#!/usr/bin/env python
"""Strand 4 Part B report, version 2 (builder analyst): tables from strand4_partB1_v1.py's partB1.json (B.1, B.2 at the two 0.1 states)
and strand4_partB3_v2.py's partB3_v2.json (every stored state), in the form of the lead's ruling (SPEC_strand4_controls.md, "Ruling on
the Part B identity"): D_lat = (A - B)/G_0 = Total - R_stat = [D_vac + S_inf] + D_mat - R_stat, every piece from its own derivative,
the closures not fits.  [paper, control]  Numbers emitted, not retyped.
(version 3: the headings name the B.3 file read and the step pair used; version 2 printed "partB3_v2" and "h = 1e-3 and 1e-4" whatever
the input, and its B4' convergence rows replaced the B5 rows (the B5 table printed the convergence rows); fixed here)"""
import argparse
import json
import os

import numpy as np

TERMS = ("mass", "radial", "angular", "E2_UM", "E2_UB")


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    if not np.isfinite(v):
        return str(v)
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--b1", required=True)
    ap.add_argument("--b3", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    P1 = json.load(open(a.b1))
    P3 = json.load(open(a.b3))
    out = ["# Strand 4 Part B tables (generated by solve/code/strand4/strand4_partB_report_v3.py)", "",
           "G_0 = %s, T_s = %s. States of %s: %s." % (f(P3["meta"]["G"], 8), f(P3["meta"]["Ts"]), os.path.basename(a.b3), "; ".join(P3["meta"]["states"])), ""]
    rows = []
    for s in P1["states"]:
        rows.append([s["state"], s["Ns"], f(s["E_rows_max_abs_diff"]), f(s["D_rows_max_abs_diff"]),
                     "%s / %s" % (f(s["A_over_B_minus_1"], 8), f(s["A_over_B_minus_1_stored"], 8)),
                     "%s / %s / %s" % (f(s["Dlat_ext"], 10), f(s["Dlat_sum"], 10), f(s["Dlat_rows"], 10)),
                     f(s["A_K_charge"], 10), f(s["E_ret_over_E_partial_minus_1"]), f(s["B2_closed"], 12), f(s["B2_closed_minus_target"]),
                     f(s["B2_fd_minus_target"])])
    out += ["## B1 and B2 at the two 0.1 states (partB1.json; reported 06:35 UTC and accepted by the lead)", "",
            table(["state", "N_s", "max abs(E row - stored)", "max abs(D row - stored)", "A/B - 1 (computed / stored)",
                   "D_lat (exterior / sums / rows)", "charge 1^T K u/(4 pi)", "E_ret/E_partial - 1", "(1/2) dF_g/ds_inf (closed form)",
                   "closed - (A - B)/G_0", "central difference - (A - B)/G_0"], rows), ""]
    rows = []
    for s in P3["states"]:
        rows.append([s["state"], s["Ns"], f(s["NB"], 8), s["n_occupied"], f(s.get("E_rows_max_abs_diff")), f(s.get("D_rows_max_abs_diff")),
                     f(s["A"], 10), f(s["B"], 10), f(s["A_over_B_minus_1"], 8), f(s["A_minus_B_over_G"], 10), f(s["E_mat_minus_E_exc"]),
                     f(s["E_mat_lam1_terms"]["E2_split_closure"]), f(s["fields_lam1_max_dev"])])
    out += ["## B1' Every state of the dilation run: the stored rows re-evaluated, the exterior A and B, D_lat = (A - B)/G_0, and the "
            "reconstruction E_mat(lam = 1) against free_energy's E_exc,ret", "",
            table(["state", "N_s", "N_B", "occupied levels", "max abs(E row - stored)", "max abs(D row - stored)", "A", "B", "A/B - 1",
                   "D_lat = (A - B)/G_0", "E_mat(1) - E_exc,ret", "E2 - E2(U_M, 0) - E2(0, U_B)", "fields at lam = 1: max abs dev"], rows), ""]
    rows = []
    for s in P3["states"]:
        rows.append([s["state"], "1", f(s["transport_lam1"]["spectrum_dev"]), f(s["transport_lam1"]["orth_dev"]), "-", "-"])
        for h, st in s["steps"].items():
            t = st["transport"]
            rows.append([s["state"], h, f(t["spectrum_dev"]), f(t["orth_dev"]), f(t["NB_change"]), f(t["Socc_change"])])
    out += ["## B3 The transport's isospectrality: the nonzero spectrum of the transported X against the occupations (largest difference "
            "over channels and over lam = 1 +- h), max abs(Q^dag Q - 1), and the changes of N_B and S_occ", "",
            table(["state", "h", "spectrum vs occupations", "orthonormality", "N_B change", "S_occ change"], rows), ""]
    rows = []
    for s in P3["states"]:
        r = s["richardson"]
        rows.append([s["state"], f(r["D_vac"], 8), f(s["S_inf_closed"], 8), f(r["S_inf_fd"], 8), f(r["D_vac_plus_S_inf"], 8),
                     f(r["D_boundary_term"], 6), f(r["D_mat"], 8), " ".join(f(r["D_mat_terms"][t], 6) for t in TERMS),
                     f(r["R_stat_direct"], 8), f(r["R_stat_sum"] - r["R_stat_direct"]), f(r["Total"], 8)])
    out += ["## B4 The pieces (Richardson over the last step pair, %s): D_vac," % ", ".join(P3["states"][0]["richardson"].get("step_pair", ["1e-3", "1e-4"])) + " S_inf (closed form and the central difference of F_g(1; lam^(1/2))), "
            "D_vac + S_inf, the boundary term's share of D_vac, D_mat and its terms (mass, radial, angular, E2 through U_M, E2 through U_B), "
            "R_stat computed directly (and D_vac + D_mat minus it), the direct total", "",
            table(["state", "D_vac", "S_inf (closed)", "S_inf (difference)", "D_vac + S_inf", "boundary term", "D_mat",
                   "D_mat: mass, radial, angular, E2(U_M), E2(U_B)", "R_stat", "D_vac + D_mat - R_stat", "Total"], rows), ""]
    rows = []
    for s in P3["states"]:
        r = s["richardson"]
        rows.append([s["state"], " ".join(f(r["share_mu_L"][t], 6) for t in TERMS), " ".join(f(r["share_kappa_L"][t], 6) for t in TERMS),
                     " ".join(f(r["share_tables_both"][t], 6) for t in TERMS), f(r["tables_share_total"], 8),
                     " ".join(f(r["D_mat_fields_only"][t], 6) for t in TERMS)])
    out += ["## B4 The dressing tables' shares of D_mat by term (the derivative of E_mat minus that with the table frozen at 1): mu_L, "
            "kappa_L (kaL and kabL), both; and the fields-only part (covariance held at lam = 1)", "",
            table(["state", "mu_L share (mass, radial, angular, E2(U_M), E2(U_B))", "kappa_L share (same order)", "both tables (same order)",
                   "both tables, total", "fields only (same order)"], rows), ""]
    rows = []
    for s in P3["states"]:
        r = s["richardson"]
        dl = s["A_minus_B_over_G"]
        rows.append([s["state"], f(dl, 10), f(r["Total_minus_R_stat"], 10), f(r["D_vac_plus_S_inf"] + r["D_mat"] - r["R_stat_direct"], 10),
                     f(r["closure_Total_minus_R_stat_minus_Dlat"]), f(r["closure_Total_minus_pieces"]), f(r["R_stat_direct"], 8),
                     f(r["tables_share_total"], 8), " ".join("%s %s" % (k, f(v)) for k, v in r["step_agreement_rel"].items())])
    rows_conv = []
    for s in P3["states"]:
        for pr, r in s.get("richardson_pairs", {}).items():
            rows_conv.append([s["state"], pr, f(r["D_vac"], 9), f(r["D_mat"], 9), f(r["R_stat_direct"]), f(r["Total"], 9), f(r["tables_share_total"], 8),
                         " ".join("%s %s" % (k, f(v)) for k, v in r["step_agreement_rel"].items())])
    if rows_conv:
        out += ["## B4' Convergence in the finite-difference step: the Richardson value of each consecutive pair of steps (the tables above "
                "use the last pair) and the relative agreement of the pair's two central differences", "",
                table(["state", "step pair", "D_vac", "D_mat", "R_stat", "Total", "tables' share", "step agreement"], rows_conv), ""]
    pair = ", ".join(P3["states"][0]["richardson"].get("step_pair", ["1e-3", "1e-4"]))
    out += ["## B5 The identity D_lat = (A - B)/G_0 = Total - R_stat = [D_vac + S_inf] + D_mat - R_stat per state, its closures, R_stat, the "
            "tables' share, and the step agreement (relative difference of the central differences at h = %s)" % pair, "",
            table(["state", "D_lat = (A - B)/G_0", "Total - R_stat", "[D_vac + S_inf] + D_mat - R_stat", "(Total - R_stat) - D_lat",
                   "Total - (D_vac + D_mat + S_inf)", "R_stat", "tables' share of D_mat", "step agreement"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
