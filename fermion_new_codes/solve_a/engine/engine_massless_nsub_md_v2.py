#!/usr/bin/env python
"""engine_massless_nsub_md_v2.py (builder analyst; engine spec 31.2 (3): "the test's md is regenerated from its json with that cause
where the json holds it (else "cause not stored" printed)"): engine_massless_nsub_test_v1's md with its main table gaining the column
"the stop's cause", read from the json row of each nsub (its "failed" entry, or the record's, where present), else "cause not stored"; a
header line names the regeneration. Nothing else changes in the md. Args: --md (version 1's md) --json --out."""
import argparse
import json


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", required=True); ap.add_argument("--json", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    J = json.load(open(a.json))
    cause = {}
    for r in J["rows"]:
        c = r.get("failed") or (r.get("record") or {}).get("failed")
        cause[int(r["nsub"])] = str(c) if c else "cause not stored"
    L = open(a.md).read().split("\n")
    out = []
    in_main = False
    for l in L:
        if l.startswith("| nsub | T/rs | continued intervals"):
            in_main = True
            out.append(l + " the stop's cause |")
            continue
        if in_main and l.startswith("|---"):
            out.append(l + "---|")
            continue
        if in_main and l.startswith("| "):
            n = int(l.split("|")[1].strip())
            out.append(l + " %s |" % cause.get(n, "cause not stored"))
            continue
        if in_main and not l.startswith("|"):
            in_main = False
        out.append(l)
    out.insert(1, "")
    out.insert(2, "- regenerated by engine_massless_nsub_md_v2.py from the test's json (engine spec 31.2 (3)): the main table's last column is the stop's cause as the json holds it; every row's json entry \"failed\" is empty, so each reads \"cause not stored\" where that holds.")
    open(a.out, "w").write("\n".join(out))
    print("\n".join(out[:16]))


if __name__ == "__main__":
    main()
