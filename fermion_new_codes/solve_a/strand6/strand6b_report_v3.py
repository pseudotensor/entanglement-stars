#!/usr/bin/env python
"""Strand 6 (b) report, version 2 (builder analyst): tables from strand6b_omega_v4.py's omega_*.json (omega/run2), the block checks
(check2/check.json), the radial node-count check (omega/nradcheck/nrad48, nrad192 beside run2's 96 at L = 1024), the spacing trend
(a Omega = 1/125, 1/500 in omega/run2), the cumulative share of the radial integrand within rho <= c a Omega (the isotropy bound's premise,
from the stored radial arrays; the weights of strand6b_omega_v4.radial_nodes), and the two-sided value at the pilot.  Numbers emitted, not
retyped.  (Version 3: the node-count error is the change from n_rad = 96 to 192, not the largest change including the under-resolved
48.)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


TARGETS = {4: {"lane certified lower bound": 0.978378347908, "target": 0.977721363402},
           6: {"lane executed Hankel bound (T35b)": 1.4392053098, "variance bound (T35a)": 0.9239, "target": 1.3686581321}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--check", required=True)
    ap.add_argument("--md", required=True)
    ap.add_argument("--nrad", required=True, help="the omega/nradcheck folder")
    a = ap.parse_args()
    runs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(a.run, "omega_*.json")))]
    out = ["# Strand 6 (b) tables (generated by solve/code/strand6/strand6b_report_v3.py)", ""]
    rows = []
    for R in sorted(runs, key=lambda R: (R["meta"]["order"], -R["meta"]["aOmega"], R["meta"]["L"], R["meta"]["nfft"])):
        M = R["meta"]
        sea = R["seas"]
        rows.append([M["order"], "1/%g" % round(1 / M["aOmega"]), M["L"], M["nfft"] // M["L"], "yes" if M.get("spec_quadrature") else "no",
                     "one" if M.get("oneblock") else "both", f(R["S_over_A_Omega2_radial"], 9), f(R.get("S_over_A_Omega2_spec_folded"), 9)] +
                    [f(sea[s]["eta_radial"] / M["aOmega"] ** 2, 7) for s in ("0", "1", "3")] +
                    [f(max(sea[s]["max_block_difference"] for s in sea), 2), f(max(sea[s]["S_at_rho_0.25"] for s in sea), 2), f(M.get("seconds"), 4)])
    out += ["## T1 S/(A Omega^2) = eta_total/(a Omega)^2 per setting: the radial form and the spec's nested grid in the folded zone; per sea "
            "(sea 1 counts twice in the total: seas 2 and 3 coincide) the radial eta/(a Omega)^2; the largest block difference where both "
            "blocks are computed; the largest S at rho = 0.25 (the tail bound)", "",
            table(["order", "a Omega", "L", "nfft/L", "spec grid", "blocks", "S/(A Omega^2) radial", "spec grid (folded)", "sea 1 (m^2 = 1e-6 Omega^2)",
                   "seas 2, 3 (each)", "sea 4", "block difference", "S(rho = 0.25)", "seconds"], rows), ""]
    # convergence in L at the pilot (radial, nfft 16 L)
    rows = []
    for order in (4, 6):
        pts = sorted([(R["meta"]["L"], R["S_over_A_Omega2_radial"]) for R in runs if R["meta"]["order"] == order and abs(R["meta"]["aOmega"] - 0.004) < 1e-12
                      and R["meta"]["nfft"] == 16 * R["meta"]["L"]])
        for i, (L, v) in enumerate(pts):
            d = v - pts[i - 1][1] if i > 0 else None
            rows.append([order, L, f(v, 10), f(d, 3), f(d / (pts[i - 1][1] - pts[i - 2][1]), 4) if i > 1 else "-"])
        if len(pts) >= 3:
            (L1, v1), (L2, v2), (L3, v3) = pts[-3:]
            r = (v3 - v2) / (v2 - v1) if v2 != v1 else None
            if r is not None and 0 < r < 1:
                ext = v3 + (v3 - v2) * r / (1 - r)
                rows.append([order, "geometric extrapolation (ratio of the last two differences %s)" % f(r, 4), f(ext, 10), "-", "-"])
    out += ["## T2 Convergence in the chain length at the pilot a Omega = 1/250 (radial form, nfft 16 L): the value, its change from the previous L "
            "and the ratio of successive changes", "", table(["order", "L", "S/(A Omega^2)", "change", "ratio of changes"], rows), ""]
    rows = []
    for order in (4, 6):
        best = [R for R in runs if R["meta"]["order"] == order and abs(R["meta"]["aOmega"] - 0.004) < 1e-12]
        if not best:
            continue
        Rb = max(best, key=lambda R: (R["meta"]["L"], R["meta"]["nfft"]))
        v = Rb["S_over_A_Omega2_radial"]
        for lab, t in TARGETS[order].items():
            rows.append([order, lab, f(t, 12), f(v, 10), "L = %d, nfft %d L" % (Rb["meta"]["L"], Rb["meta"]["nfft"] // Rb["meta"]["L"]), f(v / t - 1, 4)])
    out += ["## T3 Against lane's numbers (the largest computed L at the pilot; radial form)", "",
            table(["order", "lane number", "value", "this computation", "setting", "ratio - 1"], rows), ""]
    C = json.load(open(a.check))
    rows = [[r["order"], f(r["m"], 3), " ".join(f(x, 5) for x in r["q"]), f(r["S4_over_2"], 12), f(r["S_blocks_mean"], 12), f(r["rel_diff"], 2),
             f(r["block_plus"], 12), f(r["block_minus"], 12), f(r["offdiag_max"], 2)] for r in C]
    out += ["## T4 Control: the two 2L x 2L blocks against the addendum's 4L x 4L route on light channels (L = 64, nfft 16 L), one in the (pi, 0) "
            "valley", "", table(["order", "m", "q", "entropy(C_4L)/2", "mean of blocks", "relative difference", "block G = +1", "block G = -1",
                                 "off-diagonal block max"], rows), ""]
    # ---- version 2 additions
    def rnodes(n_rad, rmin=1e-7, rmax=0.25):
        from numpy.polynomial.legendre import leggauss
        x, w = leggauss(n_rad)
        t = 0.5 * (np.log(rmax) - np.log(rmin)) * x + 0.5 * (np.log(rmax) + np.log(rmin))
        wt = 0.5 * (np.log(rmax) - np.log(rmin)) * w
        rho = np.exp(t)
        ph, wph = leggauss(256)
        ph = np.pi / 4 * (ph + 1)
        wph = np.pi / 4 * wph
        Phi = np.array([4 * np.sum(wph / np.sqrt((1 - r * r * np.cos(ph) ** 2) * (1 - r * r * np.sin(ph) ** 2))) for r in rho])
        return rho, wt, Phi
    rows = []
    nr = {}
    for p in sorted(glob.glob(os.path.join(a.nrad, "nrad*", "omega_*.json"))):
        R = json.load(open(p))
        nr[(R["meta"]["order"], R["meta"]["n_rad"])] = R["S_over_A_Omega2_radial"]
    for R in runs:
        M = R["meta"]
        if M["L"] == 1024 and M["nfft"] == 16 * 1024 and abs(M["aOmega"] - 0.004) < 1e-12:
            nr[(M["order"], M["n_rad"])] = R["S_over_A_Omega2_radial"]
    qerr = {}
    for order in (4, 6):
        vals = sorted([(n, v) for (o, n), v in nr.items() if o == order])
        if not vals:
            continue
        v96 = dict(vals).get(96)
        dv = dict(vals)
        qerr[order] = abs(dv[192] - v96) if (v96 is not None and 192 in dv) else None
        rows.append([order] + [f(dv.get(n), 10) for n in (48, 96, 192)] + [f(abs(dv[48] - v96), 2) if 48 in dv else "-", f(qerr[order], 2)])
    out += ["## T5 The radial form's node count at the pilot (L = 1024, nfft 16 L): S/(A Omega^2) at n_rad = 48, 96 (production), 192, and the "
            "changes 48 -> 96 and 96 -> 192 (the latter is the production value's node-count error used in T8)", "",
            table(["order", "n_rad = 48", "n_rad = 96", "n_rad = 192", "48 -> 96", "96 -> 192"], rows), ""]
    rows = []
    for R in sorted(runs, key=lambda R: (R["meta"]["order"], R["meta"]["aOmega"], R["meta"]["L"])):
        M = R["meta"]
        if M["nfft"] != 16 * M["L"]:
            continue
        rows.append([M["order"], "1/%g" % round(1 / M["aOmega"]), M["L"], f(R["S_over_A_Omega2_radial"], 9), f(R.get("S_over_A_Omega2_spec_folded"), 9)])
    out += ["## T6 The spacing trend: S/(A Omega^2) per order, a Omega and L (radial form; the spec grid where computed), nfft 16 L", "",
            table(["order", "a Omega", "L", "radial", "spec grid (folded)"], rows), ""]
    rows = []
    for R in runs:
        M = R["meta"]
        if not (M["L"] == 4096 and abs(M["aOmega"] - 0.004) < 1e-12):
            continue
        rho, wt, Phi = rnodes(M["n_rad"])
        for si, sea in sorted(R["seas"].items()):
            S = np.array([x["S"] for x in sea["radial"]])
            rr = np.array([x["rho"] for x in sea["radial"]])
            assert np.allclose(rr, rho, rtol=1e-12)
            integ = wt * rho * rho * S * Phi
            tot = integ.sum()
            fr = [integ[rho <= c * M["aOmega"]].sum() / tot for c in (1, 3, 10, 30)]
            rows.append([M["order"], si, f(sea["m"], 3)] + [f(x, 6) for x in fr] + [f(1 - fr[-1], 2)])
    out += ["## T7 The share of each sea's radial integrand from rho <= c a Omega (rho = |sin k_perp| about a transverse valley centre), c = 1, 3, "
            "10, 30, at the pilot (L = 4096), and the remainder beyond 30 a Omega (the premise of the isotropy bound: the contributions lie within "
            "a few a Omega of the valley centres)", "", table(["order", "sea", "m", "c = 1", "c = 3", "c = 10", "c = 30", "beyond 30 a Omega"], rows), ""]
    rows = []
    for order in (4, 6):
        pts = sorted([(R["meta"]["L"], R["S_over_A_Omega2_radial"], R) for R in runs if R["meta"]["order"] == order and abs(R["meta"]["aOmega"] - 0.004) < 1e-12
                      and R["meta"]["nfft"] == 16 * R["meta"]["L"]], key=lambda t: t[0])
        if len(pts) < 3:
            continue
        (L1, v1, _), (L2, v2, _), (L3, v3, R3) = pts[-3:]
        r = (v3 - v2) / (v2 - v1)
        ext = v3 + (v3 - v2) * r / (1 - r)
        nf = [abs(R["S_over_A_Omega2_radial"] - Rb["S_over_A_Omega2_radial"]) for R in runs for Rb in runs
              if R["meta"]["order"] == order and Rb["meta"]["order"] == order and R["meta"]["L"] == Rb["meta"]["L"] and abs(R["meta"]["aOmega"] - 0.004) < 1e-12
              and abs(Rb["meta"]["aOmega"] - 0.004) < 1e-12 and R["meta"]["nfft"] == 16 * R["meta"]["L"] and Rb["meta"]["nfft"] == 32 * Rb["meta"]["L"]]
        enf = max(nf) if nf else 0.0
        eq = qerr.get(order) or 0.0
        tail = sum(R3["seas"][s]["S_at_rho_0.25"] * (2 if s == "1" else 1) for s in R3["seas"]) / 0.004 ** 2
        lo = v3 - eq - enf
        hi = ext + abs(ext - v3) + eq + enf + tail
        rows.append([order, f(v3, 9), f(ext, 9), f(eq, 2), f(enf, 2), f(tail, 2), "[%s, %s]" % (f(lo, 7), f(hi, 7))] +
                    ["%s: %s" % (lab, f(lo / t - 1, 3)) for lab, t in TARGETS[order].items()])
    out += ["## T8 The two-sided value at the pilot: the L = 4096 radial value (the sequence in L increases) as the lower end, the geometric "
            "extrapolation plus its own distance from the L = 4096 value as the upper end, each widened by the radial node-count change 96 -> 192 (T5), "
            "the largest nfft 16 L against 32 L difference (T1) and, on the upper end, the tail bound S(rho = 0.25)/(a Omega)^2 summed over the "
            "seas; the lower end against lane's numbers (lower/number - 1)", "",
            table(["order", "L = 4096", "extrapolation", "node-count", "nfft", "tail", "two-sided interval", "against", "", ""],
                  [r + [""] * (10 - len(r)) for r in rows]), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
