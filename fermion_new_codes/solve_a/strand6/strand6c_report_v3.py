#!/usr/bin/env python
"""Strand 6 (c) report, version 3 (builder analyst): part (c1) from strand6c1_unittest_v1.py's unittest.json, part (c2) from
strand6c2_dilation_v2.py's dilation_c2_v2.json and part (c3) from strand6c3_collar_v1.py's collar_c3.json and check_c8.json.
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--c1", required=True)
    ap.add_argument("--c2", required=True)
    ap.add_argument("--c3", required=True)
    ap.add_argument("--c3check", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    U = json.load(open(a.c1))
    rows = []
    for r in U["rows"]:
        R = r["richardson"]
        rows.append(["(%s, %s)" % (f(r["m"]), f(r["H"])), " ".join(f(x, 6) for x in r["squared_masses"]), f(R["NN"]), f(R["Npsi"], 10), f(R["psipsi"], 10),
                     f(r["Npsi_per_sum_f2"], 11), f(r["telescoped_form"], 11), f(r["minus_telescoped"]), f(r["minus_P14"]), f(r["step_agreement_Npsi"])])
    out = ["# Strand 6 (c) tables (generated by solve/code/strand6/strand6c_report_v3.py)", "",
           "## (c1) P14's 4^3 unit test: the periodic 4^3 cube, P = 1, f = cos(pi x_1/2) (sum f^2 = %s); the vacuum Hessian of W_0 in (N, psi) "
           "along f (Richardson over h = 1e-3, 1e-4); J_Npsi/sum f^2 against P14's closed form %s and the lead's telescoped shell form "
           "(both evaluated by the script)" % (f(U["meta"]["sum_f2"]), f(U["meta"]["P14_closed_form"], 11)), "",
           table(["(m, H)", "squared masses", "NN", "N psi", "psi psi", "N psi / sum f^2", "telescoped form", "difference", "minus P14",
                  "step agreement N psi"], rows), ""]
    C2 = json.load(open(a.c2))
    rows, rows2 = [], []
    for c in C2["cases"]:
        for st in ("centred", "forward"):
            x = c[st]
            L = x["LHS"]
            rows.append([c["case"], st, f(x["LHS"], 10), f(x["anomaly"], 10), f(x["DFm_partials"], 10), f(x["DFm_fd"], 10),
                         f(x["residual_contraction"], 3), f(x["closure_partials"], 2), f(x["closure_fd"], 2),
                         f(x["anomaly"] / L, 4) if L else "-", f(x["DFm_partials"] / L, 6) if L else "-"])
        x = c["centred"]
        rows2.append([c["case"], f(x["DFm_fd_minus_partials"], 3), f(x["DFm_fd_minus_partials_t_step_1e-5"], 3),
                      f(x["DFm_fd_minus_partials_richardson"], 3), " ".join(f(v, 12) for v in x["DFm_fd_steps"]), f(x["E_minus_F_m"], 2),
                      f(x["residual_norm"], 3), x["d0"], x["d0_at_tolerance"], f(x["D_one_max"], 2)])
    out += ["## (c2) The open-cube dilation identity, P14's eq. 4: LHS = (k/2) 1^T K (u + v) against -k u^T Z v + D_a F_m - rho (rho the "
            "rows contracted with the tangent; D_a R = 0 on the installed row), per solution and generator stencil; D_a F_m from 2b's "
            "fixed-Fock partials (the rows' own t, step 1e-4) and independently from the selected level's central differences along the "
            "tangent (h = 1e-4, 5e-5, Richardson); the closures with each; the anomaly's and the matter piece's shares of the LHS", "",
            table(["case", "stencil", "LHS", "-k u^T Z v", "D_a F_m (partials)", "D_a F_m (level FD)", "rho", "closure (partials)",
                   "closure (level FD)", "anomaly/LHS", "D_a F_m (partials)/LHS"], rows), "",
            "### (c2) The two evaluations of D_a F_m (centred stencil): level FD minus partials with t's step 1e-4 (the rows'), 1e-5 and their "
            "Richardson value; the level's two FD steps; the level E against F_m = sum_x N_x src_x; the residual norm |F(z)|; the projector "
            "rank used and at tolerance; max |D 1|", "",
            table(["case", "FD - partials (t 1e-4)", "FD - partials (t 1e-5)", "FD - partials (Richardson)", "level FD at h = 1e-4, 5e-5",
                   "E - F_m", "|F(z)|", "d0", "d0 at tolerance", "max |D 1|"], rows2), ""]
    C3 = json.load(open(a.c3))
    CK = json.load(open(a.c3check))
    M = C3["meta"]
    out += ["## (c3) Lane strand B's finite collar identity on the open 3^3 cube with the gate's realization and seed (lane's parameters (B1); "
            "the charge-2 pair block, 1431 pairs, in lane's natural sea chart)", "",
            "Checks: the natural-chart construction against the gate's own Dressed (2,0) block on the 2 x 2 x 2 cube (a random background, m = 0.1, "
            "(g_M, g_B, Lambda) = (0.2, 1, 1); %s pairs): largest eigenvalue difference %s dressed, %s undressed; the generator: max |V 1| = %s, "
            "max |V e_o + f/2| = %s, f has %s sites." % (CK["dim"], f(CK["max_eig_diff_dressed"], 2), f(CK["max_eig_diff_undressed"], 2),
                                                          f(M["V_one_max"], 2), f(M["V_eo_plus_f_over_2_max"], 2), M["f_count"]), ""]
    rows, rows2 = [], []
    for pt in C3["points"]:
        for vn, v in pt["vectors"].items():
            rows.append(["(%s, %s)" % (f(pt["s"]), f(pt["n"])), vn, f(v["Q_a"], 10), f(v["D_vac"], 8), f(v["D_mat"], 10), f(v["D_bdy"], 6),
                         f(v["R_stat"], 6), f(v["kappa"], 3), f(v["closure"], 2), f(v["linearity_check"], 2)])
            P = v["probes"]
            rows2.append(["(%s, %s)" % (f(pt["s"]), f(pt["n"])), vn, f(P["T_B"], 10), f(P["T_F"], 8), f(P["C_F"], 8), f(P["R_2"], 8), f(P["p_D"], 10),
                          f(v["kappa_commutator"], 3), f(v["eps"], 8), f(v["eigen_residual_norm"], 2),
                          f(max(P[k_ + "_step_agreement"] for k_ in ("T_B", "T_F", "C_F", "R_2", "p_D")), 2)])
    out += ["### (c3) The four pieces and the identity Q_a = D_vac + D_mat + D_bdy + R_stat (central differences h = 1e-4, 5e-5, Richardson), "
            "for the lowest eigenvector of H at the candidate and for a fixed random normalized pair vector; the closure and the linearity "
            "check F[p_D] - (T_B/2 + s R_2/2 - (s - 1) T_F/2 - (n - 1) C_F/2)", "",
            table(["(s, n)", "pair vector", "Q_a = T_B/2", "D_vac", "D_mat", "D_bdy", "R_stat", "kappa", "closure", "linearity"], rows), "",
            "### (c3) The probes F[p] = w[p] + <h[p]> and the state data: kappa by the commutator form beside the residual form, the Rayleigh value, "
            "the eigenpair residual norm, the largest step difference of the probes (h = 1e-4 against 5e-5)", "",
            table(["(s, n)", "pair vector", "T_B", "T_F", "C_F", "R_2", "F[p_D]", "kappa (commutator)", "eps", "|(H - eps) Psi|", "step difference"],
                  rows2), ""]
    for pt in C3["points"]:
        out += ["(s, n) = (%s, %s): ground level %s, gap to the next %s, W = %s, max |g + g^dag| = %s." % (
            f(pt["s"]), f(pt["n"]), f(pt["eps_ground"], 8), f(pt["gap"], 4), f(pt["W"], 8), f(pt["g_antihermitian_defect"], 2))]
    out += [""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
