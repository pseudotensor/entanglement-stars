#!/usr/bin/env python
"""Strand 6 (c) report (builder analyst): part (c1) from strand6c1_unittest_v1.py's unittest.json (parts (c2), (c3) appended by later
versions).  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--c1", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    U = json.load(open(a.c1))
    rows = []
    for r in U["rows"]:
        R = r["richardson"]
        rows.append(["(%s, %s)" % (f(r["m"]), f(r["H"])), " ".join(f(x, 6) for x in r["squared_masses"]), f(R["NN"]), f(R["Npsi"], 10), f(R["psipsi"], 10),
                     f(r["Npsi_per_sum_f2"], 11), f(r["telescoped_form"], 11), f(r["minus_telescoped"]), f(r["minus_P14"]), f(r["step_agreement_Npsi"])])
    out = ["# Strand 6 (c) tables (generated by solve/code/strand6/strand6c_report_v1.py)", "",
           "## (c1) P14's 4^3 unit test: the periodic 4^3 cube, P = 1, f = cos(pi x_1/2) (sum f^2 = %s); the vacuum Hessian of W_0 in (N, psi) "
           "along f (Richardson over h = 1e-3, 1e-4); J_Npsi/sum f^2 against P14's closed form %s and the lead's telescoped shell form "
           "(both evaluated by the script)" % (f(U["meta"]["sum_f2"]), f(U["meta"]["P14_closed_form"], 11)), "",
           table(["(m, H)", "squared masses", "NN", "N psi", "psi psi", "N psi / sum f^2", "telescoped form", "difference", "minus P14",
                  "step agreement N psi"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
