#!/usr/bin/env python
"""Strand 6 (a) report (builder analyst): tables from strand6a_spingrad_v3.py (the fixed-position splitting by packets) and
strand6a_spingrad_v2.py (the sigma_1-resolved chain spectra and the controls); version 1's slab output is listed as superseded.
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--v3", required=True)
    ap.add_argument("--v2", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R3 = json.load(open(a.v3))
    R2 = json.load(open(a.v2))
    out = ["# Strand 6 (a) tables (generated by solve/code/strand6/strand6a_report_v1.py)", ""]
    rows = []
    for r in R3["rows"]:
        if r["g_u"] == 0:
            continue
        rows.append([f(r["m"]), f(r["g_u"]), f(r["width"]), r["valley"], f(r["pol"]["split_over_g"], 7), f(r["pol"].get("linearity_ratio_1e-3_over_5e-4"), 6),
                     f(r["sym"]["split_over_g"], 7), f(r["sym"].get("linearity_ratio_1e-3_over_5e-4"), 6), f(r["pol"]["mean_minus_m"]), f(r["sym"]["mean_minus_m"])])
    ctl = [r for r in R3["rows"] if r["g_u"] == 0]
    out += ["## A1 The spin splitting at fixed position: a packet of width w at x_0 = %s (psi = 1 there) in the x_1 valley k_1 = 0 or pi; "
            "Delta = <phi|B_(+1)|phi> - <phi|B_(-1)|phi> divided by g_u; the polar and the symmetric placement; the linearity ratio "
            "Delta(1e-3)/Delta(5e-4); the packet's spin-averaged energy minus m" % f(R3["meta"]["x0"]), "",
            table(["m", "g_u", "w", "x_1 valley", "polar Delta/g_u", "polar linearity", "symmetric Delta/g_u", "symmetric linearity",
                   "polar mean - m", "symmetric mean - m"], rows), "",
            "Control g_u = 0: the largest |Delta| over the packets, polar %s, symmetric %s." % (
                f(max(abs(r["pol"]["split"]) for r in ctl)), f(max(abs(r["sym"]["split"]) for r in ctl))), ""]
    rows = []
    for r in R2["rows"]:
        if r["g_u"] == 0:
            rows.append([f(r["m"]), f(r["control_pol_sym_max_level_difference"]), f(r["control_spin_max_level_difference"])])
    out += ["## A2 Controls of the chain at g_u = 0 (version 2): the largest level difference between the placements and between the sigma_1 "
            "sectors over the lowest levels", "", table(["m", "polar - symmetric", "sigma_1 = +1 - (-1)"], rows), ""]
    rows = []
    for r in R2["rows"]:
        if r["g_u"] != 1e-3:
            continue
        for place in ("pol", "sym"):
            for s in ("plus", "minus"):
                rows.append([f(r["m"]), place, "+1" if s == "plus" else "-1",
                             " ".join("%s(%s, %s)" % (f(t["E"], 7), t["valley"], f(t["x1_centroid"], 3)) for t in r[place][s][:6])])
    out += ["## A3 The chain's lowest levels per sigma_1 sector at g_u = 1e-3 (version 2): energy (x_1 valley, centroid); the sectors' "
            "spectra coincide with the valley labels exchanged", "", table(["m", "placement", "sigma_1", "lowest six levels"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
