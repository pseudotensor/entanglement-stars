#!/usr/bin/env python
"""Strand 6 (a') report (builder analyst): tables from strand6a_firstvar_v1.py (firstvar.json).  Numbers emitted, not retyped."""
import argparse
import json


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    out = ["# Strand 6 (a') tables (generated by solve/code/strand6/strand6a_report_v2.py)", ""]
    rows = []
    for r in R["rows"]:
        rows.append([r["L"], f(r["m"]), f(r["width"]), r["valley"], f(r["pol_lin"], 10), f(r["pol_derivative"], 10), f(r["pol_derivative"] - r["pol_lin"], 2),
                     " ".join(f(r["pol_v3_over_g"][g], 8) for g in ("0.0005", "0.001", "0.002")), f(r["bulk_average"], 10), f(r["pol_lin"] - r["bulk_average"], 2)])
    out += ["## A'1 The polar placement: 8 m <phi|Y|phi> (E Y + Y E = -i[X, D]) beside the central derivative of the version-3 splitting at g_u = "
            "+-2.5e-4, +-1.25e-4 (Richardson) and their difference, the version-3 values Delta/g_u at g_u = 5e-4, 1e-3, 2e-3, and the bulk "
            "packet average 4 m <cos k/(m^2 + sin^2 k)^(1/2)> with the difference 8 m <Y> - bulk", "",
            table(["L", "m", "w", "valley", "8 m <Y>", "derivative", "difference", "Delta/g_u at 5e-4, 1e-3, 2e-3", "bulk average", "8 m <Y> - bulk"], rows), ""]
    rows = []
    for r in R["rows"]:
        rows.append([r["L"], f(r["m"]), f(r["width"]), r["valley"], f(r["sym_lin"], 10), f(r["sym_derivative"], 10), f(r["sym_derivative"] - r["sym_lin"], 2),
                     " ".join(f(r["sym_v3_over_g"][g], 8) for g in ("0.0005", "0.001", "0.002")), f(r["sym_derivative"] / r["pol_derivative"], 10)])
    out += ["## A'2 The symmetric placement: 2 m <phi|Y|phi> beside its central derivative and their difference, the version-3 values, and the "
            "ratio of the symmetric to the polar derivative", "",
            table(["L", "m", "w", "valley", "2 m <Y>", "derivative", "difference", "Delta/g_u at 5e-4, 1e-3, 2e-3", "sym/pol"], rows), ""]
    rows = [[r["L"], f(r["m"]), f(r["width"]), r["valley"], f(r["centroid_B0"], 6), f(r["centroid_fermion"], 6),
             f(r["centroid_fermion"] - r["centroid_B0"], 6), f(-1 / (2 * r["m"]) if r["valley"] == "0" else 1 / (2 * r["m"]), 4), f(r["valley_leakage"], 2)]
            for r in R["rows"]]
    out += ["## A'3 Per packet the B_0-space centroid <phi|X|phi>, the fermion-space centroid (1/2) <phi|(X + U^dag X U)|phi> (U the polar unitary "
            "at g_u = 0), their difference beside -+1/(2m) (sign by valley; a reference value, not a prediction of the spec), and the valley "
            "leakage (the weight of |phi^(k)|^2 in the half zone nearer the other valley)", "",
            table(["L", "m", "w", "valley", "B_0 centroid", "fermion centroid", "difference", "-+1/(2m)", "valley leakage"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
