#!/usr/bin/env python
"""Strand 3 addendum part F''' stage 2 report (builder analyst): from strand3_partFppp_eta_v1.py (partFppp_eta.json), stage 1's records
(K_N by the primary rule, the Gauss-Legendre spread and the midpoint Richardson difference) and, if given, strand3_partFppp_bound_v1.py's
record: (E1) the D4 symmetry check; (E2) per sea, kappa, L, nfft the region sums and eta, and the checks at L = 256 (nfft 16 L, the inner
square doubled at doubled points, the middle rule 96 x 96, the outer 48 x 48), with the weight sums; (E3) eta_tot = eta_light + 2 eta_mu +
eta_sqrt2mu, K_N and R = 2 eta_tot/(pi K_N) per kappa and setting; (E4) the budget of R (relative): K_N (the GL spread; the midpoint
Richardson difference beside it), L (256 -> 512 at nfft 32 L), nfft (16 L -> 32 L at L = 256), the inner square doubled, the middle and outer
rules refined (each at L = 256, nfft 32 L), their sum (a sensitivity estimate, not an enclosure); (E5) the light-sea lower bound against
pi K_N/2.  The primary R is L = 512, nfft 32 L.  Numbers emitted, not retyped.
(Version 2, part F'''(d): --eta, --K and --bound take several records (merged; the first record wins a duplicate key); K_N's primary rule is the
kappa-adapted GL panels where a kappa has them (as in stage 1's report version 4), else the GL panels refined toward 0 and pi, both at 32 nodes; the
summary adds R's local power d ln R/d ln kappa between neighbouring kappa at the primary setting; E5 adds the bound over eta_light from the
eta records at the same kappa, L and nfft where the bound record lacks it.)"""
import argparse
import json
import math


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


SEAS = ("light", "mu", "sqrt2mu")
MULT = {"light": 1, "mu": 2, "sqrt2mu": 1}
SETS = {"production": ("inner", "annulus", "middle", "outer"), "inner doubled": ("inner_doubled", "annulus_doubled", "middle", "outer"),
        "middle 96": ("inner", "annulus", "middle_96", "outer"), "outer 48": ("inner", "annulus", "middle", "outer_48")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--eta", required=True)
    ap.add_argument("--K", required=True, help="comma-separated stage-1 records")
    ap.add_argument("--bound", default=None)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    E = {"regions": [], "symmetry_check": [], "weights": {}}
    for p in a.eta.split(","):
        Ei = json.load(open(p))
        E["regions"] += Ei["regions"]
        E["symmetry_check"] += Ei.get("symmetry_check", [])
        for k, w in Ei.get("weights", {}).items():
            E["weights"].setdefault(k, w)
    reg = {}
    for r in E["regions"]:
        reg.setdefault((r["sea"], r["kappa"], r["L"], r["nfft"], r["region"]), r["eta"])
    K = {}
    for p in a.K.split(","):
        for r in json.load(open(p))["rows"]:
            if r["kappa"] == "inf":
                continue
            K.setdefault(float(r["kappa"]), {}).setdefault(r["quadrature"], r["K_N_sym"])
    kappas = sorted({r["kappa"] for r in E["regions"]}, reverse=True)
    Ls = sorted({r["L"] for r in E["regions"]})
    out = ["# Strand 3 addendum part F''' stage 2 tables (generated by solve/code/strand3/strand3_partFppp_eta_report_v2.py)", ""]
    summ = []
    rows = [[x["kappa"], x["sea"], x["region"], "%.6e" % x["S"], f(x["max_abs_dev"], 2), f(x["max_rel_dev"], 2)] for x in E["symmetry_check"]]
    mx = max(x["max_abs_dev"] for x in E["symmetry_check"])
    out += ["## E1 The transverse D4 symmetry at sample points (all eight images, L = 256, nfft 32 L): the channel entropy S and its largest absolute and "
            "relative deviation over the images", "", table(["kappa", "sea", "region", "S", "max abs dev", "max rel dev"], rows), ""]
    summ.append("E1: the eight D4 images of every sample channel agree to %s absolute (largest)." % f(mx, 2))
    wrows = []
    for k, w in E["weights"].items():
        wrows.append([k] + ["%d/%d" % (w[x]["points"], w[x]["orbits"]) for x in ("inner", "annulus", "middle", "outer", "inner_doubled", "annulus_doubled", "middle_96", "outer_48")]
                     + [f(w[x], 2) for x in ("production_sum_minus_1", "doubled_sum_minus_1", "middle_96_sum_minus_1", "outer_48_sum_minus_1")])
    out += ["## E0 The quadrature: points/orbits per region and the weight sums minus 1 of the four rules", "",
            table(["kappa", "inner", "annulus", "middle", "outer", "inner doubled", "annulus doubled", "middle 96", "outer 48", "production - 1", "doubled - 1",
                   "middle 96 - 1", "outer 48 - 1"], wrows), ""]

    def eta(sea, kap, L, nf, setname):
        parts = SETS[setname]
        v = [reg.get((sea, kap, L, nf, x)) for x in parts]
        return None if any(x is None for x in v) else math.fsum(v)

    def etatot(kap, L, nf, setname):
        v = [eta(s, kap, L, nf, setname) for s in SEAS]
        return None if any(x is None for x in v) else math.fsum(MULT[s] * x for s, x in zip(SEAS, v))
    rows = []
    for kap in kappas:
        for s in SEAS:
            for L in Ls:
                for nf in (32 * L, 16 * L):
                    for setname, parts in SETS.items():
                        v = eta(s, kap, L, nf, setname)
                        if v is None:
                            continue
                        rows.append([kap, s, L, nf // L, setname] + [f(reg[(s, kap, L, nf, x)], 6) for x in parts] + ["%.10e" % v])
    out += ["## E2 Per sea, kappa, L and nfft/L the region sums and eta (the production rule and, at L = 256, the checks; the regions listed in the "
            "rule's order: inner, annulus, middle, outer, each possibly refined)", "",
            table(["kappa", "sea", "L", "nfft/L", "rule", "inner", "annulus", "middle", "outer", "eta"], rows), ""]
    rows = []
    budget_rows = []
    Kprim, Rprim = {}, {}
    for kap in kappas:
        Kd = K[kap]
        primq = "GL kappa-adapted mirrored panels, 32" if "GL kappa-adapted mirrored panels, 32" in Kd else "GL mirrored panels, 32"
        KN = Kd[primq]
        Kprim[kap] = primq
        gl = [v for q, v in Kd.items() if q.startswith("GL") and q != primq]
        spread = max(abs(v - KN) for v in gl) / KN
        mr = [v for q, v in Kd.items() if q.startswith("midpoint Richardson")]
        mid = abs(mr[0] - KN) / KN if mr else None
        R = {}
        for L in Ls:
            for nf in (32 * L, 16 * L):
                for setname in SETS:
                    et = etatot(kap, L, nf, setname)
                    if et is None:
                        continue
                    Rv = 2 * et / (math.pi * KN)
                    R[(L, nf, setname)] = (et, Rv)
                    rows.append([kap, L, nf // L, setname, "%.10e" % et, "%.12e" % KN, "%.6f" % Rv])
        Lmax = max(Ls)
        prim = R.get((Lmax, 32 * Lmax, "production"))
        b256 = R.get((256, 32 * 256, "production"))
        ch = {}
        if prim and b256:
            ch["L 256 -> %d" % Lmax] = abs(prim[0] - b256[0]) / prim[0]
        if (256, 16 * 256, "production") in R and b256:
            ch["nfft 16 L -> 32 L"] = abs(R[(256, 16 * 256, "production")][0] - b256[0]) / b256[0]
        for setname in ("inner doubled", "middle 96", "outer 48"):
            if (256, 32 * 256, setname) in R and b256:
                ch[setname] = abs(R[(256, 32 * 256, setname)][0] - b256[0]) / b256[0]
        tot = spread + sum(ch.values())
        budget_rows.append([kap, f(spread, 2), f(mid, 2)] + [f(ch.get(x), 2) for x in ("L 256 -> %d" % Lmax, "nfft 16 L -> 32 L", "inner doubled", "middle 96", "outer 48")]
                           + [f(tot, 2), f(tot - spread + (mid or 0), 2)])
        if prim:
            Rprim[kap] = (prim[1], Lmax)
            sh = {s: MULT[s] * eta(s, kap, Lmax, 32 * Lmax, "production") / prim[0] for s in SEAS}
            summ.append(("E3 (kappa %s): R = 2 eta_tot/(pi K_N) = %s at L = %d (eta_tot %s, K_N %s by " + Kprim[kap].replace("%", "%%") + "), %s at L = 256; "
                         "R - 1 is %s; the seas' shares of eta_tot: light %s, mu (twice) %s, sqrt2 mu %s; the budget (E4) sums to %s relative (with the midpoint "
                         "difference for K_N: %s).") % (
                            kap, "%.6f" % prim[1], Lmax, "%.6e" % prim[0], "%.6e" % KN, "%.6f" % b256[1] if b256 else "-", "positive" if prim[1] > 1 else "negative",
                            "%.4f" % sh["light"], "%.4f" % sh["mu"], "%.4f" % sh["sqrt2mu"], f(tot, 2), f(tot - spread + (mid or 0), 2)))
    kr = sorted(Rprim, reverse=True)
    if len(kr) > 1:
        summ.append("E3: R's local power d ln R/d ln kappa between neighbouring kappa (each at its primary setting): " + "; ".join(
            "%s -> %s: %s" % (x, y, "%.4g" % (math.log(Rprim[y][0] / Rprim[x][0]) / math.log(y / x))) for x, y in zip(kr[:-1], kr[1:])) + ".")
    out += ["## E3 eta_tot = eta_light + 2 eta_mu + eta_sqrt2mu, K_N (stage 1's primary rule: the kappa-adapted GL panels where present, else the panels "
            "refined toward 0 and pi, 32 nodes) and R = 2 eta_tot/(pi K_N) per kappa and setting", "",
            table(["kappa", "L", "nfft/L", "rule", "eta_tot", "K_N", "R"], rows), ""]
    out += ["## E4 The budget of R (relative changes of eta_tot; K_N's Gauss-Legendre spread and, beside it, its midpoint Richardson difference), and the "
            "sum with either K_N term (a sensitivity estimate, not an enclosure)", "",
            table(["kappa", "K_N GL spread", "K_N midpoint Richardson", "L", "nfft", "inner doubled", "middle 96", "outer 48", "sum (GL)", "sum (midpoint)"], budget_rows), ""]
    if a.bound:
        B = {"rows": [], "eig_check": []}
        for p in a.bound.split(","):
            Bi = json.load(open(p))
            B["rows"] += Bi["rows"]
            B["eig_check"] += Bi.get("eig_check", [])

        def b_over_light(r):
            if "bound_over_eta_light" in r:
                return "%.6f" % r["bound_over_eta_light"]
            el = eta("light", r["kappa"], r["L"], r["nfft"], "production")
            return ("%.6f (eta records)" % (r["eta_bound"] / el)) if el else "-"
        rows = [[r["kappa"], r["L"], r["nfft"] // r["L"], "%.10e" % r["eta_bound"], "%.10e" % r["pi_K_N_over_2"], "%.6f" % r["bound_over_pi_K_N_over_2"],
                 b_over_light(r)] for r in B["rows"]]
        out += ["## E5 The light-sea lower bound eta_bound = sum_w w 4 log 2 Tr[C_R (1 - C_R)]/2 (the Fourier-sum form) against pi K_N/2, and against "
                "eta_light at the same setting; the bound against the eigenvalue form at 64 random channels: " + "; ".join(
                    "kappa %s: %s" % (x["kappa"], f(x["max_rel_diff"], 2)) for x in B["eig_check"]), "",
                table(["kappa", "L", "nfft/L", "eta_bound", "pi K_N/2", "bound/(pi K_N/2)", "bound/eta_light"], rows), ""]
        for kap in kappas:
            rr = [r for r in B["rows"] if r["kappa"] == kap]
            if rr:
                summ.append("E5 (kappa %s): the light-sea lower bound over pi K_N/2 is %s (L = %s)." % (
                    kap, ", ".join("%.4f" % r["bound_over_pi_K_N_over_2"] for r in rr), ", ".join(str(r["L"]) for r in rr)))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
