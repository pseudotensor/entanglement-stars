#!/usr/bin/env python
"""Strand 3 addendum report (builder analyst): tables for parts A to E of SPEC_strand3_addendum.md from addA.json, addB.json,
C/addC.json, addD.json and E/ball_q0_c0_0_0_box96.json (with strand 3's box-64 ball for comparison).  Numbers emitted, not retyped.
(version 2: a pipe inside a table cell is escaped, so headers such as |L - Lmax| keep the columns)"""
import argparse
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")      # a pipe inside a cell is escaped (GFM)
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="addendum1 folder")
    ap.add_argument("--ball64", required=True, help="strand 3's box-64 ball JSON at mass 0, centre (0,0,0)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    out = ["# Strand 3 addendum tables (generated by solve/code/strand3/strand3_addendum_report_v2.py)", ""]
    pA = os.path.join(a.dir, "addA.json")
    if os.path.exists(pA):
        A = json.load(open(pA))
        rows = [[f(r["kappa"]), r["L"], r["nfft"], f(r["K1"]), r["n_cells_inner_side"], "%d/%d/%d" % (r["n_inner"], r["n_middle"], r["n_outer"]),
                 f(r["eta_inner"], 7), f(r["eta_middle"], 7), f(r["eta_outer"], 7), f(r["eta_total"], 7), f(4 * r["eta_total"], 5),
                 f(r["weight_sum_minus_1"])] for r in A["rows"]]
        out += ["## A. The Wilson-type family with the nested transverse quadrature (q = 0, [100]); per-sea targets: flat 2.5e-5 (4 eta = 1e-4), "
                "static 4e-4 (4 eta = 1.6e-3)", "",
                table(["kappa", "L", "nfft", "K_1", "inner cells per side (24-grid)", "channels in/mid/out", "eta inner", "eta middle", "eta outer",
                       "eta total", "4 eta", "weights - 1"], rows), ""]
        conv = []
        for kap in sorted(set(r["kappa"] for r in A["rows"]), reverse=True):
            rr = {(r["L"], r["nfft"]): r["eta_total"] for r in A["rows"] if r["kappa"] == kap}
            Ls = sorted(set(L for L, _ in rr))
            Lmax = max(Ls)
            best = rr.get((Lmax, 32 * Lmax))
            conv.append([f(kap), f(best, 7),
                         " ".join("L%d %s" % (L, f(abs(rr[(L, 32 * L)] - best) / best)) for L in Ls if (L, 32 * L) in rr and L != Lmax),
                         " ".join("L%d %s" % (L, f(abs(rr[(L, 32 * L)] - rr[(L, 16 * L)]) / rr[(L, 32 * L)])) for L in Ls
                                  if (L, 32 * L) in rr and (L, 16 * L) in rr),
                         "below" if best is not None and best < 2.5e-5 else "above", "below" if best is not None and best < 4e-4 else "above"])
        out += ["### A. Convergence (relative change against the longest chain at nfft = 32 L; nfft 16 L against 32 L at each L) and the per-sea "
                "value against the two targets", "",
                table(["kappa", "eta total (longest L, nfft 32 L)", "|L - Lmax| relative", "nfft 16L vs 32L", "flat target 2.5e-5", "static target 4e-4"],
                      conv), ""]
    pB = os.path.join(a.dir, "addB.json")
    if os.path.exists(pB):
        B = json.load(open(pB))
        rows = [[f(r["kappa"]), r["L"], r["nfft"], f(r["K1"]), f(r["eta_inner"], 7), f(r["eta_middle"], 7), f(r["eta_outer"], 7), f(r["eta_total"], 7),
                 f(4 * r["eta_total"], 5)] for r in B["rows"]]
        out += ["## B. The 8-valley family M' = q + kappa'^-1 sum sin^2 k_i (q = 0, [100]), same quadrature", "",
                table(["kappa'", "L", "nfft", "K_1", "eta inner", "eta middle", "eta outer", "eta total", "4 eta"], rows), "",
                "Secant powers d log eta/d log kappa': " + "; ".join("L %d %s-%s: %s" % (p["L"], f(p["kappa_pair"][0]), f(p["kappa_pair"][1]), f(p["p"]))
                                                                    for p in B["secant_powers"]), "",
                "Cone check E/|k| - 1 along [100]: " + "; ".join("kappa' %s |k| %s: %s" % (f(c["kappa"]), f(c["k"]), f(c["E_over_k_minus_1"])) for c in B["cone"]),
                "", "Largest |M'| at the 8 valley centres over all kappa': %s." % f(B["valley_mass_max"]), ""]
    pC = os.path.join(a.dir, "C", "addC.json")
    if os.path.exists(pC):
        C = json.load(open(pC))
        rows = []
        for r in C["rows"]:
            sc = r.get("scan_R100_static_denominator_only", {})
            rows.append([f(r["a_over_lP"]), " ".join(f(q, 6) for q in r["q4"]), f(r["eta100_0"], 7), f(r["eta100_4q2"], 7), f(r["eta100_4q4"], 7),
                         f(r.get("total100_local_static"), 6), f(r.get("R100_static_local")), f(r.get("total_sphere_local_static"), 6),
                         f(r.get("Rsphere_static_local")), " ".join("%s %s" % (k.replace("R100_static_", ""), f(v)) for k, v in sc.items())])
        out += ["## C. The local-uniform static numerator: eta at the masses 4 q_s ((32,24) ladder; mesh-2 sphere at 0.02), the light packet "
                "massless; R^static_local = total/(16 eta_req) beside the denominator-only R/16 of strand 3's scan", "",
                table(["a/l_P", "4 q_2, 4 q_4", "eta_100(0)", "eta_100(4 q_2)", "eta_100(4 q_4)", "total [100]", "R^static_local [100]",
                       "total sphere", "R^static_local sphere", "denominator-only R/16 (ladder: value)"], rows), ""]
    pD = os.path.join(a.dir, "addD.json")
    if os.path.exists(pD):
        Dd = json.load(open(pD))
        rows = []
        for bg, r in Dd.items():
            xs = " ".join("%s: oo %s io %s ii %s" % (k[2:], f(v["outside_outside_rel"]), f(v["inside_outside_rel"]), f(v["inside_inside_rel"]))
                          for k, v in r.items() if k.startswith("X_"))
            rows.append([bg, f(r["cross_boundary_U"]), xs,
                         "%s (frac %d, max dist %s)" % (f(r["restricted_image_under_V"]["entropy"]), r["restricted_image_under_V"]["n_fractional_1e-6"],
                                                       f(r["restricted_image_under_V"]["max_distance_from_0_1"])),
                         "%s (frac %d)" % (f(r["restricted_image_under_Vdag"]["entropy"]), r["restricted_image_under_Vdag"]["n_fractional_1e-6"]),
                         f(r["restricted_A1_sites"]["entropy"])])
        out += ["## D. A2 diagnostics on the 4^3 lattice (m = 0.1, R = {x_1 in {0, 1}}): the cross-boundary block of U; the clock vertex's "
                "support (relative norms of the outside-outside, inside-outside and inside-inside blocks; sites 000 and 100 are in R, 200 is not); "
                "the A1 covariance restricted to the region's image under V = diag(1, U^dag) and under V^dag, and to R's sites", "",
                table(["background", "||P_R U (1 - P_R)||", "X_x blocks", "S on the image under V", "S on the image under V^dag",
                       "S on R's sites (A1)"], rows), ""]
    pE = os.path.join(a.dir, "E", "ball_q0_c0_0_0_box96.json")
    if os.path.exists(pE):
        E = json.load(open(pE))
        b64 = json.load(open(a.ball64))
        rows = [[b["box"], b["sites"], f(b["entropy"], 7), f(b["empirical_stderr"]), f(b["stochastic_bound"]), f(b["eta_finite"], 7)] for b in (b64, E)]
        out += ["## E. The massless ball at radius 8.5, centre (0,0,0), SLQ (32 probes, 96 steps, seed 781): box 96 against box 64 "
                "(eta_finite = S/(4 pi r^2))", "", table(["box", "sites", "S", "empirical stderr", "stochastic bound", "eta_finite"], rows), "",
                "Relative change of eta_finite from box 64 to box 96: %s." % f((E["eta_finite"] - b64["eta_finite"]) / b64["eta_finite"]), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
