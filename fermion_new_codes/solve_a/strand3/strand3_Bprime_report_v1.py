#!/usr/bin/env python
"""Strand 3 addendum parts B' and the part A refinement, report (builder analyst): tables from strand3_Bprime1_v1.py (Bprime1.json) and
strand3_Bprime2_v1.py (Bprime2.json, Arefine.json).  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--b1", required=True)
    ap.add_argument("--b2", required=True)
    ap.add_argument("--arefine", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    B1 = json.load(open(a.b1))
    B2 = json.load(open(a.b2))
    AR = json.load(open(a.arefine))
    out = ["# Strand 3 addendum B' and A-refinement tables (generated by solve/code/strand3/strand3_Bprime_report_v1.py)", ""]
    rows = [[f(r["kappa_prime"]), r["L"], r["nfft"], f(r["eta_total_printed"], 6), f(r["S_at_15_15"], 8), f(r["S_at_165_15"], 8),
             f(r["removed_outer_12_points"], 6), f(r["added_three_origin_patches"], 6), f(r["eta_total_corrected"], 6), f(r["corrected_over_printed"], 5)]
            for r in B1]
    out += ["## B' step 1: part B's printed eta_total with the coarse outer rule's 12 points in the pi/6 squares around (pi, 0), (0, pi), (pi, pi) "
            "removed (each equal to the channel at (pi/12, pi/12) by k_perp,i -> pi - k_perp,i) and three copies of the origin's fine patch "
            "(inner + middle) added; S at (11 pi/12, pi/12) beside S at (pi/12, pi/12) as the symmetry check", "",
            table(["kappa'", "L", "nfft", "printed", "S(15, 15 deg)", "S(165, 15 deg)", "removed", "added", "corrected", "corrected/printed"], rows), ""]
    rows = [[f(r["kappa_prime"]), r["L"], r["nfft"], f(r["inner"], 6), f(r["middle"], 6), f(r["outer_origin_only"], 6), f(r["outer_four_centres"], 6),
             f(r["eta_part_B_rule"], 7), f(r["eta_four_centres"], 7), f(r["ratio"], 5)] for r in B2["rows"]]
    out += ["## B' step 2: the quadrature replicated at the four valley centres (eta = 4 (inner + middle) + the outer rule without the 12 points of "
            "the other three squares) beside part B's rule (inner + middle + the outer rule without the origin's square only)", "",
            table(["kappa'", "L", "nfft", "inner", "middle", "outer (part B)", "outer (four centres)", "part B rule", "four centres", "ratio"], rows), ""]
    rows = [[p["L"], p["nfft"], "%s -> %s" % (f(p["kappa_pair"][0]), f(p["kappa_pair"][1])), f(p["p_four_centres"], 5), f(p["p_part_B_rule"], 5)]
            for p in B2["secant_powers"]]
    out += ["### B' step 2: the secant powers d log eta/d log kappa'", "", table(["L", "nfft", "kappa' pair", "four centres", "part B rule"], rows), ""]
    rows = [[f(r["kappa"]), r["L"], r["nfft"], f(r["K1"], 5), f(r["inner"], 6), f(r["middle_24"], 6), f(r["middle_48"], 6), f(r["outer_12"], 6), f(r["outer_24"], 6),
             f(r["eta_printed_rule"], 6), f(r["eta_middle_refined"], 6), f(r["eta_outer_refined"], 6), f(r["eta_both_refined"], 6),
             f(r["eta_both_refined"] / r["eta_printed_rule"] - 1, 3)] for r in AR["rows"]]
    out += ["## Part A refinement (the Wilson family, one valley): the middle rule 24 x 24 -> 48 x 48 and the outer rule 12 x 12 -> 24 x 24 "
            "separately, each region at both resolutions", "",
            table(["kappa", "L", "nfft", "K_1", "inner", "middle 24", "middle 48", "outer 12", "outer 24", "printed rule", "middle refined",
                   "outer refined", "both refined", "both/printed - 1"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
