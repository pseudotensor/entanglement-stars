#!/usr/bin/env python
"""Strand 3 addendum part F'' report (builder analyst): from strand3_partFpp_K_v1.py (partFpp_K.json) and strand3_partFpp_eta_v1.py
(partFpp_eta.json): (G1) K_N = k_sym(0), k_left(0) and the unmodified k_a(0) by the composite Gauss-Legendre rule (n = 16, 32 per panel)
and the uniform midpoint grid (L = 1024, 2048), the differences, the float64 against 40-digit check of the summed integrands; (G2) the cut-
entropy coefficients eta per sea (modified, kappa = 0.0023; unmodified) and mass at every (L, nfft, quadrature), with the paper's eta.value
(12 x 12) beside the unmodified ones; (G3) eta_tot = eta(0.1) + 2 eta(sqrt(1.01)) + eta(sqrt(2.01)) per inventory and setting, R = 2 eta_tot/(pi K)
with K = K_N (modified) or k_a(0) (unmodified), the ratio R_modified/R_unmodified, and the budget: K's two quadratures (GL n = 32 against
midpoint L = 2048), eta_tot's changes from L = 128 to 256 (nfft 16 L), from nfft 16 L to 32 L (L = 256) and under the transverse refinement
(L = 128, nfft 16 L).  The primary values: K from the midpoint grid at L = 2048, eta_tot at L = 256, nfft 32 L, the production quadrature.
Numbers emitted, not retyped."""
import argparse
import json
import math


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--K", required=True)
    ap.add_argument("--eta", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    K = json.load(open(a.K))
    E = json.load(open(a.eta))
    out = ["# Strand 3 addendum part F'' tables (generated by solve/code/strand3/strand3_partFpp_report_v1.py)", ""]
    summ = []
    names = ("K_N_sym", "k_left", "k_a_unmodified")
    rows = []
    for g in K["gl"]:
        rows.append(["Gauss-Legendre, %d per panel (%d nodes per direction)" % (g["n_per_panel"], g["nodes_per_direction"])] + ["%.15e" % g[n] for n in names])
    for m in K["midpoint"]:
        rows.append(["midpoint, L = %d" % m["L"]] + ["%.15e" % m[n] for n in names])
    gl32 = [g for g in K["gl"] if g["n_per_panel"] == 32][0]
    mp2048 = [m for m in K["midpoint"] if m["L"] == 2048][0]
    mp1024 = [m for m in K["midpoint"] if m["L"] == 1024][0]
    gl16 = [g for g in K["gl"] if g["n_per_panel"] == 16][0]
    rows.append(["GL 32 - midpoint 2048"] + [f(gl32[n] - mp2048[n], 2) for n in names])
    rows.append(["midpoint 2048 - 1024"] + [f(mp2048[n] - mp1024[n], 2) for n in names])
    rows.append(["GL 32 - GL 16"] + [f(gl32[n] - gl16[n], 2) for n in names])
    mc = K["mp_check"]
    out += ["## G1 The q = 0 coefficients of the aH = 1 rectangle at kappa = 0.0023 (masses 0.1, sqrt(1.01) twice, sqrt(2.01); the packets summed inside "
            "the integrand): K_N = k_sym(0) (the symmetric placement, all four packets modified), k_left(0) (the left placement) and the "
            "unmodified k_a(0), by the two quadratures, with their differences", "",
            table(["quadrature", "K_N = k_sym(0)", "k_left(0)", "k_a(0) unmodified"], rows), "",
            "The summed integrands in float64 against 40 digits at %d random points: largest relative difference %s (K_N), %s (k_left), %s (unmodified)." % (
                mc["points"], f(mc["max_rel_diff_sym"], 2), f(mc["max_rel_diff_left"], 2), f(mc["max_rel_diff_unmodified"], 2)), ""]
    summ.append("G1: K_N = %s (midpoint L = 2048; GL n = 32 differs by %s, L = 1024 by %s); k_left(0) = %s; the unmodified k_a(0) = %s." % (
        "%.10e" % mp2048["K_N_sym"], f(gl32["K_N_sym"] - mp2048["K_N_sym"], 2), f(mp1024["K_N_sym"] - mp2048["K_N_sym"], 2), "%.8e" % mp2048["k_left"],
        "%.12f" % mp2048["k_a_unmodified"]))
    rows = []
    for r in E["rows"]:
        rows.append([r["sea"], r["mass"], r["L"], r["nfft"] // r["L"], r["quadrature"], r["channels"], f(r["weight_sum_minus_1"], 2), "%.10e" % r["eta"],
                     ("%.10e" % r["eta_value_12x12"]) if "eta_value_12x12" in r else "-"])
    out += ["## G2 The cut-entropy coefficients eta (along [100]) per sea and mass: the modified seas (M_kappa = m + kappa^-1 sum (1 - cos k_i)) on "
            "part A's nested quadrature, the unmodified seas (constant m) on part C's whole-zone grid, at L, nfft, and the refinement checks; "
            "beside the unmodified ones the paper's eta.value on its 12 x 12 grid", "",
            table(["sea", "mass", "L", "nfft/L", "quadrature", "channels", "weights - 1", "eta", "eta.value 12 x 12"], rows), ""]
    mult = E["meta"]["multiplicities"]

    def eta_tot(sea, L, nf, qprefix):
        rs = {r["mass"]: r["eta"] for r in E["rows"] if r["sea"] == sea and r["L"] == L and r["nfft"] == nf * L and r["quadrature"].startswith(qprefix)}
        if len(rs) < len(mult):
            return None
        return math.fsum(mult[m] * rs[m] for m in mult)
    prod = {"modified": "part A rule", "unmodified": "24 x 24"}
    refq = {"modified": "inner 4 cells", "unmodified": "36 x 36"}
    Kv = {"modified": mp2048["K_N_sym"], "unmodified": mp2048["k_a_unmodified"]}
    rows = []
    res = {}
    for sea in ("modified", "unmodified"):
        for L, nf in ((128, 16), (128, 32), (256, 16), (256, 32)):
            et = eta_tot(sea, L, nf, prod[sea])
            if et is None:
                continue
            Rv = 2 * et / (math.pi * Kv[sea])
            res[(sea, L, nf)] = (et, Rv)
            rows.append([sea, L, nf, prod[sea], "%.10e" % et, "%.10e" % Kv[sea], "%.6e" % Rv])
        er = eta_tot(sea, 128, 16, refq[sea])
        if er is not None:
            rows.append([sea, 128, 16, refq[sea], "%.10e" % er, "%.10e" % Kv[sea], "%.6e" % (2 * er / (math.pi * Kv[sea]))])
            res[(sea, "ref")] = (er, 2 * er / (math.pi * Kv[sea]))
    out += ["## G3 eta_tot = eta(0.1) + 2 eta(sqrt(1.01)) + eta(sqrt(2.01)) per inventory and setting, K (K_N for the modified inventory, the unmodified "
            "k_a(0) for the unmodified one; midpoint L = 2048), and R = 2 eta_tot/(pi K)", "", table(["inventory", "L", "nfft/L", "quadrature", "eta_tot", "K", "R"], rows), ""]
    if ("modified", 256, 32) in res and ("unmodified", 256, 32) in res:
        em, Rm = res[("modified", 256, 32)]
        eu, Ru = res[("unmodified", 256, 32)]
        budget = {}
        for sea, (e0, R0) in (("modified", (em, Rm)), ("unmodified", (eu, Ru))):
            dL = abs(res[(sea, 256, 16)][0] - res[(sea, 128, 16)][0]) / e0 if (sea, 128, 16) in res and (sea, 256, 16) in res else None
            dn = abs(res[(sea, 256, 32)][0] - res[(sea, 256, 16)][0]) / e0 if (sea, 256, 16) in res else None
            dq = abs(res[(sea, "ref")][0] - res[(sea, 128, 16)][0]) / e0 if (sea, "ref") in res and (sea, 128, 16) in res else None
            name = "K_N_sym" if sea == "modified" else "k_a_unmodified"
            dK = abs(gl32[name] - mp2048[name]) / abs(mp2048[name])
            budget[sea] = {"L": dL, "nfft": dn, "transverse": dq, "K": dK, "total": sum(x for x in (dL, dn, dq, dK) if x is not None)}
        rows = [[sea, f(b["K"], 2), f(b["L"], 2), f(b["nfft"], 2), f(b["transverse"], 2), f(b["total"], 2)] for sea, b in budget.items()]
        out += ["## G4 The budget of R (relative): K's two quadratures (GL n = 32 against midpoint L = 2048), eta_tot's change from L = 128 to 256 (nfft 16 L), "
                "from nfft 16 L to 32 L (L = 256) and under the transverse refinement (L = 128, nfft 16 L), and their sum", "",
                table(["inventory", "K quadratures", "L", "nfft", "transverse", "sum"], rows), ""]
        summ.append("G3: R(modified) = %s (eta_tot %s, K_N %s) and R(unmodified) = %s (eta_tot %s, k_a(0) %s) at L = 256, nfft 32 L; the ratio "
                    "R(modified)/R(unmodified) = %s; budgets %s (modified) and %s (unmodified) relative." % (
                        "%.6e" % Rm, "%.6e" % em, "%.6e" % Kv["modified"], "%.6e" % Ru, "%.6e" % eu, "%.6e" % Kv["unmodified"], "%.6e" % (Rm / Ru),
                        f(budget["modified"]["total"], 2), f(budget["unmodified"]["total"], 2)))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
