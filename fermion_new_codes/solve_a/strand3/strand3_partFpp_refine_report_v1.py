#!/usr/bin/env python
"""Strand 3 addendum part F''(b) report (builder analyst): from strand3_partFpp_refine_v1.py (partFpp_refine.json) and part F'''s records
(partFpp_K.json, partFpp_eta.json): (B1) per mass the region sums, the printed rule's eta (inner + middle24 + outer12) against part F'''s
recorded eta at L = 128, nfft 16 L (the control), and eta with the middle rule refined, the outer rule refined and both, with the relative
changes; (B2) eta_tot = eta(0.1) + 2 eta(sqrt(1.01)) + eta(sqrt(2.01)) and R = 2 eta_tot/(pi K_N) (K_N part F'''s midpoint L = 2048 value) for
the four rules at L = 128, nfft 16 L, and the relative changes of R; (B3) part F'''s budget restated as the sum of the measured changes: its
K quadratures, L (128 -> 256 at nfft 16 L), nfft (16 L -> 32 L at L = 256) and inner-square terms recomputed from its records, plus the middle
and outer refinements (a sensitivity estimate, not an enclosure); R(modified) at part F'''s primary setting (L = 256, nfft 32 L) beside it.
Numbers emitted, not retyped."""
import argparse
import json
import math


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


RULES = {"printed (inner, middle24, outer12)": ("inner", "middle24", "outer12"), "middle refined (48)": ("inner", "middle48", "outer12"),
         "outer refined (24)": ("inner", "middle24", "outer24"), "both refined": ("inner", "middle48", "outer24")}
MULT = {"0.1": 1, "sqrt(1.01)": 2, "sqrt(2.01)": 1}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refine", required=True)
    ap.add_argument("--K", required=True)
    ap.add_argument("--eta", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    D = json.load(open(a.refine))
    K = json.load(open(a.K))
    E = json.load(open(a.eta))
    reg = {(r["mass"], r["region"]): r["eta"] for r in D["rows"]}
    mp2048 = [m for m in K["midpoint"] if m["L"] == 2048][0]
    gl32 = [g for g in K["gl"] if g["n_per_panel"] == 32][0]
    KN = mp2048["K_N_sym"]
    out = ["# Strand 3 addendum part F''(b) tables (generated by solve/code/strand3/strand3_partFpp_refine_report_v1.py)", ""]
    summ = []
    rows = []
    etas = {}
    for m in MULT:
        rec = [x for x in E["rows"] if x["sea"] == "modified" and x["mass"] == m and x["L"] == 128 and x["nfft"] == 16 * 128 and x["quadrature"].startswith("part A rule")]
        recorded = rec[0]["eta"] if rec else None
        for rn, parts in RULES.items():
            v = math.fsum(reg[(m, p)] for p in parts)
            etas[(m, rn)] = v
        base = etas[(m, "printed (inner, middle24, outer12)")]
        rows.append([m] + ["%.6e" % reg[(m, p)] for p in ("inner", "middle24", "middle48", "outer12", "outer24")] + ["%.10e" % base, "%.10e" % recorded if recorded else "-",
                     f(base - recorded, 2) if recorded else "-"] + [f(etas[(m, rn)] / base - 1, 3) for rn in list(RULES)[1:]])
    out += ["## B1 Per mass (kappa = 0.0023, L = 128, nfft 16 L): the region sums, the printed rule's eta against part F'''s recorded eta (the control), and "
            "the relative changes of eta with the middle rule refined, the outer rule refined and both", "",
            table(["mass", "inner", "middle24", "middle48", "outer12", "outer24", "eta (printed rule)", "part F'' record", "difference", "middle refined",
                   "outer refined", "both"], rows), ""]
    rows = []
    Rv = {}
    for rn in RULES:
        et = math.fsum(MULT[m] * etas[(m, rn)] for m in MULT)
        Rv[rn] = 2 * et / (math.pi * KN)
        rows.append([rn, "%.10e" % et, "%.6e" % KN, "%.6f" % Rv[rn], f(Rv[rn] / Rv["printed (inner, middle24, outer12)"] - 1, 3)])
    out += ["## B2 eta_tot and R = 2 eta_tot/(pi K_N) for the four rules at L = 128, nfft 16 L (K_N part F'''s midpoint L = 2048 value), and R's relative change", "",
            table(["rule", "eta_tot", "K_N", "R", "R/R(printed) - 1"], rows), ""]
    base = "printed (inner, middle24, outer12)"
    dmid = abs(Rv["middle refined (48)"] / Rv[base] - 1)
    dout = abs(Rv["outer refined (24)"] / Rv[base] - 1)
    dboth = abs(Rv["both refined"] / Rv[base] - 1)
    # part F'''s own budget terms from its records (the modified inventory)
    mult = E["meta"]["multiplicities"]

    def eta_tot(L, nf, qprefix):
        rs = {r["mass"]: r["eta"] for r in E["rows"] if r["sea"] == "modified" and r["L"] == L and r["nfft"] == nf * L and r["quadrature"].startswith(qprefix)}
        if len(rs) < len(mult):
            return None
        return math.fsum(mult[m] * rs[m] for m in mult)
    e256_32 = eta_tot(256, 32, "part A rule")
    e256_16 = eta_tot(256, 16, "part A rule")
    e128_16 = eta_tot(128, 16, "part A rule")
    eref = eta_tot(128, 16, "inner 4 cells")
    dK = abs(gl32["K_N_sym"] - KN) / abs(KN)
    dL = abs(e256_16 - e128_16) / e256_32
    dn = abs(e256_32 - e256_16) / e256_32
    dq = abs(eref - e128_16) / e256_32
    tot = dK + dL + dn + dq + dmid + dout
    Rprim = 2 * e256_32 / (math.pi * KN)
    out += ["## B3 Part F'''s budget of R restated (relative): its four measured terms recomputed from its records (K quadratures GL 32 against midpoint 2048; "
            "L 128 -> 256 at nfft 16 L; nfft 16 L -> 32 L at L = 256; the inner square of four cells at L = 128) plus the middle and outer refinements of B2, "
            "and their sum (a sensitivity estimate, not an enclosure); R(modified) at part F'''s primary setting", "",
            table(["K", "L", "nfft", "inner square", "middle refined", "outer refined", "both (B2)", "sum", "R primary (L = 256, nfft 32 L)"],
                  [[f(dK, 2), f(dL, 2), f(dn, 2), f(dq, 2), f(dmid, 2), f(dout, 2), f(dboth, 2), f(tot, 2), "%.6f" % Rprim]]), ""]
    ctl = max(abs(etas[(m, base)] - [x for x in E["rows"] if x["sea"] == "modified" and x["mass"] == m and x["L"] == 128 and x["nfft"] == 2048 and
                                      x["quadrature"].startswith("part A rule")][0]["eta"]) / etas[(m, base)] for m in MULT)
    summ.append("B1: the printed rule recomputed (D4 orbits) reproduces part F'''s recorded eta to %s relative (largest over the masses)." % f(ctl, 2))
    summ.append("B2: refining the middle rule (24 -> 48) changes R by %s, the outer rule (12 -> 24) by %s, both by %s (relative, at L = 128, nfft 16 L)." % (
        f(Rv["middle refined (48)"] / Rv[base] - 1, 3), f(Rv["outer refined (24)"] / Rv[base] - 1, 3), f(Rv["both refined"] / Rv[base] - 1, 3)))
    summ.append("B3: part F'''s budget restated as the sum of the measured changes: %s relative (its four earlier terms %s, the two refinements %s and %s); "
                "R(modified) at its primary setting %s." % (f(tot, 2), f(dK + dL + dn + dq, 2), f(dmid, 2), f(dout, 2), "%.6f" % Rprim))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
