#!/usr/bin/env python
"""Strand 3 report: tables A.1 to A.5, B, C and controls C1 to C7 from the run directory (no physics reading).
Every number in solve/results/RESULT_strand3_entropy.md comes from here (builder analyst)."""
import argparse
import glob
import json
import os


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, str):
        return v
    v = float(v)
    if v == 0:
        return "0"
    a = abs(v)
    if a < 1e-3 or a >= 1e5:
        return "%.*e" % (sig - 1, v)
    return "%.*g" % (sig, v)


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def key(q):
    return "%.12g" % q


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = a.run
    M = json.load(open(os.path.join(R, "masses.json")))
    P = {}
    for fn in glob.glob(os.path.join(R, "planar", "planar_*.json")):
        r = json.load(open(fn))
        P[(tuple(r["normal"]), int(r["depth"]), int(r["nk"]), key(r["mass"]))] = r
    S = {}
    for fn in glob.glob(os.path.join(R, "sphere", "sphere_q*.json")):
        r = json.load(open(fn))
        S[key(r["mass"])] = r
    B = {}
    for fn in glob.glob(os.path.join(R, "balls", "ball_*.json")):
        B[os.path.basename(fn)] = json.load(open(fn))
    scan = json.load(open(os.path.join(R, "scan.json"))) if os.path.exists(os.path.join(R, "scan.json")) else None
    pB = json.load(open(os.path.join(R, "partB.json"))) if os.path.exists(os.path.join(R, "partB.json")) else None
    pC = json.load(open(os.path.join(R, "partC.json"))) if os.path.exists(os.path.join(R, "partC.json")) else None
    parts = ["# Strand 3 tables (generated by solve/code/strand3/strand3_report.py; numbers not retyped)", ""]
    # ---------------- controls
    rows = []
    ref = [(((1, 0, 0), 16, 12), 0.7849544816), (((1, 0, 0), 32, 24), 0.7861807702), (((1, 1, 0), 16, 12), 0.8678995706),
           (((1, 1, 1), 16, 12), 0.9227654142)]
    for (p, d, nk), v in ref:
        r = P.get((p, d, nk, key(0.0)))
        rows.append(["C1 eta%s (%d,%d) at q = 0 against %s" % ("".join(map(str, p)), d, nk, v), "<= 1e-9",
                     "-" if r is None else "%s (diff %s)" % (repr(r["eta"]), f(r["eta"] - v))])
    s0 = S.get(key(0.0))
    rows.append(["C1 sphere mesh 2 (16,12) at q = 0 against 0.9001144", "<= 1e-6",
                 "-" if s0 is None else "%s (diff %s)" % (repr(s0["eta_sphere"]), f(s0["eta_sphere"] - 0.9001144))])
    vb = os.path.join(R, "verify_basic.log")
    rows.append(["C1 verify_entropy.py basic()", "PASS", open(vb).read().strip().splitlines()[-1] if os.path.exists(vb) else "-"])
    seq = sorted([(r["mass"], r["eta"]) for (p, d, nk, k), r in P.items() if p == (1, 0, 0) and d == 32 and nk == 24])
    viol = [(q1, e1, q2, e2) for (q1, e1), (q2, e2) in zip(seq[:-1], seq[1:]) if e2 > e1]
    rows.append(["C2 eta_100(q) non-increasing over Q, (32,24) ladder: violations", "none",
                 "%d of %d steps%s" % (len(viol), max(len(seq) - 1, 0),
                                       "" if not viol else "; first q %s -> %s" % (f(viol[0][0]), f(viol[0][2])))])
    seq16 = sorted([(r["mass"], r["eta"]) for (p, d, nk, k), r in P.items() if p == (1, 0, 0) and d == 16 and nk == 12])
    viol16 = [(q1, q2) for (q1, e1), (q2, e2) in zip(seq16[:-1], seq16[1:]) if e2 > e1]
    rows.append(["C2 same, (16,12) ladder", "none", "%d of %d steps" % (len(viol16), max(len(seq16) - 1, 0))])
    lerr = [r["error_components"]["length"] for (p, d, nk, k), r in P.items() if p == (1, 0, 0) and r["mass"] >= 1]
    rows.append(["C2 length error component for q >= 1 (max)", "<= 1e-8", f(max(lerr)) if lerr else "-"])
    c3 = M["C3"]
    rows.append(["C3 sum_s eta_s m_s^2 (max abs over lambda)", "0 to 1e-12", f(max(abs(c["sum_eta_m2"]) for c in c3))])
    rows.append(["C3 J from masses - h_1 g(lambda) (max abs)", "<= 1e-12", f(max(abs(c["J_minus_formula"]) for c in c3))])
    rows.append(["C3 6J/pi - 1 (m_P^2 = 1) (max abs)", "<= 1e-12", f(max(abs(c["mP2_from_J_minus_1"]) for c in c3))])
    rows.append(["C3 eta_req(1.909) and its difference from the paper's 4 pi Zhat_0 = 0.9106", "report",
                 "%s (diff %s)" % (f(M["eta_req_1.909"], 6), f(M["eta_req_1.909"] - M["paper_4piZhat0"]))])
    if pB:
        rows.append(["C4 two independent copies: S - 2 S_R (max over backgrounds)", "<= 1e-12",
                     f(max(b["C4_two_copies_minus_2S"] for b in pB["backgrounds"].values()))])
        rows.append(["C5 part B: max |C' - (1 - sigma_1)/2 (x) 1| / S_R^A2 / restricted-spectrum distance from {0,1} (max over backgrounds)",
                     "<= 1e-12", "%s / %s / %s" % (f(max(b["A2_max_dev_from_product_projector"] for b in pB["backgrounds"].values())),
                                                   f(max(abs(b["S_R_A2"]) for b in pB["backgrounds"].values())),
                                                   f(max(b.get("A2_max_restricted_eig_distance_from_0_1", float("nan")) for b in pB["backgrounds"].values())))])
        rows.append(["C7 min eig B_1 (part B backgrounds, m = 0.1)", "> 0",
                     ", ".join("%s %s" % (k, f(b["B4_min_eig_B1"])) for k, b in pB["backgrounds"].items())])
    if pC:
        ctl = [r for r in pC["rows"] if "split_minus_uniform" in r]
        rows.append(["C6 kappa = 1e6: split total - eta.value(12 x 12 uniform) at L = 64, nfft = 1024", "report",
                     "; ".join("q = %s: %s" % (f(r["q"]), f(r["split_minus_uniform"])) for r in ctl)])
        rows.append(["C6 sum of weights - 1 (max abs)", "<= 1e-12", f(max(abs(r["weight_sum_minus_1"]) for r in pC["rows"]))])
    parts += ["## Controls C1 to C7", "", table(["control", "tolerance", "measured"], rows), ""]
    # ---------------- A.1
    rows = []
    for q in M["Q"]:
        cells = [f(q, 6)]
        for (d, nk) in ((16, 12), (32, 24), (64, 12)):
            r = P.get(((1, 0, 0), d, nk, key(q)))
            if r is None:
                cells += ["-", "-"]
            else:
                e = r["error_components"]
                cells += [repr(round(r["eta"], 10)), "%s / %s / %s" % (f(e["length"]), f(e["transverse"]), f(e["Fourier"]))]
        rows.append(cells)
    parts += ["## A.1 Planar [100] coefficient eta_100(q) (eta.converge; error components length / transverse / Fourier)", "",
              table(["q", "eta (16,12)", "errors (16,12)", "eta (32,24)", "errors (32,24)", "eta (64,12)", "errors (64,12)"], rows), ""]
    # ---------------- A.2
    rows = []
    for q in (0.0, 0.02, 0.1, 0.5, 1.0):
        cells = [f(q)]
        for p in ((1, 1, 0), (1, 1, 1)):
            r = P.get((p, 16, 12, key(q)))
            cells.append("-" if r is None else repr(round(r["eta"], 10)))
        r = P.get(((1, 0, 0), 16, 12, key(q)))
        cells.append("-" if r is None else repr(round(r["eta"], 10)))
        rows.append(cells)
    parts += ["## A.2 Planar [110] and [111] at (16,12) (with [100] for comparison)", "",
              table(["q", "eta_110", "eta_111", "eta_100"], rows), ""]
    # ---------------- A.3
    rows = []
    for q in M["sphere_masses"]:
        s = S.get(key(q))
        if s is None:
            rows.append([f(q, 6), "-", "-", "-", "-"])
        else:
            rows.append([f(q, 6), repr(round(s["eta_sphere"], 8)), f(s["planar_error_estimate"]), f(s["geometric_error_bound"]),
                         s["distinct_normals"]])
    parts += ["## A.3 Sphere average, angular mesh 2, (16,12) (sphere_mass.py; errors as the code prints them, not certified)", "",
              table(["q", "eta_sphere", "planar error estimate", "geometric bound", "distinct normals"], rows), ""]
    # ---------------- A.4
    rows = []
    for name in sorted(B):
        b = B[name]
        rows.append([name, f(b["mass"]), " ".join(f(c) for c in b["center"]), b["sites"], f(b["entropy"], 6),
                     f(b["eta_finite"], 6), f(b.get("empirical_stderr")), f(b.get("lanczos_bound")), f(b.get("stochastic_bound"))])
    parts += ["## A.4 Ball cut, radius 8.5, box 64, SLQ (32 probes, 96 steps, seed 781)", "",
              table(["run", "q", "center", "sites", "S", "S/(4 pi r^2)", "empirical stderr", "Lanczos bound", "stochastic bound"], rows), ""]
    # ---------------- A.5
    if scan:
        rows = []
        for r in scan["rows"]:
            rows.append([f(r["a_over_lP"]), f(r["lambda"]), " ".join(f(v, 5) for v in r["q"]), f(r["eta_req"]),
                         f(r.get("eta_tot100_32_24"), 6), f(r.get("R100_32_24")), f(r.get("R100_16_12")),
                         " ".join(f(v, 3) for v in r.get("shares_32_24", [])), f(r.get("R_sphere")),
                         f(r.get("R100_static_32_24")), f(r.get("R_sphere_static")),
                         f(r["allowed_beta"]), f(r["allowed_LLR"])])
        lp = scan["light_packet_only"]
        parts += ["## A.5 Assembly over the scan (R = eta_tot/eta_req; shares = eta_100(q_s)/eta_tot, packets 1..4)", "",
                  table(["a/l_P", "lambda", "q_1..q_4", "eta_req", "eta_tot^100 (32,24)", "R^100 (32,24)", "R^100 (16,12)",
                         "shares (32,24)", "R^sphere", "R^static = R^100/16 (32,24)", "R^sphere/16",
                         "allowed (beta)", "allowed (LLR)"], rows), "",
                  "Second column (spec sec. 3, added 2026-10-14): the cut counted at the static-chart proper spacing a_H = psi_H^2 a = 4a, "
                  "eta_req^static = 16 eta_req, R^static = R/16; the first columns are the flat-native convention (a_H = a).", "",
                  "Light packet only at a/l_P = 1.909 (eta_req %s): R_1^sphere = %s; R_1^100 (16,12) = %s; R_1^100 (32,24) = %s." % (
                      f(lp["eta_req_1.909"], 6), f(lp.get("R1_sphere"), 6), f(lp.get("R1_100_16_12"), 6), f(lp.get("R1_100_32_24"), 6)), ""]
        c3rows = [[f(c["lambda"]), f(c["h1_over_mP2"], 8), " ".join(f(v, 6) for v in c["m_over_mP"])] for c in M["C3"]]
        parts += ["### The mass rectangle from the one match (m_P = 1)", "", table(["lambda", "h_1/m_P^2", "m_1..m_4 / m_P"], c3rows), ""]
    # ---------------- B
    if pB:
        rows = []
        for k, b in pB["backgrounds"].items():
            rows.append([k, f(b["S_R_A1"], 6), f(b["A2_max_dev_from_product_projector"]), f(b["S_R_A2"]), f(b["B3_S_R"], 6),
                         f(b["B3_max_dev_from_product_projector"]), f(b["B3_max_restricted_eig_distance_from_0_1"]),
                         f(b["B3_max_entry_distance_from_0_1"]), f(b["B4_min_eig_B1"]), f(b["min_eig_AdagA"])])
        parts += ["## Part B: 4 x 4 x 4 periodic lattice, m = 0.1, region x_1 in {0, 1} (%d modes)" % pB["checks"]["R_modes"], "",
                  table(["background", "S_R (A1, c-frame)", "max |C' - (1 - sigma_1)/2 (x) 1| (A2)", "S_R (A2)", "S_R (B.3, V' = diag(U,1))",
                         "B.3 max |C'' - (1 - sigma_1)/2 (x) 1|", "B.3 max restricted-eig distance from {0,1}",
                         "B.3 max entry distance from {0,1}", "min eig B_1", "min eig A^dag A"], rows), ""]
    # ---------------- C
    if pC:
        rows = []
        for r in pC["rows"]:
            rows.append([f(r["kappa"]), f(r["q"]), r["j"], f(r["K"]), "%d + %d" % (r["n_inner"], r["n_outer"]), f(r["eta_inner"], 6),
                         f(r["eta_outer"], 6), f(r["eta_total"], 6), f(4 * r["eta_total"]), f(r["M_pi00"])])
        parts += ["## Part C (scouting, not the model): eta_100 for M_kappa(k) = q + kappa^-1 sum(1 - cos k_i), L = %d, nfft = %d" % (
            pC["meta"]["L"], pC["meta"]["nfft"]), "",
            table(["kappa", "q", "j", "K", "channels inner + outer", "eta_inner", "eta_outer", "eta_total", "4 eta_total", "M(pi,0,0)"], rows), ""]
        rows = []
        for q, lst in pC["local_power"].items():
            for x in lst:
                rows.append([q, "%s -> %s" % (f(x["kappa_pair"][0]), f(x["kappa_pair"][1])), f(x["p"])])
        parts += ["### C.2 local power d log eta_total / d log kappa (kappa <= 0.1)", "", table(["q", "kappa pair", "p"], rows), ""]
        rows = [[q, json.dumps(v)] for q, v in pC["target_kappa"].items()]
        parts += ["### C.2 the kappa at which 4 eta_total = 1e-4 (log-log interpolation; scouting)", "", table(["q", "result"], rows), ""]
        rows = [[f(c["kappa"]), f(c["k"]), f(c["E_over_k_minus_1"])] for c in pC["cone"]]
        parts += ["### C.3 cone check along [100], q = 0", "", table(["kappa", "|k|", "E_kappa(k)/|k| - 1"], rows), ""]
    with open(a.md, "w") as fh:
        fh.write("\n".join(parts) + "\n")
    print("wrote %s" % a.md)


if __name__ == "__main__":
    main()
