#!/usr/bin/env python
"""Strand 3 addendum part F report (builder analyst): tables from strand3_partF_v1.py (partF.json, control.json) and
strand3_partF_mpcheck_v1.py (control_mp.json), with eta_kappa from part A's Table A (addA.json: L = 256, nfft = 32 L) and the unmodified
massless sea's [100] coefficient (strand 3's planar record at depth 32, nk 24, q = 0) for kappa = infinity.
Variant 1: the light packet carries M_kappa, the heavy packets unmodified; variant 2: all four packets carry M_kappa (same placement).
k_a(0) by the least-squares fit a + b q^2 over q <= aH/4 where at least four points exist, else the smallest-q value (stated per row);
K_N = a^2 k_a(0) (a = 1); R = 2 eta_tot/(pi K_N) with eta_tot = 4 eta_kappa (the single-packet scout's four copies); eta at kappa = 0.0023
by eta proportional to kappa^p between Table A's kappa = 0.003 and 0.002 rows (p their secant power; the lead's interpolation).
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def kkey(k):
    return "inf" if k == "inf" else round(float(k), 10)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--control", required=True)
    ap.add_argument("--mp", required=True)
    ap.add_argument("--addA", required=True)
    ap.add_argument("--eta-inf", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.run))
    C = json.load(open(a.control))
    MP = json.load(open(a.mp))
    AA = json.load(open(a.addA))
    EI = json.load(open(a.eta_inf))
    meta = R["meta"]
    L = meta["L"]
    out = ["# Strand 3 addendum part F tables (generated by solve/code/strand3/strand3_partF_report_v1.py)", ""]
    # ---- controls
    rows = []
    for s in meta["settings"]:
        xs = [x for x in C["packet_terms"] if x["setting"] == s]
        rows.append([s, len(xs), f(max(x["rel_W2"] for x in xs), 2), f(max(x["rel_W11"] for x in xs), 2)])
    out += ["## F0a Control: kappa = infinity (M = m) against strand2c_kernel_v1.packet_terms at L = 128, n in {1, 2, 5, 17, 64}, every distinct "
            "mass of the setting, both placements: the largest relative difference of U'' - T'' and of W^(11)", "",
            table(["setting", "comparisons", "max rel W^(2)", "max rel W^(11)"], rows), ""]
    rows = [[r["L"], r["kappa"], r["placement"], f(r["W2_route"], 13), f(r["W2_R2"], 13), f(r["rel_R2"], 3), f(r["rel_R1"], 3), f(r["W_at_0"], 2)]
            for r in C["dense"]]
    out += ["## F0b Control: the float64 dense real-space W_0 of one packet (m = 0.1, q = 2 pi/L, twist 0) on the L^3 box, eps in {2e-2, 1e-2, 5e-3} "
            "both signs, twice extrapolated (R2) and once (R1), against this route's W^(2) (the dense value W(0), zero in exact arithmetic, "
            "shows the trace-difference rounding)", "",
            table(["L", "kappa", "placement", "W^(2) route", "W^(2) dense R2", "relative (R2)", "relative (R1)", "dense W(0)"], rows), ""]
    rows = [[r["L"], r["Lp"], f(r["kappa"]), r["placement"], f(r["W2_route"], 15), r["R2_digits"], f(r["rel_R2"], 3), f(r["rel_R1"], 3), f(r["seconds"], 4)]
            for r in MP]
    out += ["## F0c Control: the dense real-space W_0 in mpmath at 40 digits on the L x Lp x Lp box (m = 0.1, q = 2 pi/L, twist 0), eps in {1e-3, "
            "5e-4, 2.5e-4} both signs, twice extrapolated, against this route on the same box", "",
            table(["L", "Lp", "kappa", "placement", "W^(2) route", "W^(2) mpmath (25 digits)", "relative (R2)", "relative (R1)", "seconds"], rows), ""]
    # ---- kernels
    tab = {}
    for r in R["rows"]:
        tab[(r["setting"], r["n"], round(r["m"], 14), kkey(r["kappa"]), r["placement"])] = r
    kap_list = ["inf"] + [round(k, 10) for k in meta["kappas"]]
    # eta: Table A at L = 256, nfft = 32 L
    eA = {round(r["kappa"], 10): r["eta_total"] for r in AA["rows"] if r["L"] == 256 and r["nfft"] == 32 * 256}
    p = np.log(eA[0.003] / eA[0.002]) / np.log(0.003 / 0.002)
    eta = {"inf": EI["eta"], 0.003: eA[0.003], 0.002: eA[0.002], 0.0023: eA[0.002] * (0.0023 / 0.002) ** p}
    esrc = {"inf": "planar [100] q = 0, depth 32, nk 24", 0.003: "Table A", 0.002: "Table A", 0.0023: "Table A, kappa^%s between 0.003 and 0.002" % f(p, 5)}
    out += ["## F1 eta per sea used in R: Table A (L = 256, nfft = 32 L) and the unmodified massless sea", "",
            table(["kappa", "eta per sea", "source"], [[str(k), f(eta[k], 7), esrc[k]] for k in kap_list]), ""]
    rowsK = []
    rowsR = []
    nsmall = [1, 2, 3, 5, 8, 16, 32, 64]
    for s, S in meta["settings"].items():
        ms = [round(m, 14) for m in S["masses"]]
        etas = S["etas"]
        aH = S["aH"]
        ns = sorted({k[1] for k in tab if k[0] == s})
        qs = np.array([2 * np.pi * n / L for n in ns])
        fitn = [n for n, q in zip(ns, qs) if q <= aH / 4]
        Kinf = None
        for kap in kap_list:
            pls = ["any"] if kap == "inf" else ["left", "sym"]
            for pl in pls:
                for var in ((1,) if kap == "inf" else (1, 2)):
                    def ka(n):
                        tot = 0.0
                        for i, (m, e) in enumerate(zip(ms, etas)):
                            if i == 0 or var == 2:
                                key = (s, n, m, kap, pl)
                            else:
                                key = (s, n, m, "inf", "any")
                            tot += e * tab[key]["k"]
                        return tot
                    kav = np.array([ka(n) for n in ns])
                    if len(fitn) >= 4:
                        idx = [ns.index(n) for n in fitn]
                        X = np.stack([np.ones(len(idx)), qs[idx] ** 2], 1)
                        c, *_ = np.linalg.lstsq(X, kav[idx], rcond=None)
                        K = c[0]
                        how = "fit over n = %d..%d (q <= aH/4)" % (fitn[0], fitn[-1])
                    else:
                        K = kav[0]
                        how = "smallest q (n = 1; %d points with q <= aH/4)" % len(fitn)
                    if kap == "inf":
                        Kinf = K
                    lab = "unmodified" if kap == "inf" else "variant %d" % var
                    rowsK.append([s, str(kap), pl, lab] + [f(kav[ns.index(n)], 6) for n in nsmall if n in ns] + [f(K, 7), how, f(K / Kinf, 6)])
                    et = 4 * eta[kap]
                    Rv = 2 * et / (np.pi * K)
                    Rinf = 2 * 4 * eta["inf"] / (np.pi * Kinf)
                    rowsR.append([s, str(kap), pl, lab, f(et, 6), f(K, 7), f(Rv, 6), f(Rv / Rinf, 6)])
    out += ["## F2 The inventory's k_a(q) at n = %s (q = 2 pi n/%d) per setting, kappa, placement (left: M psi^-1; sym: psi^-1/2 M psi^-1/2) and variant "
            "(1: the light packet carries M_kappa; 2: all four), K_N = k_a(0) and K_N(kappa)/K_N(infinity)" % (", ".join(str(n) for n in nsmall), L), "",
            table(["setting", "kappa", "placement", "variant"] + ["n = %d" % n for n in nsmall] + ["K_N", "K_N from", "K_N/K_N(inf)"], rowsK), ""]
    out += ["## F3 The matched ratio R = 2 eta_tot/(pi K_N), eta_tot = 4 eta_kappa (F1), and R/R(infinity)", "",
            table(["setting", "kappa", "placement", "variant", "eta_tot", "K_N", "R", "R/R(inf)"], rowsR), ""]
    # ---- per packet at n = 1
    rows = []
    for s, S in meta["settings"].items():
        for m in sorted({round(x, 14) for x in S["masses"]}):
            base = tab[(s, 1, m, "inf", "any")]["k"]
            for kap in kap_list[1:]:
                for pl in ("left", "sym"):
                    r = tab[(s, 1, m, kap, pl)]
                    rows.append([s, f(m, 6), str(kap), pl, f(r["k"], 8), f(base, 8), f(r["k"] / base, 6), f(r["mixed"] / r["k"], 4)])
    out += ["## F4 Single packets at n = 1: k with M_kappa against the unmodified packet, their ratio, and mixed/k (the clock-ruler coefficient "
            "relative to the ruler-ruler one)", "", table(["setting", "m", "kappa", "placement", "k (M_kappa)", "k (unmodified)", "ratio", "mixed/k"], rows), ""]
    out.append("Run: %s seconds on %s (L = %d)." % (f(meta.get("seconds"), 4), meta.get("host"), L))
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
