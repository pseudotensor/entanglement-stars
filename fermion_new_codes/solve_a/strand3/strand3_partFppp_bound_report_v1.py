#!/usr/bin/env python
"""Strand 3 addendum part F'''(d), the light-sea lower bound's report (builder analyst): from strand3_partFppp_bound_v2.py (partFppp_bound.json):
per kappa and L the bound eta_bound = sum_w w 4 log 2 Tr[C_R (1 - C_R)]/2 against pi K_N/2 (K_N from the stage-1 rule recorded, kappa-adapted
where present), the ratio, the annulus's geometric cell count, and the Fourier-sum form against the eigenvalue form at 64 random channels;
the ratio's local power in kappa at the largest L.  Numbers emitted, not retyped."""
import argparse
import json
import math


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bound", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    B = json.load(open(a.bound))
    rows = ["| %s | %s | %s | %d | %.10e | %.10e | %.6f |" % (r["kappa"], B["meta"]["K_N_rule"].get(str(r["kappa"]), "-"), B["meta"]["n_geo"].get(str(r["kappa"]), "-"),
                                                          r["L"], r["eta_bound"], r["pi_K_N_over_2"], r["bound_over_pi_K_N_over_2"]) for r in B["rows"]]
    Lmax = max(r["L"] for r in B["rows"])
    top = sorted([r for r in B["rows"] if r["L"] == Lmax], key=lambda r: -r["kappa"])
    pw = ["%s -> %s: %s" % (x["kappa"], y["kappa"], "%.4g" % (math.log(y["bound_over_pi_K_N_over_2"] / x["bound_over_pi_K_N_over_2"]) / math.log(y["kappa"] / x["kappa"])))
          for x, y in zip(top[:-1], top[1:])]
    summ = ["E5d: the light-sea lower bound over pi K_N/2 at L = %d: %s; its local power in kappa %s; the Fourier-sum form against the eigenvalue form: %s." % (
        Lmax, ", ".join("%s at kappa %s" % ("%.4f" % r["bound_over_pi_K_N_over_2"], r["kappa"]) for r in top), "; ".join(pw),
        "; ".join("kappa %s %s" % (x["kappa"], f(x["max_rel_diff"], 2)) for x in B["eig_check"]))]
    out = ["# Strand 3 addendum part F'''(d), the light-sea lower bound (generated by solve/code/strand3/strand3_partFppp_bound_report_v1.py)", "",
           "## S Summary (emitted)", ""] + ["- " + x for x in summ] + [
        "", "## E5d The bound against pi K_N/2 per kappa and L (K_N's stage-1 rule and the annulus's geometric cell count beside)", "",
        "| kappa | K_N rule | annulus cells | L | eta_bound | pi K_N/2 | ratio |", "|---|---|---|---|---|---|---|"] + rows
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
