#!/usr/bin/env python
"""Strand 3 addendum part F''' stage 1 report (builder analyst): from strand3_partFppp_K_v1.py (partFppp_K.json): per kappa (0.0023, 0.001 and
the infinity control) the physical inventory's K_N = k_sym(0), k_left(0) and the massless packet's c_0(kappa) by every quadrature (the
specification's Gauss-Legendre panels at 32 and 16 nodes, the panels graded to 1e-5, the midpoint grid at L = 2048 and 4096 and its
Richardson step), the spreads between them; the controls at kappa = infinity against J2e (k_a(0; phys) = 7.2222462613476e-5, c_0 =
1.5382631884368); the 40-digit check of the summed integrands; the sign of K_N at each finite kappa.  Numbers emitted, not retyped.
(Version 2: several records (--K comma-separated: version 1's run with the midpoint grids and version 2's with the panels refined toward pi);
the primary rule is the Gauss-Legendre panels refined toward 0 and pi at 32 nodes, the one that passes the kappa = infinity control.)
(Version 3: also version 3's records (kappa = 3e-4 and 1e-4): the kappa-adapted rule among the GL comparisons, the 40-digit check at the
near-origin nodes beside the random points, and K_N relative to the unmodified k_a(0; phys) and its local power between neighbouring kappa.)
(Version 4: where a kappa has the kappa-adapted rule (version 3's records), that rule is the primary one and the panels refined toward 0 and pi are a
comparison; elsewhere as before.)"""
import argparse
import json
import math


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--K", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    recs = [json.load(open(p)) for p in a.K.split(",")]
    D = {"meta": recs[0]["meta"], "rows": [], "mp_check": {}}
    seen = set()
    for R in recs:
        for r in R["rows"]:
            key = (r["kappa"], r["quadrature"])
            if key not in seen:
                seen.add(key)
                D["rows"].append(r)
        D["mp_check"].update(R.get("mp_check", {}))
        D.setdefault("mp_check_near_origin", {}).update(R.get("mp_check_near_origin", {}))
    J2E = D["meta"]["J2e"]
    out = ["# Strand 3 addendum part F''' stage 1 tables (generated by solve/code/strand3/strand3_partFppp_report_v4.py)", ""]
    summ = []
    rows = []
    kappas = []
    for r in D["rows"]:
        if r["kappa"] not in kappas:
            kappas.append(r["kappa"])
    prims = {}
    for kap in kappas:
        rs = [r for r in D["rows"] if r["kappa"] == kap]
        adapted = [r for r in rs if r["quadrature"] == "GL kappa-adapted mirrored panels, 32"]
        prim = adapted[0] if adapted else [r for r in rs if r["quadrature"] == "GL mirrored panels, 32"][0]
        rich = [r for r in rs if r["quadrature"].startswith("midpoint Richardson")]
        for r in rs:
            rows.append("| %s | %s | %.15e | %.15e | %.15e | %s |" % (kap, r["quadrature"], r["K_N_sym"], r["k_left"], r["c0_massless"],
                                                                     f(r["K_N_sym"] - prim["K_N_sym"], 2)))
        conv = [r for r in rs if r["quadrature"] in ("GL mirrored panels, 16", "GL graded panels, 32", "GL spec panels, 32", "GL kappa-adapted mirrored panels, 32",
                                                      "GL mirrored panels, 32") and r is not prim]
        spread = max(abs(r["K_N_sym"] - prim["K_N_sym"]) for r in conv)
        mr = [r for r in rs if r["quadrature"].startswith("midpoint Richardson")]
        rule_name = "the kappa-adapted GL panels, 32 nodes" if adapted else "the GL panels refined toward 0 and pi, 32 nodes"
        line = ("F1 (kappa %s): K_N = %s (%s); its largest difference from the other GL rules (refined toward 0 and pi at 32 and 16 nodes, graded "
                "to 1e-5, toward 0 only at 32, kappa-adapted where run) %s, from the midpoint Richardson %s; k_left(0) = %s; the massless packet's c_0 = %s") % (
                   kap, "%.12e" % prim["K_N_sym"], rule_name, f(spread, 2), f(mr[0]["K_N_sym"] - prim["K_N_sym"], 2) if mr else "-", "%.8e" % prim["k_left"],
                   "%.12e" % prim["c0_massless"])
        if kap == "inf":
            line += "; against J2e: K_N - k_a(0; phys) = %s, c_0 - J2e = %s" % (f(prim["K_N_sym"] - J2E["k_a_phys"], 2), f(prim["c0_massless"] - J2E["c0"], 2))
            if rich:
                line += " (midpoint Richardson: %s and %s)" % (f(rich[0]["K_N_sym"] - J2E["k_a_phys"], 2), f(rich[0]["c0_massless"] - J2E["c0"], 2))
        else:
            line += "; the sign of K_N: %s; K_N/k_a(0; phys) = %s" % ("positive" if prim["K_N_sym"] > 0 else ("negative" if prim["K_N_sym"] < 0 else "zero"),
                                                                     "%.4g" % (prim["K_N_sym"] / J2E["k_a_phys"]))
            prims[float(kap)] = prim["K_N_sym"]
        summ.append(line + ".")
    out += ["## F1 The physical inventory (the massless light packet; heavies mu, mu, sqrt2 mu, mu = 0.0130903478; orientations (+, -, -, +)) with the "
            "Wilson-type mass M_kappa = m + kappa^-1 sum (1 - cos k_i): K_N = k_sym(0), k_left(0) and the massless packet's c_0(kappa) by every "
            "quadrature, and each K_N's difference from the primary rule (the GL panels refined toward 0 and pi, 32 nodes)", "",
            "| kappa | quadrature | K_N = k_sym(0) | k_left(0) | c_0 (massless packet) | K_N - primary |", "|---|---|---|---|---|---|"] + rows + [""]
    mc = D.get("mp_check", {})
    out += ["## F2 The summed integrands in float64 against 40 digits (2000 random points per kappa): the largest relative difference", "",
            "| kappa | K_N integrand | k_left integrand |", "|---|---|---|"] + ["| %s | %s | %s |" % (k, f(v["max_rel_diff_sym"], 2), f(v["max_rel_diff_left"], 2)) for k, v in mc.items()] + [""]
    mn = D.get("mp_check_near_origin", {})
    if mn:
        out += ["## F2' The same check at up to 2000 node triples of the kappa-adapted rule with every coordinate below 10 kappa (the near-origin nodes)", "",
                "| kappa | K_N integrand | k_left integrand |", "|---|---|---|"] + ["| %s | %s | %s |" % (k, f(v["max_rel_diff_sym"], 2), f(v["max_rel_diff_left"], 2)) for k, v in mn.items()] + [""]
    ks = sorted(prims, reverse=True)
    if len(ks) > 1:
        pw = ["%s -> %s: %s" % (x, y, "%.4g" % (math.log(prims[y] / prims[x]) / math.log(y / x))) for x, y in zip(ks[:-1], ks[1:]) if prims[x] > 0 and prims[y] > 0]
        summ.append("F3: the local power d log K_N/d log kappa between neighbouring kappa: " + "; ".join(pw) + ".")
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
