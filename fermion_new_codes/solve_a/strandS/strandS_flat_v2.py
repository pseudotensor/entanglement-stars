import lattice_entropy as LE  # noqa: E402

XG, WG = leggauss(16)
ETAS = (1.0, -1.0, -1.0, 1.0)


def s_chain(args):
    mu, Lf = args
    L = max(64, int(math.ceil(Lf / mu)))
    out = []
    for Lx in (L, 2 * L):
        C = LE.interval_covariance((1, 0, 0), (0.0, 0.0), Lx, 8 * Lx, mass=mu)
        out.append(LE.entropy(C, -1) / 2.0)
    return mu, L, out[1], abs(out[1] - out[0])


def panels(a, b, per_decade):
    n = max(1, int(math.ceil(math.log10(b / a) * per_decade)))
    e = np.geomspace(a, b, n + 1)
    x = (0.5 * (e[1:] - e[:-1])[:, None] * XG[None, :] + 0.5 * (e[1:] + e[:-1])[:, None]).ravel()
    w = (0.5 * (e[1:] - e[:-1])[:, None] * WG[None, :]).ravel()
    return x, w


class Sch:
    def __init__(self, mus, vals, fit_hi):
        lm = np.log(mus)
        sel = mus <= fit_hi
        X = np.stack([-np.log(mus[sel]), np.ones(sel.sum()), mus[sel] ** 2 * np.log(mus[sel]), mus[sel] ** 2], 1)
        coef, *_ = np.linalg.lstsq(X, vals[sel], rcond=None)
        self.alpha, self.beta, self.gamma, self.delta = (float(c) for c in coef)
        self.fit_resid = float(np.max(np.abs(X @ coef - vals[sel])))
        self.mu_lo = float(mus.min())
        self.spl = CubicSpline(lm, vals + self.alpha * lm)

    def __call__(self, mu):
        mu = np.asarray(mu, float)
        out = np.empty_like(mu)
        lo = mu < self.mu_lo
        hi = ~lo
        out[hi] = self.spl(np.log(mu[hi])) - self.alpha * np.log(mu[hi])
        m = np.maximum(mu[lo], 1e-300)
        out[lo] = -self.alpha * np.log(m) + self.beta + self.gamma * m * m * np.log(m) + self.delta * m * m
        return out


def zone_points(r_min, per_decade, n_phi):
    xp, wp = leggauss(n_phi)
    phi = 0.5 * (math.pi / 4) * (xp + 1)
    wphi = 0.5 * (math.pi / 4) * wp
    K, W = [], []
    for ph, wph in zip(phi, wphi):
        rmax = (math.pi / 2) / math.cos(ph)
        r, wr = panels(r_min, rmax, per_decade)
        K.append(np.stack([r * math.cos(ph), r * math.sin(ph)], 1))
        W.append(wr * r * wph)
    K = np.concatenate(K)
    W = np.concatenate(W) * 8 / math.pi ** 2
    d2 = np.sin(K[:, 0]) ** 2 + np.sin(K[:, 1]) ** 2
    return d2, W


def ive_safe(nu, x):
    """the exponentially scaled Bessel function; scipy's ive returns NaN above about 1e9, so the asymptotic series (three terms) is used
    above 1e6 (relative error below 1e-18 there)."""
    x = np.asarray(x, float)
    out = np.empty_like(x)
    big = x > 1e6
    out[~big] = ive(nu, x[~big])
    xb = x[big]
    m = 4.0 * nu * nu
    out[big] = (1 - (m - 1) / (8 * xb) + (m - 1) * (m - 9) / (2 * (8 * xb) ** 2) - (m - 1) * (m - 9) * (m - 25) / (6 * (8 * xb) ** 3)) / np.sqrt(2 * np.pi * xb)
    return out


def F_graded(y, etas, t_max, per_decade):
    t, w = panels(1e-8, t_max, per_decade)
    G0 = ive_safe(0, t / 2)
    G1 = 0.5 * (ive_safe(0, t / 2) + ive_safe(1, t / 2))
    g = sum(e * np.exp(-t * yy) for e, yy in zip(etas, y))
    return float(np.sum(w * t ** -0.5 * g * G1 * G0 * G0) / math.sqrt(math.pi))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rects", default="0,0.5,0.5,1;1,2,2,3")
    ap.add_argument("--aM", default="1.6,0.8,0.4,0.2,0.1,0.05,0.025,0.0125,0.00625")
    ap.add_argument("--mu-lo", type=float, default=0.025)
    ap.add_argument("--mu-hi", type=float, default=4.0)
    ap.add_argument("--mu-per-decade", type=int, default=40)
    ap.add_argument("--mu-fit-hi", type=float, default=0.1)
    ap.add_argument("--Lf", type=float, default=12.0)
    ap.add_argument("--r-min", type=float, default=1e-7)
    ap.add_argument("--panels-per-decade", type=int, default=8)
    ap.add_argument("--n-phi", type=int, default=32)
    ap.add_argument("--t-max", type=float, default=1e13)
    ap.add_argument("--check-mass", default="0.5,1.0")
