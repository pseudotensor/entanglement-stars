#!/usr/bin/env python
"""Strand 5 J2e report (builder analyst): from strand5_J2e_v2.py (J2e.json) and strand5_J2d_v1.py (J2d.json): (U1) the two quadrature
routes for c_0 = k(0), k(m_1), k(m_2) and k_a(0; phys), their difference, route 1's quad error estimate and both routes' analytic tails,
and the rectangle assembled from the three packet integrals beside the rectangle integrated under one integral; (U2) k_a(0; phys)/k_lat
beside J2d's value and budget (recomputed here from J2d.json by the J2d report's formulas: the two-step 1/L^2 Richardson of c_0(L) for
the 'massless' run, the heavy least-squares fits k_s0 + k_s2 q^2 + k_s4 q^4 over n = 1..4 and the three-point fits); c_0 beside J2d's
c_0(infinity); each heavy k(m) beside J2d's two fits and the direct q = 0 sums at L = 2048, 4096; (U3) every per-packet record's moment
beside the integral at its mass; (U4) the J2b T3i fit k(m) = c_0 + m^2 (alpha log m^2 + beta) over the J2b records with L = 256 and
m <= 0.3 (the T3i selection, the massless packet included), on the moments (T3i reproduced) and on the integrals at the same masses;
(U5) the small-m fit (k(m) - c_0)/m^2 = alpha log m^2 + beta over 16 masses 1e-4 to 2e-2 and over m <= 2e-3, alpha against 3/pi^2.
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


M1, M2 = 0.013090347820517666, 0.01851254742395717


def j2d_values(D):
    """The J2d report's 'massless' run: c_0(infinity) (two-step 1/L^2), the heavy k_s0 fits, k_a(0; phys), ratio and budget."""
    cs = sorted([(r["L"], r["c0"]) for r in D["c0"] if r["run"] == "massless"])
    c = [x[1] for x in cs]
    d1, d2 = c[1] - c[0], c[2] - c[1]
    p = np.log2(d1 / d2)
    r1 = c[2] + (c[2] - c[1]) / 3
    r1b = c[1] + (c[1] - c[0]) / 3
    r2 = r1 + (r1 - r1b) / 15
    rp = c[2] + (c[2] - c[1]) / (2 ** p - 1)
    best = r2 if abs(p - 2) < 0.1 else rp
    rem = max(abs(best - r1), abs(best - r2), abs(best - rp))
    fits = {}
    for m in (M1, M2):
        hs = sorted([r for r in D["heavy"] if r["run"] == "massless" and abs(r["m"] - m) < 1e-12], key=lambda r: r["n"])
        q = np.array([r["q"] for r in hs])
        k = np.array([r["k"] for r in hs])
        X = np.stack([np.ones_like(q), q ** 2, q ** 4], 1)
        cl, *_ = np.linalg.lstsq(X, k, rcond=None)
        ce = np.linalg.solve(X[:3], k[:3])
        fits[m] = {"ls": float(cl[0]), "exact": float(ce[0]), "spread": abs(cl[0] - ce[0]), "maxres": float(np.max(np.abs(k - X @ cl)))}
    kl = 3 * sum(e * m * m * np.log(m * m) for m, e in zip([M1, M1, M2], [-1, -1, 1])) / np.pi ** 2
    ka = best - 2 * fits[M1]["ls"] + fits[M2]["ls"]
    total = rem + 2 * fits[M1]["spread"] + fits[M2]["spread"] + 2 * fits[M1]["maxres"] + fits[M2]["maxres"]
    return {"c0": best, "c0_rem": rem, "fits": fits, "k_a": ka, "k_lat": kl, "ratio": ka / kl, "budget_over_klat": total / kl}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--j2e", required=True)
    ap.add_argument("--j2d", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    E = json.load(open(a.j2e))
    J = j2d_values(json.load(open(a.j2d)))
    I = E["integrals"]
    out = ["# Strand 5 J2e tables (generated by solve/code/strand5/strand5_J2e_report_v1.py from J2e.json and J2d.json)", ""]
    summ = []
    # U1
    rows = []
    for name in ("c0", "k(m1)", "k(m2)", "k_a(0; phys)"):
        r = I[name]
        rows.append([name, "%.16e" % r["route1"], "%.16e" % r["route2"], f(r["difference"], 2), f(r["route1_quad_error"], 2), f(r["route1_tail"], 2),
                     f(r["route2_tail"], 2)])
    maxdiff = max(abs(I[n]["difference"]) for n in I)
    rect = E["rectangle_from_packets"]
    out += ["## U1 The two quadrature routes (route 1: scipy quad in t^(1/2) with scipy ive to t = 1e7 plus the exponential-integral tail; route 2: "
            "mpmath tanh-sinh in log t at 30 digits with mpmath besseli to t = e^30 plus the asymptotic tail)", "",
            table(["integral", "route 1", "route 2", "route 1 - route 2", "route 1 quad error estimate", "route 1 tail", "route 2 tail"], rows), "",
            "The rectangle assembled from the packet integrals, c_0 - 2 k(m_1) + k(m_2) = %.16e, against the rectangle under one integral "
            "(route 1) %.16e: difference %s." % (rect, I["k_a(0; phys)"]["route1"], f(rect - I["k_a(0; phys)"]["route1"], 2)), ""]
    summ.append("U1: the two quadrature routes agree to %s absolute at worst over c_0, k(m_1), k(m_2) and k_a(0; phys) (route 1's summed quad "
                "error estimate at most %s); the rectangle assembled from the packet integrals differs from the single-integral value by %s." % (
                    f(maxdiff, 2), f(max(I[n]["route1_quad_error"] for n in I), 2), f(rect - I["k_a(0; phys)"]["route1"], 2)))
    # U2
    ka = I["k_a(0; phys)"]["route1"]
    ratio = E["k_a_over_k_lat"]["route1"]
    rows = [["J2e (the integral)", "%.13e" % ka, "%.13e" % E["k_lat"], "%.9f" % ratio, f(maxdiff / E["k_lat"], 2)],
            ["J2d (periodic sums, Richardson and fits)", "%.13e" % J["k_a"], "%.13e" % J["k_lat"], "%.9f" % J["ratio"], f(J["budget_over_klat"], 2)]]
    out += ["## U2 k_a(0; phys) and k_a(0; phys)/k_lat: J2e beside J2d (J2d recomputed from J2d.json by the J2d report's formulas)", "",
            table(["source", "k_a(0; phys)", "k_lat", "ratio", "error (J2e: route difference/k_lat; J2d: its budget/k_lat)"], rows), ""]
    dr = J["ratio"] - ratio
    summ.append("U2: k_a(0; phys) = %s (J2e), k_a(0; phys)/k_lat = %s; J2d's %s with budget %s of k_lat lies %s of k_lat above it, %s of J2d's budget." % (
        "%.12e" % ka, "%.9f" % ratio, "%.6f" % J["ratio"], f(J["budget_over_klat"], 2), f(dr, 2), "%.2f" % (dr / J["budget_over_klat"])))
    rows = [["c_0", "%.16e" % I["c0"]["route1"], "%.16e" % J["c0"], f(I["c0"]["route1"] - J["c0"], 2), "Richardson remainder %s" % f(J["c0_rem"], 2), "-", "-"]]
    hd = {(r["L"], round(r["m"], 12)): r for r in E["heavy_direct"]}
    for name, m in (("k(m1)", M1), ("k(m2)", M2)):
        Fm = J["fits"][m]
        v = I[name]["route1"]
        rows.append([name, "%.16e" % v, "%.16e (least squares); %.16e (three-point)" % (Fm["ls"], Fm["exact"]),
                     "%s; %s" % (f(Fm["ls"] - v, 3), f(Fm["exact"] - v, 3)), "spread %s, largest residual %s" % (f(Fm["spread"], 2), f(Fm["maxres"], 2)),
                     "%.16e" % hd[(2048, round(m, 12))]["c0_direct"], "%.16e" % hd[(4096, round(m, 12))]["c0_direct"]])
    out += ["## U2b c_0 and the heavy q = 0 constants: J2e's integral beside J2d (c_0(infinity); the heavy symbols' fits) and the direct q = 0 sums "
            "(3/L^3) sum_k cos^2 k_1/E(k) at twist 0.371", "",
            table(["quantity", "J2e integral", "J2d", "J2d - J2e", "J2d's own error terms", "direct sum L = 2048", "direct sum L = 4096"], rows), ""]
    summ.append("U2b: c_0 = %s (J2e) against J2d's c_0(infinity) %s (difference %s); the heavy fits sit %s (m_1) and %s (m_2) from the integrals "
                "(least squares), and the direct q = 0 sums at L = 2048 and 4096 match the integrals to %s." % (
                    "%.13f" % I["c0"]["route1"], "%.13f" % J["c0"], f(I["c0"]["route1"] - J["c0"], 2), f(J["fits"][M1]["ls"] - I["k(m1)"]["route1"], 2),
                    f(J["fits"][M2]["ls"] - I["k(m2)"]["route1"], 2), f(max(abs(r["direct_minus_integral"]) for r in E["heavy_direct"]), 2)))
    # U3
    rows = []
    for r in E["records"]:
        rows.append([r["record"], r["set"], f(r["m"], 9), r["L"], "%g" % r["theta"], "%.13f" % r["k_moment"], "%.13f" % r["k_integral"], f(r["moment_minus_integral"], 3)])
    out += ["## U3 Each per-packet record's line-kernel moment beside the integral at its mass", "",
            table(["record", "set", "m", "L", "twist", "moment", "integral", "moment - integral"], rows), ""]
    for L in sorted({r["L"] for r in E["records"]}):
        rs = [r for r in E["records"] if r["L"] == L]
        worst = max(rs, key=lambda r: abs(r["moment_minus_integral"]))
        summ.append("U3 (L = %d, %d records): largest |moment - integral| %s at m = %s; smallest %s." % (
            L, len(rs), f(abs(worst["moment_minus_integral"]), 2), f(worst["m"], 6), f(min(abs(r["moment_minus_integral"]) for r in rs), 2)))
    # U4
    pts = sorted([r for r in E["records"] if r["record"].startswith("J2b_run1/") and r["L"] == 256 and r["m"] <= 0.3 + 1e-12], key=lambda r: r["m"])
    m = np.array([r["m"] for r in pts])
    lm = np.where(m > 0, np.log(np.where(m > 0, m * m, 1.0)), 0.0)
    A3 = np.column_stack([np.ones_like(m), m * m * lm, m * m])
    rows = []
    fitres = {}
    for lab, key in (("moments (T3i)", "k_moment"), ("integrals", "k_integral")):
        kv = np.array([r[key] for r in pts])
        c3, *_ = np.linalg.lstsq(A3, kv, rcond=None)
        fitres[lab] = c3
        rows.append([lab, len(pts), "%.10f" % c3[0], "%.6f" % c3[1], "%.6f" % c3[2], f(np.max(np.abs(A3 @ c3 - kv)), 2), "%.6f" % (c3[1] / (3 / np.pi ** 2))])
    out += ["## U4 The T3i form k(m) = c_0 + m^2 (alpha log m^2 + beta) over the J2b records with L = 256 and m <= 0.3 (the massless packet included), "
            "on the moments and on the integrals at the same masses", "",
            table(["fitted values", "points", "c_0", "alpha", "beta", "largest residual", "alpha/(3/pi^2)"], rows), ""]
    summ.append("U4: the T3i form on the integrals gives c_0 = %s (the exact c_0 is %s), alpha = %s (alpha/(3/pi^2) = %s); on the moments (T3i "
                "reproduced) c_0 = %s, alpha = %s." % ("%.10f" % fitres["integrals"][0], "%.10f" % I["c0"]["route1"], "%.6f" % fitres["integrals"][1],
                                                       "%.5f" % (fitres["integrals"][1] / (3 / np.pi ** 2)), "%.10f" % fitres["moments (T3i)"][0],
                                                       "%.6f" % fitres["moments (T3i)"][1]))
    # U5
    sf, s4 = E["small_m_fit"], E["small_m_fit_m_le_2e-3"]
    rows = [[f(s["m"], 4), "%.15f" % s["k"], "%.9f" % s["y"], f(rr, 2)] for s, rr in zip(E["small_m"], sf["residuals"])]
    out += ["## U5 The small-m expansion: (k(m) - c_0)/m^2 against alpha log m^2 + beta over 16 masses 1e-4 to 2e-2 (fit residuals), alpha against "
            "3/pi^2 = %s" % ("%.9f" % (3 / np.pi ** 2)), "",
            table(["m", "k(m)", "(k(m) - c_0)/m^2", "fit residual"], rows), "",
            "All 16: alpha = %s (alpha/(3/pi^2) = %s), beta = %s.  The masses m <= 2e-3: alpha = %s (alpha/(3/pi^2) = %s), beta = %s." % (
                "%.8f" % sf["alpha"], "%.8f" % sf["alpha_over_3_pi2"], "%.6f" % sf["beta"], "%.8f" % s4["alpha"], "%.8f" % s4["alpha_over_3_pi2"], "%.6f" % s4["beta"]), ""]
    summ.append("U5: the small-m fit gives alpha/(3/pi^2) = %s over 1e-4 <= m <= 2e-2 and %s over m <= 2e-3 (beta %s and %s)." % (
        "%.8f" % sf["alpha_over_3_pi2"], "%.8f" % s4["alpha_over_3_pi2"], "%.6f" % sf["beta"], "%.6f" % s4["beta"]))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
