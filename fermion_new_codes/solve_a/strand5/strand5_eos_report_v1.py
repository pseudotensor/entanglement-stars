#!/usr/bin/env python
"""Strand 5 J3 report (builder analyst): tables T4 (the lattice EOS, its checks, the first coupling correction, the continuum limit, the
n -> 0 limit of e_1) from strand5_eos_v4.py's eos_v4.json.  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    T = R["table"]
    M = R["meta"]
    out = ["# Strand 5 J3 tables (generated by solve/code/strand5/strand5_eos_report_v1.py from eos_v4.json)", "",
           "Units b = 1 (hats: m b, n b^3, e b^4, mu b, P b^4); quadrature N_2 = %s, N_3 = %s against the coarse (%s, %s); e_1 at (g_M, g_B, "
           "Lambda, l) = (%s, %s, %s, %s) in lattice units." % (M["N2"], M["N3"], M["coarse"][0], M["coarse"][1], *[f(M["couplings_e1"][k]) for k in
                                                                                                                   ("g_M", "g_B", "Lambda", "ell")]), ""]
    rows = []
    for r in T:
        q = max(r["quadrature_rel_diff"].values())
        rows.append([f(r["m_hat"]), f(r["theta_F"]), f(r["kappa"], 6), f(r["rho"], 8), f(r["kF_cont_b"], 6), f(r["e_hat"], 8), f(r["mu_hat"], 8),
                     f(r["P_hat"], 8), f(r["T_hat"], 8), f(r["bdbe_hat_closed"], 6), f(r["J_psi_free"], 8), f(q, 2), f(r["inner_check_rel"], 2)])
    out += ["## T4a The free lattice EOS e_{0,b}: per (m b, theta_F = k_F b on the axis, kappa = sin theta_F) the filling rho = n b^3, the "
            "continuum-equivalent k_F b = (3 pi^2 rho/8)^(1/3), e, mu = sqrt(m^2 + kappa^2), P = n mu - e, the fixed-filling strain coefficient "
            "T = -2 int t eps' (r3 (R13)), b d_b e at fixed n = T + 3P, the free ruler row J_psi/(N psi^5) = 6e - 6n mu + 2 b d_b e at psi = N = 1, "
            "the largest relative quadrature difference (rho, e, T) against the coarse rule, and the th_3-node check on int sin^2", "",
            table(["m b", "theta_F", "kappa", "rho", "k_F b (continuum-equivalent)", "e", "mu", "P", "T", "b d_b e (fixed n)", "J_psi free",
                   "quadrature rel diff", "inner check"], rows), ""]
    rows = []
    for r in T:
        rows.append([f(r["m_hat"]), f(r["theta_F"]), f(r["mu_FD_rel"], 2), f(r["P_FD_rel"], 2), f(r["bdbe_hat_FD_fixed_n"], 6), f(r["bdbe_fixed_n_rel"], 2),
                     f(r["T_hat_FD_fixed_filling"], 8), f(r["T_fixed_filling_rel"], 2), f(r["J_psi_FD_minus_2T_rel"], 2)])
    out += ["## T4b Checks per point: e' by direct differentiation (central differences in kappa at fixed b, Richardson) against mu, so P by "
            "the direct derivative against n mu - e; b d_b e at fixed n by central differences in b (kappa re-solved from rho = n b^3; steps "
            "1e-3, 5e-4, Richardson) against T + 3P; the fixed-filling derivative by central differences in b at fixed kappa against T; the "
            "ruler row with the two differentiated pieces, 6e - 6n e'_FD + 2 (b d_b e)_FD, against 2T (r3's identity J_psi = 2 N psi^5 T)", "",
            table(["m b", "theta_F", "e'_FD/mu - 1", "P_FD/P - 1", "b d_b e at fixed n (FD)", "FD/(T + 3P) - 1", "T at fixed filling (FD)",
                   "FD/T - 1", "J_psi(FD pieces)/(2T) - 1"], rows), ""]
    keys = [("mu_FD_rel", "e'_FD/mu - 1"), ("P_FD_rel", "P_FD/P - 1"), ("bdbe_fixed_n_rel", "b d_b e at fixed n, FD/(T + 3P) - 1"),
            ("T_fixed_filling_rel", "fixed filling, FD/T - 1"), ("J_psi_FD_minus_2T_rel", "J_psi(FD pieces)/(2T) - 1")]
    rows = []
    for k, lab in keys:
        vals = [abs(r[k]) for r in T if r[k] is not None]
        i = int(np.argmax(vals))
        Tk = [r for r in T if r[k] is not None]
        rows.append([lab, f(max(vals), 2), "(%s, %s)" % (f(Tk[i]["m_hat"]), f(Tk[i]["theta_F"])), f(np.median(vals), 2)])
    qv = [max(r["quadrature_rel_diff"].values()) for r in T]
    rows.append(["quadrature, fine against coarse", f(max(qv), 2), "(%s, %s)" % (f(T[int(np.argmax(qv))]["m_hat"]), f(T[int(np.argmax(qv))]["theta_F"])),
                 f(np.median(qv), 2)])
    out += ["### T4b summary over the table: the largest |relative difference|, where, and the median", "",
            table(["check", "largest", "at (m b, theta_F)", "median"], rows), ""]
    rows = []
    for r in T:
        e1 = r["e1"]
        rows.append([f(r["m_hat"]), f(r["theta_F"]), f(e1["k_F"], 6), f(e1["e_M"], 4), f(e1["e_B"], 4), f(e1["e_1"], 4), f(e1["e_1"] / r["e_hat"], 3),
                     f(e1["de_1_dn"], 4), f(r["P1_hat"], 4), f(r["J_N_total"], 8), f(r["J_psi_total"], 8), f(r["mu_hat_total"], 8),
                     "attractive" if e1["e_M"] < 0 else "repulsive"])
    out += ["## T4c The first coupling correction e_1 = e_M + e_B ([S: lane strand A], the resolved-cone forms with R(p) = m, eight cones at "
            "the continuum-equivalent k_F), its n-derivative, P_1 = n e_1' - e_1, and the totals at these couplings: J_N = e_0 + e_1, "
            "J_psi/(N psi^5) = J_psi free + 6 e_1 - 6 n e_1' (b d_b e_1 = 0 in these forms), the TF chemical potential e_0' + e_1'; the sign of e_M", "",
            table(["m b", "theta_F", "k_F b", "e_M", "e_B", "e_1", "e_1/e_0", "e_1'", "P_1", "J_N total", "J_psi total", "mu total", "e_M sign"], rows), ""]
    rows = []
    for r in R["continuum_limit"]:
        rows.append([f(r["kF_over_m"]), f(r["m_hat"]), f(r["kF_b"]), f(r["kappa"], 8), f(r["e_lat"], 10), f(r["e_cont"], 10), f(r["rel"], 3)])
    out += ["## T4d The continuum limit at fixed k_F/m (the same n = 8 k_F^3/(3 pi^2)): e_{0,b} against the g = 16 continuum form as m b -> 0", "",
            table(["k_F/m", "m b", "k_F b", "kappa", "e lattice", "e continuum", "relative difference"], rows), ""]
    rows = []
    for r in R["e1_small_n"]:
        rows.append([f(r["m_hat"]), f(r["rho"]), f(r["k_F"], 4), f(r["e_M"], 4), f(r["e_B"], 4), f(r["e_1"], 4), f(r["e1_over_m_n"], 3)])
    out += ["## T4e e_1 as n -> 0: e_1/(m n)", "", table(["m b", "rho", "k_F b", "e_M", "e_B", "e_1", "e_1/(m n)"], rows), ""]
    out += ["Run time %s s." % f(M["seconds"]), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
