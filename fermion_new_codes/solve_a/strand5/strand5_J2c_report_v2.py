#!/usr/bin/env python
"""Strand 5 J2c report (builder analyst): tables from strand5_J2c_v1.py (J2c_<run>_L<L>_n<n>.json and control.json): the eta-summed physical
row symbol k_a(q) at L = 1024, 2048, n = 1..4 for both runs, the L-dependence at the common q, the fits (k_0 + k_2 q^2 over q <= m_1/2;
k_0 + k_2 q^2 + k_4 q^4 through n = 1, 2, 3 of L = 2048 with n = 4 as the check, and by least squares over all eight points; the q^2-with-log
form k_0 + k_2 q^2 + k_l q^2 log q the same ways), k_0/k_lat with the residuals, and the light packet alone (its symbol c_0(q)).
m_1 = 0.0130903 (the lightest heavy packet); k_lat = 3 sum_s eta_s m_s^2 log m_s^2/pi^2 (the massless packet contributing zero).
Numbers emitted, not retyped.  (Version 2: T2 adds the absolute changes of the eta-sum and of the light packet alone.)"""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


M1 = 0.013090347820517666


def klat(masses, etas):
    return 3 * sum(e * m * m * np.log(m * m) for m, e in zip(masses, etas) if m > 0) / np.pi ** 2


def fit(q, k, form, idx):
    q = np.asarray(q)[idx]
    k = np.asarray(k)[idx]
    if form == "poly2":
        X = np.stack([np.ones_like(q), q ** 2], 1)
    elif form == "poly4":
        X = np.stack([np.ones_like(q), q ** 2, q ** 4], 1)
    else:
        X = np.stack([np.ones_like(q), q ** 2, q ** 2 * np.log(q)], 1)
    c, *_ = np.linalg.lstsq(X, k, rcond=None)
    return c, X


def predict(c, q, form):
    q = np.asarray(q)
    if form == "poly2":
        return c[0] + c[1] * q ** 2
    if form == "poly4":
        return c[0] + c[1] * q ** 2 + c[2] * q ** 4
    return c[0] + c[1] * q ** 2 + c[2] * q ** 2 * np.log(q)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    recs = [json.load(open(p)) for p in glob.glob(os.path.join(a.dir, "J2c_*_L*_n*.json"))]
    out = ["# Strand 5 J2c tables (generated by solve/code/strand5/strand5_J2c_report_v2.py)", ""]
    cpath = os.path.join(a.dir, "control.json")
    if os.path.exists(cpath):
        C = json.load(open(cpath))
        rows = [[r["run"], r["L"], r["n"], f(r["k_a_first_variation"], 12), f(r["k_a_second_order"], 12), f(r["rel"], 3), f(r["light_first_variation"], 13),
                 f(r["light_second_order"], 13), f(r["light_rel"], 3)] for r in C]
        out += ["## C1 Control: the first-variation form against strand2c_kernel_v1's second-order kernel (eta-summed, and the light packet alone)", "",
                table(["run", "L", "n", "k_a first variation", "k_a second order", "relative", "light: first variation", "light: second order", "relative"],
                      rows), ""]
    for run in sorted({r["run"] for r in recs}):
        R = sorted([r for r in recs if r["run"] == run], key=lambda r: (r["L"], r["n"]))
        kl = klat(R[0]["masses"], R[0]["etas"])
        rows = [[r["L"], r["n"], f(r["q"], 6), f(r["k_a"], 12), f(r["k_a"] / kl, 8), f(r["light_alone_c0"], 13), r["transverse_classes"], f(r["seconds"], 4)]
                for r in R]
        out += ["## T1 (%s: masses %s, twist %s) k_a(q) and k_a/k_lat (k_lat = %s), the light packet alone c_0(q)" % (
            run, " ".join(f(m, 6) for m in R[0]["masses"]), f(R[0]["theta"], 4), f(kl, 8)), "",
                table(["L", "n", "q", "k_a(q)", "k_a/k_lat", "light alone c_0(q)", "transverse classes", "seconds"], rows), ""]
        by = {(r["L"], r["n"]): r for r in R}
        rows = []
        for n2, n1 in ((2, 1), (4, 2)):
            if (2048, n2) in by and (1024, n1) in by:
                x, y = by[(2048, n2)], by[(1024, n1)]
                dk = y["k_a"] - x["k_a"]
                dl = y["light_alone_c0"] - x["light_alone_c0"]
                rows.append([f(x["q"], 6), f(x["k_a"], 12), f(y["k_a"], 12), f(y["k_a"] / x["k_a"] - 1, 3), f(y["light_alone_c0"] / x["light_alone_c0"] - 1, 3),
                             f(dk, 4), f(dl, 4), f(dk / dl, 6), f(dk - dl, 3)])
        out += ["### T2 (%s) L = 1024 against 2048 at the common q: the relative changes, and the absolute change of the eta-sum beside the light "
                "packet's own absolute change (eta = +1), their ratio and difference (the three heavy packets' combined change)" % run, "",
                table(["q", "k_a (L = 2048)", "k_a (L = 1024)", "1024/2048 - 1", "light alone: 1024/2048 - 1", "change of k_a", "change of light alone",
                       "ratio", "difference"], rows), ""]
        rows = []
        L2 = [r for r in R if r["L"] == 2048]
        if L2:
            q = [r["q"] for r in L2]
            k = [r["k_a"] for r in L2]
            sel_small = [i for i, x in enumerate(q) if x <= M1 / 2]
            cases = [("k_0 + k_2 q^2", "poly2", sel_small, "q <= m_1/2 (L = 2048)"),
                     ("k_0 + k_2 q^2 + k_4 q^4", "poly4", [0, 1, 2], "n = 1, 2, 3 (L = 2048); n = 4 the check"),
                     ("k_0 + k_2 q^2 + k_4 q^4", "poly4", list(range(len(q))), "least squares over n = 1..4 (L = 2048)"),
                     ("k_0 + k_2 q^2 + k_l q^2 log q", "log", [0, 1, 2], "n = 1, 2, 3 (L = 2048); n = 4 the check"),
                     ("k_0 + k_2 q^2 + k_l q^2 log q", "log", list(range(len(q))), "least squares over n = 1..4 (L = 2048)")]
            for lab, form, idx, how in cases:
                if len(idx) < (2 if form == "poly2" else 3):
                    rows.append([lab, how, "%d points" % len(idx), "-", "-", "-", "-"])
                    continue
                c, _ = fit(q, k, form, idx)
                res = (np.array(k) - predict(c, q, form)) / c[0]
                rows.append([lab, how, "%d points" % len(idx), f(c[0], 10), f(c[0] / kl, 8), " ".join(f(x, 6) for x in c[1:]),
                             " ".join("n%d %s" % (i + 1, f(x, 2)) for i, x in enumerate(res))])
        out += ["### T3 (%s) Fits for k_0 = k_a(0): coefficients, k_0/k_lat and the residuals (k_a - fit)/k_0 at every L = 2048 point (m_1/2 = %s)" % (
            run, f(M1 / 2, 4)), "", table(["form", "points", "count", "k_0", "k_0/k_lat", "other coefficients", "residuals/k_0"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
