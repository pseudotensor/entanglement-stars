#!/usr/bin/env python
"""Strand 5 J4 sec. 10(r) report (builder analyst): (a) from strand5_J4_softdir_v1.py's records (softdir_<family>.json): per family and S3b
member the lowest full-node eigenvalue(s), the Richardson estimate of the gradient's directional derivative along the eigenvector, its error,
the error over the eigenvalue's distance from zero and the acceptance; (b) from the refine families (strand5_J4_members_v1.py) with stage 2
version 10 (--full-node all): per member M, the full-node inertia and the lowest eigenvalues; the refined maximum (the parabola through the
three largest-M members) and the crossing (the lowest eigenvalue's zero by linear interpolation between the members bracketing it; for the
second crossing the second-lowest eigenvalue's), with the stage-1 scan's vertex (scanmax) beside it where present.  Numbers emitted, not
retyped."""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def zero_cross(z, y):
    for i in range(len(z) - 1):
        if y[i] == 0:
            return z[i]
        if y[i] * y[i + 1] < 0:
            return z[i] + (z[i + 1] - z[i]) * y[i] / (y[i] - y[i + 1])
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--softdir", required=True, help="folder of softdir_*.json")
    ap.add_argument("--refine", required=True, help="folder of the refine families and their stage2_*.json")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    out = ["# Strand 5 J4 sec. 10(r) tables (generated by solve/code/strand5/strand5_J4_r_report_v1.py)", ""]
    summ = []
    rows = []
    worst, nacc, ntot = 0.0, 0, 0
    for p in sorted(glob.glob(os.path.join(a.softdir, "softdir_*.json"))):
        D = json.load(open(p))
        fam = os.path.basename(D["meta"]["family"]).replace("lstar_", "").replace(".json", "")
        run = os.path.basename(os.path.dirname(D["meta"]["family"]))
        for m in D["members"]:
            for d in m["directions"]:
                ntot += 1
                nacc += int(d["accepted"])
                if d["error_over_distance_from_zero"] is not None:
                    worst = max(worst, d["error_over_distance_from_zero"])
                rows.append([run, fam, "%.4f" % m["z_c"], m["inertia"], d["index"], "%.6e" % d["eigenvalue"], "%.6e" % d["estimate"], f(d["estimate_minus_eigenvalue"], 2),
                             f(d["error"], 2), f(d["error_over_distance_from_zero"], 2), "yes" if d["capped"] else "no", "yes" if d["accepted"] else "NO"])
    out += ["## Ra The soft full-node directions at the S3b members: the eigenvalue, the Richardson estimate of the gradient's directional derivative "
            "along its eigenvector, their difference, the error |R2 - R1|, its ratio to the eigenvalue's distance from zero, whether the steps were capped "
            "by positivity, and the acceptance (error below the distance)", "",
            table(["run", "family", "z_c", "inertia", "direction", "eigenvalue", "estimate", "estimate - eigenvalue", "error", "error/|eigenvalue|", "capped",
                   "accepted"], rows), ""]
    summ.append("Ra: %d of %d directions accepted (the error below the eigenvalue's distance from zero); the largest ratio %s." % (nacc, ntot, f(worst, 2)))
    rows = []
    for p in sorted(glob.glob(os.path.join(a.refine, "stage2_lstar_*_ref*.json"))):
        S2 = json.load(open(p))
        famf = S2["meta"]["family"]
        F = json.load(open(famf))
        suffix = "refmax" if famf.endswith("_refmax.json") else "ref2nd"
        fam = os.path.basename(famf).replace("lstar_", "").replace("_%s.json" % suffix, "")
        Mz = {round(m["z_c"], 10): m["M"] for m in F["members"] if m.get("newton_ok")}
        z, l1, l2, inert, Ms = [], [], [], [], []
        for m in S2["members"]:
            fn = m.get("full_node")
            if not fn:
                continue
            z.append(m["z_c"])
            l1.append(fn["lowest3"][0])
            l2.append(fn["lowest3"][1])
            inert.append(fn["inertia"])
            Ms.append(Mz.get(round(m["z_c"], 10), m["M"]))
            rows.append([fam, suffix, "%.4f" % m["z_c"], "%.12g" % Ms[-1], fn["inertia"], "%.6e" % fn["lowest3"][0], "%.6e" % fn["lowest3"][1]])
        z, l1, l2, Ms = map(np.array, (z, l1, l2, Ms))
        if suffix == "refmax":
            i = int(np.argmax(Ms))
            j = sorted(range(len(z)), key=lambda k: -Ms[k])[:3]
            c = np.polyfit(z[j], Ms[j], 2)
            vert = float(-c[1] / (2 * c[0]))
            cross = zero_cross(list(z), list(l1))
            scan = os.path.join(a.refine, "scan", os.path.basename(famf).replace("_refmax", "_scanmax"))
            sv = None
            if os.path.exists(scan):
                Sd = json.load(open(scan))
                zz = np.array([m["z_c"] for m in Sd["members"]])
                MM = np.array([m["M"] for m in Sd["members"]])
                k = int(np.argmax(MM))
                cc = np.polyfit(zz[max(0, k - 2):k + 3], MM[max(0, k - 2):k + 3], 2)
                sv = float(-cc[1] / (2 * cc[0]))
            summ.append("Rb (%s, maximum): the three-point maximum at z_c = %s (stage-1 scan vertex %s), the lowest full-node eigenvalue crossing zero at z_c = %s; "
                        "inertia %s over z_c %s." % (fam, "%.5f" % vert, "%.5f" % sv if sv else "-", "%.5f" % cross if cross else "outside the members",
                                                      list(inert), ["%.4f" % x for x in z]))
        else:
            cross2 = zero_cross(list(z), list(l2))
            summ.append("Rb (%s, second crossing): the second-lowest full-node eigenvalue %s over z_c %s, crossing zero at %s; inertia %s." % (
                fam, ["%.4e" % x for x in l2], ["%.2f" % x for x in z], ("z_c = %.4f" % cross2) if cross2 else "no sign change among these members",
                list(inert)))
    out += ["## Rb The refine families: per member M, the full-node inertia and the two lowest eigenvalues (stage 2 version 10, every member)", "",
            table(["family", "set", "z_c", "M", "inertia", "lowest", "second"], rows), ""]
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
