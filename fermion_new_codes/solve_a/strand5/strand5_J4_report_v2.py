#!/usr/bin/env python
"""Strand 5 J4 stage 1 report (builder analyst): tables from strand5_lattice_star_v2/v3 runs (lstar_<tag>.json): the family summaries
and controls, the mass maximum and the fold against the continuum family of J1 (star_v4.json, g = 16, G = m = 1, mapped to lattice units
with G = 1/(2 pi k_op), length unit 1/(m^2 sqrt G), mass unit (length unit)/G), the per-member columns of the kernel families (P14 eq. 21's
free-TF prediction beside the measured (A - B)/A, gamma, beta), the kernel-against-local differences (T5) and, at (0.01, 0.1), the packet-
built kernel (light packet at L = 512) against the L = 256 table kernel.  Numbers emitted, not retyped.  (Version 2: the continuum maximum's compactness read from its key compactness_2GM_over_Rs.)"""
import argparse
import glob
import json
import os

import numpy as np
from scipy.interpolate import CubicSpline


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if not np.isfinite(v):
        return str(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


POINTS = [(0.1, 1.0), (0.1, 0.5), (0.03, 0.3), (0.01, 0.1)]
OPS = ["kernel", "local_ka0", "local_klat"]
COUPS = [(0.0, 0.0), (0.2, 1.0)]


def load(run_dirs):
    fams = {}
    for d in run_dirs:
        for p in glob.glob(os.path.join(d, "lstar_*.json")):
            if p.endswith("_profiles.npz"):
                continue
            R = json.load(open(p))
            M = R["meta"]
            pk = p.endswith("_pk.json")
            key = (round(M["mlight"], 10), round(M["aH"], 10), M["operator"], tuple(round(x, 10) for x in M["couplings"]), pk)
            R["_path"] = p
            fams[key] = R
    return fams


def primary(fams, m, aH, op, c):
    """The (0.01, 0.1) kernel and local_ka0 families from the packet-built kernel (v3, light at L = 512) where present."""
    k_pk = (round(m, 10), round(aH, 10), op, tuple(round(x, 10) for x in c), True)
    k_tab = (round(m, 10), round(aH, 10), op, tuple(round(x, 10) for x in c), False)
    return fams.get(k_pk) or fams.get(k_tab)


def cont_mapper(J1):
    ref = sorted(J1["reference"], key=lambda r: r["z_c"])
    lz = np.log([r["z_c"] for r in ref])
    sM = CubicSpline(lz, [r["M"] for r in ref])
    sR = CubicSpline(lz, [r["R_s_areal"] for r in ref])
    sAB = CubicSpline(lz, [r["A_over_B_minus_1"] for r in ref])

    def at(zc, m, kop):
        G = 1.0 / (2 * np.pi * kop)
        ell = 1.0 / (m * m * np.sqrt(G))
        x = np.log(zc)
        return {"M": float(sM(x)) * ell / G, "R_s": float(sR(x)) * ell, "A_over_B_minus_1": float(sAB(x))}
    rm = J1["controls"]["reference_maximum"]
    return at, rm


def members(R):
    return {round(d["z_c"], 10): d for d in R["members"] if d.get("newton_ok")}


def maximum(R):
    mem = sorted(members(R).values(), key=lambda d: d["z_c"])
    if len(mem) < 3:
        return None
    Ms = np.array([d["M"] for d in mem])
    i = int(np.argmax(Ms))
    if i == 0 or i == len(mem) - 1:
        return {"z_c": mem[i]["z_c"], "M": Ms[i], "interior": False, "R_s": mem[i]["R_s"], "compactness": mem[i]["compactness"]}
    x = np.log([mem[j]["z_c"] for j in (i - 1, i, i + 1)])
    y = Ms[i - 1:i + 2]
    c = np.polyfit(x, y, 2)
    xm = -c[1] / (2 * c[0])
    return {"z_c": float(np.exp(xm)), "M": float(np.polyval(c, xm)), "interior": True, "R_s": mem[i]["R_s"], "compactness": mem[i]["compactness"],
            "grid_member_z_c": mem[i]["z_c"]}


def sign_changes(R, key):
    mem = sorted(members(R).values(), key=lambda d: d["z_c"])
    out = []
    for a, b in zip(mem[:-1], mem[1:]):
        if a.get(key) is not None and b.get(key) is not None and a[key] != b[key]:
            out.append("%s to %s (%+d to %+d)" % (f(a["z_c"], 4), f(b["z_c"], 4), a[key], b[key]))
    return "; ".join(out) or "none"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True, help="comma-separated run folders (J4run2, J4run3)")
    ap.add_argument("--j1", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    fams = load(a.runs.split(","))
    J1 = json.load(open(a.j1))
    at, rm = cont_mapper(J1)
    out = ["# Strand 5 J4 stage 1 tables (generated by solve/code/strand5/strand5_J4_report_v2.py)", ""]
    # T1 family summaries
    rows = []
    for (m, aH) in POINTS:
        for c in COUPS:
            for op in OPS:
                for pk in (False, True):
                    R = fams.get((round(m, 10), round(aH, 10), op, tuple(round(x, 10) for x in c), pk))
                    if R is None:
                        continue
                    M = R["meta"]
                    ki = M["kernel_info"]
                    mem = list(members(R).values())
                    src = "packets (light L = 512)" if pk else ("2c table" if m == 0.1 else "J2b L = 256 table")
                    rows.append(["%g, %g" % (m, aH), op, "%g, %g" % c, src, f(M["k_op"], 8), f(M["k_op"] / ki["k_lat"], 6), ki.get("stencil_half_width"),
                                 M["Rc"], "%d of %d" % (len(mem), len(M["z_c"])), "%d to %d" % (min(d["J"] for d in mem), max(d["J"] for d in mem)) if mem else "-",
                                 f(max((d["residual"] for d in mem), default=None), 2),
                                 f(max((abs(d["A_vol_minus_A"] / d["A"]) for d in mem), default=None), 2),
                                 f(max((abs(d["B_vol_minus_B"] / d["B"]) for d in mem), default=None), 2),
                                 f(max((abs(d["E_tot_minus_2A_over_G"] / d["E_bdy"]) for d in mem), default=None), 2),
                                 f(max((abs(d["mu_centre_check"]) for d in mem), default=None), 2), f(M.get("seconds"), 4)])
    out += ["## T1 The families: kernel source, the operator's Gauss coefficient k_op (the kernel's moment k_a(0) for kernel and local_ka0, "
            "2c's k_lat for local_klat) and k_op/k_lat, the stencil half-width, R_c, converged members, the grid J, and the controls (largest "
            "Newton residual, Gauss law |A_vol - A|/A and |B_vol - B|/B, the energy identity |E_tot - 2A/G|/(2A/G), the centre condition)", "",
            table(["(m a, aH)", "operator", "(g_M, g_B)", "kernel", "k_op", "k_op/k_lat", "stencil R", "R_c", "members", "J", "max residual",
                   "Gauss A", "Gauss B", "energy identity", "centre", "seconds"], rows), ""]
    # T2 the maximum and the fold
    rows = []
    for (m, aH) in POINTS:
        for c in COUPS:
            for op in OPS:
                R = primary(fams, m, aH, op, c)
                if R is None:
                    continue
                mx = maximum(R)
                kop = R["meta"]["k_op"]
                G = 1.0 / (2 * np.pi * kop)
                ell = 1.0 / (m * m * np.sqrt(G))
                Mc = rm["M"] * ell / G if "M" in rm else None
                rows.append(["%g, %g" % (m, aH), op, "%g, %g" % c, f(mx["z_c"], 5) if mx else "-", f(mx["M"], 7) if mx else "-",
                             f(Mc, 7), f(mx["M"] / Mc - 1, 3) if (mx and Mc) else "-", f(mx["compactness"], 5) if mx else "-",
                             sign_changes(R, "det_sign_fixed_NB"), sign_changes(R, "det_sign_fixed_zc")])
    out += ["## T2 The mass maximum (parabola in log z_c through the largest member and its neighbours) against the continuum maximum of J1 "
            "mapped with the family's G = 1/(2 pi k_op) (the reference maximum's M times (length unit)/G), the compactness 2GM/R_s of the "
            "largest member, and the sign changes of the Jacobian determinant at fixed N_B and at fixed z_c along the family", "",
            table(["(m a, aH)", "operator", "(g_M, g_B)", "z_c at max", "M_max", "continuum M_max", "ratio - 1", "2GM/R_s (largest member)",
                   "det sign changes, fixed N_B", "det sign changes, fixed z_c"], rows), "",
            "Continuum reference maximum (J1, g = 16, G = m = 1): z_c %s, M %s, R_s %s, 2GM/R_s %s." % (
                f(rm.get("z_c"), 6), f(rm.get("M"), 8), f(rm.get("R_s_areal"), 8), f(rm.get("compactness_2GM_over_Rs"), 6)), ""]
    # T3 per member, kernel families
    for (m, aH) in POINTS:
        for c in COUPS:
            R = primary(fams, m, aH, "kernel", c)
            if R is None:
                continue
            kop = R["meta"]["k_op"]
            rows = []
            for zc, d in sorted(members(R).items()):
                cm = at(zc, m, kop)
                pr = d["P14_TF_prediction_AmB_over_A"]
                ms = d["measured_AmB_over_A"]
                rows.append([f(zc, 4), f(d["M"], 8), f(d["M"] / cm["M"] - 1, 3), f(d["r_s"], 5), f(d["R_s"], 5), f(d["R_s"] / cm["R_s"] - 1, 3),
                             f(d["compactness"], 4), f(d["r_s_over_A"], 4), f(d["A_over_B_minus_1"], 4), f(ms, 4), f(pr, 4),
                             f(pr / ms if ms else None, 4), f(d["gamma_minus_1"], 4), f(d["beta_minus_1"], 4), f(d["N_B"], 7),
                             "%+d" % d["det_sign_fixed_NB"] if d.get("det_sign_fixed_NB") is not None else "-", d["J"]])
            out += ["## T3 Members of the kernel family (m a, aH) = (%g, %g), (g_M, g_B) = (%g, %g): M and R_s against the continuum family at "
                    "the same z_c (J1 mapped with G = 1/(2 pi k_op)), r_s, 2GM/R_s, r_s/A, A/B - 1, the measured (A - B)/A beside P14 eq. 21's "
                    "free-TF prediction -(2 a^2/5) sum r^2 N psi^10 I_6/sum r^2 psi^5 I_rho and their ratio, gamma - 1 = D/(E_bdy - D), beta - 1 = "
                    "D/(2 (E_bdy - D)) (P33 [S]), N_B, the fixed-N_B determinant sign, J" % (m, aH, c[0], c[1]), "",
                    table(["z_c", "M", "M/M_cont - 1", "r_s", "R_s", "R_s/R_s,cont - 1", "2GM/R_s", "r_s/A", "A/B - 1", "(A - B)/A measured",
                           "P14 eq. 21", "prediction/measured", "gamma - 1", "beta - 1", "N_B", "det fixed N_B", "J"], rows), ""]
    # T5 kernel against local
    for (m, aH) in POINTS:
        for c in COUPS:
            Rk = primary(fams, m, aH, "kernel", c)
            R0 = primary(fams, m, aH, "local_ka0", c)
            Rl = primary(fams, m, aH, "local_klat", c)
            if Rk is None:
                continue
            mk, m0, ml = members(Rk), members(R0) if R0 else {}, members(Rl) if Rl else {}
            rows = []
            for zc, d in sorted(mk.items()):
                e0, el = m0.get(zc), ml.get(zc)
                rows.append([f(zc, 4), f(d["M"], 8),
                             f((d["M"] - e0["M"]) / d["M"], 3) if e0 else "-", f((d["M"] - el["M"]) / d["M"], 3) if el else "-",
                             f((d["R_s"] - e0["R_s"]) / d["R_s"], 3) if e0 else "-", f((d["R_s"] - el["R_s"]) / d["R_s"], 3) if el else "-",
                             f(d["A_over_B_minus_1"], 4), f(e0["A_over_B_minus_1"], 4) if e0 else "-", f(el["A_over_B_minus_1"], 4) if el else "-"])
            out += ["## T5 Kernel against local rows, (m a, aH) = (%g, %g), (g_M, g_B) = (%g, %g): member by member the relative differences "
                    "(kernel - local)/kernel of M and R_s for the local row with k_a(0) (local_ka0) and with k_lat (local_klat), and A/B - 1 for "
                    "the three operators" % (m, aH, c[0], c[1]), "",
                    table(["z_c", "M (kernel)", "dM/M (k_a(0))", "dM/M (k_lat)", "dR_s/R_s (k_a(0))", "dR_s/R_s (k_lat)", "A/B - 1 kernel",
                           "A/B - 1 local k_a(0)", "A/B - 1 local k_lat"], rows), ""]
    # T6 (0.01, 0.1): packet-built kernel against the L = 256 table kernel
    for op in ("kernel", "local_ka0"):
        for c in COUPS:
            kk = (0.01, 0.1, op, tuple(round(x, 10) for x in c))
            Rp = fams.get(kk + (True,))
            Rt = fams.get(kk + (False,))
            if Rp is None or Rt is None:
                continue
            mp_, mt = members(Rp), members(Rt)
            rows = [[f(zc, 4), f(d["M"], 8), f(d["M"] / mt[zc]["M"] - 1, 3), f(d["R_s"] / mt[zc]["R_s"] - 1, 3), f(d["A_over_B_minus_1"], 4),
                     f(mt[zc]["A_over_B_minus_1"], 4)] for zc, d in sorted(mp_.items()) if zc in mt]
            out += ["## T6 (m a, aH) = (0.01, 0.1), %s, (g_M, g_B) = (%g, %g): the kernel from per-packet symbols with the light packet at L = 512 "
                    "(k_op %s) against the L = 256 table kernel (k_op %s)" % (op, c[0], c[1], f(Rp["meta"]["k_op"], 10), f(Rt["meta"]["k_op"], 10)), "",
                    table(["z_c", "M (L = 512 light)", "M ratio - 1", "R_s ratio - 1", "A/B - 1 (L = 512 light)", "A/B - 1 (L = 256)"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
