#!/usr/bin/env python
"""Strand 5 J2b report (builder analyst): tables from strand5_kernel_packets_v1.py's per-packet records (J2b_run1, J4kernels_run1) with
the 2c table kernel_L256.json as the control, and the J4 kernel tables for strand 5 J4.  Numbers emitted, not retyped.
Per packet: k(m) = (1/2) sum n^2 K_n (the line-kernel moment), k(m; q_1), the ring decay, the raw log-log slope of |C| over q in
[0.05, 0.4] (the spec's (iii) quantity) and the slope of the q-dependent remainder |k(m; q) - k(m)| q_lat^2 over the same range.
Control: sum_s eta_s k(m_s; q) against the 2c table at every aH and for the physical row (largest relative difference over q).
Fit: k(m) = c_0 + m^2 (alpha log m^2 + beta) over the masses <= 0.3 at L = 256 (twist 0 and 0.371 rows separately listed), and the
spec's form without c_0.  (ii) the physical k_a(0) = k(0) - 2 k(m_1) + k(m_2) from the moments.  The J4 points' grouped kernels
k_a(q) = sum eta_s k(m_s; q), their moments and decay, and the light packet's L = 256 against L = 512.  Writes the tables (md) and
<out>/kernel_J4_L256.json (rows in the 2c table's format)."""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def load(d):
    out = []
    for p in sorted(glob.glob(os.path.join(d, "packets_*.json"))):
        r = json.load(open(p))
        r["_file"] = os.path.basename(p)
        out.append(r)
    return out


def sym(rec):
    rows = sorted(rec["rows"], key=lambda r: r["n"])
    return np.array([r["q"] for r in rows]), np.array([r["k"] for r in rows])


def moments(qv, kv, L):
    kk = kv.copy()
    kk[-1] = kk[-1] / 2
    Cq = np.zeros(L)
    ql2 = 2 * (1 - np.cos(qv))
    for j, q in enumerate(qv):
        n = int(round(q * L / (2 * np.pi)))
        Cq[n % L] = -kk[j] * ql2[j]
        Cq[(-n) % L] = -kk[j] * ql2[j]
    K = np.real(np.fft.ifft(Cq))
    nn = np.arange(L)
    nn = np.where(nn > L // 2, nn - L, nn)
    return float(0.5 * np.sum(nn ** 2 * K)), float(-np.sum(nn.astype(float) ** 4 * K) / 24), float(abs(K[L // 2]) / abs(K[0]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--j2b", required=True)
    ap.add_argument("--j4", required=True)
    ap.add_argument("--kernel", required=True)
    ap.add_argument("--md", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    P = load(a.j2b)
    P4 = load(a.j4)
    D = json.load(open(a.kernel))
    out = ["# Strand 5 J2b tables (generated by solve/code/strand5/strand5_J2b_report_v1.py)", ""]
    rows = []
    for r in sorted(P + P4, key=lambda r: (r["L"], r["set"], r["m"])):
        an = r["analysis"]
        q, k = sym(r)
        sel = (q >= 0.05) & (q <= 0.4)
        rem = np.abs((k - an["k_moment"]) * 2 * (1 - np.cos(q)))
        slope_rem = float(np.polyfit(np.log(q[sel]), np.log(rem[sel]), 1)[0]) if np.all(rem[sel] > 0) else None
        r["_slope_rem"] = slope_rem
        rows.append([r["set"] if r in P else "J4", f(r["m"], 8), r["L"], "%g" % r["theta"][0], f(an["k_moment"], 11), f(an["k_smallest_q"], 11),
                     f(an["decay_half"], 2), f(an["decay_quarter"], 2), f(an["c4_moment"], 5), f(an.get("loglog_slope_C_q_0.05_0.4"), 4), f(slope_rem, 4)])
    out += ["## T3g Single packets (orientation +): k(m) = the line-kernel moment, k(m; q_1) at the smallest q, the ring decay |K_n|/|K_0| at "
            "n = L/2 and L/4, the fourth moment's c_4, the raw log-log slope of |C(q)| over q in [0.05, 0.4] (the spec's (iii) quantity) and "
            "the slope of the q-dependent remainder |k(m; q) - k(m)| q_lat^2 over the same range", "",
            table(["set", "m", "L", "twist", "k(m) moment", "k(m; q_1)", "decay L/2", "decay L/4", "c_4", "raw slope", "remainder slope"], rows), ""]
    # control against the 2c table
    byk = {}
    for r in P:
        byk[(round(r["m"], 10), r["L"], r["theta"][0])] = r
    rows = []
    for aH in sorted({r["aH"] for r in D["equal"]}, reverse=True):
        ms = [0.1, np.sqrt(0.01 + aH * aH), np.sqrt(0.01 + aH * aH), np.sqrt(0.01 + 2 * aH * aH)]
        et = [1, -1, -1, 1]
        recs = [byk.get((round(m, 10), 256, 0.0)) for m in ms]
        if any(x is None for x in recs):
            rows.append(["equal, aH = %s" % f(aH), "missing packets"] + ["-"] * 2)
            continue
        tab = sorted([r for r in D["equal"] if r["aH"] == aH], key=lambda r: r["n"])
        kt = np.array([r["k_a"] for r in tab])
        ks = sum(e * sym(x)[1] for e, x in zip(et, recs))
        rows.append(["equal, aH = %s" % f(aH), f(np.max(np.abs(ks / kt - 1)), 2), f(kt[0], 8), f(ks[0], 8)])
    ph = D["physical"]
    msP = ph["masses"]
    recs = [byk.get((round(m, 10), 256, 0.371)) for m in msP]
    if all(x is not None for x in recs):
        tab = sorted(ph["rows"], key=lambda r: r["n"])
        kt = np.array([r["k_a"] for r in tab])
        ks = sum(e * sym(x)[1] for e, x in zip([1, -1, -1, 1], recs))
        rows.append(["physical a/l_P 0.0213", f(np.max(np.abs(ks / kt - 1)), 2), f(kt[0], 8), f(ks[0], 8)])
    out += ["## T3h Control: the eta-weighted sum of the single-packet symbols against the 2c table (L = 256), largest relative difference over q, "
            "and the two at the smallest q", "", table(["set", "max relative difference", "table k_a(q_1)", "sum of packets"], rows), ""]
    # fit
    pts = sorted([(r["m"], r["analysis"]["k_moment"], r["theta"][0], r["set"]) for r in P if r["L"] == 256 and r["m"] <= 0.3 + 1e-12])
    m = np.array([p[0] for p in pts])
    kv = np.array([p[1] for p in pts])
    lm = np.where(m > 0, np.log(np.where(m > 0, m * m, 1.0)), 0.0)
    A3 = np.column_stack([np.ones_like(m), m * m * lm, m * m])
    c3, *_ = np.linalg.lstsq(A3, kv, rcond=None)
    pos = m > 0
    A2 = np.column_stack([m[pos] ** 2 * lm[pos], m[pos] ** 2])
    c2, *_ = np.linalg.lstsq(A2, kv[pos], rcond=None)
    rows = [[f(p[0], 8), "%g" % p[2], p[3], f(p[1], 11), f(A3[i] @ c3 - p[1], 3)] for i, p in enumerate(pts)]
    out += ["## T3i The fit over m <= 0.3 at L = 256: k(m) = c_0 + m^2 (alpha log m^2 + beta) gives c_0 = %s, alpha = %s, beta = %s (largest "
            "residual %s); the spec's form without c_0, k(m) = m^2 (alpha log m^2 + beta), gives alpha = %s, beta = %s (largest residual %s); "
            "P14's leading per-packet form 3 m^2 log m^2/pi^2 has alpha = %s" % (
                f(c3[0], 10), f(c3[1], 6), f(c3[2], 6), f(np.max(np.abs(A3 @ c3 - kv)), 2), f(c2[0], 6), f(c2[1], 6),
                f(np.max(np.abs(A2 @ c2 - kv[pos])), 2), f(3 / np.pi ** 2, 6)), "",
            table(["m", "twist", "set", "k(m) moment", "fit residual (with c_0)"], rows), ""]
    # (ii) physical
    k0 = byk.get((0.0, 256, 0.371))
    k1 = {L: byk.get((round(msP[1], 10), L, 0.371)) for L in (256, 512)}
    k2 = {L: byk.get((round(msP[3], 10), L, 0.371)) for L in (256, 512)}
    klat = ph["rows"][0]["k_lat"]
    rows = []
    for lab, a1, a2 in (("L = 256 (heavy and massless)", k1[256], k2[256]), ("heavy at L = 512, massless at L = 256", k1[512], k2[512])):
        if k0 is None or a1 is None or a2 is None:
            rows.append([lab, "missing"] + ["-"] * 3)
            continue
        val = k0["analysis"]["k_moment"] - 2 * a1["analysis"]["k_moment"] + a2["analysis"]["k_moment"]
        rows.append([lab, f(val, 8), f(val / klat, 6), f(ph["rows"][0]["k_a_over_k_lat"], 6), f(klat, 8)])
    fitval = 0.0 - 2 * (msP[1] ** 2 * (c3[1] * np.log(msP[1] ** 2) + c3[2])) + msP[3] ** 2 * (c3[1] * np.log(msP[3] ** 2) + c3[2])
    rows.append(["the fit's m-dependent part (c_0 cancels)", f(fitval, 8), f(fitval / klat, 6), f(ph["rows"][0]["k_a_over_k_lat"], 6), f(klat, 8)])
    out += ["## T3j The physical row's Newtonian coefficient k_a(0; phys) = k(0) - 2 k(m_1) + k(m_2) (eta = (+, -, -, +), m_1 = %s, m_2 = %s, the "
            "massless packet's own moment), against 2c's k_lat and the physical table's k_a(q_1)/k_lat" % (f(msP[1], 8), f(msP[3], 8)), "",
            table(["evaluation", "k_a(0; phys)", "/ k_lat", "table k_a(q_1)/k_lat", "k_lat"], rows), ""]
    # J4 kernels
    j4 = {(round(r["m"], 10), r["L"]): r for r in P4}
    rows, jrows = [], []
    for (ml, aH) in ((0.03, 0.3), (0.01, 0.1)):
        ms = [ml, np.sqrt(ml * ml + aH * aH), np.sqrt(ml * ml + aH * aH), np.sqrt(ml * ml + 2 * aH * aH)]
        recs = [j4.get((round(mm, 10), 256)) for mm in ms]
        if any(x is None for x in recs):
            rows.append(["(%s, %s)" % (f(ml), f(aH)), "missing"] + ["-"] * 6)
            continue
        q = sym(recs[0])[0]
        ka = sum(e * sym(x)[1] for e, x in zip([1, -1, -1, 1], recs))
        k0m, c4m, dec = moments(q, ka, 256)
        l512 = j4.get((round(ml, 10), 512))
        light_cmp, k0m_512 = None, None
        if l512 is not None:
            q5, k5 = sym(l512)
            ql, kl = sym(recs[0])
            common = {round(x, 12): y for x, y in zip(q5, k5)}
            dif = [abs(common[round(x, 12)] / y - 1) for x, y in zip(ql, kl) if round(x, 12) in common]
            light_cmp = max(dif) if dif else None
            k0m_512 = l512["analysis"]["k_moment"] - 2 * recs[1]["analysis"]["k_moment"] + recs[3]["analysis"]["k_moment"]
        rows.append(["(%s, %s)" % (f(ml), f(aH)), " ".join(f(x, 6) for x in ms[:1] + ms[1:2] + ms[3:]), f(k0m, 8), f(c4m, 6), f(dec, 2), f(ka[0], 8),
                     f(light_cmp, 2), f(k0m_512, 8)])
        for qq, kk in zip(q, ka):
            jrows.append({"set": "J4 equal rectangle", "m_light": ml, "aH": aH, "n": int(round(qq * 256 / (2 * np.pi))), "q": float(qq), "k_a": float(kk)})
    out += ["## T3k The J4 kernels at L = 256 (twist 0): the grouped k_a(q) = sum eta_s k(m_s; q) with masses (m_l, sqrt(m_l^2 + H^2) twice, "
            "sqrt(m_l^2 + 2 H^2)); its moment k_a(0), c_4, the ring decay at n = 128, k_a(q_1); the light packet at L = 512 against L = 256 "
            "(largest relative difference at the common q) and k_a(0) with the light packet's L = 512 moment in place of its L = 256 one", "",
            table(["(m_l a, aH)", "masses (light, heavy, heaviest)", "k_a(0) moment", "c_4", "decay L/2", "k_a(q_1)", "light: L = 512 vs 256",
                   "k_a(0) with the light at L = 512"], rows), ""]
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "kernel_J4_L256.json"), "w") as fh:
        json.dump({"meta": {"L": 256, "source": "strand5_kernel_packets_v1.py per-packet symbols, eta-summed", "twist": 0.0}, "equal": jrows}, fh, indent=1)
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
