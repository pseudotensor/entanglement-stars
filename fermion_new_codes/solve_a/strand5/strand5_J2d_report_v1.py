#!/usr/bin/env python
"""Strand 5 J2d report (builder analyst): from strand5_J2d_v1.py (J2d.json) and the J2c records (the eta-summed and light-alone symbols at
L = 2048): (T1) the light packet's q = 0 constant c_0(L) per run, the successive differences, their ratio and the apparent order
p = log2(ratio), Richardson in 1/L^2 (one step from L = 4096, 8192; two steps (1/L^2, 1/L^4) from the three L) and with the apparent order,
the remainder estimate (the spread of these extrapolations); (T2) each heavy packet's L = 2048 symbol fitted by k_s0 + k_s2 q^2 + k_s4 q^4
(least squares over n = 1..4, and exactly through n = 1, 2, 3 with n = 4 as the check), the residuals relative to the packet's k_s0 and to
k_lat; (T3) k_a(0; phys) = sum_heavy eta_s k_s0 + c_0(infinity) (eta = -1, -1, +1 for 0.0130903, 0.0130903, 0.0185125; eta_light = +1)
per run with k_a(0; phys)/k_lat and the budget (c_0's remainder; the heavy fits' spread between the two fit routes and their largest
residual, propagated with the eta weights); the two runs side by side; (T4) the cross-check against J2c: sum_heavy eta_s k_s(q) + c_light(q)
at L = 2048 against J2c's eta-summed k_a(q) at the same q, and c_light(q) - c_0(infinity) at J2c's q.  Numbers emitted, not retyped."""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


M1, M2 = 0.013090347820517666, 0.01851254742395717
LIGHT = {"massless": 0.0, "m1e-4": 1e-4}


def klat(ml):
    ms, etas = [ml, M1, M1, M2], [1, -1, -1, 1]
    return 3 * sum(e * m * m * np.log(m * m) for m, e in zip(ms, etas) if m > 0) / np.pi ** 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--j2d", required=True)
    ap.add_argument("--j2c", required=True, help="J2c run folder")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    D = json.load(open(a.j2d))
    J2C = {(r["run"], r["L"], r["n"]): r for r in (json.load(open(p)) for p in glob.glob(os.path.join(a.j2c, "J2c_*_L*_n*.json")))}
    out = ["# Strand 5 J2d tables (generated by solve/code/strand5/strand5_J2d_report_v1.py)", ""]
    summ = []
    c0inf = {}
    rows = []
    for run in ("massless", "m1e-4"):
        cs = sorted([(r["L"], r["c0"]) for r in D["c0"] if r["run"] == run])
        Ls = [x[0] for x in cs]
        c = [x[1] for x in cs]
        d1, d2 = c[1] - c[0], c[2] - c[1]
        ratio = d1 / d2
        p = np.log2(ratio)
        r1 = c[2] + (c[2] - c[1]) / 3                                       # one step, 1/L^2
        r1b = c[1] + (c[1] - c[0]) / 3
        r2 = r1 + (r1 - r1b) / 15                                          # two steps, 1/L^2 then 1/L^4
        rp = c[2] + (c[2] - c[1]) / (2 ** p - 1)                           # apparent order
        best = r2 if abs(p - 2) < 0.1 else rp
        rem = max(abs(best - r1), abs(best - r2), abs(best - rp))
        c0inf[run] = (best, rem)
        for L, x in cs:
            rows.append([run, L, f(x, 14), "", "", "", ""])
        rows.append([run, "extrapolations", "-", "differences %s, %s; ratio %s; p %s" % (f(d1, 4), f(d2, 4), f(ratio, 6), f(p, 5)),
                     "1/L^2 one step %s" % f(r1, 14), "two steps %s; apparent order %s" % (f(r2, 14), f(rp, 14)),
                     "adopted %s (%s), remainder %s (%s relative)" % (f(best, 14), "two-step 1/L^2" if abs(p - 2) < 0.1 else "apparent order",
                                                                    f(rem, 2), f(rem / best, 2))])
        summ.append("T1 (%s): c_0 differences in ratio %s (apparent order %s); adopted c_0(infinity) = %s with remainder %s (%s relative)." % (
            run, f(ratio, 6), f(p, 4), f(best, 13), f(rem, 2), f(rem / best, 2)))
    out += ["## T1 The light packet's q = 0 constant c_0(L) = (3/L^3) sum_k cos^2 k_1/E(k) and its extrapolation", "",
            table(["run", "L", "c_0(L)", "differences, ratio, order", "Richardson (one step)", "two steps; apparent order", "adopted"], rows), ""]
    # heavy fits
    fits = {}
    rows = []
    for run in ("massless", "m1e-4"):
        for m in (M1, M2):
            hs = sorted([r for r in D["heavy"] if r["run"] == run and abs(r["m"] - m) < 1e-12], key=lambda r: r["n"])
            q = np.array([r["q"] for r in hs])
            k = np.array([r["k"] for r in hs])
            X = np.stack([np.ones_like(q), q ** 2, q ** 4], 1)
            cl, *_ = np.linalg.lstsq(X, k, rcond=None)
            ce = np.linalg.solve(X[:3], k[:3])
            resl = k - X @ cl
            rese = k - X @ ce
            kl = klat(LIGHT[run])
            fits[(run, m)] = {"ls": cl[0], "exact": ce[0], "spread": abs(cl[0] - ce[0]), "maxres": float(np.max(np.abs(resl)))}
            rows.append([run, f(m, 7), f(cl[0], 14), " ".join(f(x, 6) for x in cl[1:]), " ".join(f(x, 2) for x in resl / cl[0]),
                         f(ce[0], 14), f(rese[3] / ce[0], 2), f(abs(cl[0] - ce[0]) / kl, 2), f(np.max(np.abs(resl)) / kl, 2)])
    out += ["## T2 The heavy packets' L = 2048 symbols (n = 1..4) fitted by k_s0 + k_s2 q^2 + k_s4 q^4: least squares over the four points "
            "(coefficients, residuals relative to k_s0) and exactly through n = 1, 2, 3 (k_s0, the n = 4 check relative to k_s0); the two "
            "routes' k_s0 spread and the largest least-squares residual relative to k_lat", "",
            table(["run", "m", "k_s0 (least squares)", "k_s2, k_s4", "residuals/k_s0 (n = 1..4)", "k_s0 (through n = 1, 2, 3)",
                   "n = 4 check/k_s0", "spread/k_lat", "max residual/k_lat"], rows), ""]
    # assembly
    rows = []
    res_k = {}
    for run in ("massless", "m1e-4"):
        c0, rem = c0inf[run]
        h1, h2 = fits[(run, M1)], fits[(run, M2)]
        ka = c0 - 2 * h1["ls"] + h2["ls"]
        kae = c0 - 2 * h1["exact"] + h2["exact"]
        kl = klat(LIGHT[run])
        b_fit = 2 * h1["spread"] + h2["spread"]
        b_res = 2 * h1["maxres"] + h2["maxres"]
        total = rem + b_fit + b_res
        res_k[run] = (ka, total, kl)
        rows.append([run, f(c0, 13), f(h1["ls"], 13), f(h2["ls"], 13), f(ka, 10), f(kae, 10), f(kl, 10), f(ka / kl, 7),
                     "c_0 %s; fit spread %s; residuals %s; total %s (%s of k_lat)" % (f(rem, 2), f(b_fit, 2), f(b_res, 2), f(total, 2), f(total / kl, 2))])
        summ.append("T3 (%s): k_a(0; phys) = %s, k_a(0; phys)/k_lat = %s; budget %s of k_lat (c_0 remainder %s, heavy fits' spread %s, their residuals %s)." % (
            run, f(ka, 9), f(ka / kl, 7), f(total / kl, 2), f(rem / kl, 2), f(b_fit / kl, 2), f(b_res / kl, 2)))
    out += ["## T3 k_a(0; phys) = c_0(infinity) - 2 k_{0.0130903,0} + k_{0.0185125,0} per run (the heavy k_s0 by least squares; beside it with the "
            "three-point fits), k_lat, the ratio, and the budget (absolute; the fit terms propagated with |eta| = 2 and 1)", "",
            table(["run", "c_0(infinity)", "k_s0 (0.0130903)", "k_s0 (0.0185125)", "k_a(0; phys)", "k_a(0; phys), three-point fits", "k_lat", "ratio",
                   "budget"], rows), ""]
    (ka1, t1, kl1), (ka2, t2, kl2) = res_k["massless"], res_k["m1e-4"]
    summ.append("T3: the two runs differ by %s of k_lat against the combined budgets %s (the light mass 1e-4 shifts k_lat itself by %s relative)." % (
        f((ka1 / kl1) - (ka2 / kl2), 2), f(t1 / kl1 + t2 / kl2, 2), f(kl2 / kl1 - 1, 2)))
    # cross-check against J2c
    rows = []
    for run in ("massless", "m1e-4"):
        c0, _ = c0inf[run]
        for n in (1, 2, 3, 4):
            r = J2C.get((run, 2048, n))
            if r is None:
                continue
            hk = {m: [x for x in D["heavy"] if x["run"] == run and abs(x["m"] - m) < 1e-12 and x["n"] == n][0]["k"] for m in (M1, M2)}
            asm = r["light_alone_c0"] - 2 * hk[M1] + hk[M2]
            rows.append([run, n, f(r["q"], 5), f(asm, 12), f(r["k_a"], 12), f(asm / r["k_a"] - 1, 2), f(r["light_alone_c0"] - c0, 4)])
    out += ["## T4 Cross-check at L = 2048: the per-packet assembly sum_heavy eta_s k_s(q) + c_light(q) against J2c's eta-summed k_a(q), and the "
            "light symbol's distance from c_0(infinity) at J2c's q", "",
            table(["run", "n", "q", "assembled", "J2c eta-sum", "relative difference", "c_light(q) - c_0(infinity)"], rows), ""]
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
