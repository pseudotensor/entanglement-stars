#!/usr/bin/env python
"""Strand 5 J2 report (builder analyst): tables T3 (the kernel ingredients) from strand5_kernel_v3.py's kernel_v3.json, with k_lat from the
2c kernel table.  Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--kernel", required=True, help="the 2c kernel table (for k_lat)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    D = json.load(open(a.kernel))
    klat = {}
    for r in D["equal"]:
        klat[r["aH"]] = r["k_lat"]
    rows_all = R["rows"]
    eq = [o for o in rows_all if o["set"].startswith("equal")]
    ph = [o for o in rows_all if not o["set"].startswith("equal")]
    out = ["# Strand 5 J2 tables (generated by solve/code/strand5/strand5_kernel_report_v1.py from kernel_v3.json)", "",
           "The 2c part A table (L = 256, the equal rectangle with the light packet at m = 0.1, H = aH); k_a(pi) halved (the zone-edge mode's "
           "norm, see the result's reading 1).", ""]
    rows = []
    for o in eq:
        kl = klat.get(o["aH"])
        rows.append([f(o["aH"]), o["fit_points"], f(o["k_a0"], 8), f(o["k_2"], 6), f(o["fit_max_residual"], 2), f(o["k_a0_moment"], 8),
                     f(o["k_a0_moment"] / o["k_a0"] - 1, 3), f(kl, 8), f(o["k_a0"] / kl, 6), f(o["k_a0_moment"] / kl, 6)])
    out += ["## T3a k_a(0; aH): the spec's fit a + b q^2 over q <= aH/4 (points used; one point: its value), and the line kernel's second "
            "moment (1/2) sum n^2 K_n (the exact q -> 0 curvature of the table's symbol when K decays within the ring, T3c); against 2c's k_lat", "",
            table(["aH", "fit points", "k_a(0) fit", "k_2 fit", "fit max residual", "k_a(0) moment", "moment/fit - 1", "k_lat", "fit/k_lat",
                   "moment/k_lat"], rows), ""]
    rows = []
    for o in eq:
        p = o.get("c4_100_pred")
        rows.append([f(o["aH"]), f(o["L_sum_eta_log_m2"], 6), f(o.get("g_4"), 6), f(o.get("b_iso_pred"), 6), f(o.get("b_cubic_pred"), 6), f(p, 6),
                     f(o["c4_100_fit"], 6), f(o["c4_100_fit"] / p - 1 if (o["c4_100_fit"] is not None and p) else None, 3),
                     f(o["c4_100_moment"], 6), f(o["c4_100_moment"] / p - 1 if p else None, 3)])
    out += ["## T3b The [100] q^4 coefficient of F(q) = k_a(q) q_lat^2 against P14 (F = k_a q^2 + b_iso q^4 + b_cubic sum_i q_i^4, P = a = 1, "
            "k := the fitted k_a(0; aH)): L = sum eta_s log m_s^2, g_4 = L/(2 pi^2), b_iso = g_4 + k/8, b_cubic = -k/6, the [100] prediction "
            "b_iso + b_cubic; the spec's c_4 = k_2 - k_a(0)/12 and the line kernel's -(1/24) sum n^4 K_n", "",
            table(["aH", "L", "g_4", "b_iso", "b_cubic", "[100] prediction", "c_4 (spec's fit)", "fit/prediction - 1", "c_4 (fourth moment)",
                   "moment/prediction - 1"], rows), ""]
    rows = []
    for o in rows_all:
        d = o["decay"]
        rows.append([o["set"], f(o["aH"]), f(o["k_a_zone_edge_tabulated"], 6), f(o["k_a_zone_edge_used"], 6), f(o["k_a_next_to_edge"], 6), f(o["K0"], 6),
                     f(o["sum_K"], 2)] + [f(d[k], 2) for k in ("1", "4", "8", "16", "32", "64", "128")])
    out += ["## T3c The line kernel K_n (the [100] symbol's inverse transform on the 256-ring; the 3D kernel summed over transverse planes): the "
            "zone-edge value as tabulated and as used, its neighbour, K_0, sum_n K_n (= C(0) = 0), and |K_n|/|K_0|", "",
            table(["set", "aH", "k_a(pi) tabulated", "used", "k_a at n = 127", "K_0", "sum K_n", "n = 1", "4", "8", "16", "32", "64", "128"], rows), ""]
    rows = []
    for o in rows_all:
        for g in o["green"]:
            rows.append([o["set"][:24], f(o["aH"]), f(g["r"]), f(g["G_C_over_Newton_minus_1"], 3), f(g["G_local_cut_over_Newton_minus_1"], 3),
                         f(g["kernel_part_over_Newton"], 3)])
    out += ["## T3d The radial Green function by the spec's formula, (2 pi^2 r)^-1 int_0^pi dq sin(qr)/(q k_a(q)), against the Newtonian tail "
            "1/(4 pi k_a(0) r) (k_a(0) fitted): G_C/G_N - 1; the same integral with k_a(q) -> k_a(0) (the local row cut at pi, its deviation the "
            "cut alone); their difference", "",
            table(["set", "aH", "r", "G_C/G_N - 1", "G_local, cut/G_N - 1", "difference"], rows), ""]
    rows = []
    for o in rows_all:
        g = o["green_lattice"]
        rows.append([o["set"][:24], f(o["aH"]), f(g["U_inf_times_4pi_k_a0_fit"], 8), f(g["U_inf_times_4pi_k_a0_moment"], 10)] +
                    [" ".join("%s: %s" % (f(r_["r"]), f(r_["rel_moment"], 2)) for r_ in g["rows"])])
    out += ["## T3e The Green function on the radial lattice: the field of a smeared unit source (Gaussian, w = 3 lattice units) solved with "
            "the line kernel; its exterior constant U_inf times 4 pi k (k fitted, k from the moment), and the relative deviation of f(r) from "
            "1/(4 pi k r) with k from the moment, per r", "",
            table(["set", "aH", "4 pi k_fit U_inf", "4 pi k_moment U_inf", "f(r) 4 pi k_moment r - 1 at r"], rows), ""]
    rows = []
    for o in rows_all:
        c = o["C_coulomb_at_r"]
        rows.append([o["set"][:24], f(o["aH"]), f(o["C1_max_abs_inner"] / o["C1_scale_k_a0"], 2),
                     " ".join("%s: %s" % (k, f(c[k] / o["k_a0"], 3)) for k in ("1", "2", "4", "8", "16", "32", "64", "128")),
                     f(o["C_coulomb_max_abs_beyond_128_over_k_a0"], 2), f(o["gauss_over_minus_4pi_k_a0_minus_1"], 3),
                     f(o["gauss_4pi_sum_r2_C_coulomb"] / (-4 * np.pi * o["k_a0_moment"]) - 1, 2)])
    out += ["## T3f The radial convolution operator on the uniform radial grid r_j = j a, (C f)_j = (1/r_j) sum_n K_n u_{j-n}, u = r f odd: "
            "max |C 1|/k_a(0) over the nodes whose stencil stays on the grid; C(1/r)/k_a(0) at r; max |C(1/r)|/k_a(0) beyond r = 128; the Gauss "
            "law 4 pi sum r^2 C(1/r) against -4 pi k_a(0) with k fitted and with k from the moment", "",
            table(["set", "aH", "max |C 1|/k", "C(1/r)/k at r", "max |C(1/r)|/k beyond 128", "Gauss/(-4 pi k_fit) - 1", "Gauss/(-4 pi k_moment) - 1"], rows), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
