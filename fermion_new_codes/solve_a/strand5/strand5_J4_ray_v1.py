#!/usr/bin/env python
"""Strand 5 J4 stage 2 along the ray m/aH = 0.1 (the lead's run order after the stage-2 judgment; builder analyst): from the stage-2 files
(strand5_J4_stage2_v9.py: stage2_<family>.json) of the kernel families (0.1, 1), (0.03, 0.3) [J4run2] and (0.01, 0.1) [J4run4, the light
packet at L = 1024], both couplings: at each family's largest-M member and at the most compact member, (A - B)/G, Total, the matter piece at
fixed N_B (D_mat - mu_inf dN_B/dlam) and the kernel row's own piece D_vac + S_inf (Total - D_mat), their shares of -(A - B)/G, the parts of
(A - B)/A, the closure, aH r_s; and each family's vacuum share and vacuum part of (A - B)/A divided by the (0.03, 0.3) family's at the same
couplings and the same member's place.  Numbers emitted, not retyped."""
import argparse
import json
import os

import numpy as np

FAMS = [("J4run2", "lstar_m0.1_aH1_kernel_g%s.json", 0.1, 1.0), ("J4run2", "lstar_m0.03_aH0.3_kernel_g%s.json", 0.03, 0.3),
        ("J4run4", "lstar_m0.01_aH0.1_kernel_g%s_pk.json", 0.01, 0.1)]


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage2", required=True, help="comma-separated folders: the stage-2 folder of J4run2's families, then J4run4's")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    folders = a.stage2.split(",")
    rows, summ = [], []
    ref = {}
    recs = []
    for g in ("0_0", "0.2_1"):
        for run, pat, m, aH in FAMS:
            name = pat % g
            p = None
            for fo in folders:
                q = os.path.join(fo, "stage2_" + name)
                if os.path.exists(q):
                    p = q
                    break
            if p is None:
                continue
            R = json.load(open(p))
            mem = R["members"]
            imax = int(np.argmax([x["M"] for x in mem]))
            for place, x in (("max", mem[imax]), ("most compact", mem[-1])):
                L = x["lock"]
                rec = {"run": run, "family": name, "m": m, "aH": aH, "g": g, "place": place, "z_c": x["z_c"], "AmB_over_G": L["AmB_over_G"], "Total": L["Total"],
                       "matter_fixed_NB": L["D_mat_fixed_NB"], "vac_piece": L["vac_piece"], "share_matter": L["share_matter_fixed_NB"], "share_vac": L["share_vac"],
                       "matter_part": L["matter_part_of_AmB_over_A"], "vac_part": L["vac_part_of_AmB_over_A"], "closure": L["closure_total_with_mu_dNB"],
                       "aH_r_s": aH * x["r_s"]}
                recs.append(rec)
                if (m, aH) == (0.03, 0.3):
                    ref[(g, place)] = rec
    for rec in recs:
        r0 = ref.get((rec["g"], rec["place"]))
        rv = rec["vac_part"] / r0["vac_part"] if r0 else None
        rs = rec["share_vac"] / r0["share_vac"] if r0 else None
        rows.append("| %s (%g, %g) kernel (%s) | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            rec["run"], rec["m"], rec["aH"], rec["g"].replace("_", ", "), rec["place"], f(rec["z_c"], 4), f(rec["AmB_over_G"], 6), f(rec["Total"], 6),
            f(rec["matter_fixed_NB"], 6), f(rec["vac_piece"], 6), f(rec["share_matter"], 5), f(rec["share_vac"], 5), f(rec["matter_part"], 5),
            f(rec["vac_part"], 5), f(rec["closure"], 2), f(rec["aH_r_s"], 5), "%s; %s" % (f(rs, 5), f(rv, 5))))
        if rec["place"] == "max":
            summ.append("Ray (%s (%g, %g), couplings %s, maximum z_c %s): the kernel row's own share D_vac + S_inf of -(A - B)/G is %s and its part of "
                        "(A - B)/A %s (aH r_s %s); relative to (0.03, 0.3) at the same couplings: share %s, part %s." % (
                            rec["run"], rec["m"], rec["aH"], rec["g"].replace("_", ", "), f(rec["z_c"], 4), f(rec["share_vac"], 5), f(rec["vac_part"], 5),
                            f(rec["aH_r_s"], 5), f(rs, 5), f(rv, 5)))
    out = ["# Strand 5 J4 stage 2 along the ray m/aH = 0.1 (generated by solve/code/strand5/strand5_J4_ray_v1.py)", "", "## S Summary (emitted)", ""] + \
          ["- " + s for s in summ] + ["", "## R1 Per kernel family on the ray (both couplings) at the largest-M member and the most compact one: (A - B)/G, Total, the matter "
                                      "piece at fixed N_B, the kernel row's own piece D_vac + S_inf, their shares of -(A - B)/G, their parts of (A - B)/A, the closure, aH r_s, "
                                      "and the vacuum share and part relative to the (0.03, 0.3) family's at the same couplings and place", "",
                                      "| family | member | z_c | (A - B)/G | Total | matter (fixed N_B) | D_vac + S_inf | matter share | vacuum share | matter part of (A-B)/A | "
                                      "vacuum part of (A-B)/A | closure | aH r_s | vacuum share; part relative to (0.03, 0.3) |", "|" + "---|" * 15] + rows
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
