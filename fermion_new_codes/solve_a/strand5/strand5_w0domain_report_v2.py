#!/usr/bin/env python
"""Strand 5 J5 domain control report (builder's addition, revision 3; builder analyst): the flat-ruler Gaussians psi = 1 + e f_w (N = 1) at
h = 1 from every record given (the dense pilot's J5pilot2 at R_max = 322 and 480, J5decomp2 at R_max = 4.5 w, J5domain1 at R_max/w = 4.5, 8, 16):
per width w and grid R_max = n h, W_0^(2) = (W(e) + W(-e))/(2 e^2) and c_3 = (W(e) - W(-e))/(2 e^3) at e = 1e-2, and the two-width solve
-k a(w) - g_4 b(w) = W_0^(2) (a(w) = (3/2) pi^(3/2) w, b(w) = (15/4) pi^(3/2)/w) for the width pairs (20, 60) and (30, 100) at each R_max/w
present for both widths (matched within 5 percent), with the route of each record.  Numbers emitted, not retyped.
(Version 2: the j count of each configuration (version 10's records carry it; earlier records used n) is a key beside w and n, and the
two-width pairs are matched in j count over n as well; J5jres1's records (the j count 2n and 4n) enter.)"""
import argparse
import json
import math

A_ = lambda w: 1.5 * math.pi ** 1.5 * w
B_ = lambda w: 3.75 * math.pi ** 1.5 / w
E0 = 1e-2


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True, help="comma-separated Gaussian records (h = 1)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    G = {}  # (w, n) -> {e: W}, route
    for p in a.records.split(","):
        R = json.load(open(p))
        h = float(R["meta"]["h"])
        route = R["meta"].get("route", "dense")
        for key, c in R["configs"].items():
            if not key.startswith("gauss") or float(c.get("ruler", 1.0)) != 1.0 or h != 1.0:
                continue
            w, n = float(c["width"]), int(c["n"])
            jc = int(c.get("j_count", n))
            G.setdefault((w, n, jc), {"route": route, "src": p.split("/")[0], "W": {}})["W"][round(float(c["eps"]), 12)] = c["L_variants"]["psi_only"]["W_c"]
    rows, D = [], {}
    for (w, n, jc), g in sorted(G.items()):
        Wp, Wm = g["W"].get(round(E0, 12)), g["W"].get(round(-E0, 12))
        if Wp is None or Wm is None:
            continue
        w2, c3 = (Wp + Wm) / (2 * E0 * E0), (Wp - Wm) / (2 * E0 ** 3)
        D[(w, n, jc)] = (w2, c3)
        rows.append(["%g" % w, n, "%.3g" % (n / w), jc, "%.3g" % (jc / n), g["src"], g["route"], "%.12e" % w2, "%.6e" % c3])
    out = ["# Strand 5 J5 domain control (generated by solve/code/strand5/strand5_w0domain_report_v2.py)", "",
           "## G Per width, grid and j count (h = 1, P = 1, e = 1e-2): R_max/w, the j count and its ratio to n, the record, W_0^(2) and c_3", "",
           table(["w", "n = R_max", "R_max/w", "j count", "j count/n", "record", "route", "W_0^(2)", "c_3"], rows), ""]
    krow, summ = [], []
    for w1, w2_ in ((20.0, 60.0), (30.0, 100.0)):
        for (wa, na, ja) in sorted(k for k in D if k[0] == w1):
            for (wb, nb, jb) in sorted(k for k in D if k[0] == w2_):
                ra, rb = na / wa, nb / wb
                if abs(ra / rb - 1) > 0.05 or abs((ja / na) / (jb / nb) - 1) > 0.05:
                    continue
                det = A_(wa) * B_(wb) - A_(wb) * B_(wa)
                ya, yb = -D[(wa, na, ja)][0], -D[(wb, nb, jb)][0]
                k = (ya * B_(wb) - yb * B_(wa)) / det
                g4 = (A_(wa) * yb - A_(wb) * ya) / det
                krow.append(["(%g, %g)" % (w1, w2_), "%.3g, %.3g" % (ra, rb), "%.3g" % (ja / na), "%.12e" % k, "%.8e" % g4])
    out += ["## K The two-width solve per width pair at matched R_max/w and j count/n", "", table(["widths", "R_max/w", "j count/n", "k", "g_4"], krow), ""]
    for w in sorted({k[0] for k in D}):
        ser = sorted((n / w, jc / n, D[(w, n, jc)]) for (ww, n, jc) in D if ww == w)
        summ.append("w = %g: (R_max/w, j count/n) -> (c_3, W_0^(2)): %s." % (w, "; ".join("(%.3g, %.3g) -> (%.4e, %.10e)" % (s[0], s[1], s[2][1], s[2][0])
                                                                                         for s in ser)))
    if krow:
        summ.append("k per width pair at (R_max/w, j count/n): " + "; ".join("%s at (%s; %s): %s" % (r[0], r[1], r[2], r[3]) for r in krow) + ".")
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
