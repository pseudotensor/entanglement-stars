#!/usr/bin/env python
"""Strand 5 J1 report (builder analyst): tables T1 (the continuum family) and T2 (its controls) from strand5_star_v3.py's star_v3.json.
Numbers emitted, not retyped."""
import argparse
import json

import numpy as np


def f(v, sig=4):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    R = json.load(open(a.json))
    g = R["meta"]["g"]
    sq = np.sqrt(g / 2)
    ref = R["reference"]
    grids = sorted(R["grid"].keys(), key=int)
    gfin = grids[-1]
    out = ["# Strand 5 J1 tables (generated by solve/code/strand5/strand5_star_report_v1.py from star_v3.json)", ""]
    # T1a reference family
    rows = []
    for r in ref:
        rows.append([f(r["z_c"]), f(r["M"], 6), f(r["M"] * sq, 6), f(r["N_B"], 6), f(r["N_B"] * sq, 6), f(r["r_s"], 6), f(r["R_s_areal"], 6),
                     f(r["compactness_2GM_over_Rs"], 6), f(r["mu_inf"], 6), f(r["N0"], 6), f(r["f_s"], 6), f(r["r_s_over_A"], 5),
                     f(r["A_over_B_minus_1"], 2), f(r["E_canonical_minus_2A"], 2), f(r["komar_adm_rel"], 2), f(r["first_law"]["dM_minus_mu_dNB_rel"], 2),
                     f(r["tf_surface_check"], 2)])
    out += ["## T1a The continuum family, reference integration (g = %s, G = m = 1; M_0 = R_0 = (g/2)^(-1/2) for P16's units)" % f(g), "",
            table(["z_c", "M = 2A", "M/M_0", "N_B", "m N_B/M_0", "r_s (isotropic)", "R_s (areal)", "2GM/R_s", "mu_inf", "N(0)", "f_s", "r_s/A",
                   "A/B - 1", "E_canonical - 2A", "Komar-ADM rel", "first law rel", "mu_inf - N(r_s) exterior"], rows), ""]
    # T1b grid solver against the reference
    rows = []
    mem = {ng: R["grid"][ng]["members"] for ng in grids}
    for i, r in enumerate(ref):
        ms = {ng: (mem[ng][i] if i < len(mem[ng]) and not mem[ng][i].get("failed") else None) for ng in grids}
        d = ms[gfin]
        row = [f(r["z_c"])] + [f(ms[ng]["minus_reference_rel"]["M"], 3) if ms[ng] else "fail" for ng in grids]
        if d:
            row += [f(d["minus_reference_rel"]["N_B"], 3), f(d["minus_reference_rel"]["R_s_areal"], 3), f(d["minus_reference_rel"]["mu_inf"], 3),
                    f(d["A_over_B_minus_1"], 3), f(d["A_over_B_minus_1_vol"], 3), f(d["A_vol_minus_A_tail"], 2), f(d["B_vol_minus_B_tail"], 2),
                    f(d["charges_at_10rs"][2], 2), f(d["E_canonical_minus_2A"], 2), f(d.get("first_law", {}).get("dM_minus_mu_dNB_rel"), 2),
                    f(d["sigma_min_fixed_zc"], 4), f(d["sigma_min_fixed_NB"], 4), d["newton_it"], f(d["R_max_over_r_s"], 4)]
        else:
            row += ["-"] * 14
        rows.append(row)
    out += ["## T1b The grid solver (Newton on [0, 50 r_s], finite volumes) against the reference: relative differences of M per grid, and on "
            "the %s-node grid the other relative differences, the lock from the tail and from the volume integrals, the Gauss-law and "
            "second-radius checks, the energy identity, the first law, sigma_min of the row-scaled Jacobian at fixed z_c and at fixed N_B" % gfin, "",
            table(["z_c"] + ["M rel, n = %s" % ng for ng in grids] + ["N_B rel", "R_s rel", "mu_inf rel", "A/B - 1 (tail)", "A/B - 1 (volume)",
                                                                       "A_vol - A_tail", "B_vol - B_tail", "A(10 r_s)/A - 1", "E_canonical - 2A",
                                                                       "first law rel", "sigma_min fixed z_c", "sigma_min fixed N_B", "Newton steps",
                                                                       "R_max/r_s"], rows), ""]
    # T2 controls
    C = R["controls"]
    P16 = C["P16"]
    rm = C["reference_maximum"]
    rows = []
    keys = [("z_c", "z_c"), ("M/M_0", "M_over_M0"), ("R_s/R_0", "R_s_over_R0"), ("2GM/R_s", "compactness"), ("m N_B/M_0", "m_NB_over_M0"),
            ("mu_inf/m", "mu_inf_over_m")]
    gm = {ng: R["grid"][ng]["maximum"] for ng in grids}
    for lab, k in keys:
        row = [lab, f(P16[k], 6), f(rm["in_P16_units"][k], 8)]
        vals = []
        for ng in grids:
            x = gm[ng]
            v = (x["z_c"] if k == "z_c" else x["in_P16_units"][k]) if x else None
            vals.append(v)
            row.append(f(v, 8))
        rich = vals[-1] + (vals[-1] - vals[-2]) / 3 if (len(vals) >= 2 and vals[-1] is not None and vals[-2] is not None) else None
        row += [f(rich, 8), f(rm["in_P16_units"][k] / P16[k] - 1, 3)]
        rows.append(row)
    out += ["## T2a The mass maximum against P16 (free TF, Oppenheimer-Volkoff numbers): the reference (Brent on the integration), each grid "
            "(Brent on the grid solver, fixed grid at the reference maximum's r_s), Richardson over the two finest grids (second order), and the "
            "reference's relative difference from P16's printed value", "",
            table(["quantity", "P16", "reference"] + ["grid n = %s" % ng for ng in grids] + ["Richardson", "reference/P16 - 1"], rows), ""]
    g2 = C["reference_maximum_g2"]
    out += ["## T2b The degeneracy mapping: the reference maximum at g = 2 (the OV normalization, M_0 = R_0 = 1) and the ratio", "",
            table(["g", "z_c", "M", "R_s", "m N_B", "mu_inf/m", "2GM/R_s", "M(g = %s) (g/2)^(1/2)/M(g = 2)" % f(g)],
                  [["2", f(g2["z_c"], 8), f(g2["M"], 8), f(g2["R_s_areal"], 8), f(g2["N_B"], 8), f(g2["mu_inf"], 8), f(g2["compactness"], 8),
                    f(g2["ratio_M_g16_over_g2_times_sqrt8"], 12)]]), "",
            "Reference integration tolerance: at the maximum, rtol 1e-10 against 1e-12 changes M by %s, N_B by %s, R_s by %s, mu_inf by %s, "
            "A/B - 1 by %s." % tuple(f(rm["rtol_1e-10_differences"][k_], 2) for k_ in ("M", "N_B", "R_s_areal", "mu_inf", "A_over_B_minus_1")), ""]
    V = C["vacuum_grid"]
    out += ["## T2c Family-wide controls", ""]
    rows = []
    rows.append(["C1 vacuum (source off), grid n = %s" % grids[0], "Newton %s; max |psi - 1| %s, max |N - 1| %s, A %s, B %s, mu_inf %s, sigma_min %s" % (
        "converged" if V["ok"] else "failed", f(V["max_abs_psi_minus_1"], 2), f(V["max_abs_N_minus_1"], 2), f(V["A"], 2), f(V["B"], 2),
        f(V["mu_inf"], 8), f(V["sigma_min_vacuum"], 4))])
    rows.append(["C2 Komar-ADM: max over the family of |A/B - 1|", "reference %s; grid n = %s: tail %s, volume %s" % (
        f(max(abs(r["A_over_B_minus_1"]) for r in ref), 2), gfin, f(max(abs(d["A_over_B_minus_1"]) for d in mem[gfin] if not d.get("failed")), 2),
        f(max(abs(d["A_over_B_minus_1_vol"]) for d in mem[gfin] if not d.get("failed")), 2))])
    for ng in grids:
        ok = [d for d in mem[ng] if not d.get("failed")]
        rows.append(["C2 per grid n = %s: max |A/B - 1| tail, volume; members solved" % ng, "%s, %s; %d of %d" % (
            f(max(abs(d["A_over_B_minus_1"]) for d in ok), 2), f(max(abs(d["A_over_B_minus_1_vol"]) for d in ok), 2), len(ok), len(ref))])
    rows.append(["C3 charges at 10 r_s against R_max (grid n = %s): max relative difference A, B" % gfin, "%s, %s" % (
        f(max(abs(d["charges_at_10rs"][2]) for d in mem[gfin] if not d.get("failed")), 2),
        f(max(abs(d["charges_at_10rs"][3]) for d in mem[gfin] if not d.get("failed")), 2))])
    rows.append(["energy identity: max |E_canonical - 2A|", "reference %s; grid n = %s %s" % (
        f(max(abs(r["E_canonical_minus_2A"]) for r in ref), 2), gfin, f(max(abs(d["E_canonical_minus_2A"]) for d in mem[gfin] if not d.get("failed")), 2))])
    okf = [d for d in mem[gfin] if not d.get("failed")]
    i1 = int(np.argmin([d["sigma_min_fixed_zc"] for d in okf]))
    i2 = int(np.argmin([d["sigma_min_fixed_NB"] for d in okf]))
    rows.append(["C5 sigma_min along the family (grid n = %s): smallest at fixed z_c, and at fixed N_B, with the member" % gfin,
                 "fixed z_c: %s at z_c = %s (largest %s); fixed N_B: %s at z_c = %s (largest %s)" % (
                     f(okf[i1]["sigma_min_fixed_zc"], 4), f(okf[i1]["z_c"], 5), f(max(d["sigma_min_fixed_zc"] for d in okf), 4),
                     f(okf[i2]["sigma_min_fixed_NB"], 4), f(okf[i2]["z_c"], 5), f(max(d["sigma_min_fixed_NB"] for d in okf), 4))])
    rows.append(["C6 first law: max |dM - mu_inf dN_B|/(|dM| + mu_inf |dN_B|) over the family", "reference %s; grid n = %s %s" % (
        f(max(abs(r["first_law"]["dM_minus_mu_dNB_rel"]) for r in ref), 2), gfin,
        f(max(abs(d["first_law"]["dM_minus_mu_dNB_rel"]) for d in okf if "first_law" in d), 2))])
    rows.append(["trapping: min over the family of r_s/A (isotropic; the exterior f = (r - A)/(r + A) vanishes at r = A) and of R_s/(2GM) (areal)",
                 "r_s/A %s (r_s/(2A) %s); R_s/(2GM) %s" % (f(min(r["r_s_over_A"] for r in ref), 5), f(min(r["r_s_over_A"] for r in ref) / 2, 5),
                                                         f(min(r["R_s_areal"] / (2 * r["M"]) for r in ref), 5))])
    rows.append(["largest compactness 2GM/R_s over the family, and at z_c", "%s at z_c = %s" % (
        f(max(r["compactness_2GM_over_Rs"] for r in ref), 6), f(ref[int(np.argmax([r["compactness_2GM_over_Rs"] for r in ref]))]["z_c"], 4))])
    rows.append(["the TF surface condition mu_inf = N(r_s) read on the exterior: max |difference|", "reference %s; grid n = %s %s" % (
        f(max(abs(r["tf_surface_check"]) for r in ref), 2), gfin, f(max(abs(d["tf_surface_check"]) for d in okf), 2))])
    rows.append(["Gauss-law check of the integration: max |a/(I_A/2) - 1|, |b/(I_B/2) - 1|",
                 "%s, %s" % (f(max(abs(r["gauss_check"][0]) for r in ref), 2), f(max(abs(r["gauss_check"][1]) for r in ref), 2))])
    out += [table(["control", "value"], rows), ""]
    out += ["Run time %s s." % f(R["meta"]["seconds"]), ""]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("wrote", a.md)


if __name__ == "__main__":
    main()
