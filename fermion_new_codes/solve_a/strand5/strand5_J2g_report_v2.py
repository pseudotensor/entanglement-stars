#!/usr/bin/env python
"""Strand 5 J2g report (builder analyst): from strand5_J2g_v2.py (J2g.json): (G1) per mass assignment k_a(0; phys) = K(h), k_a'(1) = D(h),
k_a'(1)/k_a(0), k_a'(1)/k_lat against the red team's expansion estimate, both routes' differences at P = 1, 1.25, 1.5 and the route-1
quadrature error estimates; (G2) k_a(P), k_a'(P) and k_a'(P)/k_a(1) over the ruler (every fifth point of the 51) and the spline check;
(G3) P14 eq. 7's piece on J1's members: z_c, GM/R_s, psi_c, the field integral (interior, exterior, total at 200 and 400 panels), the
f = 1 control against the ODE's own integral, the piece, piece/A, P33's gamma - 1 and beta - 1, against Cassini for the solar member.
Numbers emitted, not retyped.
(Version 2, for strand5_J2g_v3.py's record: the route comparisons as D(h P^4) differences and divided by P^5; G3 with the coefficient-channel
term q_0 gamma^2/8 and beta - 1 with it, the exterior rule split at the spline knots and its change, the f = 1 control's raw values, and
J1's most compact member.)"""
import argparse
import json


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--J2g", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    D = json.load(open(a.J2g))
    out = ["# Strand 5 J2g tables (generated by solve/code/strand5/strand5_J2g_report_v2.py)", ""]
    summ = []
    names = ("physical", "window edge")
    rows = []
    for nm in names:
        s = D[nm]
        r2 = {x["P"]: x for x in s["route2"]}
        rel = s["ka_prime_1_over_k_lat"] / s["red_team_estimate_over_k_lat"] - 1
        rows.append([nm, "%.10g" % s["m1"], "%.15e" % s["K_route1"], "%.15e" % s["D_route1"], "%.10e" % s["ka_prime_1_over_ka_0"], "%.10e" % s["ka_prime_1_over_k_lat"],
                     f(s["red_team_estimate_over_k_lat"], 3), f(rel, 3),
                     "; ".join("%s: %s, %s" % (P, f(x["K_hP4_minus_route1"], 2), f(x["D_hP4_minus_route1"], 2)) for P, x in sorted(r2.items())),
                     "; ".join("%s: %s, %s" % (P, f(x["k_a_P_minus_route1"], 2), f(x["k_a_prime_P_minus_route1"], 2)) for P, x in sorted(r2.items())),
                     "%s, %s" % (f(s["K_quad_error"], 2), f(s["D_quad_error"], 2))])
        summ.append("G1 (%s, m_1 = %s): k_a(0; phys) = %s, k_a'(1) = %s, k_a'(1)/k_a(0) = %s, k_a'(1)/k_lat = %s against the red team's expansion "
                    "estimate %s (relative difference %s); route 2 - route 1 at P = 1: %s (K), %s (k_a')." % (
                        nm, "%.10g" % s["m1"], "%.13e" % s["K_route1"], "%.13e" % s["D_route1"], "%.8e" % s["ka_prime_1_over_ka_0"], "%.8e" % s["ka_prime_1_over_k_lat"],
                        f(s["red_team_estimate_over_k_lat"], 3), f(rel, 3), f(r2[1.0]["K_hP4_minus_route1"], 2), f(r2[1.0]["D_hP4_minus_route1"], 2)))
    out += ["## G1 The physical rectangle (0, m_1, m_1, sqrt2 m_1), orientations (+, -, -, +): K(h) = k_a(0; phys) and D(h) = k_a'(1) by route 1, "
            "the ratios, the red team's expansion estimate of k_a'(1)/k_lat and the relative difference, route 2 - route 1 of the raw integrals "
            "K(h P^4) and D(h P^4) at P = 1, 1.25, 1.5, the same divided by P^4 and P^5 (the k_a(P) and k_a'(P) differences), and route 1's summed "
            "quad error estimates (K, k_a')", "",
            table(["assignment", "m_1", "k_a(0; phys)", "k_a'(1)", "k_a'(1)/k_a(0)", "k_a'(1)/k_lat", "red team", "relative difference",
                   "route 2 - route 1 (P: K(hP^4), D(hP^4))", "the same over P^4, P^5 (P: k_a, k_a')", "quad error (K, k_a')"], rows), ""]
    for nm in names:
        s = D[nm]
        tb = s["table"]
        sel = [x for i, x in enumerate(tb) if i % 5 == 0 or i == len(tb) - 1]
        out += ["## G2 (%s) k_a(P) = P^-4 K(h P^4), k_a'(P) = P^-5 D(h P^4) and k_a'(P)/k_a(1) over the ruler (every fifth of the 51 points; the "
                "cubic spline of k_a'/k_a(1) used in G3 agrees with route 1 at ten midpoints to %s)" % (nm, f(s["spline_check_max_abs"], 2)), "",
                table(["P", "k_a(P)", "k_a'(P)", "k_a'(P)/k_a(1)"], [["%.4f" % x["P"], "%.12e" % x["k_a"], "%.12e" % x["k_a_prime"], "%.10e" % x["k_a_prime_over_k_a1"]] for x in sel]), ""]
    rows = []
    for nm in names:
        for mn in ("maximum", "most compact", "solar"):
            e = D[nm]["eq7"][mn]
            cmp_ = ("Cassini (2.1 +- 2.3)e-5: %s sigma" % f(e["against_cassini"]["ratio_to_sigma"], 3)) if "against_cassini" in e else e.get("against_named_bound", "-")
            rows.append([nm, mn, "%.10g" % e["z_c"], f(e["GM_over_R_s"], 5), "%.8f" % e["psi_c"], "%.10e" % e["I7_interior"], "%.10e" % e["I7_exterior"],
                         f(e["exterior_split_minus_single"], 2), "%.10e" % e["I7_400"], f(e["I7_400"] - e["I7_200"], 2), "%.10e; %.10e (%s)" % (
                             e["control_IW_quad"], e["control_IW_ode"], f(e["control_rel"], 2)), "%.6e" % e["piece"], "%.6e" % e["piece_over_A"],
                         "%.6e" % e["gamma_minus_1"], "%.6e" % e["beta_minus_1"], "%.6e" % e["beta_coefficient_channel_q0_gamma2_over_8"],
                         "%.6e" % e["beta_minus_1_with_coefficient_channel"], cmp_])
            summ.append("G3 (%s, %s member, z_c = %s, GM/R_s = %s): P14 eq. 7's piece over A = %s; P33's charge-channel gamma - 1 = %s, beta - 1 = %s; the "
                        "coefficient-channel term q_0 gamma^2/8 = %s, beta - 1 with it %s; %s." % (
                nm, mn, "%.8g" % e["z_c"], f(e["GM_over_R_s"], 4), "%.4e" % e["piece_over_A"], "%.4e" % e["gamma_minus_1"], "%.4e" % e["beta_minus_1"],
                "%.4e" % e["beta_coefficient_channel_q0_gamma2_over_8"], "%.4e" % e["beta_minus_1_with_coefficient_channel"], cmp_))
    out += ["## G3 P14 eq. 7's piece -(1/(4 pi)) int psi [k_a'(psi)/k_a(1)] grad psi . grad chi d^3x on J1's continuum members (G = m = 1, k = 1/(2 pi), "
            "g = 16): the field integral I = int 4 pi r^2 psi f(psi) psi' chi' dr (interior on the reference ODE's dense output, exterior analytic; "
            "400 panels, and the change from 200; the exterior rule split at the spline knots minus the single rule), the f = 1 control (the quadrature, "
            "the ODE's IW, relative), the piece = -I/(4 pi), piece/A, the charge-channel gamma - 1 = D_7/(E_bdy - D_7) and beta - 1 = D_7/(2 (E_bdy - D_7)) "
            "with D_7 = the piece and E_bdy = 2A (P33 [S]), the coefficient-channel term q_0 gamma^2/8 (q_0 = k_a'(1)/k_a(1)) and beta - 1 with it, and "
            "the comparison", "",
            table(["assignment", "member", "z_c", "GM/R_s", "psi_c", "I interior", "I exterior", "split - single", "I (400 panels)", "400 - 200",
                   "f = 1 control (quad; ODE; rel)", "piece", "piece/A", "gamma - 1", "beta - 1 (charge)", "q_0 gamma^2/8", "beta - 1 (with it)", "against"], rows), ""]
    mm = D["members"]
    out += ["## G4 The two J1 members (the reference ODE, strand5_star_v4.shoot)", "",
            table(["member", "z_c", "A", "B", "A/B - 1", "r_s", "R_s (areal)", "2GM/R_s", "N_B", "mu_inf", "Komar-ADM rel"],
                  [[k, "%.12g" % v["z_c"], "%.10e" % v["A"], "%.10e" % v["B"], f(v["A_over_B_minus_1"], 2), "%.8g" % v["r_s"], "%.8g" % v["R_s_areal"],
                    "%.8e" % v["compactness_2GM_over_Rs"], "%.8e" % v["N_B"], "%.12g" % v["mu_inf"], f(v["komar_adm_rel"], 2)] for k, v in mm.items()]), ""]
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
