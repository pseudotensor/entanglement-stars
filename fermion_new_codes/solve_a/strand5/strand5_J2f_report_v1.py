#!/usr/bin/env python
"""Strand 5 J2f report (builder analyst): from strand5_J2f_v2.py (J2f.json): (V1) C_lat by the two routes beside P14's quoted value and the
asymptotic coefficients f_k; (V2) the physical and window-edge rectangles: k_a(0) by both routes, k_lat, the ratio, the integral's excess
k_a/k_lat - 1 beside P14's expansion 3 Z/(8 pi^2 k_lat) and their difference; (V3) J2's equal control rectangles: the integral against J2's
moment and fit, its ratio to k_lat, the integral's excess over k_lat beside P14's; (V4) the J4 families' k_op against the integral.
Numbers emitted, not retyped."""
import argparse
import json


def f(v, sig=4):
    if v is None:
        return "-"
    v = float(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--j2f", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    D = json.load(open(a.j2f))
    out = ["# Strand 5 J2f tables (generated by solve/code/strand5/strand5_J2f_report_v1.py from J2f.json)", ""]
    summ = []
    C = D["C_lat"]
    out += ["## V1 C_lat = 3/2 - gamma_E + 4 int_0^inf [f(u) - 1 - 1/(4(1 + u))] du by two routes, beside P14's quoted value", "",
            table(["route 1 (U = 1e3)", "route 1 (U = 3e3)", "route 2 (80 digits)", "route 1 - route 2", "P14 quoted", "route 1 - P14", "route 2 - P14",
                   "route 1 quad error estimate", "route 1 tail beyond U"],
                  [["%.15f" % C["route1"], "%.15f" % C["route1_U3e3"], "%.15f" % C["route2"], f(C["difference"], 2), "%.10f" % D["meta"]["C_lat_P14"],
                    f(C["minus_P14"], 2), f(C["route2_minus_P14"], 2), f(C["route1_quad_error"], 2), f(C["route1_tail"], 4)]]), "",
            "The asymptotic coefficients f_k of f = sum_k f_k u^-k (exact): " + ", ".join(C["f_k"][:6]) + "; the check u^2 (f - 1 - 1/(4u)) against "
            "13/32 at u = " + ", ".join("%g: %.8f" % (r["u"], r["u2_times_f_minus_1_minus_1_over_4u"]) for r in D["f_coefficient_check"]) + ".", ""]
    summ.append("V1: C_lat = %s (route 1) and %s (route 2), difference %s; P14's quoted %s differs by %s." % (
        "%.13f" % C["route1"], "%.13f" % C["route2"], f(C["difference"], 2), "%.10f" % D["meta"]["C_lat_P14"], f(C["minus_P14"], 2)))
    rows = []
    for name in ("physical", "window edge"):
        r = D[name]
        rows.append([name, ", ".join("%.10g" % m for m in r["masses"]), "%.15e" % r["route1"], "%.15e" % r["route2"], f(r["difference"], 2), "%.13e" % r["k_lat"],
                     "%.12f" % r["ratio"], "%.7e" % r["integral_excess"], "%.7e" % r["P14"]["excess"], f(r["integral_minus_P14_excess"], 3),
                     f(r["integral_minus_P14_excess"] / r["integral_excess"], 3)])
        summ.append("V2 (%s): k_a(0)/k_lat = %s (routes differ by %s absolute); the excess %s against P14's expansion %s, which leaves %s (%s of the excess)." % (
            name, "%.12f" % r["ratio"], f(r["difference"], 2), "%.7e" % r["integral_excess"], "%.7e" % r["P14"]["excess"], f(r["integral_minus_P14_excess"], 3),
            f(r["integral_minus_P14_excess"] / r["integral_excess"], 3)))
    out += ["## V2 The physical rectangle (a/l_P = 0.0213) and the window edge (masses scaled by 0.0055/0.0213): the integral by both routes, k_lat, "
            "the ratio; the excess k_a/k_lat - 1 beside P14's expansion 3 Z/(8 pi^2 k_lat) with the computed C_lat", "",
            table(["rectangle", "masses", "k_a(0) route 1", "k_a(0) route 2", "route 1 - route 2", "k_lat", "k_a(0)/k_lat", "excess (integral)", "excess (P14)",
                   "integral - P14", "(integral - P14)/excess"], rows), ""]
    sc = D["window edge"]["integral_excess"] / D["physical"]["integral_excess"]
    summ.append("V2: the window-edge excess is %s of the physical one (the mass-squared ratio is %s)." % (f(sc, 5), f(D["meta"]["scale"] ** 2, 5)))
    rows = []
    for r in D["controls"]:
        rows.append(["%g" % r["aH"], "%.13e" % r["route1"], f(r["difference"], 2), "%.13e" % r["J2_moment"], f(r["moment_over_integral"] - 1, 3),
                     "%.11e" % r["J2_fit"], f(r["fit_over_integral"] - 1, 3), "%.8f" % r["ratio"], f(r["ratio"] - 1, 4), f(r["P14"]["excess"], 4)])
    out += ["## V3 J2's equal control rectangles (light mass 0.1): the integral against J2's L = 256 moment and fit; the integral's ratio to k_lat and "
            "its excess beside P14's expansion", "",
            table(["aH", "integral (route 1)", "route 1 - route 2", "J2 moment", "moment/integral - 1", "J2 fit", "fit/integral - 1", "integral/k_lat",
                   "excess (integral)", "excess (P14)"], rows), ""]
    for H in (1.0, 0.5, 0.25):
        r = [x for x in D["controls"] if abs(x["aH"] - H) < 1e-12][0]
        summ.append("V3 (aH = %g): J2's moment / integral - 1 = %s; J2's fit / integral - 1 = %s." % (H, f(r["moment_over_integral"] - 1, 3),
                                                                                                      f(r["fit_over_integral"] - 1, 3)))
    rows = []
    for r in D["families"]:
        rows.append([r["family"], r["operator"], "%g" % r["mlight"], "%g" % r["aH"], "%.13e" % r["route1"], f(r["difference"], 2), "%.13e" % r["k_op"],
                     f(r["k_op_over_integral"] - 1, 3)])
        summ.append("V4 (%s, m_l %g, aH %g): k_op/integral - 1 = %s." % (r["operator"], r["mlight"], r["aH"], f(r["k_op_over_integral"] - 1, 3)))
    out += ["## V4 The J4 families' k_op (the line-kernel moment of each family's kernel table) against the integral of its rectangle", "",
            table(["family", "operator", "m_l", "aH", "integral (route 1)", "route 1 - route 2", "k_op", "k_op/integral - 1"], rows), ""]
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
