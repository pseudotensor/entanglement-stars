#!/usr/bin/env python
"""Strand 5 J4 sec. 10(m)(3): the table of strand5_J4_gauss_split_v1.py's records (gauss_split_<family>.json): per family the stencil's
half-width, K_0, the zero-sum of the stencil as used, symmetrized in float64 and in long double, its largest asymmetry; per member the
term -Z/(k_op A) as used and its parts (asymmetry, float64 zero-sum and rounding, long-double remainder) beside the record's
(A_vol - A)/A.  Numbers emitted, not retyped."""
import argparse
import glob
import json
import os


def f(v):
    return "%.3e" % v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    rows = []
    for p in sorted(glob.glob(os.path.join(a.dir, "gauss_split_*.json"))):
        d = json.load(open(p))
        m = d["meta"]
        for x in d["members"]:
            rows.append("| %s | %d | %s | %s | %s | %s | %s | %.4g | %d | %s | %s | %s | %s | %s |" % (
                m["family"], m["R"], f(m["K0"]), f(m["zero_sum_used"]), f(m["zero_sum_sym64"]), f(m["zero_sum_symL"]), f(m["asymmetry_max"]),
                x["z_c"], x["J"], f(-x["Z_used_rel"]), f(-x["asymmetry_part_rel"]), f(-x["float64_zero_sum_and_rounding_part_rel"]),
                f(-x["remainder_rel"]), f(x["record_A_vol_minus_A_rel"])))
    out = ["# Strand 5 J4 sec. 10(m)(3): the zero-sum/symmetry term split (generated by solve/code/strand5/strand5_J4_gauss_split_report_v1.py)", "",
           "| family | R | K_0 | zero-sum (used) | zero-sum (symmetrized, float64) | zero-sum (symmetrized, long double) | max asymmetry | z_c | J | "
           "-Z/(k_op A) as used | asymmetry part | float64 zero-sum and rounding | long-double remainder | record (A_vol - A)/A |",
           "|" + "---|" * 14] + rows
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
