#!/usr/bin/env python
"""Strand 5 J4 sec. 10(m)(3) report (builder analyst): tables from strand5_J4_exterior_v1.py (exterior_<family>.json): per family the
stencil (half-width, zero-sum relative to K_0, symmetry, k_mom/k_op - 1, the per-packet moments' sum); per compact member the buffer J - r_s
against R + 20, the Gauss decomposition of (A_vol - A)/A and (B_vol - B)/B into the residual, exterior-row, zero-sum/symmetry and moment
terms with the closure (sum of terms minus the value), the exterior rows' largest value, and the re-solve on the extended grid (the changes
of A, B, A/B - 1 and the new (A_vol - A)/A).  Numbers emitted, not retyped."""
import argparse
import glob
import json
import os

import numpy as np


def f(v, sig=3):
    if v is None:
        return "-"
    v = float(v)
    if not np.isfinite(v):
        return str(v)
    if v == 0:
        return "0"
    return ("%.*e" % (sig - 1, v)) if (abs(v) < 1e-3 or abs(v) >= 1e5) else ("%.*g" % (sig, v))


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(esc(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ext", required=True, help="comma-separated folders of exterior_*.json")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    E = []
    for folder in a.ext.split(","):
        for p in sorted(glob.glob(os.path.join(folder, "exterior_lstar_*.json"))):
            E.append(json.load(open(p)))
    out = ["# Strand 5 J4 sec. 10(m)(3) tables (generated by solve/code/strand5/strand5_J4_exterior_report_v1.py)", ""]
    summ = []
    rows = []
    for d in E:
        m = d["meta"]
        lab = "%s (%g, %g) %s (%g, %g)" % (os.path.dirname(m["family"]), m["mlight"], m["aH"], m["operator"], m["couplings"][0], m["couplings"][1])
        rows.append([lab, m["stencil_half_width"], f(m["zero_sum_rel_K0"]), f(m["symmetry_max"]), f(m["k_mom_minus_k_op_rel"]),
                     f(m["sum_of_packet_moments"] / m["k_op"] - 1) if m.get("sum_of_packet_moments") else "-"])
    out += ["## X1 The stencils: half-width R, the zero-sum sum K_n relative to K_0, the symmetry max |K_n - K_-n|, k_mom/k_op - 1 (k_mom = (1/2) "
            "sum n^2 K_n of the stencil used), and for packet-built kernels the sum of the per-packet moments relative to k_op", "",
            table(["family", "R", "zero-sum/K_0", "symmetry", "k_mom/k_op - 1", "packet moments/k_op - 1"], rows), ""]
    rows, rows_b = [], []
    worst = {}
    for d in E:
        m = d["meta"]
        lab = "%s (%g, %g) %s (%g, %g)" % (os.path.dirname(m["family"]), m["mlight"], m["aH"], m["operator"], m["couplings"][0], m["couplings"][1])
        for x in d["members"]:
            for side in ("A", "B"):
                g = x["at_J"][side]
                t = g["terms_rel"]
                rows.append([lab, f(x["z_c"], 4), side, f(x["buffer"], 4), x["at_J"]["R"] + 20, f(g["vol_minus_rel"]), f(t["residual"]), f(t["exterior"]),
                             f(t["zero_sum_symmetry"]), f(t["moment"]), f(g["sum_minus_record"], 2), f(g["exterior_rows_max_abs"], 2), f(g["exterior_rows_rel_source"], 2)])
            e = x.get("extended")
            if e:
                rows_b.append([lab, f(x["z_c"], 4), x["J"], e["J_new"], "yes" if e["newton_ok"] else "no",
                               f(e["residual"], 2), f(e["dA_rel"], 2), f(e["dB_rel"], 2), f(e["d_AoB"], 2), f(x["A_over_B_minus_1"], 4), f(e["A_vol_minus_A_rel"], 2),
                               f(e["analysis"]["A"]["exterior_rows_max_abs"], 2)])
                key = lab
                worst[key] = max(worst.get(key, 0.0), abs(e["dA_rel"]), abs(e["dB_rel"]))
    out += ["## X2 The Gauss decomposition at the three most compact members: (A_vol - A)/A and (B_vol - B)/B against the sum of the residual, "
            "exterior-row, zero-sum/symmetry and moment terms (each divided by k_op A or k_op B), the closure (sum minus value), the buffer "
            "J - r_s against R + 20, and the exterior rows on J < j <= J + R (largest absolute value, and relative to the largest interior source)", "",
            table(["family", "z_c", "side", "J - r_s", "R + 20", "vol/amplitude - 1", "residual", "exterior", "zero-sum/symmetry", "moment", "closure",
                   "exterior rows max", "relative to source"], rows), "",
            "## X3 The members whose buffer was shorter than R + 20, re-solved at the same z_c on J_new = ceil(r_s) + R + 20: Newton, residual, the "
            "relative changes of A and B, the change of A/B - 1 (beside its value), the new (A_vol - A)/A and the new exterior rows' largest value", "",
            table(["family", "z_c", "J", "J_new", "Newton ok", "residual", "dA/A", "dB/B", "d(A/B - 1)", "A/B - 1", "(A_vol - A)/A new", "exterior rows new"], rows_b), ""]
    for d in E:
        m = d["meta"]
        if m["mlight"] == 0.01 and m["operator"] == "kernel":
            lab = "%s (%g, %g) %s (%g, %g)" % (os.path.dirname(m["family"]), m["mlight"], m["aH"], m["operator"], m["couplings"][0], m["couplings"][1])
            x = d["members"][-1]
            t = x["at_J"]["A"]["terms_rel"]
            summ.append("X2 (%s, z_c %s): (A_vol - A)/A = %s = residual %s + exterior %s + zero-sum/symmetry %s + moment %s (closure %s)." % (
                lab, f(x["z_c"], 4), f(x["at_J"]["A"]["vol_minus_rel"]), f(t["residual"]), f(t["exterior"]), f(t["zero_sum_symmetry"]), f(t["moment"]),
                f(x["at_J"]["A"]["sum_minus_record"], 2)))
    if worst:
        k = max(worst, key=worst.get)
        summ.append("X3: %d members re-solved on a longer buffer; the largest relative change of A or B is %s (%s)." % (len(rows_b), f(worst[k], 2), k))
    cl = max((abs(x["at_J"][s]["sum_minus_record"]) for d in E for x in d["members"] for s in ("A", "B")), default=None)
    summ.append("X2: the decomposition closes to %s at worst over all members and both sides." % f(cl, 2))
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + s for s in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + s for s in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
