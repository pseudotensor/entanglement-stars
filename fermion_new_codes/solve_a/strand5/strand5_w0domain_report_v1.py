#!/usr/bin/env python
"""Strand 5 J5 domain control report (builder's addition, revision 3; builder analyst): the flat-ruler Gaussians psi = 1 + e f_w (N = 1) at
h = 1 from every record given (the dense pilot's J5pilot2 at R_max = 322 and 480, J5decomp2 at R_max = 4.5 w, J5domain1 at R_max/w = 4.5, 8, 16):
per width w and grid R_max = n h, W_0^(2) = (W(e) + W(-e))/(2 e^2) and c_3 = (W(e) - W(-e))/(2 e^3) at e = 1e-2, and the two-width solve
-k a(w) - g_4 b(w) = W_0^(2) (a(w) = (3/2) pi^(3/2) w, b(w) = (15/4) pi^(3/2)/w) for the width pairs (20, 60) and (30, 100) at each R_max/w
present for both widths (matched within 5 percent), with the route of each record.  Numbers emitted, not retyped."""
import argparse
import json
import math

A_ = lambda w: 1.5 * math.pi ** 1.5 * w
B_ = lambda w: 3.75 * math.pi ** 1.5 / w
E0 = 1e-2


def table(head, rows):
    return "\n".join(["| " + " | ".join(str(c) for c in head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True, help="comma-separated Gaussian records (h = 1)")
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    G = {}  # (w, n) -> {e: W}, route
    for p in a.records.split(","):
        R = json.load(open(p))
        h = float(R["meta"]["h"])
        route = R["meta"].get("route", "dense")
        for key, c in R["configs"].items():
            if not key.startswith("gauss") or float(c.get("ruler", 1.0)) != 1.0 or h != 1.0:
                continue
            w, n = float(c["width"]), int(c["n"])
            G.setdefault((w, n), {"route": route, "src": p.split("/")[0], "W": {}})["W"][round(float(c["eps"]), 12)] = c["L_variants"]["psi_only"]["W_c"]
    rows, D = [], {}
    for (w, n), g in sorted(G.items()):
        Wp, Wm = g["W"].get(round(E0, 12)), g["W"].get(round(-E0, 12))
        if Wp is None or Wm is None:
            continue
        w2, c3 = (Wp + Wm) / (2 * E0 * E0), (Wp - Wm) / (2 * E0 ** 3)
        D[(w, n)] = (w2, c3)
        rows.append(["%g" % w, n, "%.3g" % (n / w), g["src"], g["route"], "%.12e" % w2, "%.6e" % c3])
    out = ["# Strand 5 J5 domain control (generated by solve/code/strand5/strand5_w0domain_report_v1.py)", "",
           "## G Per width and grid (h = 1, P = 1, e = 1e-2): R_max/w, the record, W_0^(2) and c_3", "",
           table(["w", "n = R_max", "R_max/w", "record", "route", "W_0^(2)", "c_3"], rows), ""]
    krow, summ = [], []
    for w1, w2_ in ((20.0, 60.0), (30.0, 100.0)):
        for (wa, na) in sorted(k for k in D if k[0] == w1):
            for (wb, nb) in sorted(k for k in D if k[0] == w2_):
                ra, rb = na / wa, nb / wb
                if abs(ra / rb - 1) > 0.05:
                    continue
                det = A_(wa) * B_(wb) - A_(wb) * B_(wa)
                ya, yb = -D[(wa, na)][0], -D[(wb, nb)][0]
                k = (ya * B_(wb) - yb * B_(wa)) / det
                g4 = (A_(wa) * yb - A_(wb) * ya) / det
                krow.append(["(%g, %g)" % (w1, w2_), "%.3g, %.3g" % (ra, rb), "%.12e" % k, "%.8e" % g4])
    out += ["## K The two-width solve per width pair at matched R_max/w", "", table(["widths", "R_max/w", "k", "g_4"], krow), ""]
    for w in sorted({k[0] for k in D}):
        ser = sorted((n / w, D[(w, n)]) for (ww, n) in D if ww == w)
        summ.append("w = %g: c_3 = %s and W_0^(2) = %s at R_max/w = %s." % (w, ", ".join("%.4e" % s[1][1] for s in ser), ", ".join("%.10e" % s[1][0] for s in ser),
                                                                        ", ".join("%.3g" % s[0] for s in ser)))
    if krow:
        summ.append("k per width pair and R_max/w: " + "; ".join("%s at %s: %s" % (r[0], r[1], r[2]) for r in krow) + ".")
    out = out[:2] + ["## S Summary (emitted)", ""] + ["- " + x for x in summ] + [""] + out[2:]
    open(a.md, "w").write("\n".join(out) + "\n")
    print("\n".join("- " + x for x in summ))
    print("wrote", a.md)


if __name__ == "__main__":
    main()
