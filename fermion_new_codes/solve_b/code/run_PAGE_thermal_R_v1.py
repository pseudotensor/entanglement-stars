"""Independent Schwarzschild radial Dirac comparator, PAGE spec section 8."""

import argparse
from concurrent.futures import ProcessPoolExecutor
import json
import math
from pathlib import Path
from cpu_runtime import require_remote_cpu


def channel_job(job):
    kappa,setting,output,previous = job
    import numpy as np
    from scipy.integrate import quad,solve_ivp
    refined = setting == "refined"
    order = 12 if refined else 8
    left = -70 if refined else -60
    far_factor = 80 if refined else 40
    rtol,atol = (3e-12,3e-14) if refined else (1e-10,1e-12)
    absolute,relative = (1e-11,1e-7) if refined else (1e-10,1e-6)
    path = Path(output)/f"scattering_k{kappa}_{setting}.jsonl"
    stream = path.open("w")
    cache = {}
    if previous:
        prior = Path(previous)/f"scattering_k{kappa}_{setting}.jsonl"
        if prior.exists():
            for line in prior.read_text().splitlines():
                row = json.loads(line)
                desired_far = max(400.0,80*max(kappa,1)/row["q"]) if refined else max(200.0,40*max(kappa,1)/row["q"])
                if row["outer_x"] == desired_far and row["inner_y"] == left and row["Jost_order"] == order:
                    row["reused_from"] = str(prior)
                    cache[row["q"],row["potential_sign"]] = row
                    stream.write(json.dumps(row)+"\n")
            stream.flush()

    def scatter(q,potential_sign=1):
        key = (q,potential_sign)
        if key in cache: return cache[key]
        def potential(x,f):
            return kappa*kappa*f/(x*x)+potential_sign*kappa*math.sqrt(f)*(3-2*x)/(2*x**3)
        def rhs(y,state):
            ey = math.exp(y)
            x,f = 1+ey,ey/(1+ey)
            return [state[1], f*state[1]-x*x*(q*q-potential(x,f))*state[0]]
        x0 = 1+math.exp(left)
        z0 = x0+left
        phase = np.exp(-1j*q*z0)
        far = max(400.0 if refined else 200.0,far_factor*max(kappa,1)/q)
        solution = solve_ivp(rhs,(left,math.log(far-1)),[phase,-1j*q*x0*phase],
                             method="DOP853",rtol=rtol,atol=atol)
        if not solution.success: raise RuntimeError(solution.message)
        z,dzdy = solution.y[:,-1]
        derivative = dzdy/far
        # sqrt(1-t) coefficients generated by its binomial recurrence.
        root = np.zeros(order+3)
        root[0] = 1
        for j in range(1,len(root)):
            root[j] = -root[j-1]*(1.5-j)/j
        v = np.zeros(order+3)
        for n in range(2,len(v)):
            v[n] = ((kappa*kappa if n == 2 else 0)
                    -(kappa*kappa if n == 3 else 0)
                    +potential_sign*kappa*(-root[n-2]+(1.5*root[n-3] if n>=3 else 0)))
        coefficients = np.zeros(order+1,dtype=complex)
        coefficients[0] = 1
        for j in range(1,order+1):
            n = j+1
            residual = 0j
            for l in range(j):
                c = coefficients[l]
                if n == l+2: residual += (l*(l+1)+2j*q*l)*c
                if n == l+3: residual += (-2*l*(l+1)-l)*c
                if n == l+4: residual += (l*(l+1)+l)*c
                residual -= v[n-l]*c
            coefficients[j] = residual/(2j*q*j)
        powers = far**(-np.arange(order+1,dtype=float))
        indices = np.arange(order+1)
        f = 1-1/far
        polynomial = np.sum(coefficients*powers)
        first = np.sum(-indices*coefficients*powers/far)
        second = np.sum(indices*(indices+1)*coefficients*powers/far**2)
        tortoise = far+math.log(far-1)
        outgoing = np.exp(1j*q*tortoise)*polynomial
        outgoing_derivative = np.exp(1j*q*tortoise)*(1j*q*polynomial+f*first)
        matching = np.array([[outgoing.conjugate(),outgoing],
                             [outgoing_derivative.conjugate(),outgoing_derivative]])
        incoming_amplitude,outgoing_amplitude = np.linalg.solve(matching,[z,derivative])
        gamma = float(1/abs(incoming_amplitude)**2)
        reflection = float(abs(outgoing_amplitude/incoming_amplitude)**2)
        residual = f*f*second+f*first/far**2+2j*q*f*first-potential(far,f)*polynomial
        result = {"kappa":kappa,"q":q,"potential_sign":potential_sign,"setting":setting,
                  "Gamma":gamma,"reflection":reflection,"unitarity_residual":gamma+reflection-1,
                  "Jost_relative_residual":float(abs(residual)/max(q*q*abs(polynomial),1e-300)),
                  "inner_y":left,"outer_x":far,"Jost_order":order,"rtol":rtol,"atol":atol,
                  "small_transmission_conditioning":gamma<1e-12,
                  "solver_evaluations":solution.nfev}
        if not math.isfinite(gamma) or gamma<0 or gamma>1+1e-7:
            raise ValueError("Transmission outside the unitarity interval")
        stream.write(json.dumps(result,allow_nan=False)+"\n")
        stream.flush()
        cache[key] = result
        return result

    if kappa == 0:
        controls = [scatter(q) for q in (0.001,0.1,1.0)]
        stream.close()
        return {"setting":setting,"kappa":0,"free_scattering":controls}

    def integrand(q,kind):
        occupation = scatter(float(q))["Gamma"]/(1+math.exp(4*math.pi*q))
        if kind == "energy": return q*occupation
        if kind == "number": return occupation
        if occupation <= 0: return 0.0
        if occupation >= 1: raise ValueError("Invalid thermal output occupation")
        return -occupation*math.log(occupation)-(1-occupation)*math.log1p(-occupation)
    panels = (0.001,0.003,0.01,0.03,0.1,0.2,0.4,0.8,1.5,3.0)
    integrals,errors = {},{}
    weight = 64*kappa/(2*math.pi)
    for kind in ("energy","number","entropy"):
        terms,allowances = [],[]
        for a,b in zip(panels[:-1],panels[1:]):
            value,error = quad(lambda q:integrand(q,kind),a,b,
                               epsabs=absolute/(8*len(panels)*weight),epsrel=relative,limit=100)
            terms.append(value)
            allowances.append(error)
        integrals[kind] = weight*math.fsum(terms)
        errors[kind] = weight*math.fsum(allowances)
    checks = []
    if refined and kappa in (1,2,8):
        for q in (0.001,0.03,0.1,0.3,1.0):
            plus,minus = scatter(q),scatter(q,-1)
            checks.append({"q":q,"Gamma_plus":plus["Gamma"],"Gamma_minus":minus["Gamma"],
                           "relative_difference":minus["Gamma"]/plus["Gamma"]-1})
    low = [scatter(q) for q in (0.001,0.0005,0.00025)] if refined and kappa==1 else []
    stream.close()
    result = {"kappa":kappa,"weight":64*kappa,"setting":setting,
              "integrals":integrals,"quadrature_errors":errors,"potential_pair_checks":checks,
              "low_frequency_controls":low,"R":integrals["entropy"]/(4*math.pi*integrals["energy"])}
    (Path(output)/f"rates_k{kappa}_{setting}.json").write_text(json.dumps(result,indent=2)+"\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path,required=True)
    parser.add_argument("--workers",type=int,default=8)
    parser.add_argument("--reuse-directory",type=Path)
    args = parser.parse_args()
    runtime = require_remote_cpu(args.output)
    if not 1<=args.workers<=8: raise ValueError("At most eight single-thread workers")
    for name in ("OMP_NUM_THREADS","MKL_NUM_THREADS","OPENBLAS_NUM_THREADS"):
        import os
        if os.environ[name] != "1": raise ValueError("Each scattering worker must have one BLAS thread")
    from scipy.integrate import quad
    def thermal_integrand(x,kind):
        decay = math.exp(-x)
        occupation = decay/(1+decay)
        if kind == "energy": return x*occupation
        if kind == "number": return occupation
        return 0.0 if occupation == 0 else (-occupation*math.log(occupation)
                    -(1-occupation)*math.log1p(-occupation))
    known = {}
    for kind,expected in (("energy",math.pi**2/12),("number",math.log(2)),("entropy",math.pi**2/6)):
        value,error = quad(lambda x:thermal_integrand(x,kind),0,math.inf,epsabs=1e-12,epsrel=1e-12)
        known[kind] = {"value":value,"error_estimate":error,"known_answer_residual":value-expected}
    known["R"] = known["entropy"]["value"]/known["energy"]["value"]
    (args.output/"thermal_known_answers.json").write_text(json.dumps(known,indent=2)+"\n")
    if abs(known["R"]-2)>1e-10 or any(abs(known[k]["known_answer_residual"])>1e-10 for k in ("energy","number","entropy")):
        raise RuntimeError("Fully transmitted thermal-port quadrature failed")
    previous = str(args.reuse_directory) if args.reuse_directory else None
    free = channel_job((0,"refined",str(args.output),previous))
    if any(abs(r["Gamma"]-1)>1e-7 or r["reflection"]>1e-10 for r in free["free_scattering"]):
        raise RuntimeError("Free scattering known answer failed")
    jobs = [(k,setting,str(args.output),previous) for setting in ("base","refined") for k in range(1,9)
            if not (previous and setting=="base")]
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        results = list(pool.map(channel_job,jobs))
    if previous:
        results.extend(json.loads((args.reuse_directory/f"rates_k{k}_base.json").read_text())
                       for k in range(1,9))
    rates = {}
    for setting in ("base","refined"):
        subset = [r for r in results if r["setting"]==setting]
        rate = {kind:math.fsum(r["integrals"][kind] for r in subset)
                for kind in ("energy","number","entropy")}
        rate["R"] = rate["entropy"]/(4*math.pi*rate["energy"])
        rates[setting] = rate
    b,Q,weight = 4*math.pi,3.0,math.fsum(64*k for k in range(1,9))/(2*math.pi)
    high = {"number":weight*math.exp(-b*Q)/b,
            "energy":weight*math.exp(-b*Q)*(Q/b+1/b**2),
            "entropy":weight*math.exp(-b*Q)*(Q+2/b)}
    result = {"scope":"Independent stationary continuum comparator on |k|<=8 and 0.001<=q<=3; "
                       "low-frequency and infinite angular remainders are not certified.",
              "runtime":runtime,"thermal_known_answers":known,"free_control":free,
              "channels":results,"rates":rates,
              "high_frequency_tail_bounds":high,
              "high_frequency_relative_bounds":{k:v/rates["refined"][k] for k,v in high.items()}}
    (args.output/"thermal_R.json").write_text(json.dumps(result,indent=2,allow_nan=False)+"\n")
    print(json.dumps({"status":"saved","output":str(args.output/"thermal_R.json")}))


if __name__ == "__main__":
    main()
