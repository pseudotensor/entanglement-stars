def herm(X):
    return 0.5 * (X + X.conj().T)


def tr(X):
    return complex(np.trace(X))


# ============================================================================ the cluster
def cluster(kind, m):
    kmax = {'star13': 2, 'cross7': 1}[kind]
    sites = [(0, 0, 0)] + [tuple(s * k if j == i else 0 for j in range(3)) for i in range(3) for k in range(1, kmax + 1) for s in (1, -1)]
    ns = len(sites)
    idx = {s: n for n, s in enumerate(sites)}
    h0 = np.kron(np.eye(ns), m * BETA).astype(complex)
    for i in range(3):
        T = np.zeros((ns, ns))
        for s in sites:
            t = list(s)
            t[i] += 1
            if tuple(t) in idx:
                T[idx[s], idx[tuple(t)]] = 1.0
        p = (T - T.T) / 2j
        h0 = h0 + np.kron(p, ALPHA[i])
    rad = np.array([int(round(math.sqrt(sum(c * c for c in s)))) for s in sites])
    shells = sorted(set(rad.tolist()))
    e = []
    for r in shells:
        Pi = np.kron(np.diag((rad == r).astype(float)), np.eye(4))
        e.append(herm(Pi @ h0))
    eps, U = np.linalg.eigh(h0)
    N0 = int(np.sum(eps < 0))
    P0 = U[:, :N0] @ U[:, :N0].conj().T
    return dict(kind=kind, m=m, sites=sites, ns=ns, d=4 * ns, h0=h0, e=e, eps=eps, U=U, N0=N0, P0=P0, rad=rad)


# ============================================================================ functionals (vertex form)
def E_pair(V, ev, X, direct_only=False):
    q = np.array([tr(A @ X).real for A in ev])
    val = 0.5 * float(q @ V @ q)
    if not direct_only:
        val -= 0.5 * sum(V[r, s] * tr(ev[r] @ X @ ev[s] @ X).real for r in range(len(ev)) for s in range(len(ev)))
    return val


def f_of(V, ev, X, direct_only=False):
    """dE_pair/dX as an operator (Tr(f dX) = dE_pair)."""
    q = np.array([tr(A @ X).real for A in ev])
    F = sum(V[r, s] * q[s] * ev[r] for r in range(len(ev)) for s in range(len(ev)))
    if not direct_only:
        F = F - sum(V[r, s] * (ev[s] @ X @ ev[r]) for r in range(len(ev)) for s in range(len(ev)))
    return herm(F)


def kinetic_excess(h0, eps0, U0, C, m, Nf):
    """Tr(h0 (C - P0)) - Nf m without the sea's cancellation, in the h0 eigenbasis: sum_{a>0} (eps_a - m) C_aa +
    sum_{i<0} (m - eps_i) (1 - C_ii); valid when Tr C = N0 + Nf."""
    Ct = U0.conj().T @ C @ U0
    d = np.real(np.diag(Ct))
    pos = eps0 > 0
    return float(np.sum((eps0[pos] - m) * d[pos]) + np.sum((m - eps0[~pos]) * (1.0 - d[~pos])))


def kinetic_excess_orbitals(eps0, U0, Phi, m):
    """the same from occupied orbitals Phi (idempotent C): the sea's holes 1 - C_ii as squares of the unoccupied
    complement's overlaps (no cancellation)."""
    A = U0.conj().T @ Phi
    occ = np.sum(np.abs(A) ** 2, axis=1)
    Q, _ = np.linalg.qr(np.concatenate([Phi, np.eye(Phi.shape[0])], axis=1))
    Comp = Q[:, Phi.shape[1]:Phi.shape[0]]
    Bc = U0.conj().T @ Comp
    hole = np.sum(np.abs(Bc) ** 2, axis=1)
    pos = eps0 > 0
    return float(np.sum((eps0[pos] - m) * occ[pos]) + np.sum((m - eps0[~pos]) * hole[~pos]))


# ============================================================================ the Grassmannian minimizer
def minimize_det(energy, fock, Phi0, tol=1e-14, maxit=500, shift=0.05, logf=None):
    """minimize energy(C) over rank-N projectors C = Phi Phi^+ by preconditioned gradient steps: in the
    semicanonical basis of the generator F = fock(C) (occupied and virtual blocks diagonalized), the rotation
    kappa_ai = -F_ai/(e_a - e_i + shift), applied as the unitary exp([[0, -k^+], [k, 0]]); backtracking on the energy.
    Returns Phi, the energy, the gradient norm ||(1 - C) F C||, iterations."""
    d, N = Phi0.shape
    Q, _ = np.linalg.qr(np.concatenate([Phi0, np.eye(d)], axis=1))
    Phi = Q[:, :N]
    Psi = Q[:, N:d]
    C = Phi @ Phi.conj().T
    E = energy(C)
    it = 0
    g = np.inf
    for it in range(1, maxit + 1):
        F = fock(C)
        eo, Ro = np.linalg.eigh(herm(Phi.conj().T @ F @ Phi))
        ev, Rv = np.linalg.eigh(herm(Psi.conj().T @ F @ Psi))
        Phi, Psi = Phi @ Ro, Psi @ Rv
        Fvo = Psi.conj().T @ F @ Phi
        g = float(np.linalg.norm(Fvo))
        if g < tol:
            break
        kap = -Fvo / (ev[:, None] - eo[None, :] + shift)
        step = 1.0
        while True:
            K = np.zeros((d, d), complex)
            K[N:, :N] = step * kap
            K[:N, N:] = -step * kap.conj().T
            Uk = sla.expm(K)
            B = np.concatenate([Phi, Psi], axis=1) @ Uk
            Pn, Sn = B[:, :N], B[:, N:]
            Cn = Pn @ Pn.conj().T
            En = energy(Cn)
            if En <= E + 1e-18 or step < 1e-6:
                break
            step *= 0.5
        dE = E - En
        Phi, Psi, C, E = Pn, Sn, Cn, En
        if logf and (it % 50 == 0):
            logf('    it %d E %.17g grad %.2e step %.2g' % (it, E, g, step))
        if abs(dE) < 1e-19 and g < 1e-11:
            break
    F = fock(C)
    g = float(np.linalg.norm((np.eye(d) - C) @ F @ C))
    return Phi, E, g, it


def orbital_hessian_min(energy, Phi, nfd=6, eps_fd=1e-4, seed=11):
    """the lowest curvature of the energy along random orbital rotations (central second differences; a local
    certificate, information)."""
    d, N = Phi.shape
    Q, _ = np.linalg.qr(np.concatenate([Phi, np.eye(d)], axis=1))
    Phi, Psi = Q[:, :N], Q[:, N:d]
    rng = np.random.default_rng(seed)
    E0 = energy(Phi @ Phi.conj().T)
    curv = []
    for _ in range(nfd):
        k = rng.standard_normal((d - N, N)) + 1j * rng.standard_normal((d - N, N))
        k /= np.linalg.norm(k)
        vals = []
        for s in (eps_fd, -eps_fd):
            K = np.zeros((d, d), complex)
            K[N:, :N] = s * k
            K[:N, N:] = -s * k.conj().T
            B = np.concatenate([Phi, Psi], axis=1) @ sla.expm(K)
            vals.append(energy(B[:, :N] @ B[:, :N].conj().T))
        curv.append((vals[0] + vals[1] - 2 * E0) / eps_fd ** 2)
    return float(min(curv)), curv


# ============================================================================ Fock tools (small spaces)
_POP = np.array([bin(x).count('1') & 1 for x in range(1 << 11)], dtype=np.int64)


def parity_below(s, j):
    """parity of the occupied modes below j for the integer array s."""
    x = s & ((1 << j) - 1)
    p = np.zeros_like(x)
    while np.any(x):
        p ^= _POP[x & ((1 << 11) - 1)]
        x >>= 11
    return p


def annihilators(d):
    dim = 1 << d
    s = np.arange(dim, dtype=np.int64)
    out = []
    for j in range(d):
        occ = ((s >> j) & 1) == 1
        sign = np.where(parity_below(s, j) == 1, -1.0, 1.0)
        out.append(sp.csr_matrix((sign[occ], ((s ^ (1 << j))[occ], s[occ])), shape=(dim, dim)))
    return out


def gamma(cs, A):
    d = len(cs)
    out = sp.csr_matrix(cs[0].shape, dtype=complex)
    for i in range(d):
        for j in range(d):
            if A[i, j] != 0:
                out = out + A[i, j] * (cs[i].T @ cs[j])
    return out


def slater_vector(cs, Phi):
    dim = cs[0].shape[0]
    psi = np.zeros(dim, complex)
    psi[0] = 1.0
    for k in range(Phi.shape[1]):
        cd = sum(Phi[i, k] * cs[i].T for i in range(len(cs)))
        psi = cd @ psi
    return psi / np.linalg.norm(psi)


def covariance(cs, psi):
    d = len(cs)
    return np.array([[np.vdot(psi, cs[b].T @ (cs[a] @ psi)) for b in range(d)] for a in range(d)])


def pair_tensor(V, ev):
    U = sum(V[r, s] * np.einsum('ac,bd->abcd', ev[r], ev[s]) for r in range(len(ev)) for s in range(len(ev)))
    return U, U - np.transpose(U, (0, 1, 3, 2))


def W_operator(cs, T):
    d = len(cs)
    out = sp.csr_matrix(cs[0].shape, dtype=complex)
    for a in range(d):
        for b in range(d):
            for c in range(d):
                for dd in range(d):
                    if abs(T[a, b, c, dd]) > 0:
                        out = out + T[a, b, c, dd] * (cs[a].T @ cs[b].T @ cs[dd] @ cs[c])
    return 0.25 * out


def sector_indices(d, N):
    return np.array([sum(1 << i for i in c) for c in combinations(range(d), N)])


# ============================================================================ second order and Temple
def mp2_vertex(V, ev, Phi, Psi, eo, ev_):
    """E2 = -sum_{i<j, a<b} |T_ab;ij|^2/(e_a + e_b - e_i - e_j) and sum |T|^2 over the 2p2h amplitudes of the
    determinant Phi (canonical orbital energies eo, virtual Psi with ev_); U_abij = sum V_rs (e_r)_ai (e_s)_bj."""
    Evo = [Psi.conj().T @ A @ Phi for A in ev]
    U = sum(V[r, s] * np.einsum('ai,bj->abij', Evo[r], Evo[s]) for r in range(len(ev)) for s in range(len(ev)))
    T = U - np.transpose(U, (0, 1, 3, 2))
    den = ev_[:, None, None, None] + ev_[None, :, None, None] - eo[None, None, :, None] - eo[None, None, None, :]
    nv, no = len(ev_), len(eo)
    T2 = np.abs(T) ** 2
    av = np.arange(nv)
    ov = np.arange(no)
    mask = (av[:, None, None, None] < av[None, :, None, None]) & (ov[None, None, :, None] < ov[None, None, None, :])
    E2 = -float(np.sum(T2[mask] / den[mask]))
    S = float(np.sum(T2[mask]))
    return E2, S, int(mask.sum())


# ============================================================================ the block (route 2's derivation)
def commutant_basis(gens, tol=1e-9):
    d = gens[0].shape[0]
    I = np.eye(d)
    M = np.concatenate([np.kron(I, g) - np.kron(g.T, I) for g in gens], axis=0)
    _, s, Vh = np.linalg.svd(M, full_matrices=True)
    null = Vh[np.sum(s > tol * s[0]):].conj()
    return [x.reshape(d, d, order='F') for x in null]


def derive_types(cl, gens, seed=5, logf=log):
    """types and copies from the commutant: a random Hermitian commutant element splits the modes into copies
    (eigenspaces), copies with equal spectra of a generic algebra element form a type; within a type every copy is
    given the h0 eigenbasis with phases matched to copy 1 through a generic algebra element."""
    d = cl['d']
    rng = np.random.default_rng(seed)
    basis = commutant_basis(gens)
    Y = sum((rng.standard_normal() + 1j * rng.standard_normal()) * B for B in basis)
    Y = herm(Y)
    y, Uy = np.linalg.eigh(Y)
    # group the eigenvalues into clusters (copies)
    groups = [[0]]
    for k in range(1, d):
        (groups[-1].append(k) if abs(y[k] - y[groups[-1][-1]]) < 1e-8 else groups.append([k]))
    h0, ev = cl['h0'], cl['e']
    X = h0 + 0.37 * ev[0] + 0.61 * ev[1] + 0.83 * (ev[2] if len(ev) > 2 else ev[1])
    X = X + 0.29 * herm(ev[1] @ h0 @ (ev[2] if len(ev) > 2 else ev[0])) + 0.17 * herm(ev[0] @ ev[1] @ h0)
    copies = []
    for g in groups:
        Vc = Uy[:, g]
        spec = np.linalg.eigvalsh(herm(Vc.conj().T @ X @ Vc))
        copies.append(dict(V=Vc, spec=spec))
    types = []
    for c in copies:
        for t in types:
            if len(t['spec']) == len(c['spec']) and np.max(np.abs(t['spec'] - c['spec'])) < 1e-8:
                t['copies'].append(c['V'])
                break
        else:
            types.append(dict(spec=c['spec'], copies=[c['V']]))
    for t in types:
        V1 = t['copies'][0]
        e1, R1 = np.linalg.eigh(herm(V1.conj().T @ h0 @ V1))
        W1 = V1 @ R1
        X1 = W1.conj().T @ X @ W1
        newc = [W1]
        for Vc in t['copies'][1:]:
            ec, Rc = np.linalg.eigh(herm(Vc.conj().T @ h0 @ Vc))
            Wc = Vc @ Rc
            Xc = Wc.conj().T @ X @ Wc
            # phases p_j with conj(p_i) p_j Xc[i, j] = X1[i, j], fixed level by level along the nonzero links of X1
            # (version 1 used row 0 only; X1[0, 2] = 0 in the b types made p_2 a 0/0, so the copies' matrices differed)
            p = np.ones(len(ec), complex)
            fixed = {0}
            while len(fixed) < len(ec):
                best = max(((abs(X1[i, j]), i, j) for i in fixed for j in range(len(ec)) if j not in fixed), default=(0, None, None))
                assert best[0] > 1e-8, 'no link to fix a phase'
                _, i, j = best
                p[j] = p[i] * X1[i, j] / Xc[i, j]
                p[j] /= abs(p[j])
                fixed.add(j)
            newc.append(Wc * p[None, :])
        t['copies'] = newc
        t['eps'] = e1
        t['n'] = len(e1)
        t['mult'] = len(newc)
    types.sort(key=lambda t: (t['n'], tuple(np.round(t['eps'], 9))))
    Wall = np.concatenate([V for t in types for V in t['copies']], axis=1)
    return types, dict(n_commutant=len(basis), ortho_err=float(np.linalg.norm(Wall.conj().T @ Wall - np.eye(d))),
                       complete=Wall.shape[1] == d, dims=[(t['n'], t['mult']) for t in types])


def reduce_op(types, X):
    mats, err = [], 0.0
    for t in types:
        X1 = t['copies'][0].conj().T @ X @ t['copies'][0]
        for Vc in t['copies'][1:]:
            err = max(err, float(np.linalg.norm(Vc.conj().T @ X @ Vc - X1)))
        mats.append(X1)
    rebuilt = sum(Vc @ X1 @ Vc.conj().T for t, X1 in zip(types, mats) for Vc in t['copies'])
    err = max(err, float(np.linalg.norm(rebuilt - X)))
    return mats, err


_MODCACHE = {}


def type_module(n, mult, occ_levels_full, extra_copy_levels=()):
    key = (n, mult, tuple(occ_levels_full), tuple(extra_copy_levels))
    if key not in _MODCACHE:
        _MODCACHE[key] = TypeModule(n, mult, occ_levels_full, extra_copy_levels)
    return _MODCACHE[key]


class TypeModule:
    """the gl(n) module generated from the type's free vector inside the type's own Fock space (modes i*mult + c;
    level i, copy c), by Krylov closure under E_ij = sum_c a^+_ic a_jc; the basis rotated to the weight basis
    (common eigenbasis of the E_ll)."""

    def __init__(self, n, mult, occ_levels_full, extra_copy_levels=()):
        d = n * mult
        cs = annihilators(d)
        mode = lambda i, c: i * mult + c
        E = [[sum((cs[mode(i, c)].T @ cs[mode(j, c)]) for c in range(mult)).tocsr() for j in range(n)] for i in range(n)]
        occ = [mode(i, c) for i in occ_levels_full for c in range(mult)] + [mode(i, c) for (i, c) in extra_copy_levels]
        v = np.zeros(1 << d, complex)
        v[sum(1 << k for k in occ)] = 1.0
        basis = [v]
        frontier = [v]
        while frontier:
            new = []
            for x in frontier:
                for i in range(n):
                    for j in range(n):
                        if i == j:
                            continue
                        y = E[i][j] @ x
                        B = np.array(basis).T
                        y = y - B @ (B.conj().T @ y)
                        y = y - B @ (B.conj().T @ y)
                        nr = np.linalg.norm(y)
                        if nr > 1e-10:
                            y /= nr
                            basis.append(y)
                            new.append(y)
            frontier = new
        B = np.array(basis).T
        Ered = [[B.conj().T @ (E[i][j] @ B) for j in range(n)] for i in range(n)]
        Z = sum((0.1 + 0.37 * l) * Ered[l][l] for l in range(n))
        wz, Rz = np.linalg.eigh(herm(Z))
        self.E = [[Rz.conj().T @ Ered[i][j] @ Rz for j in range(n)] for i in range(n)]
        self.weights = np.array([[self.E[l][l][a, a].real for l in range(n)] for a in range(len(wz))])
        self.free = Rz.conj().T @ (B.conj().T @ v)
        self.dim, self.n, self.mult, self.N = len(wz), n, mult, len(occ)
        self.offdiag_weight_err = max(float(np.max(np.abs(self.E[l][l] - np.diag(np.diag(self.E[l][l]))))) for l in range(n))


class Block:
    def __init__(self, types, mods):
        self.types, self.mods = types, mods
        self.dims = [md.dim for md in mods]
        self.dim = int(np.prod(self.dims))

    def embed(self, k, A):
        left = int(np.prod(self.dims[:k])) if k else 1
        right = int(np.prod(self.dims[k + 1:])) if k + 1 < len(self.dims) else 1
        return np.kron(np.kron(np.eye(left), A), np.eye(right))

    def dG(self, mats):
        out = np.zeros((self.dim, self.dim), complex)
        for k, (md, X) in enumerate(zip(self.mods, mats)):
            A = sum(X[i, j] * md.E[i][j] for i in range(md.n) for j in range(md.n) if X[i, j] != 0)
            out += self.embed(k, A)
        return out

    def kron_sum(self, vecs):
        out = np.zeros(1)
        for x in vecs:
            out = (out[:, None] + np.asarray(x)[None, :]).ravel()
        return out

    def free(self):
        v = self.mods[0].free
        for md in self.mods[1:]:
            v = np.kron(v, md.free)
        return v


def build_block(cl, types, Nf):
    """the modules: in each type the free vector fills the type's negative levels in every copy; Nf particles go to
    the lowest positive level (its type must hold it with copies enough), copy by copy."""
    pos = [(float(t['eps'][l]), ti, l) for ti, t in enumerate(types) for l in range(t['n']) if t['eps'][l] > 0]
    emin, ti_star, l_star = min(pos)
    mods = []
    for ti, t in enumerate(types):
        nsea = int(np.sum(t['eps'] < 0))
        extra = []
        if ti == ti_star and Nf > 0:
            assert l_star == nsea and Nf <= t['mult']
            extra = [(l_star, c) for c in range(Nf)]
        mods.append(type_module(t['n'], t['mult'], list(range(nsea)), extra))
    return Block(types, mods), emin


def exact_in_block(cl, types, V, Nf, logf=log, want_cov=True):
    """H = dGamma(h0) - Tr(P0 h0) + W_P0 on the block; ground vector by Lanczos (eigsh) checked by dense eigh; the
    conditioned energy shift s = E - E_free = sum |psi_k|^2 dE_k + <psi|W_P|psi>."""
    blk, emin = build_block(cl, types, Nf)
    h0, ev, P0 = cl['h0'], cl['e'], cl['P0']
    nsh = len(ev)
    e_m, err_e = zip(*[reduce_op(types, A) for A in ev])
    h_m, err_h = reduce_op(types, h0)
    fP = f_of(V, ev, P0)
    f_m, err_f = reduce_op(types, fP)
    ee_m = {}
    err_ee = 0.0
    for r in range(nsh):
        for s in range(nsh):
            mm, er = reduce_op(types, ev[r] @ ev[s])
            ee_m[(r, s)] = mm
            err_ee = max(err_ee, er)
    struct_err = max(max(err_e), err_h, err_f, err_ee)
    dGe = [blk.dG(e_m[r]) for r in range(nsh)]
    # W_P = (1/2) sum V_rs [Gamma(e_r) Gamma(e_s) - Gamma(e_r e_s)] - Gamma(f[P0]) + E_pair[P0]
    WP = np.zeros((blk.dim, blk.dim), complex)
    for r in range(nsh):
        WP += 0.5 * (dGe[r] @ sum(V[r, s] * dGe[s] for s in range(nsh)))
    ee_sum = [sum(V[r, s] * ee_m[(r, s)][k] for r in range(nsh) for s in range(nsh)) for k in range(len(types))]
    WP -= 0.5 * blk.dG(ee_sum)
    WP += -blk.dG(f_m) + E_pair(V, ev, P0) * np.eye(blk.dim)
    WP = herm(WP)
    # free excitation energies in the weight basis (exact integer differences times the levels)
    dE = blk.kron_sum([md.weights @ t['eps'] - md.weights[int(np.argmax(np.abs(md.free)))] @ t['eps'] for md, t in zip(blk.mods, types)])
    H0diag = blk.dG(h_m)
    H0_offdiag = float(np.max(np.abs(H0diag - np.diag(np.diag(H0diag)))))
    Hs = np.diag(dE).astype(complex) + WP
    Hs = herm(Hs)
    w_l, v_l = spla.eigsh(Hs, k=2, which='SA', tol=1e-14, ncv=40)
    o = np.argsort(w_l)
    w_l, v_l = w_l[o], v_l[:, o]
    w_d = np.linalg.eigvalsh(Hs)
    psi = v_l[:, 0]
    s_cond = float(np.sum(np.abs(psi) ** 2 * dE) + np.vdot(psi, WP @ psi).real)
    res = float(np.linalg.norm(Hs @ psi - w_l[0] * psi))
    i_free = int(np.argmax(np.abs(blk.free())))
    out = dict(Nf=Nf, dim=blk.dim, dims=blk.dims, struct_err=struct_err, H0_offdiag=H0_offdiag, shift_lanczos=float(w_l[0]),
               shift_eigh=float(w_d[0]), shift_conditioned=s_cond, first_excited=float(w_l[1]), residual=res,
               free_weight=float(abs(psi[i_free]) ** 2), lowest_positive=emin, free_gap_block=float(np.sort(np.unique(np.round(dE, 12)))[1]))
    if want_cov:
        out['C'] = block_covariance(blk, types, psi)
    out['psi'] = psi
    out['block'] = blk
    out['dE'] = dE
    out['WP'] = WP
    return out


def block_covariance(blk, types, psi):
    """C_qp = <c^+_p c_q> of a block vector whose types are copy-symmetric: per type rho_ij = <E_ji>/mult."""
    d = sum(t['n'] * t['mult'] for t in types)
    Tn = psi.reshape(blk.dims)
    C = np.zeros((d, d), complex)
    for k, (md, t) in enumerate(zip(blk.mods, types)):
        pk = np.moveaxis(Tn, k, 0).reshape(blk.dims[k], -1)
        Mr = pk @ pk.conj().T
        rho = np.array([[np.sum(md.E[i][j] * Mr.conj()) for j in range(md.n)] for i in range(md.n)]) / md.mult
        # rho[i, j] = <E_ij> / mult = <c^+_i c_j>/mult ; C_qp = <c^+_p c_q>  ->  C = sum_c V (rho^T) V^+
        for Vc in t['copies']:
            C += Vc @ rho.T @ Vc.conj().T
    return herm(C)


def onebody_sector_range(X, N):
    w = np.linalg.eigvalsh(herm(X))
    return float(np.sum(w[:N])), float(np.sum(w[-N:]))


def gap_certificate(cl, V, N):
    """a bound on the spread of W_P0 in the N-particle sector: W_P(A,B) = Gt(A) Gt(B) - dG(A(1-P)B) + dG(BPA) -
    Tr(PBPA), Gt(A) = dG(A) - Tr(PA); ||(1/2) sum V W_P|| <= (1/2) sum |V_rs| ||Gt_r|| ||Gt_s|| + the one-body part's
    half spread + 0 (constants do not move gaps)."""
    ev, P = cl['e'], cl['P0']
    nrm = []
    for A in ev:
        lo, hi = onebody_sector_range(A, N)
        c = tr(P @ A).real
        nrm.append(max(abs(hi - c), abs(lo - c)))
    quart = 0.5 * sum(abs(V[r, s]) * nrm[r] * nrm[s] for r in range(len(ev)) for s in range(len(ev)))
    Y = sum(0.5 * V[r, s] * (-(ev[r] @ (np.eye(cl['d']) - P) @ ev[s]) + ev[s] @ P @ ev[r]) for r in range(len(ev)) for s in range(len(ev)))
    lo, hi = onebody_sector_range(Y, N)
    return quart + 0.5 * (hi - lo)


