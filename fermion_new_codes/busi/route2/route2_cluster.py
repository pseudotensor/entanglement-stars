def hartree_fock(cl, V, Nf, mode, nrand=5, seed=1, logf=log):
    h0, ev, P0 = cl['h0'], cl['e'], cl['P0']
    N = cl['N0'] + Nf
    direct = (mode == 'H')
    m = cl['m']

    def energy(C):
        D = C - P0
        return tr(h0 @ D).real + E_pair(V, ev, D, direct_only=direct)

    def fock(C):
        return h0 + f_of(V, ev, C - P0, direct_only=direct)

    U0 = cl['U']
    starts = [U0[:, :N]]
    rng = np.random.default_rng(seed)
    for k in range(nrand):
        Xr = rng.standard_normal((cl['d'], cl['d'])) + 1j * rng.standard_normal((cl['d'], cl['d']))
        Ur = sla.expm(0.05 * (Xr - Xr.conj().T))
        starts.append(Ur @ U0[:, :N])
    best = None
    runs = []
    for k, Phi0 in enumerate(starts):
        Phi, E, g, it = minimize_det(energy, fock, Phi0, logf=None)
        C = Phi @ Phi.conj().T
        D = C - P0
        Econd = kinetic_excess_orbitals(cl['eps'], U0, Phi, m) + Nf * m + E_pair(V, ev, D, direct_only=direct)
        runs.append(dict(start=k, E_direct=E, E_conditioned=Econd, grad=g, iterations=it))
        if best is None or Econd < best['E_conditioned']:
            best = dict(Phi=Phi, E_direct=E, E_conditioned=Econd, grad=g, iterations=it, start=k)
    hmin, curv = orbital_hessian_min(energy, best['Phi'])
    best['hessian_min_curvature'] = hmin
    best['runs'] = runs
    best['spread_over_starts'] = float(max(r['E_conditioned'] for r in runs) - min(r['E_conditioned'] for r in runs))
    return best


def run_cluster(args):
    G = 2.0 ** -12
    m = 0.2
    cl = cluster('star13', m)
    V = -G * K13
    out = dict(script='route2_cluster.py', G=G, m=m, N0=cl['N0'], d=cl['d'])
    log('13-site cluster: d=%d N0=%d, levels %s' % (cl['d'], cl['N0'], np.round(np.unique(np.round(cl['eps'], 10)), 6)))
    # Hartree and HF at Nf = 2
    H = hartree_fock(cl, V, 2, 'H')
    HF = hartree_fock(cl, V, 2, 'HF')
    E_H, E_HF = H['E_conditioned'], HF['E_conditioned']
    B_H = 2 * m - E_H
    B_HF = 2 * m - E_HF
    log('Hartree: E_H - 2m = %.15e (direct %.15e), grad %.1e, it %d, min curvature %.3e, spread over starts %.1e'
        % (E_H - 2 * m, H['E_direct'] - 2 * m, H['grad'], H['iterations'], H['hessian_min_curvature'], H['spread_over_starts']))
    log('HF: E_HF - 2m = %.15e (direct %.15e), grad %.1e, it %d, min curvature %.3e, spread over starts %.1e'
        % (E_HF - 2 * m, HF['E_direct'] - 2 * m, HF['grad'], HF['iterations'], HF['hessian_min_curvature'], HF['spread_over_starts']))
    # the block
    gens = [cl['h0']] + cl['e']
    types, tinfo = derive_types(cl, gens)
    log('types (n, mult): %s; commutant dimension %d; orthonormality %.1e' % (tinfo['dims'], tinfo['n_commutant'], tinfo['ortho_err']))
    ex = {}
    for Nf in (0, 1, 2):
        r = exact_in_block(cl, types, V, Nf, want_cov=(Nf != 1))
        cert = gap_certificate(cl, V, cl['N0'] + Nf)
        r['gap_bound_2W'] = 2 * cert
        ex[Nf] = r
        log('exact Nf=%d: block dim %d %s, structure err %.1e, shift (conditioned) %.15e, Lanczos %.15e, eigh %.15e, residual %.1e, '
            'first excited %.6e, free weight %.12f, 2||W_P|| bound %.4f vs block free gap %.4f'
            % (Nf, r['dim'], r['dims'], r['struct_err'], r['shift_conditioned'], r['shift_lanczos'], r['shift_eigh'], r['residual'],
               r['first_excited'], r['free_weight'], 2 * cert, r['free_gap_block']))
    s0, s1, s2 = ex[0]['shift_conditioned'], ex[1]['shift_conditioned'], ex[2]['shift_conditioned']
    E_exact_sub2 = 2 * m + s2 - s0
    E_exact_sub1 = m + s1 - s0
    B_ex = 2 * m - E_exact_sub2
    targets = dict(B_HF_over_B_H=B_HF / B_H, B_exact_sub_over_B_H=B_ex / B_H, E_exact_sub_1=E_exact_sub1)
    ref = dict(B_HF_over_B_H=0.5000102341, B_exact_sub_over_B_H=0.5000377989, E_exact_sub_1=0.19999999982818614)
    # (the spec's targets: conditioned route of HF_cluster_v1 section 1)
    ref_full = dict(B_HF_over_B_H=0.5000102340807, B_exact_sub_over_B_H=0.5000377989206, E_exact_sub_1=0.19999999982818614)
    acc = {}
    for k in targets:
        if k == 'E_exact_sub_1':
            acc[k] = dict(value=targets[k], target=ref_full[k], abs_diff=abs(targets[k] - ref_full[k]), tol=1e-13,
                          ok=abs(targets[k] - ref_full[k]) <= 1e-13)
        else:
            rel = abs(targets[k] - ref_full[k]) / ref_full[k]
            acc[k] = dict(value=targets[k], target=ref_full[k], target_spec_digits=ref[k], rel_diff=rel, tol=1e-9, ok=rel <= 1e-9)
        log('target %s: %.13f against %.13f -> %s' % (k, targets[k], ref_full[k], acc[k]))
    # c2_ref by three-point Richardson in G
    # c2_ref by Richardson in G: shifts at G, G/2, G/4, G/8 fitted with c1 G + c2 G^2 + c3 G^3 + c4 G^4 (version 1 used three
    # points without the linear term; the roundoff first-order term ~1e-17 of the free diagonal then entered c2 at 4e-10)
    sh = []
    for fac in (1.0, 0.5, 0.25, 0.125):
        Vg = -(G * fac) * K13
        sh.append(exact_in_block(cl, types, Vg, 0, want_cov=False)['shift_conditioned'])
    Gs = np.array([G, G / 2, G / 4, G / 8])
    Mfit = np.stack([Gs, Gs ** 2, Gs ** 3, Gs ** 4], axis=1)
    c1, c2, c3, c4 = np.linalg.solve(Mfit, np.array(sh))
    Eb = math.sqrt(m * m + 7.0 / 4.0)
    c2_closed = -(27.0 / 38416.0) * 1.9 ** 2 * (Eb - m) ** 6 / (Eb ** 2 * (Eb + m))
    # perturbative c2 of the reference: -sum |<k|W_P/G|free>|^2 / dE_k
    r0 = ex[0]
    i_free = int(np.argmax(np.abs(r0['block'].free())))
    col = r0['WP'][:, i_free] / G
    msk = r0['dE'] > 1e-9
    c2_pert = -float(np.sum(np.abs(col[msk]) ** 2 / r0['dE'][msk]))
    log('c2_ref: Richardson %.15e (c3 %.4e), perturbative %.15e, closed form %.15e; |diff| %.1e, %.1e'
        % (c2, c3, c2_pert, c2_closed, abs(c2 - c2_closed), abs(c2_pert - c2_closed)))
    # second-order energy of the HF determinant less the reference's own; Temple bound
    N = cl['N0'] + 2
    PhiH = HF['Phi']
    C = PhiH @ PhiH.conj().T
    F = cl['h0'] + f_of(V, cl['e'], C - cl['P0'])
    Qc, _ = np.linalg.qr(np.concatenate([PhiH, np.eye(cl['d'])], axis=1))
    Psi = Qc[:, N:cl['d']]
    eo, Ro = np.linalg.eigh(herm(PhiH.conj().T @ F @ PhiH))
    evv, Rv = np.linalg.eigh(herm(Psi.conj().T @ F @ Psi))
    E2_hf, S_hf, namp = mp2_vertex(V, cl['e'], PhiH @ Ro, Psi @ Rv, eo, evv)
    U0 = cl['U']
    E2_ref, S_ref, _ = mp2_vertex(V, cl['e'], U0[:, :cl['N0']], U0[:, cl['N0']:], cl['eps'][:cl['N0']], cl['eps'][cl['N0']:])
    E2 = E2_hf - E2_ref
    corr = E_exact_sub2 - E_HF
    # Temple: E0 >= <H> - Var/(E1 - <H>) on the block of Nf = 2, energies relative to the free state
    E_HF_rel = E_HF - 2 * m
    E1_rel = ex[2]['first_excited'] + 0.0
    temple = E_HF_rel - S_hf / (E1_rel - E_HF_rel)
    E0_rel = ex[2]['shift_conditioned']
    log('E2: HF determinant %.6e (amplitudes %d), reference %.6e, difference %.6e against E_exact,sub - E_HF = %.6e (rel %.2e); '
        'Temple bound %.6e <= exact %.6e: %s' % (E2_hf, namp, E2_ref, E2, corr, abs(E2 - corr) / abs(E2), temple, E0_rel, temple <= E0_rel))
    # Gaussian energy of the exact state's covariance (Nf = 2 and 0)
    gauss = {}
    for Nf in (0, 2):
        Cq = ex[Nf]['C']
        D = Cq - cl['P0']
        kin = kinetic_excess(cl['h0'], cl['eps'], U0, Cq, m, Nf)
        Eg = kin + Nf * m + E_pair(V, cl['e'], D)
        Eq = Nf * m + ex[Nf]['shift_conditioned']
        gauss[Nf] = dict(E_exact=Eq, E_gauss=Eg, cumulant=Eq - Eg, trace_C=float(np.trace(Cq).real), N=cl['N0'] + Nf)
        log('Nf=%d: E_exact - E_Gaussian(C_exact) = %.6e (Tr C %.12f)' % (Nf, Eq - Eg, np.trace(Cq).real))
    # seven-site closed forms
    seven = seven_site_closed_forms()
    log('seven-site closed forms: max |diff| %.1e over %d cases' % (seven['max_abs_diff'], seven['cases']))
    out.update(E_H=E_H, E_HF=E_HF, B_H=B_H, B_HF=B_HF, B_exact_sub=B_ex, E_exact_sub2=E_exact_sub2, E_exact_sub1=E_exact_sub1,
               hartree={k: v for k, v in H.items() if k != 'Phi'}, hf={k: v for k, v in HF.items() if k != 'Phi'},
               types=tinfo, exact={Nf: {k: v for k, v in r.items() if k not in ('C', 'psi', 'block', 'dE', 'WP')} for Nf, r in ex.items()},
               targets=acc, c2=dict(richardson=c2, c1_fit=c1, c3=c3, c4=c4, perturbative=c2_pert, closed=c2_closed,
                                    abs_diff_richardson=abs(c2 - c2_closed), abs_diff_pert=abs(c2_pert - c2_closed), ok=abs(c2 - c2_closed) <= 1e-12,
                                    shifts=sh),
               E2=dict(E2_hf_det=E2_hf, E2_ref=E2_ref, E2=E2, correlation=corr, rel=abs(E2 - corr) / abs(E2), ok=abs(E2 - corr) <= 1e-3 * abs(E2),
                       amplitudes=namp, Var_HF=S_hf),
               temple=dict(bound=temple, exact=E0_rel, E1=E1_rel, ok=bool(temple <= E0_rel)), gaussian=gauss, seven_site=seven,
               native_parent_brute_force='not built: the native 7x1x1 parent table (HF_cluster section 4) uses GAP06 native '
                                         'density-current kernel V = B(I + P^A B)^-1, whose construction is not part of the route-2 '
                                         'specification; the seven-site closed forms (cross7, monopole K_7) are checked instead')
    os.makedirs(args.out, exist_ok=True)
    dump_json(os.path.join(args.out, 'route2_cluster.json'), out)
    np.savez(os.path.join(args.out, 'route2_cluster.npz'), C_exact_Nf2=ex[2]['C'], C_exact_Nf0=ex[0]['C'], C_HF=C, Phi_HF=PhiH, Phi_H=H['Phi'],
             eps0=cl['eps'], shifts=np.array(sh), G_list=Gs)
    log('saved %s' % os.path.join(args.out, 'route2_cluster.json'))
    return out


def seven_site_closed_forms():
    cl = cluster('cross7', 1.0)
    m = cl['m']
    U0, eps = cl['U'], cl['eps']
    mlev = np.nonzero(np.abs(eps - m) < 1e-9)[0]
    diffs = []
    cases = 0
    for G in (2.0 ** -10, 2.0 ** -8, 2.0 ** -6):
        V = -G * K7
        for Nf in range(1, len(mlev) + 1):
            Phi = U0[:, mlev[:Nf]]
            D = Phi @ Phi.conj().T
            EH = tr(cl['h0'] @ D).real + E_pair(V, cl['e'], D, direct_only=True)
            EHF = tr(cl['h0'] @ D).real + E_pair(V, cl['e'], D)
            diffs.append(abs(EH - (Nf * m - 0.5 * G * m * m * Nf * Nf)))
            diffs.append(abs(EHF - (Nf * m - 0.5 * G * m * m * Nf * (Nf - 1))))
            cases += 1
    return dict(max_abs_diff=float(max(diffs)), cases=cases, ok=max(diffs) <= 1e-12, m_level_degeneracy=len(mlev))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--threads', default='3')
    a = ap.parse_args()
    t0 = time.time()
    run_cluster(a)
    log('done %.0f s' % (time.time() - t0))


if __name__ == '__main__':
    main()
